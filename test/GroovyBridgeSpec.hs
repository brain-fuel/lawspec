module GroovyBridgeSpec (test_groovyJavaBody) where

import Data.List (isInfixOf)
import Test.Hspec
import qualified LawSpec.Code.Doc as D
import LawSpec.Groovy.Source (adapterStub)
import qualified LawSpec.JavaAbi as Abi
import LawSpec.Groovy.Spock (Feature(..), spockSpecification, classSpecification, specClassName)

test_groovyJavaBody :: Spec
test_groovyJavaBody = describe "Groovy Spock specifications" $ do
  it "runs each Java test as a feature, keeping skip, order and law comments" $ do
    let features =
          [ Feature "normalizers agree: spaces become hyphens" ["|normalizers agree| — slug.lawspec:6"] Nothing "normalizersAgree_spacesBecomeHyphens" Abi.SingleCase
          , Feature "normalizers agree: skipped" [] (Just "deferred") "normalizersAgree_skipped" Abi.SingleCase ]
        specification = spockSpecification "Generated by LawSpec from slug.lawspec. Do not edit." "example" "SlugLawSpecTest" "The laws of example.slug." True False features
    specClassName "SlugLawSpecTest" `shouldBe` "SlugLawSpec"
    specification `shouldSatisfy` isInfixOf "class SlugLawSpec extends Specification"
    specification `shouldSatisfy` isInfixOf "@lawspec.testing.LawSpecRandomOrder"
    specification `shouldSatisfy` isInfixOf "// |normalizers agree| — slug.lawspec:6"
    specification `shouldSatisfy` isInfixOf "normalizers agree: spaces become hyphens"
    specification `shouldSatisfy` isInfixOf ".normalizersAgree_spacesBecomeHyphens()"
    specification `shouldSatisfy` isInfixOf "@spock.lang.Ignore("
    specification `shouldNotSatisfy` isInfixOf "throw new AssertionError"
  it "runs every JUnit test of another Java test class" $ do
    let specification = classSpecification "Generated by LawSpec. Do not edit." "lawspec" "CryptoVectorsTest"
    specification `shouldSatisfy` isInfixOf "class CryptoVectorsSpec extends Specification"
    specification `shouldSatisfy` isInfixOf "LawSpecGroovy.run(CryptoVectorsTest, method)"
  it "wraps long adapter labels while leaving their payload in string pieces" $ do
    let label = "priceOrder -> Either (example.ordering::type::OrderError) (example.ordering::type::PricedOrder)"
        operation = Abi.operation (D.text "void") "priceOrder" [] label
        source = adapterStub (Abi.Stub "" [] "LabelProbe" [Abi.Function [] operation])
    source `shouldSatisfy` all ((<= 100) . length) . lines
    source `shouldSatisfy` isInfixOf "throw new UnsupportedOperationException("
    source `shouldSatisfy` isInfixOf "+ \""
