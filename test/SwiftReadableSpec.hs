-- | Readable Swift: generated code keeps the specification's names, writes
-- text as Swift literals, links tests to their source lines and is laid out
-- as swift-format lays it out (acceptance checks it against swift-format
-- itself). ref:DEC-swift-readable-output ref:DEC-readable-generated-names
-- ref:DEC-tests-cite-requirements
module SwiftReadableSpec (test_swiftReadableOutput) where

import Test.Hspec
import Data.List (isInfixOf, isPrefixOf)
import LawSpec.Common
import LawSpec.Frontend (compileCore)
import LawSpec.Testing (planTesting)
import LawSpec.CoreEmit (emitPlanWithFormat)

generated :: String -> Either [Diagnostic] [Artifact]
generated text = compileCore 64 defaultGeneration [Source "slug.lawspec" text]
  >>= planTesting >>= emitPlanWithFormat False "swift"

contentOf :: FilePath -> Either [Diagnostic] [Artifact] -> String
contentOf path = either (error . show) (\as -> concat [artifactContent a | a <- as, artifactPath a == path])

test_swiftReadableOutput :: Spec
test_swiftReadableOutput = describe "Readable Swift output" $ do
  let source = unlines
        [ "unit example.slug"
        , ""
        , "normalize :: Text -> Text"
        , ""
        , "law \"|normalizers agree| is"
        , "  definition :"
        , "    for all (phrase :: Text) => normalize (normalize phrase) = normalize phrase end for all"
        , "  end definition"
        , "  example \"|spaces become hyphens| :"
        , "    phrase = \"Hello, World!\""
        , "    expect normalize phrase = \"Hello,-World!\""
        , "  end example"
        , "end law"
        , "end unit" ]
      files = generated source
      tests = contentOf "tests/LawSpec/ExampleSlug.swift" files
  it "names tests from the law and the example and binders from the source" $ do
    tests `shouldSatisfy` isInfixOf "func lawNormalizersAgree_spacesBecomeHyphens() async throws {"
    tests `shouldSatisfy` isInfixOf "func lawNormalizersAgree_property() async throws {"
    tests `shouldSatisfy` isInfixOf "let phrase = Runtime.item(0, inputs)"
    tests `shouldNotSatisfy` isInfixOf "input0"
  it "writes text as Swift string literals" $ do
    tests `shouldSatisfy` isInfixOf "Value.text(\"Hello, World!\")"
    tests `shouldNotSatisfy` isInfixOf "textUnits"
  it "links the law and its tests to their source lines" $ do
    tests `shouldSatisfy` isInfixOf "// |normalizers agree| — slug.lawspec:5"
    tests `shouldSatisfy` isInfixOf "// example |spaces become hyphens| — slug.lawspec:1"
    tests `shouldSatisfy` isPrefixOf "// Generated by LawSpec from slug.lawspec. Do not edit.\n\nimport LawSpecRuntime\n"
  it "lays code out in swift-format's two-space indentation within 100 columns" $ do
    let swift = [artifactContent a | a <- either (const []) id files, ".swift" `isSuffixOf'` artifactPath a,
                 not ("lawspec/" `isPrefixOf` artifactPath a)]
        long = [l | content <- swift, l <- lines content, length l > 100, not (literalLine l)]
    long `shouldBe` []
    tests `shouldSatisfy` isInfixOf "\n  @Suite(\"example.slug\") struct ExampleSlug {\n"
  where
    isSuffixOf' suffix s = reverse suffix `isPrefixOf` reverse s
    -- A string literal swift-format cannot break may run past the width.
    literalLine l = take 1 (dropWhile (== ' ') l) == "\""
