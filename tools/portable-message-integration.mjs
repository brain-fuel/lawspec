// Parse emitted code independently and evaluate only literal string additions.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const ts = require(process.env.LAWSPEC_TYPESCRIPT ?? path.join(root, '.artifacts/web-data-deps/typescript/lib/typescript.js'));
const compiler = process.env.LAWSPEC_CORE;
assert.ok(compiler, 'Set LAWSPEC_CORE');
const label = 'a long diagnostic with apostrophes \' quotes " and backslashes \\ plus supplementary Unicode 🙂 preserved exactly';
const source = `unit diagnostic
echo :: Int32 -> Int32
law \`${label}\` is
  definition is \`for all\` (x :: Int32) . echo x = x end
  example \`fixed\` is x = 1 expect echo x = 1 end
end`;
const expectedPrefix = `diagnostic::${label}`;
for (const target of ['python', 'javascript', 'typescript']) {
  for (const minify of [false, true]) {
    const result = JSON.parse(execFileSync(compiler, [], {
      input: JSON.stringify({method: 'planGeneration', target, minify, sources: [{path: 'diagnostic', content: source}]}),
      encoding: 'utf8', maxBuffer: 16 * 1024 * 1024,
    }));
    assert.deepEqual(result.diagnostics, []);
    const files = result.files.filter((a) => a.placement === 'test' && a.content.includes('Generated by LawSpec.'));
    const messages = [];
    for (const artifact of files) {
      if (target === 'python') {
        messages.push(...JSON.parse(execFileSync(process.env.LAWSPEC_PYTHON ?? 'python3', ['-c', `
import ast, json, sys
source = ast.parse(sys.stdin.read())
def literal(node):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return literal(node.left) + literal(node.right)
    raise AssertionError(ast.dump(node))
print(json.dumps([literal(n.args[0]) for n in ast.walk(source)
    if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)
    and n.func.id == '_lawspec_assert']))
`], {input: artifact.content, encoding: 'utf8'})));
      } else {
        const parsed = ts.createSourceFile(artifact.path, artifact.content, ts.ScriptTarget.ESNext, true,
          target === 'typescript' ? ts.ScriptKind.TS : ts.ScriptKind.JS);
        assert.deepEqual(parsed.parseDiagnostics, []);
        const literal = (node) => {
          if (ts.isStringLiteral(node)) return node.text;
          if (ts.isParenthesizedExpression(node)) return literal(node.expression);
          if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken)
            return literal(node.left) + literal(node.right);
          throw new Error(`Unexpected message expression: ${node.getText(parsed)}`);
        };
        const visit = (node) => {
          if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) &&
              ['test', '_lawspecAssert'].includes(node.expression.text)) messages.push(literal(node.arguments[0]));
          ts.forEachChild(node, visit);
        };
        visit(parsed);
      }
    }
    assert.ok(messages.length > 5);
    assert.ok(messages.every((message) => message.startsWith(expectedPrefix)));
    assert.ok(messages.some((message) => message.startsWith(expectedPrefix + ' example fixed | expect ')));
    console.log(`${target}/${minify ? 'compact' : 'readable'}: diagnostic text preserved through native parsing`);
  }
}
