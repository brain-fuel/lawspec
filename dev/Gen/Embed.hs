{-# LANGUAGE NoOverloadedStrings #-}
-- The reviewed runtime sources, embedded in the native and WASM compiler as
-- src/LawSpec/RuntimeSources.hs. Strings are quoted as Python's json.dumps
-- quotes them (ASCII only), which is also valid Haskell string syntax.
module Gen.Embed (runtimeFiles, embedRuntimes, embedDefaults) where

import Data.Char (ord)
import Numeric (showHex)
import Data.List (isSuffixOf, sort)
import System.Directory (doesDirectoryExist, listDirectory)
import System.FilePath ((</>))

runtimeFiles :: [(String, FilePath)]
runtimeFiles =
  [ ("python", "lawspec_runtime.py"), ("python-schema", "lawspec_schema.py")
  , ("python-data-strategies", "lawspec_data_strategies.py"), ("javascript", "lawspec_runtime.mjs")
  , ("web-schema", "lawspec_schema.mjs"), ("web-data-strategies", "lawspec_data_strategies.mjs")
  , ("java", "LawSpecRuntime.java"), ("java-schema", "LawSpecSchema.java")
  , ("java-data-strategies", "LawSpecDataStrategies.java"), ("go", "lawspec_runtime.go")
  , ("go-schema", "lawspec_schema.go"), ("go-codecs", "lawspec_codecs.go")
  , ("go-data-strategies", "lawspec_data_strategies.go"), ("haskell", "LawSpecRuntime.hs")
  , ("haskell-schema", "LawSpecSchema.hs"), ("haskell-codecs", "LawSpecCodecs.hs")
  , ("haskell-collection-codecs", "LawSpecCollectionCodecs.hs")
  , ("haskell-transports", "LawSpecTransports.hs")
  , ("haskell-data-strategies", "LawSpecDataStrategies.hs"), ("rust", "lawspec_runtime.rs")
  , ("rust-strategies", "lawspec_strategies.rs"), ("kotlin-strategies", "LawSpecStrategies.kt")
  , ("kotlin-native", "LawSpecKotlin.kt"), ("kotlin-codecs", "LawSpecKotlinCodecs.kt")
  , ("kotlin-data-strategies", "LawSpecKotlinStrategies.kt") ]

embedRuntimes :: IO String
embedRuntimes = do
  equations <- mapM (\(key, file) -> do
    source <- readFile ("runtime" </> file)
    pure ("runtimeSource " ++ quote key ++ " = " ++ quote source)) runtimeFiles
  pure (unlines (
    [ "-- Generated by lawspec-dev generate. Edit runtime/ sources."
    , "module LawSpec.RuntimeSources (runtimeSource) where"
    , "runtimeSource :: String -> String" ] ++ equations ++ ["runtimeSource _ = \"\""]))

-- The built-in abilities' default handlers and known-answer vectors, by
-- their path under runtime/defaults (LawSpec.BuiltinDefaults), in their own
-- module so the scalar runtimes stay apart.
embedDefaults :: IO String
embedDefaults = do
  files <- walk "runtime/defaults"
  equations <- mapM (\path -> do
    source <- readFile path
    pure ("defaultSource " ++ quote (drop (length "runtime/defaults/") path) ++ " = " ++ quote source)) files
  pure (unlines (
    [ "-- Generated by lawspec-dev generate. Edit runtime/defaults/ sources."
    , "module LawSpec.DefaultSources (defaultSource) where"
    , "defaultSource :: String -> String" ] ++ equations ++ ["defaultSource _ = \"\""]))
  where
    walk dir = do
      entries <- sort <$> listDirectory dir
      concat <$> mapM (\entry -> do
        let path = dir </> entry
        isDirectory <- doesDirectoryExist path
        -- Sources only: no caches or editor files.
        if isDirectory then (if take 2 entry == "__" || take 1 entry == "." then pure [] else walk path)
        else pure [path | take 1 entry /= ".", any (`isSuffixOf` entry) [".py", ".mjs", ".ts", ".go", ".java", ".kt", ".hs", ".rs", ".txt"]]) entries

quote :: String -> String
quote s = "\"" ++ concatMap escape s ++ "\""
  where
    escape '"' = "\\\""
    escape '\\' = "\\\\"
    escape '\n' = "\\n"
    escape '\r' = "\\r"
    escape '\t' = "\\t"
    escape '\b' = "\\b"
    escape '\f' = "\\f"
    escape c
      | c >= ' ' && c <= '~' = [c]
      | ord c > 0xffff = let n = ord c - 0x10000
                         in unicode (0xd800 + n `div` 0x400) ++ unicode (0xdc00 + n `mod` 0x400)
      | otherwise = unicode (ord c)
    unicode n = let digits = showHex n "" in "\\u" ++ replicate (4 - length digits) '0' ++ digits
