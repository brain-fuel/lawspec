import Data.List (intercalate, stripPrefix)

-- | What the Scala test emitter needs besides the plan: names, layout and
-- bindings, gathered so the emitter takes one argument.
data Config = Config
  { packageName :: String
  -- An async adapter's call, awaited.
  , awaitResult :: String -> D.Doc -> D.Doc
  , className :: String
  , constructorContracts :: Bool
  , nativeGenerators :: Bool
  , nodeBudget :: Integer
  , machineBits :: Int
  , expression :: Expr -> D.Doc
  , literal :: V.Value -> Either [Diagnostic] D.Doc
  , checked :: Type -> D.Doc -> D.Doc
  , structural :: Type -> Bool
  , reference :: Type -> D.Doc
  , typeKey :: Type -> String
  , generator :: Type -> D.Doc
  -- A generator drawing a top-level integer from a refinement's range.
  , generatorWithin :: Maybe (Integer, Integer) -> Type -> D.Doc
  , nativeArgument :: Type -> D.Doc -> D.Doc
  , nativeResult :: Type -> D.Doc -> D.Doc
  -- The statements that install a law's handlers in symbols, for each case.
  , handlerInstalls :: Expanded -> [D.Doc]
  -- The native handlers made with a resource, installed once the case has
  -- acquired its resources.
  , lateHandlerInstalls :: Expanded -> [D.Doc]
  -- Each input's descriptor, for LawSpec's own search (LawSpec.Search):
  -- Nothing when the law takes no part in it.
  , searchDescriptors :: Expanded -> Maybe [String]
  -- Imports the unit's tests need besides the runtime's.
  , extraImports :: [String]
  }

text :: String -> D.Doc
text = D.text

statements :: [D.Doc] -> D.Doc
statements = D.joinWith D.hardline

separate :: [D.Doc] -> D.Doc
separate = D.joinWith (D.hardline <> D.hardline)

block :: D.Doc -> D.Doc
block = D.block 2

call :: String -> [D.Doc] -> D.Doc
call = E.call

quoted :: String -> D.Doc
quoted = E.quoted

number :: Show a => a -> D.Doc
number = text . show

bind :: String -> D.Doc -> D.Doc
bind named value = D.group (text ("val " ++ named ++ " =") <> D.nest 2 (D.softline <> value))

-- | A braced function literal; with no parameters, a block.
closure :: String -> D.Doc -> D.Doc
closure parameters body = D.multiline (text "{" <>
  (if null parameters then mempty else text (" " ++ parameters ++ " =>")) <>
  D.nest 2 (D.hardline <> body) <> D.hardline <> text "}")

trailing :: D.Doc -> String -> D.Doc -> D.Doc
trailing invocation parameters body = invocation <> text " " <> closure parameters body

runtime :: String -> [D.Doc] -> D.Doc
runtime named = call ("LawSpecRuntime." ++ named)

truth :: D.Doc -> D.Doc
truth value = runtime "truth" [value]

conjunction :: [D.Doc] -> D.Doc
conjunction [] = text "true"
conjunction xs = D.group (D.joinWith (text " &&" <> D.softline) xs)

symbols :: D.Doc
symbols = text "val symbols = LawSpecScala.symbols()"

fromValues :: [Input] -> D.Doc
fromValues xs = statements [bind (inputId input) (text ("_values(" ++ show index ++ ")")) |
  (index,input) <- zip [0::Int ..] xs]

-- | Laws become ScalaTest tests whose properties run on ScalaCheck, so they
-- run with the tools a Scala project already uses.
-- ref:DEC-native-property-frameworks ref:DEC-scala-property-library
emitTests :: Config -> Unit -> [Expanded] -> Either [Diagnostic] D.Doc
emitTests Config{..} unit laws = do
  let testNames = unitTestNames "scala" (map name laws)
  generated <- mapM (law testNames) (zip [0::Int ..] laws)
  let bodies=map snd generated
      sharedCases=concatMap fst generated
  let imports = ["org.scalatest.funsuite.AnyFunSuite", "scala.jdk.CollectionConverters.*",
        "lawspec.runtime.{LawSpecDataCodecs, LawSpecDataSchema, LawSpecRuntime, LawSpecSchema, LawSpecScala, LawSpecScalaCodecs}",
        "lawspec.testing.{Arb, LawSpecProperty, LawSpecScalaStrategies}"] ++ extraImports
      testClass = className ++ "LawSpecTest"
  pure $ text "// Generated by LawSpec." <> D.hardline <>
    (if null packageName then mempty else text ("package " ++ packageName) <> D.hardline <> D.hardline) <>
    statements [text ("import " ++ i) | i <- imports] <> D.hardline <> D.hardline <>
    -- The helpers live in the companion object, so two units in one package
    -- never clash.
    text ("object " ++ testClass ++ " ") <> block (separate ([Helpers.assertionDoc, Helpers.dataHelpersDoc machineBits generator] ++
      map contract (contracts unit) ++ sharedCases)) <> D.hardline <> D.hardline <>
    text ("class " ++ testClass ++ " extends AnyFunSuite" ++ (if parallel then " with lawspec.testing.LawSpecParallel" else "") ++ " ") <>
    block (separate (statements ([text ("import " ++ testClass ++ ".*")] ++
      -- Workflows wait on a virtual clock under test, and workflows and
      -- mailboxes read the Clock handler a law installs.
      [text "lawspec.runtime.LawSpecRuntime.useVirtualClock(0)"] ++
      [text "lawspec.Time.registerClock()" | installsClock unit]) :
      [call "lawspec.testing.LawSpecHarness.parallelism" [quoted unitLabel, quoted "tests on a thread per processor (LawSpecParallel)",
         text "Runtime.getRuntime().availableProcessors()"] | parallel] ++
      ordered (zipWith registration [0 :: Int ..] (bodies ++ map benchmark (maybe [] C.harnessBenchmarks settings))))) <> D.hardline
  where
    -- The harness plane (LawSpec.Harness). A test the harness runs is a
    -- function value (harness:name), which the generated test passes to the
    -- runtime shared with Java.
    settings = C.unitHarnessSettings unit
    orderRandom = maybe False C.harnessOrderRandom settings
    parallel = maybe False C.harnessParallel settings
    unitLabel = C.idText (C.unitId unit)
    -- order random: the unit's tests are collected, then registered in an
    -- order the run's seed chooses.
    ordered docs
      | orderRandom =
          [ text "private val _lawspecTests = scala.collection.mutable.ArrayBuffer[(String, () => Unit)]()"
          , text "private def lawspecTest(name: String)(body: => Unit): Unit = _lawspecTests += ((name, () => body))"
          , separate docs
          , text "for ((name, body) <- lawspec.testing.LawSpecHarness.shuffled(" <> quoted unitLabel <> text ", _lawspecTests.asJava).asScala) " <> text (finalRegister ++ "(name)(body())") ]
      | otherwise = docs
    register = if orderRandom then "lawspecTest" else finalRegister
    -- A parallel unit's tests start together (lawspec.testing.LawSpecParallel).
    finalRegister = if parallel then "parallelTest" else "test"
    -- Each law registers its tests from a method of its own, so a unit with
    -- many laws keeps the suite's constructor within the JVM's method size.
    registration i doc = text ("private def lawspecRegister" ++ show i ++ "(): Unit = ") <> block doc <> D.hardline <>
      text ("lawspecRegister" ++ show i ++ "()")
    testFunction label run = case stripPrefix "harness:" label of
      Just rest -> text ("val lawspecHarness" ++ takeWhile (/= ':') rest ++ ": () => Unit = () => ") <> closure "" run
      Nothing -> text (register ++ "(") <> quoted label <> text ") " <> block run
    runSettings h = C.harnessTimeout h /= Nothing || C.harnessRepeat h /= 1 || C.harnessRetries h /= 0 || observed h
    observed h = not (null (C.harnessCover h) && null (C.harnessClassify h) && null (C.harnessLabels h)) || C.harnessTarget h /= Nothing
    harness name' = call ("lawspec.testing.LawSpecHarness." ++ name')
    body name' = text ("(() => " ++ name' ++ "()): lawspec.testing.LawSpecHarness.Body")
    observations e =
      let h = C.propertyHarness (original e)
          label = owner e ++ "::" ++ name e
      in [harness "observe" [quoted label,
            call "Array[String]" [quoted l | C.Cover _ l _ <- C.harnessCover h], call "Array[Boolean]" [truth (expr w) | C.Cover _ _ w <- C.harnessCover h],
            call "Array[String]" [quoted l | (_, l) <- C.harnessClassify h], call "Array[Boolean]" [truth (expr c) | (c, _) <- C.harnessClassify h],
            call "Array[LawSpecRuntime.Value]" (map expr (C.harnessLabels h))] | observed h] ++
         [harness "target" [expr score, quoted label] | Just score <- [C.harnessTarget h]]
    -- The tests a law's harness wraps, skips or expects to fail.
    harnessTests fn label h kinds docs = case (C.harnessSkip h, C.harnessKnownFailing h) of
      (Just reason, _) -> [text "ignore(" <> quoted (fn ++ "_skipped: " ++ label) <> text ") " <> block (text ("// " ++ reason))]
      (_, Just reason) -> docs ++ [text (register ++ "(") <> quoted (fn ++ "_knownFailing: " ++ label) <> text ") " <> block (harness "knownFailing"
        [quoted label, quoted (fn ++ "_knownFailing"), quoted reason, call "java.util.List.of[lawspec.testing.LawSpecHarness.Body]" [body ("lawspecHarness" ++ fn ++ k) | k <- kinds]])]
      _ | runSettings h -> docs ++ [text (register ++ "(") <> quoted (fn ++ k ++ (if k == "_property" then ": " ++ label else "")) <> text ") " <> block (harness "run"
            [quoted label, quoted (fn ++ k), number (maybe 0 id (C.harnessTimeout h)), number (C.harnessRepeat h), number (C.harnessRetries h),
             call "Array[Int]" [number p | k == "_property", C.Cover p _ _ <- C.harnessCover h],
             call "Array[String]" [quoted l | k == "_property", C.Cover _ l _ <- C.harnessCover h],
             text (if k == "_property" && observed h then "true" else "false"), body ("lawspecHarness" ++ fn ++ k)]) | k <- kinds]
        | otherwise -> docs
    benchmark (n, b) = text (register ++ "(") <> quoted ("benchmark " ++ n) <> text ") " <> block (statements [symbols,
      harness "benchmark" [quoted n, text "(() => { val _measured = " <> expr b <> text "; () }): lawspec.testing.LawSpecHarness.Body"]])
    -- A property whose inputs harness strategies draw, from ScalaCheck's
    -- random source; their values' refinements are checked in the property.
    harnessProperty fn label e check = do
      let h = C.propertyHarness (original e)
          strategyOf inp = [(n, d) | (i, n, d) <- C.harnessDraws h, i == C.binderId (C.quantifiedBinder inp)]
      draws <- mapM (\plan -> do
        let inp = domainInput plan
        case strategyOf inp of
          (strategy, d) : _ -> bind (inputId inp) <$> drawDoc inp strategy d
          [] -> pure (bind (inputId inp) (generatorWithin (inputRange machineBits inp) (inputType inp) <> text ".sample(_random).value"))) (generationPlan e)
      let defaults = [inp | inp <- inputs e, null (strategyOf inp)]
          strategyChecks = [harness "checkDrawn" [quoted named, quoted (inputName inp),
              conjunction (map (truth . expr) (inputRefinements inp)), text (inputId inp)]
            | inp <- inputs e, (named, _) : _ <- [strategyOf inp], not (null (inputRefinements inp))]
          base = trailing (text "Arb.from") "_random" (statements
            ([symbols] ++ draws ++ [text "(" <> call "List" [text (inputId inp) | inp <- inputs e] <> text ", symbols)"]))
          predicates = concatMap inputRefinements defaults
          bindingsDoc = statements [text "val symbols = _inputs._2", text "val _values = _inputs._1", fromValues (inputs e)]
          strategy = if null predicates then base else trailing (base <> text ".filter") "_inputs"
            (statements [bindingsDoc, conjunction (map (truth . expr) predicates)])
      pure $ testFunction (fn ++ "_property: " ++ label) $ trailing
        (call "LawSpecProperty.checkAll" [quoted label, number (cases (generation e)), strategy]) "_inputs"
        (statements ([bindingsDoc] ++ strategyChecks ++ handlerInstalls e ++ [check]))
    chooser = text "((_n: Int) => _random.nextInt(_n)): java.util.function.IntUnaryOperator"
    supplier doc = text "(() => " <> doc <> text "): java.util.function.Supplier[LawSpecRuntime.Value]"
    drawDoc inp strategy d = case d of
      C.DrawAny ty aim -> pure (maybe (generator ty) (\range -> generatorWithin (Just range) ty) (drawRange machineBits inp ty aim) <> text ".sample(_random).value")
      C.DrawOneOf _ values -> pure (harness "oneOf" [chooser, call "java.util.List.of[java.util.function.Supplier[LawSpecRuntime.Value]]" [supplier (expr v) | v <- values]])
      C.DrawFrequency alternatives -> do
        options <- mapM (\(w, a) -> (\doc -> call "lawspec.testing.LawSpecHarness.Weighted" [number w, supplier doc]) <$> drawDoc inp strategy a) alternatives
        pure (harness "frequency" [chooser, call "java.util.List.of[lawspec.testing.LawSpecHarness.Weighted]" options])
      C.DrawSuchThat inner binder predicate limit -> do
        doc <- drawDoc inp strategy inner
        pure (harness "suchThat" [supplier doc,
          text ("((" ++ localName (C.binderId binder) ++ ": LawSpecRuntime.Value) => ") <> truth (expr predicate) <> text "): java.util.function.Predicate[LawSpecRuntime.Value]",
          number limit, quoted strategy])
      C.DrawBind binder from rest -> do
        fromDoc <- drawDoc inp strategy from
        restDoc <- drawDoc inp strategy rest
        pure (block (statements [bind (localName (C.binderId binder)) fromDoc, restDoc]))
    expr = expression
    assertionDoc context = contextualAssertion (quoted . (context ++))
    contextualAssertion context proposition = case proposition of
      AssertAll ps -> statements (map (contextualAssertion context) ps)
      AssertImplies guard body' -> text "if (" <> truth (expr guard) <> text ") " <>
        block (contextualAssertion context body')
      AssertEqual a b ->
        let message = context (" | expect " ++ prettyExpr a ++ " = " ++ prettyExpr b)
            isData = structural (expressionType a)
        in call (if isData then "_lawspecDataAssert" else "_lawspecAssert")
          ([message] ++ (if isData then [reference (expressionType a),text "symbols"] else []) ++
          [closure "" (expr a),closure "" (expr b)])
    contract c =
      let args = contractArguments c
          (rn,rt) = contractResult c
          params = text "symbols: LawSpecScala.Symbols" : [text (n ++ ": LawSpecRuntime.Value") | (n,_) <- args]
          context stage ps = quoted (contractName c ++ " " ++ stage ++ ": " ++ intercalate " && " (map prettyExpr ps))
          require stage ps = runtime "requireContract" [conjunction (map (truth . expr) ps),context stage ps]
          invocation = awaitResult (adapterName unit (C.contractDeclaration c)) (call (qualifiedAdapter ++ "." ++ adapterName unit (C.contractDeclaration c)) [nativeArgument ty (text n) | (n,ty) <- args])
      in call ("def _lawspec_call_" ++ contractName c) params <> text ": LawSpecRuntime.Value = " <>
        block (statements [require "precondition" (contractPreconditions c),
          bind rn (nativeResult rt invocation),require "postcondition" (contractPostconditions c),text rn])
    qualifiedAdapter = if null packageName then className else packageName ++ "." ++ className
    -- A law's resources: each case acquires them, then runs, then releases
    -- them, the last first, even when the case fails.
    bracketed e docs = foldr wrap (statements (lateHandlerInstalls e ++ docs)) (C.propertyResources (original e))
      where
        -- A shared resource (share R per ...): the runtime keeps one per
        -- scope key, resets it before each later use, and releases it when
        -- the JVM exits.
        wrap r inner | Just key <- C.resourceShared r, Just reset <- C.resourceReset r =
          let local = localName (C.binderId (C.resourceBinder r))
              use body' = text ("((" ++ local ++ ": LawSpecRuntime.Value) => ") <> block body' <> text ")"
          in statements [bind local (runtime "share" [quoted key, text "(() => " <> block (expr (C.resourceAcquire r)) <> text ")",
              use (expr reset), use (expr (C.resourceRelease r)),
              text (if C.resourceConcurrent r then "true" else "false")]),
            text "try " <> block inner <> text " finally " <> block (runtime "unshare" [quoted key])]
        wrap r inner =
          let local = localName (C.binderId (C.resourceBinder r))
          in statements [bind local (expr (C.resourceAcquire r)),
            text "try " <> block inner <> text " finally " <> block (expr (C.resourceRelease r))]
    law testNames (index,e) = do
      let label = owner e ++ "::" ++ name e
          h = C.propertyHarness (original e)
          base' = testNames !! index
          fn = (if C.harnessSkip h == Nothing && (C.harnessKnownFailing h /= Nothing || runSettings h) then "harness:" else "") ++ base'
      exampleDocs <- mapM (\(i,ex) -> pure $ testFunction (fn ++ "_example" ++ show i) $ statements
        ([symbols] ++ handlerInstalls e ++ [bind n (expr v) | (n,v) <- bindings ex] ++
        [bracketed e (map (assertionDoc (label ++ " example " ++ exampleName ex)) (expectations ex) ++
          [assertionDoc label (assertion e)])])) (zip [0::Int ..] (examples (original e)))
      boundaryValues <- mapM (mapM literal) (maybe (boundaryCases e) id (finiteCases e))
      let sharedBoundaries=length boundaryValues >= 1024
          helper="_lawspecBoundary"++show index
          names=map inputId (inputs e) ++ [localName (C.binderId (C.resourceBinder resource)) | resource<-C.propertyResources (original e)]
          valuesArray=call "Array[LawSpecRuntime.Value]" (map text names)
          boundaryDocs=[testFunction (fn ++ "_boundary" ++ show i) $ statements
            ([symbols] ++ handlerInstalls e ++ [bind (inputId inp) (checked (inputType inp) v) | (inp,v) <- zip (inputs e) values] ++
            [bracketed e [if sharedBoundaries then call helper [quoted (label++" boundary "++show i),text "symbols",valuesArray]
            else assertionDoc (label++" boundary "++show i) (assertion e)]]) | (i,values)<-zip [0::Int ..] boundaryValues]
          sharedDocs=[text ("private def "++helper++"(_lawspecContext: String, symbols: LawSpecScala.Symbols, _values: Array[LawSpecRuntime.Value]): Unit = ") <>
            block (statements ([bind name (text ("_values("++show i++")")) | (i,name)<-zip [0::Int ..] names] ++
              [contextualAssertion (\suffix->text "_lawspecContext + "<>quoted suffix) (assertion e)])) | sharedBoundaries,C.harnessSkip h==Nothing]
          -- A registration method also has a JVM bytecode size limit. Keep
          -- the same test names and order in bounded registration methods.
          registeredBoundaries
            | sharedBoundaries && C.harnessSkip h==Nothing && C.harnessKnownFailing h==Nothing && not (runSettings h) =
                concat [let registerPart="_lawspecBoundaries"++show index++"_"++show part in
                  [text ("def "++registerPart++"(): Unit = ")<>block (separate group),call registerPart []]
                  | (part,group)<-zip [0::Int ..] (groupsOf 64 boundaryDocs)]
            | otherwise = boundaryDocs
      -- LawSpec's own search (LawSpec.Search): the failure database's
      -- inputs are replayed before the law's generated cases, a failing
      -- case's inputs are kept, and a law with `target maximize` climbs
      -- after them, as ScalaCheck has no targeting.
      let descriptors = searchDescriptors e
          inputsName = "_lawspecInputs" ++ show index
          caseName = "_lawspecCase" ++ show index
          remembered doc = case descriptors of
            Nothing -> doc
            Just _ -> text "try " <> block doc <> text " catch " <> block (text "case _lawspecError: Throwable => " <> block (statements
              [runtime "searchRemember" [quoted label, text inputsName, call "java.util.List.of[LawSpecRuntime.Value]" [text (inputId inp) | inp <- inputs e]], text "throw _lawspecError"]))
          searchCase = text ("((_values: java.util.List[LawSpecRuntime.Value]) => " ++ caseName ++ "(_values.asScala.toList)): LawSpecRuntime.SearchCase")
          (searchBefore, searchAfter) = case descriptors of
            Nothing -> ([], [])
            Just ds ->
              let refinements = concatMap inputRefinements (inputs e)
              in ( [ bind inputsName (call "java.util.List.of[String]" (map quoted ds))
                   , text ("def " ++ caseName ++ "(_values: List[LawSpecRuntime.Value]): java.lang.Double = ") <> block (statements
                       ([symbols] ++ handlerInstalls e ++
                        [bind (inputId inp) (checked (inputType inp) (text ("_values(" ++ show i ++ ")"))) | (i, inp) <- zip [0::Int ..] (inputs e)] ++
                        [text "if (!(" <> conjunction (map (truth . expr) refinements) <> text ")) null else " <> block (statements
                          [bracketed e [assertionDoc (label ++ " search") (assertion e)],
                           maybe (text "java.lang.Double.valueOf(0.0)") (\score -> runtime "searchNumber" [expr score]) (C.harnessTarget h)])
                        | not (null refinements)] ++
                        (if null refinements then [bracketed e [assertionDoc (label ++ " search") (assertion e)],
                           maybe (text "java.lang.Double.valueOf(0.0)") (\score -> runtime "searchNumber" [expr score]) (C.harnessTarget h)] else [])))
                   , text (register ++ "(") <> quoted (base' ++ "_replay") <> text ") " <> block (runtime "searchReplay" [quoted label, text inputsName, searchCase]) ]
                 , [text (register ++ "(") <> quoted (base' ++ "_search") <> text ") " <> block (runtime "searchClimb" [quoted label, text inputsName, searchCase]) | C.harnessTarget h /= Nothing] )
      let check = bracketed e (observations e ++ [remembered (assertionDoc (label ++ " property") (assertion e))])
      property <- if finiteCases e /= Nothing then pure []
        else if not (null (C.harnessDraws h)) then (:[]) <$> harnessProperty fn label e check
        else if constructorContracts || nativeGenerators || any (maybe False (const True) . generatorIndex) (generationPlan e)
          then (:[]) <$> contextualProperty fn label e check
        else if any (structural . inputType) (inputs e) then pure [nativeProperty fn label e check]
        else if any (not . null . inputRefinements) (inputs e) || propertyKind e == "contract"
          then (:[]) <$> refinedProperty fn label e check
          else pure [nativeProperty fn label e check]
      let kinds = ["_example" ++ show i | i <- [0 .. length exampleDocs - 1]] ++ ["_boundary" ++ show i | i <- [0 .. length boundaryDocs - 1]] ++
            ["_property" | not (null property)]
      pure (sharedDocs,metadataDocument 96 "//" e <> separate (searchBefore ++ harnessTests base' label h kinds (exampleDocs ++ registeredBoundaries ++ property) ++ searchAfter))
    groupsOf _ []=[]
    groupsOf count values=let (group,rest)=splitAt count values in group:groupsOf count rest
    contextualProperty fn label e check = do
      let valuesDoc xs = statements [text "val symbols = _inputs.symbols",
            text "val _values = _inputs.values",fromValues xs]
          state value = call "LawSpecScalaStrategies.Case"
            [value,text "symbols",text "_checked.error"]
          step prior (index,plan) = do
            let input = domainInput plan
                ty = inputType input
            seeds <- mapM literal (generatorBoundaries plan)
            let hints = [expr hint | hint <- generatorHints plan, expressionType hint == ty,
                  case C.expressionNode hint of
                    C.Constant _ -> True
                    C.Local _ -> True
                    _ -> False]
                -- Restrict only the top-level primitive. Recursive products keep
                -- their own fields' generators and the checked schema boundary.
                scalar = case inputRange machineBits input of
                  Nothing -> text "_lawspecScalarGenerator"
                  Just range -> text "(_lawspecScalarName: String) => if (_lawspecScalarName == " <> quoted (typeKey ty) <> text ") " <>
                      generatorWithin (Just range) ty <> text " else _lawspecScalarGenerator(_lawspecScalarName)"
                strategy = case (if nativeGenerators then [] else requiredSymbol plan) of
                  value:_ -> call "Arb.constant" [call "LawSpecScalaStrategies.Checked" [expr value,text "null"]]
                  -- The target is evaluated from the inputs bound above.
                  [] | Just indexed <- generatorIndex plan -> call "LawSpecScalaStrategies.indexedGenerator"
                    [text "_schema",reference ty,number machineBits,number nodeBudget,text "symbols",
                     expr (indexedTarget indexed),
                     call "Map" [quoted (C.idText tag) <> text " -> " <> call "List" (map quoted texts)
                       | (tag,texts) <- indexedEquations indexed],
                     text "_lawspecScalarGenerator"]
                  [] -> call "LawSpecScalaStrategies.checkedGenerator" $
                    [text "_schema",reference ty,number machineBits,number nodeBudget,
                     number (maxAttempts (generation e)),text "symbols",call "List" (seeds ++ hints)] ++
                    [text "lawspec.testing.LawSpecNativeGenerators.factories()" | nativeGenerators] ++
                    [scalar]
                added = trailing (strategy <> text ".map") "_checked"
                  (text "if (_checked.error != null) " <> block (state (text "_values")) <>
                   text " else " <> block (state (text "_values :+ _checked.requireValue()")))
            pure $ trailing (text "Arb.flatMap" <> D.delimitTrailing 2 "(" ")" [prior]) "_inputs"
              (text "if (_inputs.error != null) " <> block (text "Arb.constant(_inputs)") <>
               text " else " <> block (statements [valuesDoc (take index (inputs e)),added]))
      base <- foldM step (text "LawSpecScalaStrategies.cases()") (zip [0::Int ..] (generationPlan e))
      let predicates = concatMap inputRefinements (inputs e)
          strategy = if null predicates then base else trailing
            (call "LawSpecScalaStrategies.filterCases" [base,number (maxAttempts (generation e))]) "_inputs"
            (statements [valuesDoc (inputs e),conjunction (map (truth . expr) predicates)])
          body' = statements ([text "val symbols = _inputs.symbols",
            text "val _values = _inputs.requireValues()",fromValues (inputs e)] ++ handlerInstalls e ++ [check])
      pure $ testFunction (fn ++ "_property: " ++ label) $ trailing
        (call "LawSpecProperty.checkAll" [quoted label, number (cases (generation e)),strategy]) "_inputs" body'
    requiredSymbol plan
      | inputType (domainInput plan) /= C.scalarType "Symbol" = []
      | otherwise = concatMap required (generatorPredicates plan)
      where
        current = C.binderId (generatorBinder plan)
        required term = case C.expressionNode term of
          C.ShortCircuit C.And a b -> required a ++ required b
          C.Binary C.Equal _ a b -> [value | (local,value) <- [(a,b),(b,a)],
            C.expressionNode local == C.Local current,
            expressionType value == C.scalarType "Symbol",
            current `notElem` C.freeBinders value,
            case C.expressionNode value of
              C.Constant _ -> True
              C.Local _ -> True
              _ -> False]
          _ -> []
    nativeProperty fn label e check =
      let -- Constant hints (regex samples, compared literals) are mixed in so
          -- a narrow refinement still meets the filter often enough.
          hinted inp gen = case [expr hint | plan <- generationPlan e,
              inputId (domainInput plan) == inputId inp, hint <- generatorHints plan,
              expressionType hint == inputType inp, expressionType hint /= C.scalarType "Symbol",
              case C.expressionNode hint of C.Constant _ -> True; _ -> False] of
            [] -> gen
            hints -> call "Arb.choice" [call "Arb.element" [block
              (statements [symbols, call "List" hints])],gen]
          tuple = foldl (\prior inp -> call "Arb.bind" [prior,hinted inp (generatorWithin (inputRange machineBits inp) (inputType inp))] <>
            text " { (_values, _value) => _values :+ _value }")
            (text "Arb.constant(List.empty[LawSpecRuntime.Value])") (inputs e)
          base = trailing (tuple <> text ".map") "_values"
            (text "(_values, LawSpecScala.symbols())")
          predicates = concatMap inputRefinements (inputs e)
          bindingsDoc = statements [text "val symbols = _inputs._2",
            text "val _values = _inputs._1",fromValues (inputs e)]
          strategy = if null predicates then base else trailing (base <> text ".filter") "_inputs"
            (statements [bindingsDoc,conjunction (map (truth . expr) predicates)])
      in testFunction (fn ++ "_property: " ++ label) $ trailing
        (call "LawSpecProperty.checkAll" [quoted label, number (cases (generation e)),strategy]) "_inputs"
        (statements ([bindingsDoc] ++ handlerInstalls e ++ [check]))
    domain e (index,plan) = do
      seeds <- mapM literal (generatorBoundaries plan)
      let inp = domainInput plan
          prior = take index (inputs e)
          valuesOf = text "val _values = _javaValues.asScala.toList"
          bounds = call "Array[LawSpecRuntime.Bound]" [call "LawSpecRuntime.Bound" [quoted op,expr v] | (op,v) <- domainBounds plan]
          candidates = runtime "domainCandidates" [quoted (typeKey (inputType inp)),text "_seed",number machineBits,
            bounds,E.array (seeds ++ map expr (generatorHints plan))]
          seedFn = text "(_javaValues: java.util.List[LawSpecRuntime.Value], _seed: Integer) => " <>
            block (statements ([valuesOf | not (null prior)] ++ [fromValues prior | not (null prior)] ++ [candidates]))
          predicate = text "(_javaValues: java.util.List[LawSpecRuntime.Value]) => " <> block (statements
            [valuesOf, fromValues (prior ++ [inp]),conjunction (map (truth . expr) (inputRefinements inp))])
      pure (call "LawSpecRuntime.Domain" [seedFn,predicate])
    refinedProperty fn label e check = do
      domains <- mapM (domain e) (zip [0::Int ..] (generationPlan e))
      let cfg = generation e
          callback = text "(_javaValues: java.util.List[LawSpecRuntime.Value]) => " <> block (statements
            ([text "val _values = _javaValues.asScala.toList", fromValues (inputs e)] ++ handlerInstalls e ++ [check]))
          invocation = runtime "refinedCase" [call "Array[LawSpecRuntime.Domain]" domains,
            text "seed",number (maxAttempts cfg),number (maxShrinks cfg),callback,
            quoted (label ++ " | " ++ intercalate "; " (map prettyExpr (concatMap inputRefinements (inputs e))))]
      pure $ testFunction (fn ++ "_property: " ++ label) $ trailing
        (call "LawSpecProperty.checkAll" [quoted label, number (cases cfg),text "Arb.int(Int.MinValue to Int.MaxValue)"]) "seed" (statements [symbols,invocation])

-- Whether a unit's laws install a Clock handler, so the test registers how
-- the runtime reads one (lawspec.time's registerClock).
installsClock :: Unit -> Bool
installsClock unit = or [ C.abilityKey a == "lawspec.time::ability::Clock"
                        | p <- C.unitProperties unit, (a, _) <- C.propertyHandlers p ]
