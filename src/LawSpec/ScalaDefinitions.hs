-- | Scala native APIs over the shared JVM total-definition bodies, and the
-- bridge through which those bodies call Scala adapters and handlers.
module LawSpec.ScalaDefinitions (emitScalaDefinitions, adapterResult) where

import Control.Monad (forM)
import Data.Char (toUpper)
import Data.List (intercalate)
import LawSpec.Common
import LawSpec.Core
import qualified LawSpec.ScalaData as Native
import qualified LawSpec.ScalaExpr as E
import qualified LawSpec.JavaDefinitions as Jvm
import LawSpec.AbilityNames (interfaceName, specName, ownerName)
import qualified LawSpec.Code.Doc as D

-- | An adapter's native result: Either[E, R] when it fails with E, in a
-- Future when it is async.
adapterResult :: [DataDeclaration] -> Declaration -> Either String D.Doc
adapterResult declarations adapter = do
  let (_, result) = functionType (declarationType adapter)
  value <- if result == scalarType "Integer" then pure (D.text "scala.Int | scala.Long | scala.math.BigInt")
    else Native.scalaDataTypeDoc declarations result
  failing <- case [failure | AbilityRef _ [failure] <- filter isFail (declarationUses adapter)] of
    failure : _ -> do
      failureType <- Native.scalaDataTypeDoc declarations failure
      pure (D.text "scala.util.Either[" <> failureType <> D.text ", " <> value <> D.text "]")
    [] -> pure value
  pure (if declarationAsync adapter then D.text "scala.concurrent.Future[" <> failing <> D.text "]" else failing)

-- | Checked definitions are emitted as ordinary Scala code, so adapters and
-- tests call the same proved implementation. ref:DEC-total-definitions
emitScalaDefinitions :: D.Layout -> Int -> [DataDeclaration] -> [Unit] -> Either String [Artifact]
emitScalaDefinitions layout bits declarations units = do
  bodies <- Jvm.emitScalaDefinitionBodies layout bits declarations units
  native <- forM (filter (not . null . unitDefinitions) units) $ \unit -> do
    let parts = split '.' (idText (unitId unit))
        name = concatMap capitalize (split '_' (last parts))
        package = intercalate "." ("lawspec" : "definitions" : init parts)
    methods <- mapM definition (unitDefinitions unit)
    let content = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
          D.text ("package " ++ package) <> D.hardline <> D.hardline <>
          D.text "import lawspec.runtime.{LawSpecDataCodecs, LawSpecDataSchema, LawSpecRuntime, LawSpecSchema, LawSpecScala, LawSpecScalaCodecs}" <>
          D.hardline <> D.hardline <> D.text ("object " ++ name ++ " ") <>
          D.block 2 (D.joinWith (D.hardline <> D.hardline)
            ([D.text "private val schema: LawSpecSchema = LawSpecDataSchema.create()",
              D.text ("private val bits = " ++ show bits)] ++ methods)) <> D.hardline
    pure (Artifact ("src/main/scala/" ++ map (\c -> if c == '.' then '/' else c) package ++ "/" ++ name ++ ".scala")
      (D.render layout content) "generated" "source")
  bridge <- adapterBridge
  pure (bodies ++ native ++ bridge)
  where
    codecOf = Native.scalaCodecDocWithContext (D.text "symbols") declarations
    parametersOf count = D.text ("symbols: " ++ Native.symbolsType) :
      [D.text ("value" ++ show i ++ ": LawSpecRuntime.Value") | i <- [0 .. count - 1]]
    -- Scala adapters, called from the shared JVM bodies through Scala codecs.
    adapterBridge = case (Jvm.orchestratedAdapters units, Jvm.performedOperations units, Jvm.scopedHandlers units) of
      ([], [], []) -> pure []
      (adapters, operations, scoped) -> do
        -- A spec handler a body installs with handle ... with h end.
        let made = [ D.text ("def " ++ Jvm.kotlinHandlerBridge h ++ "(symbols: " ++ Native.symbolsType ++ "): Object = " ++
                       abilitiesObject o ++ "." ++ specName x ++ "(symbols)")
                   | h <- scoped, (o, x) <- take 1 [(o, x) | o <- units, x <- unitHandlers o, handlerId x == h] ]
        -- An operation the shared bodies perform: its handler, from symbols,
        -- through Scala codecs.
        performs <- forM operations $ \op -> do
          ability <- maybe (Left ("unknown ability " ++ abilityKey (operationAbility op))) Right
            (findAbility units (operationAbility op))
          let (_, declared) = ability
              (args, result) = maybe ([], scalarType "Unit") functionType (lookup (operationName op) (abilityOperations declared))
              interface = abilityInterface (operationAbility op)
              failure = lookup (operationName op) (abilityFailures declared)
          codecs <- mapM codecOf args
          resultCodec <- codecOf result
          let invocation = call ("LawSpecRuntime.handler(symbols, " ++ show (abilityKey (operationAbility op)) ++ ").asInstanceOf[" ++ interface ++ "]." ++ Native.escaped (operationName op))
                [codec <> D.text (".decode(value" ++ show i ++ ")") | (i, codec) <- zip [0::Int ..] codecs]
              unwrapped = if failure == Nothing then invocation else call "LawSpecScala.orFail" [invocation]
          -- An operation that fails with E: a Left becomes the failure.
          pure (D.text ("def " ++ Jvm.kotlinOperationBridge op) <>
            D.delimitTrailing 2 "(" ")" (parametersOf (length args)) <> D.text ": LawSpecRuntime.Value = " <>
            failingAs (maybe [] pure failure) [] (resultCodec <> D.text ".encode(" <> unwrapped <> D.text ")"))
        methods <- fmap (++ (performs ++ made)) $ forM adapters $ \(identity, (owner, adapter)) -> do
          let (args, result) = functionType (declarationType adapter)
              parts = split '.' (idText owner)
              cls = intercalate "." (init parts ++ [concatMap capitalize (split '_' (last parts))])
              failures = [a | a@(AbilityRef _ [_]) <- declarationUses adapter, isFail a]
          codecs <- mapM codecOf args
          resultCodec <- codecOf result
          let -- An adapter that uses abilities gets their handlers first.
              handlers = [D.text ("LawSpecRuntime.handler(symbols, " ++ show (abilityKey a) ++ ").asInstanceOf[" ++ abilityInterface a ++ "]")
                | a <- declarationUses adapter, not (isFail a)]
              invocation = call (cls ++ "." ++ Native.escaped (declarationName adapter))
                (handlers ++ [codec <> D.text (".decode(value" ++ show i ++ ")") | (i, codec) <- zip [0::Int ..] codecs])
              unwrap value = if null failures then value else call "LawSpecScala.orFail" [value]
              encode value = if result == scalarType "Integer" then call "LawSpecScalaCodecs.integer" [value, D.text "bits"]
                else resultCodec <> D.text ".encode(" <> value <> D.text ")"
              -- An async adapter runs as a Future the workflow awaits, within
              -- its stage's timeout and hedge when it has them.
              body
                | declarationAsync adapter = failing owner adapter (call "LawSpecRuntime.awaitStep"
                    [D.text "symbols", D.text "() => scala.jdk.javaapi.FutureConverters.asJava(" <> invocation <> D.text ").toCompletableFuture",
                     D.text "native => " <> encode (unwrap (D.text "native"))])
                | otherwise = failing owner adapter (encode (unwrap invocation))
          pure (D.text ("def " ++ Jvm.kotlinAdapterBridge identity) <>
            D.delimitTrailing 2 "(" ")" (parametersOf (length args)) <> D.text ": LawSpecRuntime.Value = " <> body)
        let content = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
              D.text "package lawspec.runtime" <> D.hardline <> D.hardline <>
              D.text "/** The Scala adapters and handlers the shared JVM bodies call. */" <> D.hardline <>
              D.text "object LawSpecScalaAdapters " <>
              D.block 2 (D.joinWith (D.hardline <> D.hardline)
                ([D.text "private val schema: LawSpecSchema = LawSpecDataSchema.create()",
                  D.text ("private val bits = " ++ show bits)] ++ methods)) <> D.hardline
        pure [Artifact "src/main/scala/lawspec/runtime/LawSpecScalaAdapters.scala" (D.render layout content) "generated" "source"]
    callees = Jvm.definitionCalls units
    call name values = D.text name <> D.delimitTrailing 2 "(" ")" values
    assign name value = D.group (D.text ("val " ++ name ++ " =") <> D.nest 2 (D.softline <> value))
    definition d = do
      let declaration = definitionDeclaration d
          (args,result) = functionType (declarationType declaration)
      types <- mapM (Native.scalaDataTypeDoc declarations) args
      resultType <- Native.scalaDataTypeDoc declarations result
      codecs <- mapM codecOf args
      resultCodec <- codecOf result
      evaluator <- maybe (Left "unresolved Scala definition") Right (lookup (declarationId declaration) callees)
      let handlers = [ (ability, lowerFirst (interfaceName a)) | ability <- declarationUses declaration, not (isFail ability)
                     , Just (_, a) <- [findAbility units ability] ]
          parameters = D.text ("symbols: " ++ Native.symbolsType) :
            [D.text (name ++ ": " ++ abilityInterface ability) | (ability, name) <- handlers] ++
            [D.text ("value" ++ show i ++ ": ") <> ty | (i,ty) <- zip [0::Int ..] types]
          -- Native code passes a definition's handlers explicitly; they are
          -- installed in symbols, where the operations it performs find them.
          installs = [call "LawSpecRuntime.installHandlers" [D.text "symbols",
            call "java.util.Map.of[String, Object]" (concat [[E.quoted (abilityKey ability), D.text name] | (ability, name) <- handlers])] | not (null handlers)]
          signature = D.text ("def " ++ Native.escaped (declarationName declaration)) <>
            D.delimitTrailing 2 "(" ")" parameters <> D.text ": " <> resultType <> D.text " = "
          input i codec = [assign ("codec" ++ show i) codec,
            D.text ("val argument" ++ show i ++ " = codec" ++ show i ++ ".encode(value" ++ show i ++ ")")]
          body = installs ++ concat [input i codec | (i,codec) <- zip [0::Int ..] codecs] ++
            [assign "result" (call evaluator (D.text "symbols" : [D.text ("argument" ++ show i) | i <- [0 .. length args - 1]])),
             assign "resultCodec" resultCodec,D.text "resultCodec.decode(result)"]
          context = E.quoted (idText (declarationId declaration) ++ ": ")
          -- A Fail ability's failure passes through, to the attempt that awaits it.
          guarded = D.text "try " <> D.block 2 (D.joinWith D.hardline body) <>
            D.text " catch " <> D.block 2 (D.joinWith D.hardline
              [ D.text "case failure: LawSpecRuntime.Failure => throw failure"
              , D.text "case error: RuntimeException => throw " <> call "IllegalArgumentException"
                  [D.group (context <> D.text " +" <> D.nest 2 (D.softline <> D.text "error.getMessage")),D.text "error"] ])
      pure (signature <> D.block 2 guarded)
    split delimiter value = case break (== delimiter) value of
      (a,[]) -> [a]
      (a,_:rest) -> a : split delimiter rest
    capitalize [] = []
    capitalize (c:cs) = toUpper c : cs
    lowerFirst (c:cs) = toEnum (fromEnum c + (if c >= 'A' && c <= 'Z' then 32 else 0)) : cs
    lowerFirst [] = []
    abilitiesObject u = abilitiesObjectOf (idText (unitId u))
    abilityInterface ability = maybe "Any" (\(_, a) -> abilitiesObjectOf (ownerName a) ++ "." ++ interfaceName a)
      (findAbility units ability)
    abilitiesObjectOf unit = let parts = split '.' unit
      in intercalate "." ("lawspec" : "abilities" : init parts ++ [concatMap capitalize (split '_' (last parts))])
    -- An adapter that fails with E: its native code answers Left with a
    -- native E (or throws an exception lawspec.json maps to a failure).
    failing owner adapter = failingAs [a | a@(AbilityRef _ [_]) <- declarationUses adapter, isFail a]
      [b | u <- units, unitId u == owner, b <- unitFailureBindings u]
    failingAs failures failureBindings body = case failures of
      ability@(AbilityRef _ [failure]) : _ ->
        let codec = either error id (codecOf failure)
            native = either error id (Native.scalaDataType declarations failure)
            bindings = [b | b <- failureBindings, failureType b == failure]
            mapped = [ call "LawSpecRuntime.MappedFailure" [D.text ("classOf[" ++ intercalate "." (failureNative b) ++ "]"),
                         D.text "(_error: Throwable) => " <> call "LawSpecScalaCodecs.construct"
                           [D.text "schema", either error id (E.reference failure), E.quoted (idText (failureConstructor b)), call "List"
                             [call "LawSpecRuntime.fromNative" [E.quoted "Text", D.text "java.util.Objects.toString(_error.getMessage, \"\")", D.text (show bits)] | failureMessage b],
                            D.text (show bits), D.text "symbols"]]
                     | b <- bindings ]
        in call "LawSpecRuntime.nativeFailures" ([E.quoted (abilityKey ability),
             D.text "(_native: Object) => " <> codec <> D.text (".encode(_native.asInstanceOf[" ++ native ++ "])"), D.text "() => " <> body] ++ mapped)
      _ -> body
