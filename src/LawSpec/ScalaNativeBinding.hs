-- | Application bindings reuse the Scala schema codecs and canonical adapter
-- ABI: a bound unit's adapter object is generated, calling the application's
-- Scala (or Java) code through conversions.
module LawSpec.ScalaNativeBinding (emitBindings) where

import Control.Monad (forM, unless)
import Data.Char (toUpper, toLower)
import Data.List (intercalate, nub, isPrefixOf, isInfixOf, find)
import qualified LawSpec.Core as C
import LawSpec.Common
import LawSpec.Backend (unitName, inputs, inputType)
import qualified LawSpec.CoreNativeScalarEmit as Scalar
import qualified LawSpec.JavaDefinitions as Definitions
import LawSpec.Testing
import LawSpec.NativeBinding
import LawSpec.NativeRequest
import qualified LawSpec.ScalaData as S
import LawSpec.AbilityNames (interfaceName, ownAbilities, ownerName)
import LawSpec.AbilityEmit.Scala (abilitiesObjectOf, operationResult)
import LawSpec.ScalaDefinitions (adapterResult)
import qualified LawSpec.ScalaExpr as E
import qualified LawSpec.Code.Doc as D
import qualified LawSpec.ScalaLayout as L
import LawSpec.RuntimeSources (runtimeSource)

-- | Bound adapters call the user's code directly, through generated
-- conversions. ref:DEC-native-bindings-typed-identity
emitBindings :: Bool -> BindingPlan -> Plan -> [Artifact] -> Either String [Artifact]
emitBindings minify plan testing files = do
  unless (bindingRustCrate plan == Nothing) (Left "rustCrate is only valid for Rust bindings")
  unless (null mappings || not (null (bindingFunctions plan)) || not (null (bindingCalls plan)) || not (null generators))
    (Left "native types require function bindings")
  mapM_ S.identifier [name | (_,MethodCall name) <- bindingCalls plan]
  mapM_ (mapM_ S.identifier . referenceParts) ([r | (_,r) <- bindingFunctions plan] ++
    [r | (_,ConstructorCall r) <- bindingCalls plan] ++
    [resolvedNativeType m | m <- mappings] ++ [resolvedNativeConstructor c | m <- mappings,c <- resolvedConstructors m] ++
    [ref | m <- mappings, Just hook <- [resolvedCodec m], ref <- [codecToNative hook, codecFromNative hook]])
  mapM_ (S.identifier . snd) [f | m <- mappings,c <- resolvedConstructors m,f <- resolvedFields c]
  codecs <- S.emitScalaNativeCodecs layout declarations mappings
  -- Value arguments and synchronous methods retain Java's raw-generic
  -- casts. A constructor with no native arguments needs no Java shim;
  -- invoking it in Scala avoids an unnecessary mixed-compilation cycle.
  let javaCalls = [c | c@(d,nativeCall) <- bindingCalls plan,
        not (directConstructor d nativeCall),
        not (C.declarationAsync d && case nativeCall of MethodCall _ -> True; _ -> False)]
  calls <- forM (zip [0::Int ..] javaCalls) $ \(index,(d,nativeCall)) -> do
    let (args,_) = C.functionType (C.declarationType d)
    casts <- mapM javaCast args
    let parameters = ["java.lang.Object value" ++ show i | i <- [0 .. length args - 1]]
        cast i = maybe ("value" ++ show i) (\t -> "((" ++ t ++ ") value" ++ show i ++ ")") (casts !! i)
        handleArgument = lookup True [(isHandle t,i) | (i,t) <- zip [0::Int ..] args]
    expression <- case nativeCall of
      MethodCall name -> case handleArgument of
        Just i -> pure (cast i ++ "." ++ name ++ "(" ++ intercalate ", " [cast j | j <- [0 .. length args - 1], j /= i] ++ ")")
        Nothing -> Left ("method binding without a handle argument: " ++ C.idText (C.declarationId d))
      ConstructorCall r -> pure ("new " ++ intercalate "." (referenceParts r) ++ "(" ++
        intercalate ", " [cast i | (i,t) <- zip [0..] args, t /= C.scalarType "Unit"] ++ ")")
      StaticCall _ -> Left "static binding among method bindings"
    let body = case nativeCall of
          MethodCall _ | snd (C.functionType (C.declarationType d)) == C.scalarType "Unit" ->
            [expression ++ ";", "return null;"]
          _ -> ["return " ++ expression ++ ";"]
    pure (C.declarationId d, "call" ++ show index,
      "  public static java.lang.Object call" ++ show index ++ "(" ++ intercalate ", " parameters ++ ") {\n" ++
      concatMap (\line -> "    " ++ line ++ "\n") body ++ "  }\n")
  let callSupport = [Artifact "src/main/java/lawspec/runtime/LawSpecNativeCalls.java"
        ("// Generated by LawSpec. Do not edit.\npackage lawspec.runtime;\n\n" ++
         "@SuppressWarnings({\"rawtypes\", \"unchecked\"})\npublic final class LawSpecNativeCalls {\n" ++
         "  private LawSpecNativeCalls() {}\n" ++ concatMap (\(_,_,source) -> "\n" ++ source) calls ++ "}\n")
        "generated" "source" | not (null calls)]
  bridges <- fmap concat $ forM (plannedUnits testing) $ \p -> do
    let unit = plannedUnit p
        definitions = map (C.declarationId . C.definitionDeclaration) (C.unitDefinitions unit)
        adapters = [d | d <- C.unitDeclarations unit,C.declarationId d `notElem` definitions]
        bound d = lookup (C.declarationId d) ([(C.declarationId a,StaticCall r) | (a,r) <- bindingFunctions plan] ++
          [(C.declarationId a,c) | (a,c) <- bindingCalls plan])
        parts = split '.' (unitName unit)
    mapM_ S.identifier parts
    if not (any (maybe False (const True) . bound) adapters) then pure [] else do
      unless (all (maybe False (const True) . bound) adapters) (Left "a Scala bound unit must map every adapter")
      bodies <- forM adapters $ \d -> do
        let (args,result) = C.functionType (C.declarationType d)
        ref <- maybe (Left "unbound adapter") Right (bound d)
        argTypes <- mapM (S.scalaDataTypeDoc declarations) args
        resultType <- adapterResult declarations d
        canonical <- mapM (canonicalCodec) args
        native <- mapM nativeCodec args
        canonicalResult <- canonicalCodec result
        nativeResult <- nativeCodec result
        nativeResultType <- if result == C.scalarType "Integer" then pure (D.text "scala.Int | scala.Long | scala.math.BigInt")
          else S.scalaNativeTypeDoc declarations mappings [] result
        let values = [D.text ("value" ++ show i) | i <- [0::Int ..length args-1]]
            -- An adapter that uses abilities gets their handlers first, as
            -- the generated traits.
            handlerParams = [ (D.text (interfaceType a), D.text ("handler" ++ show i))
                            | (i, a) <- zip [0::Int ..] (C.declarationUses d), not (C.isFail a) ]
            converted = [method n "decode" [method c "encode" [v]] | (n,c,v) <- zip3 native canonical values]
            -- An Integer result stays polymorphic: the caller checks it.
            returnedOf value = if result == C.scalarType "Integer" then value
              else method canonicalResult "decode" [method nativeResult "encode" [value]]
            returned = returnedOf (D.text "result")
            async = C.declarationAsync d
        maybeElement <- case result of
          C.Constructor "Maybe" [C.TypeArgument element] -> Just <$> S.scalaNativeTypeDoc declarations mappings [] element
          _ -> pure Nothing
        resultBody <- case ref of
          StaticCall r -> do
            let applicationReceiver = L.callReceiver (intercalate "." (referenceParts r)) (map snd handlerParams ++ converted)
                application = L.receiverDoc applicationReceiver
            -- Unit arguments still cross both codecs, in order, before the
            -- constructor. Only the native argument list is empty.
            pure $ [value | directConstructor d ref, value <- converted] ++ if async then [mapped applicationReceiver returned]
              else if result == C.scalarType "Unit" then [application, D.text "()"] else
              [L.bind "result" application, returned]
          _ -> do
            applicationReceiver <- case ref of
              ConstructorCall constructor | directConstructor d ref ->
                pure (L.callReceiver ("new " ++ intercalate "." (referenceParts constructor)) [])
              MethodCall name | async -> case lookup True [(isHandle t,i) | (i,t) <- zip [0::Int ..] args] of
                Just i -> do
                  receiver <- javaCast (args !! i) >>= maybe (Left ("an async method binding needs a bound handle type: " ++
                    C.idText (C.declarationId d))) Right
                  pure (L.chainedReceiver (L.typedReceiver "LawSpecScala" "cast" [D.text receiver] [converted !! i])
                    [(name, [v | (j,v) <- zip [0..] converted, j /= i])])
                Nothing -> Left ("method binding without a handle argument: " ++ C.idText (C.declarationId d))
              _ -> do
                helper <- maybe (Left "unplanned native call") Right
                  (lookup (C.declarationId d) [(identity,name) | (identity,name,_) <- calls])
                pure (L.callReceiver ("lawspec.runtime.LawSpecNativeCalls." ++ helper) converted)
            -- Unit arguments still cross both codecs, in order, before the
            -- constructor. Only the native argument list is empty.
            let application = L.receiverDoc applicationReceiver
            pure $ [value | directConstructor d ref, value <- converted] ++ if async then [mapped applicationReceiver
                (if result == C.scalarType "Unit" then D.text "()" else returnedOf (L.call ("LawSpecScala.cast[" ++ D.render D.Compact nativeResultType ++ "]") [D.text "result"]))]
              else if result == C.scalarType "Unit" then [application, D.text "()"]
              -- A method's null is None; anything else is Some.
              else case maybeElement of
                Just element -> [ D.group (D.text "val found: Any =" <> D.nest 2 (D.softline <> application))
                  , D.group (D.text "val result: " <> nativeResultType <> D.text " =" <> D.nest 2 (D.softline <>
                      D.text "if (found == null) None else Some(" <> L.call ("LawSpecScala.cast[" ++ D.render D.Compact element ++ "]") [D.text "found"] <> D.text ")"))
                  , returned ]
                Nothing -> [L.bind "result" (L.call ("LawSpecScala.cast[" ++ D.render D.Compact nativeResultType ++ "]") [application]), returned]
        -- An adapter that fails with E answers Either: the exceptions
        -- lawspec.edn maps become its failures, as Lefts.
        failureCases <- case [failure | C.AbilityRef _ [failure] <- filter C.isFail (C.declarationUses d)] of
          failure : _ | not async -> do
            Just <$> mappedFailures failure
          _ -> pure Nothing
        let body = maybe resultBody (const [D.text "scala.util.Right(" <> L.block resultBody <> D.text ")"]) failureCases
        pure (L.parameters (D.text ("def " ++ S.escaped (C.declarationName d)))
            ([v <> D.text ": " <> t | (t,v) <- handlerParams] ++ [v <> D.text ": " <> t | (t,v) <- zip argTypes values]) <>
          D.text ": " <> resultType <> D.text " = " <> L.block
          ([D.text "val symbols = LawSpecScala.symbols()" | "symbols" `isInfixOf` D.render D.Compact (L.statements body)] ++
           [D.text "try " <> L.block body <> D.text " catch " <>
            L.block (maybe [] id failureCases ++ [D.text "case error: RuntimeException =>" <>
              D.nest 2 (D.hardline <> D.text "throw " <> E.call "LawSpecRuntime.nativeBindingFailure"
              [E.quoted ("native binding " ++ C.idText (C.declarationId d)), D.text "error"])])]))
      -- Each bound production handler, wrapped in the generated trait: its
      -- operations' values cross with the native codecs.
      wrappers <- forM [(a, r) | a <- ownAbilities unit, Just r <- [lookup (C.Id (C.abilityKey (C.abilityInstance a))) (bindingHandlers plan)]] $ \(a, r) -> do
        operations <- forM (C.abilityOperations a) $ \(op, ty) -> do
          let (args, result) = C.functionType ty
          types <- mapM (S.scalaDataTypeDoc declarations) args
          resultType <- operationResult declarations a op result
          canonical <- mapM (canonicalCodec) args
          native <- mapM nativeCodec args
          canonicalResult <- canonicalCodec result
          nativeResult <- nativeCodec result
          let values = [D.text ("value" ++ show i) | i <- [0::Int ..length args-1]]
              invocation = E.call ("inner." ++ S.escaped op) [method n "decode" [method c "encode" [v]] | (n,c,v) <- zip3 native canonical values]
              plain = if result == C.scalarType "Unit" then L.statements [invocation, D.text "()"]
                else method canonicalResult "decode" [method nativeResult "encode" [invocation]]
          -- An operation that fails with E answers Either: the exceptions
          -- lawspec.edn maps become its failures, as Lefts.
          body <- case lookup op (C.abilityFailures a) of
            Just (C.AbilityRef _ [failure]) -> do
              cases <- mappedFailures failure
              pure (D.text "try " <> D.block 2 (D.text "scala.util.Right(" <> D.block 2 plain <> D.text ")") <>
                (if null cases then mempty else D.text " catch " <> D.block 2 (D.joinWith D.hardline cases)))
            _ -> pure plain
          pure (L.parameters (D.text ("override def " ++ S.escaped op)) [v <> D.text ": " <> t | (t,v) <- zip types values] <> D.text ": " <> resultType <> D.text " = " <>
            L.block ([D.text "val symbols = LawSpecScala.symbols()" | "symbols" `isInfixOf` D.render D.Compact body] ++ [body]))
        pure (L.comment 78 ("The bound production handler of " ++ C.abilityName a ++ ", " ++ intercalate "." (referenceParts r) ++ ", as the generated trait.") <>
          D.text ("class " ++ interfaceName a ++ "Bound extends " ++ interfaceType' a ++ " ") <> D.block 2 (D.joinWith (D.hardline <> D.hardline)
            (D.text ("private val inner = " ++ intercalate "." (referenceParts r) ++ "()") : operations)))
      let name = concatMap cap (split '_' (last parts))
          package = intercalate "." (init parts)
          path = "src/main/scala/" ++ concatMap (++ "/") (init parts) ++ name ++ ".scala"
          header = (if null package then mempty else D.text ("package " ++ package) <> D.hardline <> D.hardline) <>
            D.text "import lawspec.runtime.*" <> D.hardline <> D.hardline
          source = header <> D.text ("object " ++ name ++ " ") <> L.block
            [ D.text "private val Schema = LawSpecDataSchema.create()" <> D.hardline <>
              D.text ("private val MachineBits = " ++ show bits)
            , D.joinWith (D.hardline <> D.hardline) (bodies ++ wrappers) ]
      pure [Artifact path (render source) "generated" "source"]
  dataFiles <- if any ((== "src/main/java/lawspec/runtime/LawSpecDataSchema.java") . artifactPath) files then pure []
    else S.emitScalaDataWithProfile bits layout declarations
  generatorFiles <- if null generators then pure [] else do
    let roots = [inputType input | unit <- plannedUnits testing, property <- plannedProperties unit, input <- inputs property]
    concrete <- if any ((>0) . generatorParameterCount) generators
      then reachableGeneratorTypes declarations representations roots else pure []
    methods <- forM (zip [0::Int ..] generators) $ \(index,generator) -> do
      mapM_ S.identifier (referenceParts (resolvedGeneratorFactory generator))
      let family = C.idText (resolvedGeneratorType generator)
          instances = if generatorParameterCount generator == 0 then [C.Constructor family []]
            else [ty | ty@(C.Constructor name _) <- concrete, name == family]
      branches <- forM instances $ \ty -> do
        let args = case ty of C.Constructor _ as -> [t | C.TypeArgument t <- as]; _ -> []
        children <- forM (zip [0::Int ..] args) $ \(i,child) -> do
          bridge <- S.scalaNativeCodecDoc declarations child
          pure (D.text ("val child" ++ show i ++ " = ") <>
            E.call "LawSpecScalaStrategies.nativeArguments" [bridge,D.text ("arguments(" ++ show i ++ ")")])
        bridge <- S.scalaNativeCodecDoc declarations ty
        tyRef <- E.reference ty
        pure (D.text "if (tpe == " <> tyRef <> D.text ") " <> D.block 2
          (D.joinWith D.hardline (children ++
            [D.text "val source = " <> E.call (intercalate "." (referenceParts (resolvedGeneratorFactory generator)))
              [D.text ("child" ++ show i) | i <- [0..length args-1]],
             D.text "return " <> E.call "LawSpecScalaStrategies.nativeValues" [bridge,D.text "source"]])))
      pure (D.text "private def " <> E.call ("factory" ++ show index) (map D.text
        ["schema: LawSpecSchema", "tpe: LawSpecSchema.Named", "bits: Int", "symbols: LawSpecScala.Symbols",
         "arguments: List[Arb[LawSpecRuntime.Value]]"]) <>
        D.text ": Arb[LawSpecRuntime.Value] = " <> D.block 2 (D.joinWith D.hardline (branches ++
          [D.text "throw IllegalArgumentException(\"unplanned native generator instantiation: \" + tpe)"])))
    let entries = [E.quoted (C.idText (resolvedGeneratorType generator)) <>
          D.text (" -> (((schema, tpe, bits, symbols, arguments) => factory" ++ show i ++ "(schema, tpe, bits, symbols, arguments)): LawSpecScalaStrategies.NativeFactory)") |
            (i,generator) <- zip [0::Int ..] generators]
        registry = D.text "def factories(): Map[String, LawSpecScalaStrategies.NativeFactory] = " <>
          E.call "Map" entries
        helper = Artifact "src/test/scala/lawspec/testing/LawSpecNativeGenerators.scala" (render
          (D.text "package lawspec.testing" <> D.hardline <> D.hardline <>
           D.text "import lawspec.runtime.*" <> D.hardline <> D.hardline <>
           D.text "object LawSpecNativeGenerators " <> D.block 2
            (D.joinWith (D.hardline <> D.hardline) (registry:methods)))) "generated" "test"
    emitted <- either (Left . show) Right $ concat <$> mapM (\unit ->
      Scalar.nativeScalarEmitWithNativeGenerators True minify declarations
        (Definitions.definitionCalls (map plannedUnit (plannedUnits testing))) bits "scala"
        (modelTestUnit testing (plannedUnit unit)) (plannedProperties unit))
        [unit | unit <- plannedUnits testing, not (null (plannedProperties unit))]
    pure (helper : [file | file <- emitted,artifactPlacement file == "test"] ++
      [Artifact path (runtimeSource key) "generated" "test" |
        (path,key) <- [("src/test/scala/lawspec/testing/LawSpecScalaStrategies.scala","scala-data-strategies"),
          ("src/test/scala/lawspec/testing/LawSpecGen.scala","scala-strategies"),
          ("src/test/scala/lawspec/testing/LawSpecScalars.scala","scala-scalars"),
          ("src/test/scala/lawspec/testing/LawSpecTesting.scala","scala-testing")],
        not (any ((== path) . artifactPath) files)])
  let support = Artifact "src/main/scala/lawspec/runtime/LawSpecNativeCodecs.scala" codecs "generated" "source"
      runtime = [Artifact "src/main/java/lawspec/runtime/LawSpecRuntime.java" (runtimeSource "java") "generated" "source" |
        not (any ((== "src/main/java/lawspec/runtime/LawSpecRuntime.java") . artifactPath) files)]
  unless (all ((/= artifactPath support) . artifactPath) files) (Left "unit shadows native codec support")
  let generated = [f | f <- files,artifactPath f `notElem` map artifactPath (bridges ++ generatorFiles)] ++ dataFiles ++ runtime ++ [support] ++ callSupport ++ bridges ++ generatorFiles
  stubs <- generatorStubs generated
  pure (generated ++ stubs)
  where
    directConstructor declaration native = case native of
      ConstructorCall _ -> all (== C.scalarType "Unit") (fst (C.functionType (C.declarationType declaration)))
      _ -> False
    declarations = planDataDeclarations testing
    bits = planMachineBits testing
    interfaceType ability = maybe "Any" (interfaceType' . snd) (C.findAbility (map plannedUnit (plannedUnits testing)) ability)
    interfaceType' a = abilitiesObjectOf (ownerName a) ++ "." ++ interfaceName a
    representations = bindingRepresentations plan
    mappings = resolvedTypes representations
    generators = resolvedGenerators representations
    layout = D.selectLayout minify L.scalaStyle
    render doc = D.render layout (D.text "// Generated by LawSpec. Do not edit." <> D.hardline <> doc <> D.hardline)
    split c s = case break (==c) s of (a,[]) -> [a]; (a,_:b) -> a:split c b
    cap [] = []; cap (a:rest) = toUpper a:rest
    method value name args = L.chain value [(name, args)]
    -- future.map(result => value)(using parasitic), as a chain.
    mapped future value = L.trailingChain' future "map" "result" value <>
      D.text "(using scala.concurrent.ExecutionContext.parasitic)"
    canonicalCodec = S.scalaCodecReceiverIn ("Schema", "MachineBits") (D.text "symbols") declarations
    nativeCodec = S.scalaNativeCodecReceiverIn ("Schema", "MachineBits") declarations
    -- The exceptions lawspec.edn maps to a failure of type failure, as cases
    -- that answer Left with it.
    mappedFailures failure = do
      failureCodec <- canonicalCodec failure
      ref <- E.reference failure
      pure [ D.text ("case error: " ++ intercalate "." (C.failureNative b) ++ " =>") <> D.nest 2 (D.hardline <> E.call "scala.util.Left" [L.chain failureCodec [("decode",
               [E.call "LawSpecScalaCodecs.construct" [D.text "Schema", ref, E.quoted (C.idText (C.failureConstructor b)),
                 E.call "List" (C.mapFailureFields (\ty tag fields -> E.call "LawSpecScalaCodecs.construct" [D.text "Schema", either error id (E.reference ty), E.quoted (C.idText tag), E.call "List" fields, D.text "MachineBits", D.text "symbols"]) (E.call "LawSpecRuntime.fromNative" [E.quoted "Text", D.text "java.util.Objects.toString(error.getMessage, \"\")", D.text "MachineBits"]) b),
                 D.text "MachineBits", D.text "symbols"]])]])
           | b <- bindingFailures plan, C.failureType b == failure ]
    handleDeclaration name = find (\d -> C.dataHandle d && C.dataId d == C.Id name) declarations
    isHandle (C.Constructor name []) = handleDeclaration name /= Nothing
    isHandle _ = False
    -- The Java class a native argument is cast to before the call: a handle's
    -- bound class, or the erasure of the argument's Scala type; none for an
    -- unbound handle and for types Java cannot name.
    javaCast ty = case ty of
      C.Constructor name [] | Just d <- handleDeclaration name ->
        pure (intercalate "." . referenceParts . resolvedNativeType <$>
          find ((== C.dataId d) . C.dataId . resolvedDeclaration) mappings)
      _ -> do
        native <- S.scalaNativeTypeDoc declarations mappings [] ty
        let rendered = D.render D.Compact native
            erased = takeWhile (/= '[') rendered
        pure $ case lookup rendered arrays of
          Just java -> Just java
          Nothing -> case lookup erased scalaClasses of
            Just java -> Just java
            Nothing | any (`isPrefixOf` erased) ["scala.", "lawspec.runtime.LawSpecScala."] -> Nothing
                    | otherwise -> Just erased
    arrays = [("scala.IArray[scala.Byte]","byte[]"),("scala.IArray[scala.Int]","int[]")]
    scalaClasses =
      [("scala.Boolean","java.lang.Boolean"),("scala.Byte","java.lang.Byte"),("scala.Short","java.lang.Short"),
       ("scala.Int","java.lang.Integer"),("scala.Long","java.lang.Long"),("scala.Float","java.lang.Float"),
       ("scala.Double","java.lang.Double"),("scala.Char","java.lang.Character"),("java.lang.String","java.lang.String")]

    generatorStubs generated = do
      let requested = filter resolvedGeneratorStub generators
          owner = init . referenceParts . resolvedGeneratorFactory
          owners = nub (map owner requested)
          classPath = intercalate "/"
          conflicts a b = map toLower a == map toLower b ||
            (a ++ "/") `isPrefixOf` b || (b ++ "/") `isPrefixOf` a
          existing = [take (length relative - suffix) relative | file <- generated,
            (prefix,suffix) <- [("src/main/scala/",6),("src/test/scala/",6),("src/main/java/",5)],
            prefix `isPrefixOf` artifactPath file, let relative = drop (length prefix) (artifactPath file)]
          application = [classPath (referenceParts ref) | ref <- map resolvedNativeType mappings ++
            map resolvedNativeConstructor (concatMap resolvedConstructors mappings)] ++
            [classPath (referenceParts r) | (_,ConstructorCall r) <- bindingCalls plan] ++
            [classPath (init parts) | ref <- map snd (bindingFunctions plan) ++
              [r | mapping <- mappings, Just hook <- [resolvedCodec mapping], r <- [codecToNative hook,codecFromNative hook]],
              let parts = referenceParts ref, length parts >= 3]
      forM owners $ \parts -> do
        unless (length parts >= 2) (Left "Scala generator scaffold requires a package, object and function")
        unless (take 1 parts `notElem` [["scala"],["java"]])
          (Left "Scala generator scaffold cannot use a reserved runtime package")
        let name = last parts
            path = classPath parts
        unless (not (any (conflicts path) ("lawspec/testing/Arb":existing ++ application)) &&
          not (any (\other -> other /= parts && conflicts path (classPath other)) owners))
          (Left "Scala generator scaffold object conflicts with another class or package")
        unless (name `notElem` (words "java scala lawspec" ++
          [r | mapping <- mappings, r : _ <- [referenceParts (resolvedNativeType mapping)]]))
          (Left "Scala generator scaffold object shadows a signature package")
        bodies <- forM (filter ((== parts) . owner) requested) $ \generator -> do
          let methodName = last (referenceParts (resolvedGeneratorFactory generator))
              parameters = [(C.Id ("scaffold::" ++ show i),"T" ++ show i) | i <- [0 .. generatorParameterCount generator - 1]]
              ty = C.Constructor (C.idText (resolvedGeneratorType generator))
                [C.TypeArgument (C.TypeVariable identity) | (identity,_) <- parameters]
          unless (not (null parameters) || methodName `notElem` words "hashCode toString equals")
            (Left "Scala generator scaffold function conflicts with Any")
          native <- S.scalaNativeTypeDoc declarations mappings parameters ty
          let generic = if null parameters then mempty else D.text ("[" ++ intercalate ", " (map snd parameters) ++ "]")
              arb value = D.group (D.text "lawspec.testing.Arb[" <> D.nest 2 (D.softbreak <> value) <> D.text "]")
              signature = D.text ("def " ++ S.escaped methodName) <> generic <> D.delimitTrailing 2 "(" ")"
                [D.text ("argument" ++ show i ++ ": ") <> arb (D.text pname) | (i,(_,pname)) <- zip [0::Int ..] parameters] <>
                D.text ": " <> arb native
          pure (signature <> D.text " =" <> D.nest 2 (D.hardline <> D.text "throw " <>
            E.call "NotImplementedError" [E.quoted ("Implement generator for " ++ C.idText (resolvedGeneratorType generator))]))
        pure (Artifact ("src/test/scala/" ++ path ++ ".scala") (D.render (D.Pretty 100)
          (D.text "// User-owned native generator factories. Implement before running properties." <> D.hardline <>
           D.text ("package " ++ intercalate "." (init parts)) <> D.hardline <> D.hardline <>
           D.text ("object " ++ name ++ " ") <> D.block 2 (D.joinWith (D.hardline <> D.hardline) bodies) <> D.hardline)) "user" "test")
