-- | Generated JavaScript and TypeScript modules: one header, only the imports
-- and support declarations a module's code uses, and a comment linking each
-- generated function, class and test to its source. Modules are printed as
-- Prettier prints them (LawSpec.Code.ECMAScript).
-- ref:DEC-readable-output-default
module LawSpec.WebModule
  ( Support(..), webModule, headerComment, linkComment, commentLines, usedNames, dialectOf, importExtension, printWebModule
  ) where

import Data.Char (isAlphaNum)
import qualified Data.Set as S
import qualified LawSpec.Code.ECMAScript as E
import qualified LawSpec.Code.Doc as D
import LawSpec.SourceLink (generatedHeader, labelled)

-- | A declaration a module includes only when its code uses the name.
data Support = Support { supportName :: String, supportStatements :: [E.Stmt] }

dialectOf :: Bool -> E.Dialect
dialectOf ts = if ts then E.TypeScript else E.JavaScript

-- | The extension imports use: TypeScript imports its compiled .js.
importExtension :: Bool -> String
importExtension ts = if ts then "js" else "mjs"

-- | // Generated by LawSpec from <spec>. Do not edit.
headerComment :: Maybe FilePath -> E.Stmt
headerComment source = E.Comment ["// " ++ generatedHeader source]

-- | The comment above a generated unit: its name and source line.
linkComment :: String -> Maybe String -> E.Stmt
linkComment label link = E.Comment (commentLines (labelled label link))

-- | Comment text wrapped at 80 columns, as // lines.
commentLines :: String -> [String]
commentLines content = map (dropWhileEnd' . ("// " ++)) (wrap [] (words content))
  where
    capacity = 77
    wrap current [] = [unwords current | not (null current)]
    wrap current (w : rest)
      | not (null current) && length (unwords (current ++ [w])) > capacity = unwords current : wrap [w] rest
      | otherwise = wrap (current ++ [w]) rest
    dropWhileEnd' = reverse . dropWhile (== ' ') . reverse

-- | The identifiers a printed text uses.
usedNames :: String -> S.Set String
usedNames = S.fromList . words . map (\c -> if isAlphaNum c || c == '_' || c == '$' then c else ' ')

-- | A module: its leading comments, then the imports and support its body
-- uses (support may use other support and imports), then the body's
-- groups separated by blank lines.
webModule :: Bool -> [E.Stmt] -> [(String, E.Stmt)] -> [Support] -> [[E.Stmt]] -> [E.Stmt]
webModule ts leading imports support groups =
  leading ++ chosenImports ++ [E.Blank | not (null chosenImports)] ++
  concat [supportStatements s ++ [E.Blank] | s <- chosenSupport] ++
  concat [g ++ [E.Blank] | g <- groups, not (null g)]
  where
    dialect = dialectOf ts
    bodyNames = usedNames (E.printModule dialect (concat groups))
    -- Support is included when used, and then its own uses count.
    closure names = let more = [s | s <- support, supportName s `S.member` names]
                        names' = S.unions (names : [usedNames (E.printModule dialect (supportStatements s)) | s <- more])
                    in if names' == names then names else closure names'
    allNames = closure bodyNames
    chosenSupport = [s | s <- support, supportName s `S.member` allNames]
    chosenImports = [i | (alias, i) <- imports, alias `S.member` allNames]

-- | A module's text, as Prettier lays it out, or on long lines when compact.
printWebModule :: D.Layout -> Bool -> [E.Stmt] -> String
printWebModule layout ts = case layout of
  D.Compact -> E.printModuleWidth maxBound (dialectOf ts)
  D.CompactTabs -> E.printModuleWidth maxBound (dialectOf ts)
  _ -> E.printModule (dialectOf ts)
