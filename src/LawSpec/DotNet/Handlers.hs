-- | Spec handlers as native classes, the embedding entry point for a
-- reference model: LawSpec.Handlers.<Unit>.<Handler> implements the native
-- interface of every ability the handler answers, with a member per
-- operation (an operation that fails returns a Result, its try-form), and a
-- stateful handler's state in native types, to read, force, reset or
-- restore. The class runs the handler's checked clauses; its state is
-- persistent, so a snapshot is shared, never copied.
-- ref:DEC-typed-native-definitions ref:DEC-fsharp-runtime-from-scratch
module LawSpec.DotNet.Handlers (emitHandlers) where

import qualified LawSpec.Core as C
import qualified LawSpec.AbilityNames as N
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.DotNet.Code (Lang(..), stringLiteral)
import qualified LawSpec.DotNet.Layout as L
import LawSpec.DotNet.Names
import qualified LawSpec.DotNet.Data as Data
import qualified LawSpec.DotNet.Effects as Effects
import qualified LawSpec.DotNet.Abilities as Abilities
import qualified LawSpec.DotNet.Definitions as Definitions
import LawSpec.Typed.FSharp (FSharpTyped(..))
import LawSpec.Typed.Plan (isTypedHandler)
import Control.Monad (forM)
import Data.List (intercalate)

-- | One file per unit with spec handlers, compiled after the unit's entries.
emitHandlers :: Lang -> D.Layout -> Int -> Maybe FSharpTyped -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitHandlers lang layout bits typed declarations units = do
  names <- dataNames declarations
  fmap concat $ forM [u | u <- units, not (null (owned u))] $ \u -> do
    classes <- forM (owned u) (handlerClass names u)
    let unitName = concatMap pascal (splitDots (C.idText (C.unitId u)))
        doc = case lang of
          FSharp -> D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text ("/// The spec handlers of " ++ C.idText (C.unitId u) ++ ", as native classes.") <> D.hardline <>
            D.text ("namespace LawSpec.Handlers." ++ unitName) <> D.hardline <> D.hardline <>
            D.text "open LawSpec.Runtime" <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) classes <> D.hardline
          CSharp -> D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text ("namespace LawSpec.Handlers." ++ unitName ++ ";") <> D.hardline <> D.hardline <>
            D.joinWith D.hardline (map D.text Definitions.csUsingLines) <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) classes <> D.hardline
    pure [Artifact ("src/LawSpec/Handlers/" ++ unitName ++ extension lang) (D.render layout doc) "generated" "source"]
  where
    -- A handler's class is in the unit whose module makes it, once.
    owned u = [h | h <- C.unitHandlers u, fst (Effects.specFunction units h) == generatedModule (C.unitId u)]
    handlerClass names u h = do
      answered <- forM (C.handlerAbilities h) $ \ref ->
        maybe (Left ("unknown .NET ability of handler " ++ C.handlerName h)) Right (N.abilityOf units ref)
      let cls = pascal (C.handlerName h)
          (owner, factory) = Effects.specFunction units h
          bridge a = "LawSpec.Generated.Abilities." ++ (if lang == FSharp then Effects.bridgeName a "ToNative" else pascal (Effects.bridgeName a "ToNative"))
          field a = camel (N.interfaceName a)
          made = if null (C.handlerAlso h) then "" else ""
          _ = made
      operations <- fmap concat $ forM answered $ \a -> forM (C.abilityOperations a) $ \(op, ty) -> do
        let (args, _) = C.functionType ty
        (ps, r) <- operationSignatureOf names a (op, ty)
        pure (a, Effects.operationMember op, zip ["value" ++ show i | i <- [0 :: Int ..]] ps, r, length args)
      stateCodec <- traverse (Data.codec lang bits names [] . fst) (C.handlerState h)
      stateType <- traverse (Data.nativeType lang bits names [] . fst) (C.handlerState h)
      let interfaces = [Effects.interfaceType a | a <- answered]
          first = head answered
          summary = "The spec handler " ++ C.handlerName h ++ " for " ++ intercalate ", " (map N.displayName answered) ++ "."
      typedOperations <- case typed of
        Just t | isTypedHandler (fsTypedPlan t) h -> fmap (Just . concat) $ forM answered $ \a -> forM (C.abilityOperations a) $ \(op, ty) -> do
          clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
          function <- maybe (Left ("untyped clause " ++ C.idText clause)) Right ((if lang == FSharp then fsTypedFunction t else fsTypedCsFunction t) clause)
          failure <- case lookup op (C.abilityFailures a) of
            Just failing@(C.AbilityRef _ [failureType]) -> (\c -> Just (C.abilityKey failing, c)) <$> Data.codec lang bits names [] failureType
            _ -> pure Nothing
          let (args, _) = C.functionType ty
          pure (op, function, fsTypedContextual t clause, failure, null args)
        _ -> pure Nothing
      pure $ case lang of
        FSharp | Just ops <- typedOperations ->
          let stateful = C.handlerState h /= Nothing
              start = case typed of
                Just t | Just f <- fsTypedStart t (C.handlerId h) -> L.App f [L.A "schema", L.A "symbols"]
                _ -> L.A "Unchecked.defaultof<_>"
              lets = [L.pad 4 "let gate = obj ()"] :
                [ L.binding 4 ("let mutable state: " ++ t) start | stateful, Just t <- [stateType] ]
              operation (_, m, ps, r, _) = case [o | o@(op, _, _, _, _) <- ops, Effects.operationMember op == m] of
                (_, function, contextual, failure, noArgs) : _ ->
                  let arguments = map L.A (concat [["schema", "symbols"] | contextual] ++ ["state" | stateful] ++
                        (if noArgs && not stateful then ["()"] else fsArguments ps))
                      invoke = L.App function arguments
                      computed = if stateful
                        then L.Block [L.LetS "let pair" invoke, L.DoS (L.A "state <- pair.Second")] (L.A "pair.First")
                        else invoke
                      -- An operation that fails returns its failure as a Result.
                      body = case failure of
                        Just (key, codec) -> L.App "Typed.tryResult" [L.A (stringLiteral FSharp key), codecFunction codec, L.Fun "()" computed]
                        Nothing -> computed
                  in [L.pad 4 ("/// " ++ m ++ (if "Result<" `isPrefix` r then ": its failure as a Result." else "."))] ++
                     L.function 4 ("member _." ++ m ++ "(" ++ intercalate ", " [v ++ ": " ++ t | (v, t) <- fsParameters ps] ++ ")") [] (Just r)
                       (L.App "lock" [L.A "gate", L.Fun "()" body])
                [] -> []
              members =
                [ map (L.pad 4) ["/// Outside any law: the program's schema and fresh symbols.",
                    "new() = " ++ cls ++ "(LawSpec.Generated.Program.schema, Scalar.SymbolContext())"] ] ++
                [ map (L.pad 4) ["/// The handler's state: a snapshot to show or keep, or one to force, reset or restore.", "member _.State"] ++
                  map (L.pad 8) ["with get (): " ++ t ++ " = lock gate (fun () -> state)", "and set (value: " ++ t ++ ") = lock gate (fun () -> state <- value)"]
                | stateful, Just t <- [stateType] ] ++
                map operation operations ++
                [ L.pad 4 ("interface " ++ Effects.interfaceType a ++ " with") :
                    [ L.pad 8 ("member this." ++ m ++ "(" ++ intercalate ", " (map fst (fsParameters ps)) ++ ") = this." ++ m ++ "(" ++ intercalate ", " (map fst (fsParameters ps)) ++ ")")
                    | (a', m, ps, _, _) <- operations, C.abilityInstance a' == C.abilityInstance a ]
                | a <- answered ]
          in L.linesDoc 0 (["/// " ++ summary ++ " It runs typed: its state is native, and shared, not copied, by a snapshot.", "[<Sealed>]"] ++
               classHeader cls ++ L.separated (lets ++ members))
        CSharp | Just ops <- typedOperations ->
          let stateful = C.handlerState h /= Nothing
              start = case typed of
                Just t | Just f <- fsTypedCsStart t (C.handlerId h) -> f ++ "(schema, symbols)"
                _ -> "default"
              csResult r = if r == "Unit" then "void" else r
              operation (_, m, ps, r, _) = case [o | o@(op, _, _, _, _) <- ops, Effects.operationMember op == m] of
                (_, function, contextual, failure, noArgs) : _ ->
                  let values = if map snd ps == ["Unit"] then ["default(Unit)"] else map fst ps
                      clauseArgs = if noArgs && not stateful then ["default(Unit)"] else values
                      -- Named unit parameters remain in the checked module
                      -- functions, including a dummy for zero-arity clauses.
                      arguments = concat [["schema", "symbols"] | contextual] ++ ["state" | stateful] ++ clauseArgs
                      invoke = function ++ "(" ++ intercalate ", " arguments ++ ")"
                      okValue x = case failure of
                        Just _ -> "return " ++ r ++ ".NewOk(" ++ x ++ ");"
                        Nothing -> if r == "Unit" then "" else "return " ++ x ++ ";"
                      computed = if stateful
                        then [ "var pair = " ++ invoke ++ ";", "state = pair.Second;", okValue "pair.First" ]
                        else if r == "Unit" && failure == Nothing then [invoke ++ ";"] else [okValue invoke]
                      body = case failure of
                        Just (key, codec) ->
                          [ D.text "try" <> D.hardline <> D.block 4 (D.joinWith D.hardline (map D.text (filter (not . null) computed)))
                          , D.text ("catch (RaisedFailure failure) when (failure.Ability == " ++ show key ++ ")") <> D.hardline <>
                            D.block 4 (D.text ("return " ++ r ++ ".NewError(" ++ codec ++ ".ToNative.Invoke(failure.Failure));")) ]
                        Nothing -> map D.text (filter (not . null) computed)
                  in D.text ("public " ++ csResult r ++ " " ++ m ++ "(" ++ intercalate ", " [t ++ " " ++ v | (v, t) <- ps, map snd ps /= ["Unit"]] ++ ")") <> D.hardline <>
                     D.block 4 (D.text "lock (gate)" <> D.hardline <> D.block 4 (D.joinWith D.hardline body))
                [] -> mempty
              members =
                [ D.text "private readonly object gate = new();" <> D.hardline <>
                  D.text "private readonly Schema.Schema schema;" <> D.hardline <>
                  D.text "private readonly Scalar.SymbolContext symbols;" ] ++
                [ D.text ("private " ++ t ++ " state;") | stateful, Just t <- [stateType] ] ++
                [ D.text "/// <summary>Outside any law: the program's schema and fresh symbols.</summary>" <> D.hardline <>
                  D.text ("public " ++ cls ++ "() : this(LawSpec.Generated.Program.Schema, new Scalar.SymbolContext()) { }")
                , D.text ("public " ++ cls ++ "(Schema.Schema schema, Scalar.SymbolContext symbols)") <> D.hardline <>
                  D.block 4 (D.joinWith D.hardline (map D.text (["this.schema = schema;", "this.symbols = symbols;"] ++ ["state = " ++ start ++ ";" | stateful]))) ] ++
                [ D.text "/// <summary>The handler's state: a snapshot to show or keep, or one to force, reset or restore.</summary>" <> D.hardline <>
                  D.text ("public " ++ t ++ " State") <> D.hardline <>
                  D.block 4 (D.text "get { lock (gate) return state; }" <> D.hardline <> D.text "set { lock (gate) state = value; }")
                | stateful, Just t <- [stateType] ] ++
                map operation operations
              header = D.text ("/// <summary>" ++ summary ++ " It runs typed: its state is native, and shared, not copied, by a snapshot.</summary>") <> D.hardline <>
                D.text ("public sealed class " ++ cls ++ " : " ++ intercalate ", " interfaces)
          in header <> D.hardline <> D.block 4 (D.joinWith (D.hardline <> D.hardline) members)
        FSharp ->
          let lets = [ L.binding 4 "let handler" (L.App (owner ++ "." ++ factory) [L.A "schema", L.A "symbols"]) ] ++
                [ L.binding 4 ("let " ++ field a) (L.App (bridge a) [L.A "schema", L.A "symbols", L.A "handler"]) | a <- answered ]
              members =
                [ map (L.pad 4) ["/// Outside any law: the program's schema and fresh symbols.",
                    "new() = " ++ cls ++ "(LawSpec.Generated.Program.schema, Scalar.SymbolContext())"]
                , map (L.pad 4) ["/// The handler as the runtime runs it.", "member _.Handler = handler"] ] ++
                [ map (L.pad 4) ["/// The handler's state in native types: a snapshot to show or keep, or one to force, reset or restore.", "member _.State"] ++
                  accessor ("with get (): " ++ t ++ " =") (codecText c "ToNative" ("(snd (Effects.handlerState " ++ field first ++ "))")) ++
                  accessor ("and set (state: " ++ t ++ ") =") ("Effects.setHandlerState " ++ field first ++ " (" ++ codecText c "FromNative" "state" ++ ")")
                | Just c <- [stateCodec], Just t <- [stateType] ] ++
                [ L.pad 4 ("/// " ++ m ++ (if "Result<" `isPrefix` r then ": its failure as a Result." else ".")) :
                  L.function 4 ("member _." ++ m ++ "(" ++ intercalate ", " [v ++ ": " ++ t | (v, t) <- fsParameters ps] ++ ")") [] (Just r)
                    (L.Method (field a ++ "." ++ m) (map (L.A . fst) (fsParameters ps)))
                | (a, m, ps, r, _) <- operations ] ++
                [ L.pad 4 ("interface " ++ Effects.interfaceType a ++ " with") :
                    [ L.pad 8 ("member this." ++ m ++ "(" ++ intercalate ", " (map fst (fsParameters ps)) ++ ") = this." ++ m ++ "(" ++ intercalate ", " (map fst (fsParameters ps)) ++ ")")
                    | (a', m, ps, _, _) <- operations, C.abilityInstance a' == C.abilityInstance a ]
                | a <- answered ]
          in L.linesDoc 0 (["/// " ++ summary ++ " A new one starts from the handler's start state.", "[<Sealed>]"] ++
               classHeader cls ++ L.separated (lets ++ members))
        CSharp ->
          let header = D.text ("/// <summary>" ++ summary ++ " A new one starts from the handler's start state.</summary>") <> D.hardline <>
                D.text ("public sealed class " ++ cls ++ " : " ++ intercalate ", " interfaces)
              csResult r = if r == "Unit" then "void" else r
              members =
                [ D.text "private readonly Effects.Handler handler;" ] ++
                [ D.text ("private readonly " ++ Effects.interfaceType a ++ " " ++ field a ++ ";") | a <- answered ] ++
                [ D.text "/// <summary>Outside any law: the program's schema and fresh symbols.</summary>" <> D.hardline <>
                  D.text ("public " ++ cls ++ "() : this(LawSpec.Generated.Program.Schema, new Scalar.SymbolContext()) { }")
                , D.text ("public " ++ cls ++ "(Schema.Schema schema, Scalar.SymbolContext symbols)") <> D.hardline <>
                  D.block 4 (D.joinWith D.hardline (
                    D.text ("handler = " ++ owner ++ "." ++ pascal factory ++ "(schema, symbols);") :
                    [ D.text (field a ++ " = " ++ bridge a ++ "(schema, symbols, handler);") | a <- answered ]))
                , D.text "/// <summary>The handler as the runtime runs it.</summary>" <> D.hardline <>
                  D.text "public Effects.Handler Handler => handler;" ] ++
                [ D.text "/// <summary>The handler's state in native types: a snapshot to show or keep, or one to force, reset or restore.</summary>" <> D.hardline <>
                  D.text ("public " ++ t ++ " State") <> D.hardline <>
                  D.block 4 (D.text ("get => " ++ c ++ ".ToNative.Invoke(Effects.HandlerState(" ++ field first ++ ").Item2);") <> D.hardline <>
                    D.text ("set => Effects.SetHandlerState(" ++ field first ++ ", " ++ c ++ ".FromNative.Invoke(value));"))
                | Just c <- [stateCodec], Just t <- [stateType] ] ++
                [ D.text ("public " ++ csResult r ++ " " ++ m ++ "(" ++ intercalate ", " [t ++ " " ++ v | (v, t) <- ps, map snd ps /= ["Unit"]] ++ ") => " ++
                    field a ++ "." ++ m ++ "(" ++ intercalate ", " [v | (v, _) <- ps, map snd ps /= ["Unit"]] ++ ");")
                | (a, m, ps, r, _) <- operations ]
          in header <> D.hardline <> D.block 4 (D.joinWith (D.hardline <> D.hardline) members)
    fsParameters ps = if map snd ps == ["unit"] then [] else ps
    -- A property's accessor: its body on its line while under 40 columns.
    accessor header body
      | L.columns body < 40 && 8 + L.columns header + 1 + L.columns body <= L.pageWidth = [L.pad 8 (header ++ " " ++ body)]
      | otherwise = [L.pad 8 header, L.pad 12 body]
    -- A class with the handler context, its parameters on a line of their
    -- own when the declaration is too wide, as Fantomas writes it.
    classHeader cls =
      let header = "type " ++ cls ++ "(schema: Schema.Schema, symbols: Scalar.SymbolContext) ="
      in if L.columns header <= L.pageWidth then [header] else ["type " ++ cls, "    (schema: Schema.Schema, symbols: Scalar.SymbolContext) ="]
    -- A codec's conversion as a function value, and applied as text.
    codecFunction c
      | take 1 c == "(" = L.App "Codec.toNative" [L.A c]
      | otherwise = L.A (c ++ ".ToNative")
    codecText c member x
      | take 1 c == "(" = "Codec." ++ (if member == "ToNative" then "toNative" else "fromNative") ++ " " ++ c ++ " " ++ x
      | otherwise = c ++ "." ++ member ++ " " ++ x
    fsArguments ps = if map snd ps == ["unit"] then ["()"] else map fst ps
    operationSignatureOf names a op = Abilities.operationSignatureFor lang bits names a op
    isPrefix p s = take (length p) s == p
