-- | Abilities as .NET interfaces. Each ability instance is an interface with a
-- method per operation (IGateway.Authorize); a native handler implements it
-- (an F# object expression, a C# class), and a bridge turns a native handler
-- into a logical one and back, converting values and failures. An operation
-- that fails with E returns Result<_, E> natively. Spec handlers are made by
-- their unit's generated module from its clause definitions.
-- ref:DEC-typed-core-boundary ref:DEC-idiomatic-generated-types
-- ref:DEC-fsharp-runtime-from-scratch
module LawSpec.DotNet.Abilities
  ( emitInterfaces, emitBridges, unitFactories, productionStubs, failureOf, nativeResult, emitDefaults, operationSignatureFor
  ) where

