-- | The failure an operation fails with, if any.
failureOf :: C.Ability -> String -> Maybe C.Type
failureOf a op = case lookup op (C.abilityFailures a) of
  Just (C.AbilityRef _ [failure]) -> Just failure
  _ -> Nothing

-- | A native result type, or its Result when the operation can fail.
nativeResult :: Lang -> String -> Maybe String -> String
nativeResult _ r Nothing = r
nativeResult FSharp r (Just e) = "Result<" ++ r ++ ", " ++ e ++ ">"
nativeResult CSharp r (Just e) = "FSharpResult<" ++ r ++ ", " ++ e ++ ">"

operationSignature :: Lang -> Int -> Data.Names -> C.Ability -> (String, C.Type) -> Either String ([String], String)
operationSignature lang bits names a (op, ty) = do
  let (args, result) = C.functionType ty
  ps <- mapM (Data.nativeType lang bits names []) args
  r <- Data.nativeType lang bits names [] result
  e <- traverse (Data.nativeType lang bits names []) (failureOf a op)
  pure (ps, nativeResult lang r e)

-- | One file of interfaces, a namespace for each unit's abilities.
emitInterfaces :: Lang -> D.Layout -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitInterfaces lang layout bits declarations units
  | null (Effects.abilities units) = pure []
  | otherwise = do
      names <- dataNames declarations
      groups <- forM [u | u <- units, not (null (own u))] $ \u -> do
        types <- forM (own u) $ \a -> do
          members <- forM (C.abilityOperations a) $ \(op, ty) -> do
            (ps, r) <- operationSignature lang bits names a (op, ty)
            let comment = "/// " ++ op
            pure $ case lang of
              FSharp -> D.text comment <> D.hardline <> D.text ("abstract " ++ Effects.operationMember op ++ ": " ++
                (if null ps then "unit" else intercalate " * " ["value" ++ show i ++ ": " ++ p | (i, p) <- zip [0 :: Int ..] ps]) ++ " -> " ++ r)
              CSharp -> D.text ("/// <summary>" ++ op ++ "</summary>") <> D.hardline <> D.text (csResult r ++ " " ++ Effects.operationMember op ++ "(" ++
                intercalate ", " [p ++ " value" ++ show i | (i, p) <- zip [0 :: Int ..] ps] ++ ");")
          let name = "I" ++ pascal (N.interfaceName a)
              doc = "The native interface of " ++ N.displayName a ++ " (" ++ C.abilityKey (C.abilityInstance a) ++ ")."
          pure $ case lang of
            FSharp -> D.text ("/// " ++ doc) <> D.hardline <> D.text ("type " ++ name ++ " =") <>
              D.nest 4 (D.hardline <> D.joinWith D.hardline members)
            CSharp -> D.text ("/// <summary>" ++ doc ++ "</summary>") <> D.hardline <> D.text ("public interface " ++ name) <>
              D.hardline <> D.block 4 (D.joinWith D.hardline members)
        pure $ case lang of
          FSharp -> D.text ("namespace " ++ Effects.abilityNamespace (C.unitId u)) <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) types
          CSharp -> D.text ("namespace " ++ Effects.abilityNamespace (C.unitId u)) <> D.hardline <>
            D.block 4 (D.joinWith (D.hardline <> D.hardline) types)
      let doc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            (if lang == CSharp then D.text "using System.Collections.Generic;" <> D.hardline <> D.text "using LawSpec.Runtime;" <> D.hardline else mempty) <>
            D.joinWith (D.hardline <> D.hardline) groups <> D.hardline
      pure [Artifact ("src/LawSpec/Abilities" ++ extension lang) (D.render layout doc) "generated" "source"]
  where
    own u = [a | a <- N.ownAbilities u, not (C.isFail (C.abilityInstance a))]
    csResult r = if r == "System.ValueTuple" then "void" else r

-- | The bridges between native interfaces and logical handlers.
emitBridges :: Lang -> D.Layout -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitBridges FSharp layout bits declarations units
  | null (Effects.abilities units) = pure []
  | otherwise = do
      names <- dataNames declarations
      bodies <- mapM (bridge names) (Effects.abilities units)
      let doc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text "/// Bridges between each ability's native interface and its logical handlers." <> D.hardline <>
            D.text "module LawSpec.Generated.Abilities" <> D.hardline <> D.hardline <>
            D.text "open LawSpec.Runtime" <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) bodies <> D.hardline
      pure [Artifact "src/LawSpec/AbilityBridges.fs" (D.render layout doc) "generated" "source"]
  where
    bridge names a = do
      let key = C.abilityKey (C.abilityInstance a)
          interface = Effects.interfaceType a
          className = pascal (Effects.bridgeName a "Bridge")
      members <- forM (C.abilityOperations a) $ \(op, ty) -> do
        let (args, result) = C.functionType ty
            values = ["value" ++ show i | (i, _) <- zip [0 :: Int ..] args]
        codecs <- mapM (Data.codec FSharp bits names []) args
        out <- Data.codec FSharp bits names [] result
        let logical = "Effects.invoke handler schema " ++ stringLiteral FSharp op ++ " [ " ++
              intercalate "; " [c ++ ".FromNative " ++ v | (c, v) <- zip codecs values] ++ " ]"
            converted = out ++ ".ToNative (" ++ logical ++ ")"
        body <- case failureOf a op of
          Nothing -> pure converted
          Just failure -> do
            fc <- Data.codec FSharp bits names [] failure
            pure ("Effects.nativeTry " ++ stringLiteral FSharp (failingKey a op) ++ " " ++ fc ++ ".ToNative (fun () -> " ++ converted ++ ")")
        pure (D.text ("member _." ++ Effects.operationMember op ++ "(" ++ intercalate ", " values ++ ") =") <>
          D.nest 4 (D.hardline <> D.text body))
      clauses <- forM (C.abilityOperations a) $ \(op, ty) -> do
        let (args, result) = C.functionType ty
        codecs <- mapM (Data.codec FSharp bits names []) args
        out <- Data.codec FSharp bits names [] result
        ref <- X.typeRef result
        let call' = "native." ++ Effects.operationMember op ++ "(" ++
              intercalate ", " [c ++ ".ToNative (Runtime.item " ++ show i ++ " arguments)" | (i, c) <- zip [0 :: Int ..] codecs] ++ ")"
        unwrapped <- case failureOf a op of
          Nothing -> pure call'
          Just failure -> do
            fc <- Data.codec FSharp bits names [] failure
            pure ("Effects.ofResult " ++ stringLiteral FSharp (failingKey a op) ++ " " ++ fc ++ ".FromNative (" ++ call' ++ ")")
        pure (D.text (stringLiteral FSharp op ++ ",") <> D.nest 4 (D.hardline <>
          D.text "fun (current: Schema.Schema) (arguments: Value list) ->" <> D.nest 4 (D.hardline <>
            D.text "Schema.validate (" <> D.text (out ++ ".FromNative (" ++ unwrapped ++ ")) ") <> D.text (renderExprInline ref) <> D.text " current")))
      let classDoc = D.text ("type private " ++ className ++ "(schema: Schema.Schema, symbols: Scalar.SymbolContext, handler: Effects.Handler) =") <>
            D.nest 4 (D.hardline <> D.text ("interface " ++ interface ++ " with") <>
              D.nest 4 (D.hardline <> D.joinWith D.hardline members) <> D.hardline <>
              D.text "interface Effects.IOrigin with" <> D.nest 4 (D.hardline <> D.joinWith D.hardline (map D.text
                [ "member _.Ability = " ++ stringLiteral FSharp key, "member _.Symbols = symbols"
                , "member _.Handler = handler", "member _.Schema = schema" ])))
          toNative = D.text ("/// " ++ N.displayName a ++ "'s native interface over a logical handler.") <> D.hardline <>
            D.text ("[<CompiledName(\"" ++ pascal (Effects.bridgeName a "ToNative") ++ "\")>]") <> D.hardline <>
            D.text ("let " ++ Effects.bridgeName a "ToNative" ++ " (schema: Schema.Schema) (symbols: Scalar.SymbolContext) (handler: Effects.Handler) : " ++ interface ++ " =") <>
            D.nest 4 (D.hardline <> D.text (className ++ "(schema, symbols, handler) :> " ++ interface))
          fromNative = D.text ("/// The logical handler of a native " ++ N.displayName a ++ ".") <> D.hardline <>
            D.text ("[<CompiledName(\"" ++ pascal (Effects.bridgeName a "FromNative") ++ "\")>]") <> D.hardline <>
            D.text ("let " ++ Effects.bridgeName a "FromNative" ++ " (_schema: Schema.Schema) (symbols: Scalar.SymbolContext) (native: " ++ interface ++ ") : Effects.Handler =") <>
            D.nest 4 (D.hardline <> D.text ("Effects.recover native " ++ stringLiteral FSharp key ++ " symbols (fun () ->") <>
              D.nest 4 (D.hardline <> D.text "Effects.stateless" <> D.nest 4 (D.hardline <> D.text "[ " <>
                D.joinWith (D.hardline <> D.text "  ") clauses <> D.text " ]")) <> D.text ")")
          recording = D.text ("/// A recording of a native " ++ N.displayName a ++ ".") <> D.hardline <>
            D.text ("[<CompiledName(\"" ++ pascal (Effects.bridgeName a "Recording") ++ "\")>]") <> D.hardline <>
            D.text ("let " ++ Effects.bridgeName a "Recording" ++ " (schema: Schema.Schema) (symbols: Scalar.SymbolContext) (native: " ++ interface ++ ") : " ++ interface ++ " =") <>
            D.nest 4 (D.hardline <> D.text (Effects.bridgeName a "ToNative" ++ " schema symbols (Effects.recording (" ++
              Effects.bridgeName a "FromNative" ++ " schema symbols native))"))
      pure (D.joinWith (D.hardline <> D.hardline) [classDoc, toNative, fromNative, recording])
    renderExprInline e = let s = D.render (D.Pretty 1000) (renderExpr FSharp e) in "(" ++ s ++ ")"
emitBridges CSharp _ _ _ units
  | null (Effects.abilities units) = pure []
  | otherwise = Left "C# ability bridges are not emitted yet"

-- | The key of the Fail ability an operation fails through.
failingKey :: C.Ability -> String -> String
failingKey a op = case lookup op (C.abilityFailures a) of
  Just failing -> C.abilityKey failing
  Nothing -> ""

-- | A unit's handler factories, in its generated module: its abilities'
-- production handlers (from its adapter) and its spec handlers.
unitFactories :: Lang -> Int -> [C.DataDeclaration] -> [C.Unit] -> C.Unit -> Either String [D.Doc]
unitFactories lang bits declarations units unit = do
  names <- dataNames declarations
  productions <- forM [a | a <- N.ownAbilities unit, not (C.isFail (C.abilityInstance a)), not (Effects.hasDefault a) || C.abilityNative a /= Nothing] $ \a -> do
    resourceCodec <- traverse (Data.codec lang bits names []) (C.abilityResource a)
    let (_, name) = Effects.productionFunction a
        -- A handler bound in lawspec.json is made by its native type or
        -- function; otherwise the unit's adapter makes it.
        made = case C.abilityNative a of
          Just ref -> intercalate "." ref
          Nothing -> unitQualified (C.unitId unit) ++ "." ++ (case lang of FSharp -> camel (N.productionName a); CSharp -> pascal (N.productionName a))
        arguments = case resourceCodec of
          Just c -> " (" ++ c ++ ".ToNative resource)"
          Nothing -> " ()"
        params = "(schema: Schema.Schema) (symbols: Scalar.SymbolContext)" ++ maybe "" (const " (resource: Value)") resourceCodec
        csMade = case C.abilityNative a of
          Just ref -> "new " ++ intercalate "." ref ++ "()"
          Nothing -> made ++ "(" ++ maybe "" (\c -> c ++ ".ToNative.Invoke(resource)") resourceCodec ++ ")"
    pure $ case lang of
      FSharp -> D.text ("/// The production handler of " ++ N.displayName a ++ ", from the adapter.") <> D.hardline <>
        D.text ("let " ++ name ++ " " ++ params ++ " : Effects.Handler =") <>
        D.nest 4 (D.hardline <> D.text ("LawSpec.Generated.Abilities." ++ Effects.bridgeName a "FromNative" ++ " schema symbols (" ++ made ++ arguments ++ ")"))
      CSharp -> D.text ("/// <summary>The production handler of " ++ N.displayName a ++ ", from the adapter.</summary>") <> D.hardline <>
        D.text ("public static Effects.Handler " ++ pascal name ++ "(Schema.Schema schema, Scalar.SymbolContext symbols" ++ maybe "" (const ", Value resource") resourceCodec ++ ") =>") <>
        D.nest 4 (D.hardline <> D.text ("LawSpec.Generated.Abilities." ++ pascal (Effects.bridgeName a "FromNative") ++ "(schema, symbols, " ++ csMade ++ ");"))
  specs <- forM (C.unitHandlers unit) $ \h -> do
    answered <- forM (C.handlerAbilities h) $ \ref -> maybe (Left "unknown .NET spec handler ability") Right (N.abilityOf units ref)
    let stateful = C.handlerState h /= Nothing
    clauses <- forM (concatMap C.abilityOperations answered) $ \(op, ty) -> do
      identity <- maybe (Left ("missing .NET spec handler clause " ++ op)) Right (lookup op (C.handlerClauses h))
      e <- maybe (Left "missing .NET spec clause definition") Right (lookup identity (entries units))
      let arity = length (fst (C.functionType ty))
          args = [call "Runtime" "item" [IntLit (toInteger i), Var "arguments"] | i <- [0 .. arity - 1]]
          parameters = if stateful then Var "state" : args else if null args then [Raw "Value.Unit" "V.Unit"] else args
          body = entryCall e (Var "current" : Var "symbols" : parameters)
          params = [("current", tSchema), ("arguments", tValues)] ++ [("state", tValue) | stateful]
      pure (TupleOf [Str op, Lambda params tValue body])
    start <- case C.handlerState h of
      Nothing -> pure Nothing
      Just (_, initial) -> Just <$> X.render (X.Context bits X.schemaVar X.symbolsVar
        (\i -> error ("unbound .NET handler state: " ++ C.idText i)) (Effects.external units) X.typeRef X.typeKeyOf) initial
    let clauseTy = if stateful then Ty "string * Effects.StatefulClause" "Tuple<string, FSharpFunc<Schema.Schema, FSharpFunc<FSharpList<Value>, FSharpFunc<Value, Value>>>>"
          else Ty "string * Effects.Clause" "Tuple<string, FSharpFunc<Schema.Schema, FSharpFunc<FSharpList<Value>, Value>>>"
        made = case start of
          Nothing -> call "Effects" "stateless" [ListOf clauseTy clauses]
          Just v -> call "Effects" "stateful" [v, ListOf clauseTy clauses]
        (_, name) = Effects.specFunction units h
    pure $ case lang of
      FSharp -> D.text ("/// The spec handler " ++ C.handlerName h ++ ".") <> D.hardline <>
        D.text ("let " ++ name ++ " (schema: Schema.Schema) (symbols: Scalar.SymbolContext) : Effects.Handler =") <>
        D.nest 4 (D.hardline <> renderBody lang (Ty "Effects.Handler" "Effects.Handler") made)
      CSharp -> D.text ("/// <summary>The spec handler " ++ C.handlerName h ++ ".</summary>") <> D.hardline <>
        D.text ("public static Effects.Handler " ++ pascal name ++ "(Schema.Schema schema, Scalar.SymbolContext symbols)") <> D.hardline <>
        D.block 4 (renderBody lang (Ty "Effects.Handler" "Effects.Handler") made)
  pure (productions ++ specs)

-- | The native handler factories a unit's adapter implements.
productionStubs :: Lang -> Int -> [C.DataDeclaration] -> C.Unit -> Either String [D.Doc]
productionStubs CSharp bits declarations unit = do
  names <- dataNames declarations
  fmap concat $ forM [a | a <- N.ownAbilities unit, not (C.isFail (C.abilityInstance a)), C.abilityNative a == Nothing, not (Effects.hasDefault a)] $ \a -> do
    members <- forM (C.abilityOperations a) $ \(op, ty) -> do
      (ps, r) <- operationSignature CSharp bits names a (op, ty)
      let params = [p ++ " value" ++ show i | (i, p) <- zip [0 :: Int ..] ps, p /= "Unit"]
          message = "not implemented: " ++ C.abilityKey (C.abilityInstance a) ++ "." ++ op
      pure (D.text ("public " ++ (if r == "Unit" then "void" else r) ++ " " ++ Effects.operationMember op ++ "(" ++ intercalate ", " params ++ ") =>") <>
        D.nest 4 (D.hardline <> D.text ("throw new NotImplementedException(" ++ stringLiteral CSharp message ++ ");")))
    resource <- traverse (Data.nativeType CSharp bits names []) (C.abilityResource a)
    let interface = Effects.interfaceType a
        cls = "Native" ++ pascal (N.interfaceName a)
        name = pascal (N.productionName a)
    pure [ D.text ("/// <summary>The native handler of " ++ N.displayName a ++ ": " ++ intercalate ", " (map fst (C.abilityOperations a)) ++ ".</summary>") <> D.hardline <>
           D.text ("public static " ++ interface ++ " " ++ name ++ "(" ++ maybe "" (++ " resource") resource ++ ") => new " ++ cls ++ "();")
         , D.text ("private sealed class " ++ cls ++ " : " ++ interface) <> D.hardline <>
           D.block 4 (D.joinWith (D.hardline <> D.hardline) members) ]
productionStubs lang bits declarations unit = do
  names <- dataNames declarations
  forM [a | a <- N.ownAbilities unit, not (C.isFail (C.abilityInstance a)), C.abilityNative a == Nothing, not (Effects.hasDefault a)] $ \a -> do
    members <- forM (C.abilityOperations a) $ \(op, ty) -> do
      (ps, _) <- operationSignature lang bits names a (op, ty)
      let values = ["value" ++ show i | (i, _) <- zip [0 :: Int ..] ps]
          message = "not implemented: " ++ C.abilityKey (C.abilityInstance a) ++ "." ++ op
      pure (D.text ("member _." ++ Effects.operationMember op ++ "(" ++ intercalate ", " [if null ps then "" else v | v <- values] ++ ") = failwith " ++ stringLiteral FSharp message))
    resource <- traverse (Data.nativeType lang bits names []) (C.abilityResource a)
    let interface = Effects.interfaceType a
        name = camel (N.productionName a)
        params = maybe "()" (\t -> "(resource: " ++ t ++ ")") resource
    pure (D.text ("/// The native handler of " ++ N.displayName a ++ ": " ++ intercalate ", " (map fst (C.abilityOperations a)) ++ ".") <> D.hardline <>
      D.text ("let " ++ name ++ " " ++ params ++ " : " ++ interface ++ " =") <>
      D.nest 4 (D.hardline <> D.text ("{ new " ++ interface ++ " with") <>
        D.nest 4 (D.hardline <> D.joinWith D.hardline members) <> D.text " }"))

-- | The default handlers of the built-in abilities, as their native
-- interfaces: what a bound handler wraps, and what applications use.
emitDefaults :: Lang -> D.Layout -> [C.Unit] -> Either String [Artifact]
emitDefaults FSharp layout units
  | null defaults = pure []
  | otherwise = do
      let functions =
            [ D.text ("/// The default handler of " ++ N.displayName a ++ ".") <> D.hardline <>
              D.text ("[<CompiledName(\"" ++ pascal (N.interfaceName a) ++ "\")>]") <> D.hardline <>
              D.text ("let " ++ escapeFSharp (camel (N.interfaceName a)) ++ " () : " ++ Effects.interfaceType a ++ " =") <>
              D.nest 4 (D.hardline <> D.text ("LawSpec.Generated.Abilities." ++ Effects.bridgeName a "ToNative" ++
                " LawSpec.Generated.Program.schema (Scalar.SymbolContext()) (Defaults.handler " ++ stringLiteral FSharp (C.abilityKey (C.abilityInstance a)) ++ ")"))
            | a <- defaults ] ++
            [ D.text "/// The SLH-DSA (FIPS 205) signature handler." <> D.hardline <>
              D.text "[<CompiledName(\"SlhDsaSignature\")>]" <> D.hardline <>
              D.text ("let slhDsaSignature () : " ++ Effects.interfaceType a ++ " =") <>
              D.nest 4 (D.hardline <> D.text ("LawSpec.Generated.Abilities." ++ Effects.bridgeName a "ToNative" ++
                " LawSpec.Generated.Program.schema (Scalar.SymbolContext()) (Crypto.slhDsaSignatureHandler ())"))
            | a <- defaults, C.abilityKey (C.abilityInstance a) == "lawspec.crypto::ability::Signature" ]
          doc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text "/// The runtime's default handlers of the built-in abilities, as native interfaces." <> D.hardline <>
            D.text "module LawSpec.DefaultHandlers" <> D.hardline <> D.hardline <>
            D.text "open LawSpec.Runtime" <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) functions <> D.hardline
      pure [Artifact "src/LawSpec/DefaultHandlers.fs" (D.render layout doc) "generated" "source"]
  where defaults = [a | a <- Effects.abilities units, Effects.hasDefault a]
emitDefaults CSharp _ _ = pure []
