-- | Typed actors for F# implementation code (see LawSpec.Actors). Every
-- actor becomes a class named for its handle type in LawSpec.Actors, and
-- the functions it runs (its start, handlers and restart) a record of
-- functions, usually the unit's adapters: the actor classes compile before
-- the adapters, so an adapter may start an actor made of its own functions.
-- LawSpec.Generated.ActorHandlers gives each actor's record made from the
-- adapters, for code compiled after them. Each handler is a method that sends
-- its message and waits for the reply, with a Tell form that does not wait;
-- an actor whose messages have wire descriptors can be served to and called
-- from other nodes. Supervisors start their children under the runtime's
-- supervision tree; their children are properties.
-- ref:DEC-actors-otp-supervision ref:DEC-fsharp-runtime-from-scratch
module LawSpec.DotNet.Actors (emitActors) where

import qualified LawSpec.Core as C
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.Actors.Types
import LawSpec.Core.Machine (SupervisionStrategy(..), Lifetime(..))
import LawSpec.MachineSpec (describe)
import LawSpec.DotNet.Code (stringLiteral, Lang(..))
import LawSpec.DotNet.Names
import qualified LawSpec.DotNet.Data as Data
import Control.Monad (foldM, forM)
import Data.List (intercalate, nubBy)

-- | The actor classes (compiled before the adapters) and the adapters'
-- handler records (compiled after them).
emitActors :: D.Layout -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String ([Artifact], [Artifact])
emitActors layout bits datas units
  | null actors && null supervisors = pure ([], [])
  | otherwise = do
      names <- dataNames datas
      let native = Data.nativeType FSharp bits names []
          codec = Data.codec FSharp bits names []
      records <- mapM (handlersRecord native) actors
      classes <- mapM (classOf native codec) actors
      supervised <- mapM supervisorClass supervisors
      defaults <- mapM defaultRecord actors
      let groups = concat records ++ concat classes ++ supervised
          classesDoc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text "/// Typed actors and supervisors: each actor runs the functions of its" <> D.hardline <>
            D.text "/// handlers record, one message at a time; a handler that throws crashes" <> D.hardline <>
            D.text "/// the actor, and a supervised one restarts (from its restart function, or" <> D.hardline <>
            D.text "/// its start) while any other stops." <> D.hardline <>
            D.text "namespace LawSpec.Actors" <> D.hardline <> D.hardline <>
            D.text "open LawSpec.Runtime" <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) (zipWith (\i (doc, g) -> D.text doc <> D.hardline <> (if i == (0 :: Int) then D.text "type " else D.text "and ") <> g) [0 ..] groups) <> D.hardline
          defaultsDoc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text "/// Each actor's handlers record, made from the adapters." <> D.hardline <>
            D.text "module LawSpec.Generated.ActorHandlers" <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) defaults <> D.hardline
      pure ( [Artifact "src/LawSpec/Actors.fs" (D.render layout classesDoc) "generated" "source"]
           , [Artifact "src/LawSpec/ActorHandlers.fs" (D.render layout defaultsDoc) "generated" "source"] )
  where
    actors = concatMap actorsOf units
    supervisors = concatMap supervisionsOf units
    unitTy t = t == C.Constructor "Unit" []
    recordName a = actorClass a ++ "Handlers"
    field d = pascal (C.declarationName d)
    adapterRef a d = unitQualified (C.unitId (actorUnit a)) ++ "." ++ functionName FSharp d
    argName (n, _) = escapeFSharp (camel n)
    -- A declaration's function type, as its adapter has it.
    functionType native d = do
      let (ps, r) = C.functionType (C.declarationType d)
      pts <- mapM native ps
      rt <- native r
      let result = if C.declarationAsync d then "System.Threading.Tasks.Task<" ++ rt ++ ">" else rt
      pure (intercalate " -> " (map paren (if null pts then ["unit"] else pts) ++ [result]))
    paren t = if ' ' `elem` t && last t /= '>' then "(" ++ t ++ ")" else t
    awaited d e = if C.declarationAsync d then "(" ++ e ++ ").GetAwaiter().GetResult()" else e
    declarations a = actorStart a : map handlerDeclaration (actorHandlers a) ++ maybe [] pure (actorRestart a)

    handlersRecord native a = do
      fields <- forM (declarations a) $ \d -> do
        t <- functionType native d
        pure (D.text ("/// " ++ C.idText (C.declarationId d)) <> D.hardline <> D.text (field d ++ ": " ++ t))
      pure [("/// The functions actor " ++ actorName a ++ " runs: usually its unit's adapters.",
        D.text ("[<NoEquality; NoComparison>] " ++ recordName a ++ " =") <> D.nest 4 (D.hardline <>
          D.text "{ " <> D.joinWith (D.hardline <> D.text "  ") (map (D.nest 2) fields) <> D.text " }"))]

    defaultRecord a = pure (D.text ("/// The handlers of actor " ++ actorName a ++ ", from the adapters.") <> D.hardline <>
      D.text ("let " ++ escapeFSharp (camel (actorName a)) ++ " : LawSpec.Actors." ++ recordName a ++ " =") <> D.nest 4 (D.hardline <>
        D.text "{ " <> D.joinWith (D.hardline <> D.text "  ") [D.text (field d ++ " = " ++ adapterRef a d) | d <- declarations a] <> D.text " }"))

    -- Each message's argument and reply descriptors, with the data types they
    -- use; Nothing when a type has no descriptor (the actor stays local).
    wires a = either (const Nothing) Just $ do
      (table, hs) <- foldM (\(t, acc) h -> do
          (args, t') <- foldM (\(xs, tt) (_, ty) -> (\(x, tt') -> (xs ++ [x], tt')) <$> describe bits datas tt ty) ([], t) (handlerArguments h)
          (reply, t'') <- describe bits datas t' (maybe (C.Constructor "Unit" []) id (handlerReply h))
          pure (t'', acc ++ [(h, args, reply)])) ([], []) (actorHandlers a)
      let prefix = concatMap ((++ " ") . snd) (reverse table)
      pure [(h, map (prefix ++) args, prefix ++ reply) | (h, args, reply) <- hs]

    classOf native codec a = do
      let cls = actorClass a
          state = "unbox<" ++ stateType ++ "> state"
          stateType = either (const "obj") id (native (actorState a))
          startArgs = actorStartArguments a
          startParams = [(argName p, t) | p@(_, t) <- startArgs, not (unitTy t)]
          startValues = [if unitTy t then "()" else argName p | p@(_, t) <- startArgs]
          startCall = awaited (actorStart a) ("handlers." ++ field (actorStart a) ++ " " ++ (if null startValues then "()" else unwords startValues))
          restartCall = case actorRestart a of
            Just d -> "(fun state -> box (" ++ awaited d ("handlers." ++ field d ++ " (" ++ state ++ ")") ++ "))"
            Nothing -> "(fun _ -> box (" ++ startCall ++ "))"
      startTypes <- mapM (native . snd) startParams
      methods <- forM (actorHandlers a) $ \h -> do
        args <- forM (handlerArguments h) $ \p@(_, t) -> (,) (argName p) <$> native t
        reply <- traverse native (handlerReply h)
        let d = handlerDeclaration h
            call = awaited d ("handlers." ++ field d ++ " (" ++ state ++ ")" ++ concatMap ((' ' :) . fst) args)
            step = case reply of
              Just _ -> "(fun state -> let pair = " ++ call ++ " in box pair.First, box pair.Second)"
              Nothing -> "(fun state -> box (), box (" ++ call ++ "))"
            params = "(" ++ intercalate ", " [n ++ ": " ++ t | (n, t) <- args] ++ ")"
            name = pascal (handlerName h)
        pure (D.text ("/// Sends " ++ handlerName h ++ " and waits for the reply.") <> D.hardline <>
          D.text ("member _." ++ name ++ params ++ " : " ++ maybe "unit" id reply ++ " =") <> D.nest 4 (D.hardline <>
            D.text ("Actors.call handle " ++ step ++ (if reply == Nothing then " |> ignore" else " |> unbox<" ++ maybe "" id reply ++ ">"))) <> D.hardline <> D.hardline <>
          D.text ("/// Sends " ++ handlerName h ++ " without waiting.") <> D.hardline <>
          D.text ("member _.Tell" ++ name ++ params ++ " : unit =") <> D.nest 4 (D.hardline <> D.text ("Actors.tell handle " ++ step)))
      remote <- case wires a of
        Nothing -> pure ([], [])
        Just hs -> do
          entries <- forM hs $ \(h, args, reply) -> do
            argCodecs <- mapM (codec . snd) (handlerArguments h)
            replyCodec <- codec (maybe (C.Constructor "Unit" []) id (handlerReply h))
            let values = [c ++ ".ToNative (Runtime.item " ++ show i ++ " arguments)" | (i, c) <- zip [0 :: Int ..] argCodecs]
                invoke = replyCodec ++ ".FromNative (this." ++ pascal (handlerName h) ++ "(" ++ intercalate ", " values ++ "))"
                signature body = D.text ("(" ++ stringLiteral FSharp (handlerName h) ++ ", { Arguments = [ " ++ intercalate "; " (map (stringLiteral FSharp) args) ++
                  " ]; Result = " ++ stringLiteral FSharp reply ++ "; Invoke = " ++ body ++ " })")
            pure (signature ("Some(fun arguments -> " ++ invoke ++ ")"), signature "None", (h, argCodecs, replyCodec))
          clientMethods <- forM [c | (_, _, c) <- entries] $ \(h, argCodecs, replyCodec) -> do
            args <- forM (handlerArguments h) $ \p@(_, t) -> (,) (argName p) <$> native t
            reply <- native (maybe (C.Constructor "Unit" []) id (handlerReply h))
            pure (D.text ("member _." ++ pascal (handlerName h) ++ "(" ++ intercalate ", " [n ++ ": " ++ t | (n, t) <- args] ++ ") : " ++ reply ++ " =") <> D.nest 4 (D.hardline <>
              D.text (replyCodec ++ ".ToNative (Remote.call client " ++ stringLiteral FSharp (handlerName h) ++ " [ " ++
                intercalate "; " [c ++ ".FromNative " ++ n | (c, (n, _)) <- zip argCodecs args] ++ " ])")))
          let served = D.text "/// Lets other nodes call this actor at <node address>/name; that address." <> D.hardline <>
                D.text "member this.Serve(node: Node, name: string) : string =" <> D.nest 4 (D.hardline <>
                  D.text "Remote.serve node name \"call\"" <> D.nest 4 (D.hardline <> D.text "[ " <> D.joinWith (D.hardline <> D.text "  ") [s | (s, _, _) <- entries] <> D.text " ]"))
              connect = D.text ("/// The actor served at address on another node; each call waits up to timeout ms.") <> D.hardline <>
                D.text ("static member Connect(node: Node, address: string, ?timeout: int) : " ++ cls ++ "Remote =") <> D.nest 4 (D.hardline <>
                  D.text (cls ++ "Remote(Remote.connect node address \"call\"") <> D.nest 4 (D.hardline <> D.text "[ " <>
                    D.joinWith (D.hardline <> D.text "  ") [s | (_, s, _) <- entries] <> D.text " ]" <> D.hardline <> D.text "(defaultArg timeout 5000))"))
              client = ("/// Actor " ++ actorName a ++ " on another node: each method sends its message and waits for the reply.",
                D.text ("[<Sealed>] " ++ cls ++ "Remote(client: RemoteClient) =") <> D.nest 4 (D.hardline <>
                  D.joinWith (D.hardline <> D.hardline) clientMethods))
          pure ([served, connect], [client])
      let doc = "/// Actor " ++ actorName a ++ ": owns its state and handles one message at a time."
          header = D.text ("[<Sealed>] " ++ cls ++ " internal (handle: Actors.Handle, handlers: " ++ recordName a ++ ") =")
          members =
            [ D.text "/// The runtime's spec of this actor, for a supervisor to start." <> D.hardline <>
              D.text ("static member Spec(handlers: " ++ recordName a ++ concatMap (\((n, _), t) -> ", " ++ n ++ ": " ++ t) (zip startParams startTypes) ++ ") : Actors.Spec =") <>
                D.nest 4 (D.hardline <> D.text ("Actors.actor (fun () -> box (" ++ startCall ++ ")) " ++ restartCall))
            , D.text ("/// Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor.") <> D.hardline <>
              D.text ("static member Start(handlers: " ++ recordName a ++ concatMap (\((n, _), t) -> ", " ++ n ++ ": " ++ t) (zip startParams startTypes) ++ ") : " ++ cls ++ " =") <>
                D.nest 4 (D.hardline <> D.text (cls ++ "(Actors.start (" ++ cls ++ ".Spec(handlers" ++ concatMap ((", " ++) . fst) startParams ++ ")), handlers)"))
            , D.text "/// The actor a supervisor started, by its handle." <> D.hardline <>
              D.text ("static member FromHandle(handle: Actors.Handle, handlers: " ++ recordName a ++ ") : " ++ cls ++ " = " ++ cls ++ "(handle, handlers)")
            , D.text "/// The runtime handle: stable across supervised restarts." <> D.hardline <> D.text "member _.Handle = handle" ] ++
            methods ++
            [ D.text "/// Crashes the actor as a failing handler would, after the messages already sent." <> D.hardline <>
              D.text "member _.Crash() : unit = Actors.crash handle"
            , D.text "/// Tells inbox about each crash, and once it stops." <> D.hardline <>
              D.text "member _.Monitor(inbox: Actors.Inbox) : unit = Actors.monitor handle inbox"
            , D.text "/// When either actor crashes, the other crashes too." <> D.hardline <>
              D.text "member _.Link(other: Actors.Handle) : unit = Actors.link handle other"
            , D.text "/// Refuses further messages; those already sent are still handled." <> D.hardline <>
              D.text "member _.Stop() : unit = Actors.stop handle" ] ++ fst remote
      pure ((doc, header <> D.nest 4 (D.hardline <> D.joinWith (D.hardline <> D.hardline) members)) : snd remote)

    -- The actors beneath a supervisor, each once: its Start takes their
    -- handlers records.
    beneath s = nubBy (\x y -> actorName x == actorName y) (concatMap child (supervisionChildren s))
      where child (_, _, ActorChild a) = [a]
            child (_, _, SupervisorChild cls) = concat [beneath s' | s' <- supervisors, supervisionClass s' == cls]
    handlersParam a = escapeFSharp (camel (actorName a)) ++ "Handlers"
    supervisorClass s = do
      let cls = supervisionClass s
          params = beneath s
          paramText = intercalate ", " [handlersParam a ++ ": " ++ recordName a | a <- params]
          args = intercalate ", " (map handlersParam params)
          childClass c = case c of ActorChild a -> actorClass a; SupervisorChild n -> n
          childArgs c = case c of
            ActorChild a -> handlersParam a
            SupervisorChild n -> intercalate ", " [handlersParam a | s' <- supervisors, supervisionClass s' == n, a <- beneath s']
          strategy = case supervisionStrategy s of OneForOne -> "Actors.OneForOne"; OneForAll -> "Actors.OneForAll"; RestForOne -> "Actors.RestForOne"
          lifetime l = case l of Permanent -> "Actors.Permanent"; Transient -> "Actors.Transient"; Temporary -> "Actors.Temporary"
          childSpec (l, n, c) = "(" ++ stringLiteral FSharp n ++ ", " ++ lifetime l ++ ", " ++ childClass c ++ ".Spec(" ++ childArgs c ++ "))"
          children = supervisionChildren s
      pure ("/// Supervisor " ++ supervisionName s ++ ": its children restart by its strategy, within its restart budget.",
        D.text ("[<Sealed>] " ++ cls ++ " internal (handle: Actors.Handle" ++ concatMap (\(_, n, c) -> ", " ++ escapeFSharp (camel n) ++ ": " ++ childClass c) children ++ ") =") <>
        D.nest 4 (D.hardline <> D.joinWith (D.hardline <> D.hardline) (
          [ D.text "/// The runtime's spec of this supervisor and its children." <> D.hardline <>
            D.text ("static member Spec(" ++ paramText ++ ") : Actors.Spec =") <> D.nest 4 (D.hardline <>
              D.text ("Actors.supervisor " ++ strategy ++ " " ++ show (supervisionRestarts s) ++ " " ++ show (supervisionPeriod s) ++ "L") <> D.nest 4 (D.hardline <>
                D.text "[ " <> D.joinWith (D.hardline <> D.text "  ") (map (D.text . childSpec) children) <> D.text " ]"))
          , D.text "/// The supervisor a parent started, by its handle." <> D.hardline <>
            D.text ("static member FromHandle(handle: Actors.Handle" ++ concatMap (", " ++) [handlersParam a ++ ": " ++ recordName a | a <- params] ++ ") : " ++ cls ++ " =") <>
              D.nest 4 (D.hardline <> D.text (cls ++ "(handle" ++ concatMap (\(_, n, c) -> ", " ++ childClass c ++ ".FromHandle(Actors.child handle " ++ stringLiteral FSharp n ++ ", " ++ childArgs c ++ ")") children ++ ")"))
          , D.text "/// Starts the supervisor and its children, in order." <> D.hardline <>
            D.text ("static member Start(" ++ paramText ++ ") : " ++ cls ++ " =") <>
              D.nest 4 (D.hardline <> D.text (cls ++ ".FromHandle(Actors.start (" ++ cls ++ ".Spec(" ++ args ++ "))" ++ concatMap (", " ++) (map handlersParam params) ++ ")"))
          , D.text "member _.Handle = handle" ] ++
          [ D.text ("/// Child " ++ n ++ ".") <> D.hardline <> D.text ("member _." ++ pascal n ++ " = " ++ escapeFSharp (camel n)) | (_, n, _) <- children ] ++
          [ D.text "/// Tells inbox when it passes its restart limit, and once stopped." <> D.hardline <>
            D.text "member _.Monitor(inbox: Actors.Inbox) : unit = Actors.monitor handle inbox"
          , D.text "/// Stops every child, last started first, without restarting them." <> D.hardline <>
            D.text "member _.Stop() : unit = Actors.stop handle" ])))
