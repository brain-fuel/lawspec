-- | Typed actors for F# implementation code (see LawSpec.Actors). Every
-- actor becomes a class named for its handle type in LawSpec.Actors, and
-- the functions it runs (its start, handlers and restart) a record of
-- functions, usually the unit's adapters: the actor classes compile before
-- the adapters, so an adapter may start an actor made of its own functions.
-- LawSpec.Generated.ActorHandlers gives each actor's record made from the
-- adapters, for code compiled after them. Each handler is a method that sends
-- its message and waits for the reply, with a Tell form that does not wait;
-- an actor whose messages have wire descriptors can be served to and called
-- from other nodes. Supervisors start their children under the runtime's
-- supervision tree; their children are properties.
-- ref:DEC-actors-otp-supervision ref:DEC-fsharp-runtime-from-scratch
module LawSpec.DotNet.Actors (emitActors, emitActorHandlersCs) where

import qualified LawSpec.Core as C
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.Actors.Types
import LawSpec.Core.Machine (SupervisionStrategy(..), Lifetime(..))
import LawSpec.MachineSpec (describe)
import LawSpec.DotNet.Code (stringLiteral, Lang(..))
import LawSpec.DotNet.Names
import qualified LawSpec.DotNet.Data as Data
import qualified LawSpec.DotNet.Layout as L
import Control.Monad (foldM, forM)
import Data.List (intercalate, nubBy)

-- | The actor classes (compiled before the adapters) and the adapters'
-- handler records (compiled after them).
emitActors :: D.Layout -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String ([Artifact], [Artifact])
emitActors _ bits datas units
  | null actors && null supervisors = pure ([], [])
  | otherwise = do
      names <- dataNames datas
      let native = Data.nativeType FSharp bits names []
          codec = Data.codec FSharp bits names []
      records <- mapM (handlersRecord native) actors
      classes <- mapM (classOf native codec) actors
      supervised <- mapM supervisorClass supervisors
      let defaults = map defaultRecord actors
          groups = concat records ++ concat classes ++ supervised
          -- The first type of the recursive group has its attributes on a
          -- line of their own, as Fantomas writes them.
          typed i (doc, header : rest)
            | i == (0 :: Int), ("[<", _) <- splitAt 2 header, (attributes, ']' : ' ' : name) <- break (== ']') header =
                [doc, attributes ++ "]", "type " ++ name] ++ rest
            | i == 0 = [doc, "type " ++ header] ++ rest
            | otherwise = [doc, "and " ++ header] ++ rest
          typed _ (doc, []) = [doc]
          classesText = unlines (
            [ "// Generated by LawSpec. Do not edit."
            , "/// Typed actors and supervisors: each actor runs the functions of its"
            , "/// handlers record, one message at a time; a handler that throws crashes"
            , "/// the actor, and a supervised one restarts (from its restart function, or"
            , "/// its start) while any other stops."
            , "namespace LawSpec.Actors", "", "open LawSpec.Runtime", "" ] ++
            L.separatedBy [""] (zipWith typed [0 ..] groups))
          defaultsText = unlines (
            [ "// Generated by LawSpec. Do not edit."
            , "/// Each actor's handlers record, made from the adapters."
            , "module LawSpec.Generated.ActorHandlers", "" ] ++ L.separatedBy [""] defaults)
      pure ( [Artifact "src/LawSpec/Actors.fs" classesText "generated" "source"]
           , [Artifact "src/LawSpec/ActorHandlers.fs" defaultsText "generated" "source"] )
  where
    actors = concatMap actorsOf units
    supervisors = concatMap supervisionsOf units
    unitTy t = t == C.Constructor "Unit" []
    recordName a = actorClass a ++ "Handlers"
    field d = pascal (C.declarationName d)
    adapterRef a d = unitQualified (C.unitId (actorUnit a)) ++ "." ++ functionName FSharp d
    argName (n, _) = escapeFSharp (camel n)
    -- A declaration's function type, as its adapter has it.
    functionType native d = do
      let (ps, r) = C.functionType (C.declarationType d)
      pts <- mapM native ps
      rt <- native r
      let result = if C.declarationAsync d then "System.Threading.Tasks.Task<" ++ rt ++ ">" else rt
      pure (intercalate " -> " (map paren (if null pts then ["unit"] else pts) ++ [result]))
    paren t = if ' ' `elem` t && last t /= '>' then "(" ++ t ++ ")" else t
    -- An async handler's result is awaited.
    awaited d e = if C.declarationAsync d then L.App "Runtime.await" [e] else e
    declarations a = actorStart a : map handlerDeclaration (actorHandlers a) ++ maybe [] pure (actorRestart a)
    -- A codec's conversion of a value.
    converted c member x
      | take 1 c == "(" = L.App ("Codec." ++ member) [L.A c, x]
      | otherwise = L.App (c ++ "." ++ (if member == "toNative" then "ToNative" else "FromNative")) [x]
    member' doc ls = L.pad 4 ("/// " ++ doc) : ls

    handlersRecord native a = do
      fields <- forM (declarations a) $ \d -> do
        t <- functionType native d
        pure [L.pad 8 ("/// " ++ C.idText (C.declarationId d)), L.pad 8 (field d ++ ": " ++ t)]
      pure [("/// The functions actor " ++ actorName a ++ " runs: usually its unit's adapters.",
        ("[<NoEquality; NoComparison>] " ++ recordName a ++ " =") : [L.pad 4 "{"] ++ concat fields ++ [L.pad 4 "}"])]

    defaultRecord a = ("/// The handlers of actor " ++ actorName a ++ ", from the adapters.") :
      L.binding 0 ("let " ++ escapeFSharp (camel (actorName a)) ++ ": LawSpec.Actors." ++ recordName a)
        (L.Record [(field d, L.A (adapterRef a d)) | d <- declarations a])

    -- Each message's argument and reply descriptors, with the data types they
    -- use; Nothing when a type has no descriptor (the actor stays local).
    wires a = either (const Nothing) Just $ do
      (table, hs) <- foldM (\(t, acc) h -> do
          (args, t') <- foldM (\(xs, tt) (_, ty) -> (\(x, tt') -> (xs ++ [x], tt')) <$> describe bits datas tt ty) ([], t) (handlerArguments h)
          (reply, t'') <- describe bits datas t' (maybe (C.Constructor "Unit" []) id (handlerReply h))
          pure (t'', acc ++ [(h, args, reply)])) ([], []) (actorHandlers a)
      let prefix = concatMap ((++ " ") . snd) (reverse table)
      pure [(h, map (prefix ++) args, prefix ++ reply) | (h, args, reply) <- hs]

    classOf native codec a = do
      let cls = actorClass a
          stateType = either (const "obj") id (native (actorState a))
          state = L.App ("unbox<" ++ stateType ++ ">") [L.A "state"]
          startArgs = actorStartArguments a
          startParams = [(argName p, t) | p@(_, t) <- startArgs, not (unitTy t)]
          startValues = [if unitTy t then L.A "()" else L.A (argName p) | p@(_, t) <- startArgs]
          startCall = awaited (actorStart a) (L.App ("handlers." ++ field (actorStart a)) (if null startValues then [L.A "()"] else startValues))
          restartCall = case actorRestart a of
            Just d -> L.Fun "state" (L.App "box" [awaited d (L.App ("handlers." ++ field d) [state])])
            Nothing -> L.Fun "_" (L.App "box" [startCall])
      startTypes <- mapM (native . snd) startParams
      methods <- forM (actorHandlers a) $ \h -> do
        args <- forM (handlerArguments h) $ \p@(_, t) -> (,) (argName p) <$> native t
        reply <- traverse native (handlerReply h)
        let d = handlerDeclaration h
            call = awaited d (L.App ("handlers." ++ field d) (state : map (L.A . fst) args))
            step = case reply of
              Just _ -> L.Fun "state" (L.Block [L.LetS "let pair" call] (L.A "box pair.First, box pair.Second"))
              Nothing -> L.Fun "state" (L.Tuple [L.App "box" [L.A "()"], L.App "box" [call]])
            params = "(" ++ intercalate ", " [n ++ ": " ++ t | (n, t) <- args] ++ ")"
            name = pascal (handlerName h)
        pure [ member' ("Sends " ++ handlerName h ++ " and waits for the reply.")
                 (L.function 4 ("member _." ++ name ++ params) [] (Just (maybe "unit" id reply))
                   (L.Infix "|>" (L.App "Actors.call" [L.A "handle", step]) (L.A (maybe "ignore" (\r -> "unbox<" ++ r ++ ">") reply))))
             , member' ("Sends " ++ handlerName h ++ " without waiting.")
                 (L.function 4 ("member _.Tell" ++ name ++ params) [] (Just "unit") (L.App "Actors.tell" [L.A "handle", step])) ]
      remote <- case wires a of
        Nothing -> pure ([], [])
        Just hs -> do
          entries <- forM hs $ \(h, args, reply) -> do
            argCodecs <- mapM (codec . snd) (handlerArguments h)
            replyCodec <- codec (maybe (C.Constructor "Unit" []) id (handlerReply h))
            let values = [converted c "toNative" (L.App "Runtime.item" [L.A (show i), L.A "arguments"]) | (i, c) <- zip [0 :: Int ..] argCodecs]
                invoke = converted replyCodec "fromNative" (L.Method ("this." ++ pascal (handlerName h)) values)
                signature body = L.Tuple [L.A (stringLiteral FSharp (handlerName h)), L.Record
                  [("Arguments", L.List (map (L.A . stringLiteral FSharp) args)), ("Result", L.A (stringLiteral FSharp reply)), ("Invoke", body)]]
            pure (signature (L.App "Some" [L.Fun "arguments" invoke]), signature (L.A "None"), (h, argCodecs, replyCodec))
          clientMethods <- forM [c | (_, _, c) <- entries] $ \(h, argCodecs, replyCodec) -> do
            args <- forM (handlerArguments h) $ \p@(_, t) -> (,) (argName p) <$> native t
            reply <- native (maybe (C.Constructor "Unit" []) id (handlerReply h))
            pure (L.function 4 ("member _." ++ pascal (handlerName h) ++ "(" ++ intercalate ", " [n ++ ": " ++ t | (n, t) <- args] ++ ")") [] (Just reply)
              (converted replyCodec "toNative" (L.App "Remote.call" [L.A "client", L.A (stringLiteral FSharp (handlerName h)),
                L.List [converted c "fromNative" (L.A n) | (c, (n, _)) <- zip argCodecs args]])))
          let served = member' "Lets other nodes call this actor at <node address>/name; that address."
                (L.function 4 "member this.Serve(node: Node, name: string)" [] (Just "string")
                  (L.App "Remote.serve" [L.A "node", L.A "name", L.A "\"call\"", L.List [s' | (s', _, _) <- entries]]))
              connect = member' "The actor served at address on another node; each call waits up to timeout ms."
                (L.function 4 "static member Connect(node: Node, address: string, timeout: System.TimeSpan)" [] (Just (cls ++ "Remote"))
                  (L.Method (cls ++ "Remote") [L.App "Remote.connect" [L.A "node", L.A "address", L.A "\"call\"", L.List [s' | (_, s', _) <- entries],
                    L.App "int" [L.A "timeout.TotalMilliseconds"]]]))
              connectDefault = member' "The actor served at address on another node; each call waits up to 5 seconds."
                (L.function 4 "static member Connect(node: Node, address: string)" [] (Just (cls ++ "Remote"))
                  (L.Method (cls ++ ".Connect") [L.A "node", L.A "address", L.App "System.TimeSpan.FromSeconds" [L.A "5.0"]]))
              client = ("/// Actor " ++ actorName a ++ " on another node: each method sends its message and waits for the reply.",
                ("[<Sealed>] " ++ cls ++ "Remote(client: RemoteClient) =") : L.separated clientMethods)
          pure ([served, connect, connectDefault], [client])
      let doc = "/// Actor " ++ actorName a ++ ": owns its state and handles one message at a time."
          header = "[<Sealed>] " ++ cls ++ " internal (handle: Actors.Handle, handlers: " ++ recordName a ++ ") ="
          startDeclaration = "(handlers: " ++ recordName a ++ concatMap (\((n, _), t) -> ", " ++ n ++ ": " ++ t) (zip startParams startTypes) ++ ")"
          members =
            [ member' "The runtime's spec of this actor, for a supervisor to start."
                (L.function 4 ("static member Spec" ++ startDeclaration) [] (Just "Actors.Spec")
                  (L.App "Actors.actor" [L.Fun "()" (L.App "box" [startCall]), restartCall]))
            , member' ("Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor.")
                (L.function 4 ("static member Start" ++ startDeclaration) [] (Just cls)
                  (L.Method cls [L.App "Actors.start" [L.Method (cls ++ ".Spec") (L.A "handlers" : map (L.A . fst) startParams)], L.A "handlers"]))
            , member' "The actor a supervisor started, by its handle."
                (L.function 4 ("static member FromHandle(handle: Actors.Handle, handlers: " ++ recordName a ++ ")") [] (Just cls)
                  (L.Method cls [L.A "handle", L.A "handlers"]))
            , member' "The runtime handle: stable across supervised restarts." [L.pad 4 "member _.Handle = handle"] ] ++
            concat methods ++
            [ member' "Crashes the actor as a failing handler would, after the messages already sent." [L.pad 4 "member _.Crash() : unit = Actors.crash handle"]
            , member' "Tells inbox about each crash, and once it stops." [L.pad 4 "member _.Monitor(inbox: Actors.Inbox) : unit = Actors.monitor handle inbox"]
            , member' "When either actor crashes, the other crashes too." [L.pad 4 "member _.Link(other: Actors.Handle) : unit = Actors.link handle other"]
            , member' "Refuses further messages; those already sent are still handled." [L.pad 4 "member _.Stop() : unit = Actors.stop handle"] ] ++ fst remote
      pure ((doc, header : L.separatedBy [""] members) : snd remote)

    -- The actors beneath a supervisor, each once: its Start takes their
    -- handlers records.
    beneath s = nubBy (\x y -> actorName x == actorName y) (concatMap child (supervisionChildren s))
      where child (_, _, ActorChild a) = [a]
            child (_, _, SupervisorChild cls) = concat [beneath s' | s' <- supervisors, supervisionClass s' == cls]
    handlersParam a = escapeFSharp (camel (actorName a)) ++ "Handlers"
    supervisorClass s = do
      let cls = supervisionClass s
          params = beneath s
          paramText = intercalate ", " [handlersParam a ++ ": " ++ recordName a | a <- params]
          childClass c = case c of ActorChild a -> actorClass a; SupervisorChild n -> n
          childArgs c = case c of
            ActorChild a -> [handlersParam a]
            SupervisorChild n -> [handlersParam a | s' <- supervisors, supervisionClass s' == n, a <- beneath s']
          strategy = case supervisionStrategy s of OneForOne -> "Actors.OneForOne"; OneForAll -> "Actors.OneForAll"; RestForOne -> "Actors.RestForOne"
          lifetime l = case l of Permanent -> "Actors.Permanent"; Transient -> "Actors.Transient"; Temporary -> "Actors.Temporary"
          childSpec (l, n, c) = L.Tuple [L.A (stringLiteral FSharp n), L.A (lifetime l), L.Method (childClass c ++ ".Spec") (map L.A (childArgs c))]
          children = supervisionChildren s
          header = "[<Sealed>] " ++ cls ++ " internal (handle: Actors.Handle" ++ concatMap (\(_, n, c) -> ", " ++ escapeFSharp (camel n) ++ ": " ++ childClass c) children ++ ") ="
      pure ("/// Supervisor " ++ supervisionName s ++ ": its children restart by its strategy, within its restart budget.",
        header : L.separatedBy [""] (
          [ member' "The runtime's spec of this supervisor and its children."
              (L.function 4 ("static member Spec(" ++ paramText ++ ")") [] (Just "Actors.Spec")
                (L.App "Actors.supervisor" [L.A strategy, L.A (show (supervisionRestarts s)), L.A (show (supervisionPeriod s) ++ "L"), L.List (map childSpec children)]))
          , member' "The supervisor a parent started, by its handle."
              (L.function 4 ("static member FromHandle(handle: Actors.Handle" ++ concatMap (", " ++) [handlersParam a ++ ": " ++ recordName a | a <- params] ++ ")") [] (Just cls)
                (L.Method cls (L.A "handle" : [L.Method (childClass c ++ ".FromHandle") (L.App "Actors.child" [L.A "handle", L.A (stringLiteral FSharp n)] : map L.A (childArgs c)) | (_, n, c) <- children])))
          , member' "Starts the supervisor and its children, in order."
              (L.function 4 ("static member Start(" ++ paramText ++ ")") [] (Just cls)
                (L.Method (cls ++ ".FromHandle") (L.App "Actors.start" [L.Method (cls ++ ".Spec") (map (L.A . handlersParam) params)] : map (L.A . handlersParam) params)))
          , [L.pad 4 "member _.Handle = handle"] ] ++
          [ member' ("Child " ++ n ++ ".") [L.pad 4 ("member _." ++ pascal n ++ " = " ++ escapeFSharp (camel n))] | (_, n, _) <- children ] ++
          [ member' "Tells inbox when it passes its restart limit, and once stopped." [L.pad 4 "member _.Monitor(inbox: Actors.Inbox) : unit = Actors.monitor handle inbox"]
          , member' "Stops every child, last started first, without restarting them." [L.pad 4 "member _.Stop() : unit = Actors.stop handle"] ]))

-- | For C#: each actor's handlers record made from the unit's C# adapters,
-- in LawSpec.Generated.ActorHandlers. C# has no compilation order, so an
-- adapter may start an actor with these. ref:DEC-csharp-over-fsharp
emitActorHandlersCs :: D.Layout -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitActorHandlersCs layout bits datas units
  | null actors = pure []
  | otherwise = do
      names <- dataNames datas
      let native = Data.nativeType CSharp bits names []
      properties <- forM actors $ \a -> do
        fields <- forM (actorStart a : map handlerDeclaration (actorHandlers a) ++ maybe [] pure (actorRestart a)) $ \d -> do
          let (ps, r) = C.functionType (C.declarationType d)
              params = if null ps then [C.Constructor "Unit" []] else ps
          pts <- mapM native params
          rt <- native r
          let isUnit t = t == C.Constructor "Unit" []
              names' = ["a" ++ show i | (i, _) <- zip [0 :: Int ..] params]
              call = unitQualified (C.unitId (actorUnit a)) ++ "." ++ functionName CSharp d ++
                "(" ++ intercalate ", " [n | (n, t) <- zip names' params, not (isUnit t)] ++ ")"
              result = if C.declarationAsync d then "System.Threading.Tasks.Task<" ++ rt ++ ">" else rt
              body = if isUnit r && not (C.declarationAsync d) then "{ " ++ call ++ "; return default(Unit); }" else call
          pure ("Fn.F" ++ show (length params) ++ "<" ++ intercalate ", " (pts ++ [result]) ++ ">((" ++
            intercalate ", " [t ++ " " ++ n | (t, n) <- zip pts names'] ++ ") => " ++ body ++ ")")
        pure (D.text ("/// <summary>The handlers of actor " ++ actorName a ++ ", from the adapters.</summary>") <> D.hardline <>
          D.text ("public static LawSpec.Actors." ++ actorClass a ++ "Handlers " ++ pascal (actorName a) ++ " =>") <> D.nest 4 (D.hardline <>
            D.text ("new LawSpec.Actors." ++ actorClass a ++ "Handlers(") <> D.nest 4 (D.hardline <>
              D.joinWith (D.text "," <> D.hardline) (map D.text fields)) <> D.text ");"))
      let doc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text "namespace LawSpec.Generated;" <> D.hardline <> D.hardline <>
            D.joinWith D.hardline (map D.text ["using System;", "using System.Numerics;", "using Microsoft.FSharp.Core;",
              "using Microsoft.FSharp.Collections;", "using LawSpec.CSharp;"]) <> D.hardline <> D.hardline <>
            D.text "/// <summary>Each actor's handlers record, made from the adapters.</summary>" <> D.hardline <>
            D.text "public static class ActorHandlers" <> D.hardline <>
            D.block 4 (D.joinWith (D.hardline <> D.hardline) properties) <> D.hardline
      pure [Artifact "src/LawSpec/ActorHandlers.cs" (D.render layout doc) "generated" "source"]
  where actors = concatMap actorsOf units
