-- | Typed channel ends for F# implementation code (see LawSpec.Sessions).
--
-- Every protocol P becomes a module LawSpec.Sessions.P: P.channel () makes a
-- channel and returns its two start ends, P.listen and P.dial give them over
-- a network (when every step has a wire form), and the nested modules
-- P.First (the end that follows the steps) and P.Second (sends and receives
-- swapped) hold a class per position, named for the step it takes next
-- (ReceiveInt32, SendInt64; the step number is appended when a name repeats)
-- and Done. Send returns the next end; Receive returns the value and the next
-- end, as a tuple. Each end is single use: the runtime refuses a spent one.
-- ref:DEC-sessions-by-construction ref:DEC-fsharp-runtime-from-scratch
module LawSpec.DotNet.Sessions (emitSessions) where

import qualified LawSpec.Core as C
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.MachineSpec (describe)
import LawSpec.DotNet.Code (stringLiteral, Lang(..))
import LawSpec.DotNet.Names
import qualified LawSpec.DotNet.Data as Data
import qualified LawSpec.DotNet.Layout as L
import Control.Monad (foldM, forM)
import Data.Char (isAlphaNum, toUpper)

data Step = Step { stepNumber :: Int, stepSends :: Bool, stepType :: C.Type }

emitSessions :: D.Layout -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitSessions layout bits datas units
  | null sessions = pure []
  | otherwise = do
      names <- dataNames datas
      let native = Data.nativeType FSharp bits names []
          codec = Data.codec FSharp bits names []
      modules <- mapM (protocolModule native codec) sessions
      let catalogue = ["/// Every protocol's steps, as the runtime checks them.", "module Protocols ="] ++
            L.separated
              [ L.pad 4 "/// The protocols an end may carry, by identity." :
                L.binding 4 "let catalogue: Map<string, SessionStep list>" (L.App "Map.ofList" [L.List (map protocolEntry sessions)])
              , L.pad 4 "/// A protocol's spec, with the network deadline of its ends." :
                L.function 4 "let spec" ["(id: string)"] (Just "SessionSpec")
                  (L.Record [("Id", L.A "id"), ("Protocols", L.A "catalogue"), ("Deadline", L.A "5000")]) ]
          text = unlines ([ "// Generated by LawSpec. Do not edit."
            , "/// Typed channel ends: for a protocol P, P.channel () makes a channel and"
            , "/// returns its two ends; P.First follows P's steps and P.Second does the"
            , "/// reverse. Each class is one end before one step: Send returns the end for"
            , "/// the next step and Receive returns the value and that end. After the last"
            , "/// step the end is a Done. An end can be used only once."
            , "namespace rec LawSpec.Sessions", "", "open LawSpec.Runtime", "" ] ++
            L.separatedBy [""] (catalogue : modules))
      pure [Artifact "src/LawSpec/Sessions.fs" text "generated" "source"]
  where
    sessions = concatMap C.unitSessions units
    sessionOf (C.Constructor n []) = case [s | s <- sessions, C.idText (C.sessionId s) == n] of
      s : _ -> Just s
      [] -> Nothing
    sessionOf _ = Nothing
    shortName n = maybe (reverse (takeWhile (\c -> c /= ':' && c /= '.') (reverse n))) id
      (lookup n [(C.idText (C.dataId d), C.dataName d) | d <- datas])
    capital s = case s of c : cs -> toUpper c : cs; [] -> s
    typeName t = case sessionOf t of
      Just other -> C.sessionName other
      Nothing -> case t of
        C.Constructor n args -> capital (filter isAlphaNum (shortName n)) ++ concat [typeName a | C.TypeArgument a <- args]
        C.TypeVariable _ -> "Value"
        C.Arrow _ _ -> "Function"
    endSteps first s = [Step k (if first then sends else not sends) t | (k, (sends, t)) <- zip [1 ..] (C.sessionSteps s)]
    classNames s ends = [base st ++ suffix st | st <- ends] ++ ["Done"]
      where
        bases = map base ends
        base st = (if stepSends st then "Send" else "Receive") ++ typeName (stepType st)
        suffix st
          | length (filter (== base st) bases) > 1 || base st == C.sessionName s = "Step" ++ show (stepNumber st)
          | otherwise = ""
    startOf s first = C.sessionName s ++ "." ++ (if first then "First" else "Second") ++ "." ++ head (classNames s (endSteps first s))
    -- A step's wire form, with the data types it uses written first; Nothing
    -- when it has none (the protocol then runs only within a process).
    wire ty = either (const Nothing) Just $ do
      (d, table) <- describe bits datas [] ty
      pure (concatMap ((++ " ") . snd) (reverse table) ++ d)
    protocolEntry s = L.Tuple [L.A (stringLiteral FSharp (C.idText (C.sessionId s))), L.List
      [ L.Record [("FirstSends", L.A (if sends then "true" else "false")), ("Part", case sessionOf ty of
          Just other -> L.App "EndPart" [L.A (stringLiteral FSharp (C.idText (C.sessionId other)))]
          Nothing -> L.App "ValuePart" [maybe (L.A "None") (\w -> L.App "Some" [L.A (stringLiteral FSharp w)]) (wire ty)])]
      | (sends, ty) <- C.sessionSteps s ]]
    -- A codec's conversion; one built by an expression goes through
    -- Codec.toNative or Codec.fromNative.
    converted c member x
      | take 1 c == "(" = "Codec." ++ member ++ " " ++ c ++ " " ++ x
      | otherwise = c ++ "." ++ (if member == "toNative" then "ToNative" else "FromNative") ++ " " ++ x
    protocolModule native codec s = do
      first <- endModule native codec s True
      second <- endModule native codec s False
      let name = C.sessionName s
          identity = stringLiteral FSharp (C.idText (C.sessionId s))
          firstStart = startOf s True
          secondStart = startOf s False
      pure (["/// Protocol " ++ name ++ " (" ++ C.idText (C.sessionId s) ++ ").", "[<RequireQualifiedAccess>]", "module " ++ name ++ " ="] ++
        L.separatedBy [""]
          [ map (L.pad 4) ["/// The protocol, as the runtime runs it.", "[<CompiledName(\"Spec\")>]"] ++
            L.binding 4 "let spec: SessionSpec" (L.App "Protocols.spec" [L.A identity])
          , map (L.pad 4) ["/// A new channel's two ends, in this process.", "[<CompiledName(\"Channel\")>]"] ++
            L.function 4 "let channel" ["()"] (Just (firstStart ++ " * " ++ secondStart))
              (L.Block [L.LetS "let first, second" (L.App "Sessions.openPair" [L.A "spec"])] (L.A (firstStart ++ "(first), " ++ secondStart ++ "(second)")))
          , map (L.pad 4) ["/// The first end, listening at name on a node; its address is Address.", "[<CompiledName(\"Listen\")>]"] ++
            L.function 4 "let listen" ["(node: Node)", "(name: string)"] (Just firstStart)
              (L.Method firstStart [L.App "Sessions.listen" [L.A "node", L.A "name", L.A "spec"]])
          , map (L.pad 4) ["/// The second end, dialling a listening first end's address.", "[<CompiledName(\"Dial\")>]"] ++
            L.function 4 "let dial" ["(node: Node)", "(address: string)"] (Just secondStart)
              (L.Method secondStart [L.App "Sessions.dial" [L.A "node", L.A "address", L.A "spec"]])
          , first, second ])
    endModule native codec s isFirst = do
      let ends = endSteps isFirst s
          classes = classNames s ends
      steps <- forM (zip3 ends classes (drop 1 classes)) $ \(st, cls, next) -> do
        body <- case sessionOf (stepType st) of
          Just other -> do
            let carried = startOf other True
            pure $ if stepSends st
              then L.pad 12 ("/// Sends an unused first end of " ++ C.sessionName other ++ "; the next end.") :
                L.function 12 ("member _.Send(value: " ++ carried ++ ")") [] (Just next) (L.Method next [L.App "Sessions.sendEnd" [L.A "e", L.A "value.End"]])
              else L.pad 12 ("/// Receives a first end of " ++ C.sessionName other ++ "; it and the next end.") :
                L.function 12 "member _.Receive()" [] (Just (carried ++ " * " ++ next))
                  (L.Block [L.LetS "let value, rest" (L.App "Sessions.receiveEnd" [L.A "e"])] (L.A (carried ++ "(value), " ++ next ++ "(rest)")))
          Nothing -> do
            t <- native (stepType st)
            c <- codec (stepType st)
            pure $ if stepSends st
              then L.pad 12 "/// Sends a value; the next end." :
                L.function 12 ("member _.Send(value: " ++ t ++ ")") [] (Just next) (L.Method next [L.App "Sessions.send" [L.A "e", L.A (converted c "fromNative" "value")]])
              else L.pad 12 "/// Receives a value; it and the next end." :
                L.function 12 "member _.Receive()" [] (Just (t ++ " * " ++ next))
                  (L.Block [L.LetS "let value, rest" (L.App "Sessions.receiveValue" [L.A "e"])] (L.A (converted c "toNative" "value" ++ ", " ++ next ++ "(rest)")))
        pure (endClass cls ("step " ++ show (stepNumber st)) body)
      let done = endClass "Done" "after the last step" (L.pad 12 "/// Gives up the end." :
            L.function 12 "member _.Close()" [] (Just "unit") (L.App "Sessions.abandon" [L.A "e"]))
      pure ([L.pad 4 ("/// " ++ (if isFirst then "The first end: it follows the steps." else "The second end: it does the reverse.")),
        L.pad 4 ("module " ++ (if isFirst then "First" else "Second") ++ " =")] ++ L.separatedBy [""] (steps ++ [done]))
    endClass cls position body =
      map (L.pad 8) ["/// The end before " ++ position ++ ".", "[<Sealed>]", "type " ++ cls ++ " internal (e: SessionEnd) ="] ++
      map (L.pad 12) ["/// The runtime's end.", "member _.End = e", "/// The address a network end is reached at.", "member _.Address = Sessions.address e"] ++
      [""] ++ body
