-- | Typed channel ends for F# implementation code (see LawSpec.Sessions).
--
-- Every protocol P becomes a module LawSpec.Sessions.P: P.channel () makes a
-- channel and returns its two start ends, P.listen and P.dial give them over
-- a network (when every step has a wire form), and the nested modules
-- P.First (the end that follows the steps) and P.Second (sends and receives
-- swapped) hold a class per position, named for the step it takes next
-- (ReceiveInt32, SendInt64; the step number is appended when a name repeats)
-- and Done. Send returns the next end; Receive returns the value and the next
-- end, as a tuple. Each end is single use: the runtime refuses a spent one.
-- ref:DEC-session-types ref:DEC-fsharp-runtime-from-scratch
module LawSpec.DotNet.Sessions (emitSessions) where

import qualified LawSpec.Core as C
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.MachineSpec (describe)
import LawSpec.DotNet.Code (stringLiteral, Lang(..))
import LawSpec.DotNet.Names
import qualified LawSpec.DotNet.Data as Data
import Control.Monad (foldM, forM)
import Data.Char (isAlphaNum, toUpper)

data Step = Step { stepNumber :: Int, stepSends :: Bool, stepType :: C.Type }

emitSessions :: D.Layout -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitSessions layout bits datas units
  | null sessions = pure []
  | otherwise = do
      names <- dataNames datas
      let native = Data.nativeType FSharp bits names []
          codec = Data.codec FSharp bits names []
      modules <- mapM (protocolModule native codec) sessions
      let catalogue = D.text "/// Every protocol's steps, as the runtime checks them." <> D.hardline <>
            D.text "module Protocols =" <> D.nest 4 (D.hardline <>
              D.text "/// The protocols an end may carry, by identity." <> D.hardline <>
              D.text "let catalogue : Map<string, SessionStep list> =" <> D.nest 4 (D.hardline <>
                D.text "Map.ofList" <> D.nest 4 (D.hardline <> D.text "[ " <>
                  D.joinWith (D.hardline <> D.text "  ") (map protocolEntry sessions) <> D.text " ]")) <> D.hardline <> D.hardline <>
              D.text "/// A protocol's spec, with the network deadline of its ends." <> D.hardline <>
              D.text "let spec (id: string) : SessionSpec = { Id = id; Protocols = catalogue; Deadline = 5000 }")
          doc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
            D.text "/// Typed channel ends: for a protocol P, P.channel () makes a channel and" <> D.hardline <>
            D.text "/// returns its two ends; P.First follows P's steps and P.Second does the" <> D.hardline <>
            D.text "/// reverse. Each class is one end before one step: Send returns the end for" <> D.hardline <>
            D.text "/// the next step and Receive returns the value and that end. After the last" <> D.hardline <>
            D.text "/// step the end is a Done. An end can be used only once." <> D.hardline <>
            D.text "namespace rec LawSpec.Sessions" <> D.hardline <> D.hardline <>
            D.text "open LawSpec.Runtime" <> D.hardline <> D.hardline <>
            D.joinWith (D.hardline <> D.hardline) (catalogue : modules) <> D.hardline
      pure [Artifact "src/LawSpec/Sessions.fs" (D.render layout doc) "generated" "source"]
  where
    sessions = concatMap C.unitSessions units
    sessionOf (C.Constructor n []) = case [s | s <- sessions, C.idText (C.sessionId s) == n] of
      s : _ -> Just s
      [] -> Nothing
    sessionOf _ = Nothing
    shortName n = maybe (reverse (takeWhile (\c -> c /= ':' && c /= '.') (reverse n))) id
      (lookup n [(C.idText (C.dataId d), C.dataName d) | d <- datas])
    capital s = case s of c : cs -> toUpper c : cs; [] -> s
    typeName t = case sessionOf t of
      Just other -> C.sessionName other
      Nothing -> case t of
        C.Constructor n args -> capital (filter isAlphaNum (shortName n)) ++ concat [typeName a | C.TypeArgument a <- args]
        C.TypeVariable _ -> "Value"
        C.Arrow _ _ -> "Function"
    endSteps first s = [Step k (if first then sends else not sends) t | (k, (sends, t)) <- zip [1 ..] (C.sessionSteps s)]
    classNames s ends = [base st ++ suffix st | st <- ends] ++ ["Done"]
      where
        bases = map base ends
        base st = (if stepSends st then "Send" else "Receive") ++ typeName (stepType st)
        suffix st
          | length (filter (== base st) bases) > 1 || base st == C.sessionName s = "Step" ++ show (stepNumber st)
          | otherwise = ""
    startOf s first = C.sessionName s ++ "." ++ (if first then "First" else "Second") ++ "." ++ head (classNames s (endSteps first s))
    -- A step's wire form, with the data types it uses written first; Nothing
    -- when it has none (the protocol then runs only within a process).
    wire ty = either (const Nothing) Just $ do
      (d, table) <- describe bits datas [] ty
      pure (concatMap ((++ " ") . snd) (reverse table) ++ d)
    protocolEntry s = D.text ("(" ++ stringLiteral FSharp (C.idText (C.sessionId s)) ++ ", [ " ++
      concatMap (\(i, (sends, ty)) -> (if i > (0 :: Int) then "; " else "") ++ "{ FirstSends = " ++ (if sends then "true" else "false") ++ "; Part = " ++
        (case sessionOf ty of
          Just other -> "EndPart " ++ stringLiteral FSharp (C.idText (C.sessionId other))
          Nothing -> "ValuePart " ++ maybe "None" (\w -> "(Some " ++ stringLiteral FSharp w ++ ")") (wire ty)) ++ " }")
        (zip [0 ..] (C.sessionSteps s)) ++ " ])")
    protocolModule native codec s = do
      first <- endModule native codec s True
      second <- endModule native codec s False
      let name = C.sessionName s
          identity = stringLiteral FSharp (C.idText (C.sessionId s))
          firstStart = startOf s True
          secondStart = startOf s False
      pure (D.text ("/// Protocol " ++ name ++ " (" ++ C.idText (C.sessionId s) ++ ").") <> D.hardline <>
        D.text "[<RequireQualifiedAccess>]" <> D.hardline <>
        D.text ("module " ++ name ++ " =") <> D.nest 4 (D.hardline <> D.joinWith (D.hardline <> D.hardline)
          [ D.text "/// The protocol, as the runtime runs it." <> D.hardline <>
            D.text ("let spec : SessionSpec = Protocols.spec " ++ identity)
          , D.text "/// A new channel's two ends, in this process." <> D.hardline <>
            D.text ("let channel () : " ++ firstStart ++ " * " ++ secondStart ++ " =") <> D.nest 4 (D.hardline <>
              D.text "let first, second = Sessions.openPair spec" <> D.hardline <>
              D.text (firstStart ++ "(first), " ++ secondStart ++ "(second)"))
          , D.text "/// The first end, listening at name on a node; its address is Address." <> D.hardline <>
            D.text ("let listen (node: Node) (name: string) : " ++ firstStart ++ " = " ++ firstStart ++ "(Sessions.listen node name spec)")
          , D.text "/// The second end, dialling a listening first end's address." <> D.hardline <>
            D.text ("let dial (node: Node) (address: string) : " ++ secondStart ++ " = " ++ secondStart ++ "(Sessions.dial node address spec)")
          , first, second ]))
    endModule native codec s isFirst = do
      let ends = endSteps isFirst s
          classes = classNames s ends
      steps <- forM (zip3 ends classes (drop 1 classes)) $ \(st, cls, next) -> do
        body <- case sessionOf (stepType st) of
          Just other -> do
            let carried = startOf other True
            pure $ if stepSends st
              then D.text ("/// Sends an unused first end of " ++ C.sessionName other ++ "; the next end.") <> D.hardline <>
                D.text ("member _.Send(value: " ++ carried ++ ") : " ++ next ++ " = " ++ next ++ "(Sessions.sendEnd e value.End)")
              else D.text ("/// Receives a first end of " ++ C.sessionName other ++ "; it and the next end.") <> D.hardline <>
                D.text ("member _.Receive() : " ++ carried ++ " * " ++ next ++ " =") <> D.nest 4 (D.hardline <>
                  D.text "let value, rest = Sessions.receiveEnd e" <> D.hardline <>
                  D.text (carried ++ "(value), " ++ next ++ "(rest)"))
          Nothing -> do
            t <- native (stepType st)
            c <- codec (stepType st)
            pure $ if stepSends st
              then D.text "/// Sends a value; the next end." <> D.hardline <>
                D.text ("member _.Send(value: " ++ t ++ ") : " ++ next ++ " = " ++ next ++ "(Sessions.send e (" ++ c ++ ".FromNative value))")
              else D.text "/// Receives a value; it and the next end." <> D.hardline <>
                D.text ("member _.Receive() : " ++ t ++ " * " ++ next ++ " =") <> D.nest 4 (D.hardline <>
                  D.text "let value, rest = Sessions.receiveValue e" <> D.hardline <>
                  D.text (c ++ ".ToNative value, " ++ next ++ "(rest)"))
        pure (endClass cls ("step " ++ show (stepNumber st)) body)
      let done = endClass "Done" "after the last step" (D.text "/// Gives up the end." <> D.hardline <> D.text "member _.Close() : unit = Sessions.abandon e")
      pure (D.text ("/// " ++ (if isFirst then "The first end: it follows the steps." else "The second end: it does the reverse.")) <> D.hardline <>
        D.text ("module " ++ (if isFirst then "First" else "Second") ++ " =") <> D.nest 4 (D.hardline <>
          D.joinWith (D.hardline <> D.hardline) (steps ++ [done])))
    endClass cls position body =
      D.text ("/// The end before " ++ position ++ ".") <> D.hardline <>
      D.text "[<Sealed>]" <> D.hardline <> D.text ("type " ++ cls ++ " internal (e: SessionEnd) =") <> D.nest 4 (D.hardline <>
        D.text "/// The runtime's end." <> D.hardline <> D.text "member _.End = e" <> D.hardline <>
        D.text "/// The address a network end is reached at." <> D.hardline <> D.text "member _.Address = Sessions.address e" <> D.hardline <> D.hardline <> body)
