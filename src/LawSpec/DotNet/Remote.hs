-- | Remote evaluation on .NET (see LawSpec.Remote): LawSpec.RemoteDefinitions
-- serves the program's checked definitions on a node, by content hash, and
-- evaluates one on another node. It compiles before the adapters, so an
-- adapter can use it; the functions it runs live in
-- LawSpec.Generated.RemoteInvoke, compiled after the entries they call, and
-- are found once by name. ref:DEC-distribution-canonical-wire
module LawSpec.DotNet.Remote (emitRemote) where

import qualified LawSpec.Core as C
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.Remote (Remote(..), remoteManifest)
import LawSpec.Testing (Plan)
import LawSpec.DotNet.Code (stringLiteral, Lang(..))
import LawSpec.DotNet.Entries
import Data.List (intercalate)

-- | The serving module (before the adapters) and the invoking one (after
-- every entry).
emitRemote :: Lang -> D.Layout -> [C.Unit] -> Plan -> ([Artifact], [Artifact])
emitRemote CSharp layout units plan
  | null callable = ([], [])
  | otherwise = (early, [Artifact "src/LawSpec/RemoteInvoke.cs" (D.render layout doc) "generated" "source"])
  where
    (early, _) = emitRemote FSharp layout units plan
    (_, remotes) = remoteManifest plan
    callable = [(r, e) | r <- remotes, Just e <- [lookup (remoteId r) (entries units)]]
    doc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
      D.text "namespace LawSpec.Generated;" <> D.hardline <> D.hardline <>
      D.text "using System;" <> D.hardline <> D.text "using Microsoft.FSharp.Core;" <> D.hardline <>
      D.text "using Microsoft.FSharp.Collections;" <> D.hardline <> D.text "using LawSpec.Runtime;" <> D.hardline <>
      D.text "using LawSpec.CSharp;" <> D.hardline <> D.text "using Runtime = LawSpec.Runtime.Runtime;" <> D.hardline <>
      D.text "using Value = LawSpec.Runtime.Value;" <> D.hardline <> D.hardline <>
      D.text "/// <summary>How each remotely evaluable definition runs: its checked entry.</summary>" <> D.hardline <>
      D.text "public static class RemoteInvoke" <> D.hardline <>
      D.block 4 (D.text "public static FSharpList<Tuple<string, FSharpFunc<FSharpList<Value>, Value>>> Invokers =>" <> D.nest 4 (D.hardline <>
        D.text "Fn.List(" <> D.joinWith (D.text "," <> D.hardline <> D.text "    ")
          [ D.text ("Fn.Tuple(" ++ stringLiteral CSharp (remoteName r) ++ ", Fn.F1((FSharpList<Value> arguments) => " ++ entryModule e ++ "." ++ entryCs e ++
              "(" ++ intercalate ", " (["LawSpec.Generated.Program.Schema", "new Scalar.SymbolContext()"] ++
                ["Runtime.Item(" ++ show i ++ ", arguments)" | i <- [0 .. length (remoteArguments r) - 1]]) ++ ")))")
          | (r, e) <- callable ] <> D.text ");")) <> D.hardline
emitRemote FSharp layout units plan
  | null callable = ([], [])
  | otherwise = ([Artifact "src/LawSpec/RemoteDefinitions.fs" (D.render layout early) "generated" "source"],
                 [Artifact "src/LawSpec/RemoteInvoke.fs" (D.render layout late) "generated" "source"])
  where
    (forms, remotes) = remoteManifest plan
    prefix = concatMap (++ " ") forms
    callable = [(r, e) | r <- remotes, Just e <- [lookup (remoteId r) (entries units)]]
    quote = stringLiteral FSharp
    early = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
      D.text "/// Checked definitions other nodes can evaluate, by content hash: serve lets" <> D.hardline <>
      D.text "/// them run on a node, and evaluate runs one on the node at an address." <> D.hardline <>
      D.text "/// Values are portable values, as the runtime's checks use them." <> D.hardline <>
      D.text "module LawSpec.RemoteDefinitions" <> D.hardline <> D.hardline <>
      D.text "open LawSpec.Runtime" <> D.hardline <> D.hardline <>
      D.joinWith (D.hardline <> D.hardline)
        [ D.text "/// Each definition's qualified name, content hash and wire forms." <> D.hardline <>
          D.text "let private signatures : (string * string * string list * string) list =" <> D.nest 4 (D.hardline <>
            D.text "[ " <> D.joinWith (D.hardline <> D.text "  ")
              [ D.text ("(" ++ quote (remoteName r) ++ ", " ++ quote (remoteDigest r) ++ ", [ " ++
                  foldr1' "; " (map (quote . (prefix ++)) (remoteArguments r)) ++ " ], " ++ quote (prefix ++ remoteResult r) ++ ")")
              | (r, _) <- callable ] <> D.text " ]")
        , D.text "/// The functions that evaluate each definition, by name: in" <> D.hardline <>
          D.text "/// LawSpec.Generated.RemoteInvoke, which compiles after the entries." <> D.hardline <>
          D.text "let private invokers : Lazy<Map<string, Value list -> Value>> =" <> D.nest 4 (D.hardline <>
            D.text "lazy" <> D.nest 4 (D.hardline <>
              D.text "let owner =" <> D.nest 4 (D.hardline <>
                D.text "System.AppDomain.CurrentDomain.GetAssemblies()" <> D.hardline <>
                D.text "|> Array.pick (fun assembly -> Option.ofObj (assembly.GetType \"LawSpec.Generated.RemoteInvoke\"))") <> D.hardline <>
              D.text "let property = match owner.GetProperty \"invokers\" with null -> owner.GetProperty \"Invokers\" | p -> p" <> D.hardline <>
              D.text "let table = property.GetValue(null)" <> D.hardline <>
              D.text "Map.ofList (table :?> (string * (Value list -> Value)) list)"))
        , D.text "/// The content hash of the definition with this qualified name." <> D.hardline <>
          D.text "[<CompiledName(\"Digest\")>]" <> D.hardline <> D.text "let digest (name: string) : string =" <> D.nest 4 (D.hardline <>
            D.text "match signatures |> List.tryFind (fun (n, _, _, _) -> n = name) with" <> D.hardline <>
            D.text "| Some(_, hash, _, _) -> hash" <> D.hardline <>
            D.text "| None -> Fail.raiseWith \"Remote\" (\"unknown definition \" + name)")
        , D.text "/// Lets other nodes evaluate these definitions on node; the address they are served at." <> D.hardline <>
          D.text "[<CompiledName(\"Serve\")>]" <> D.hardline <> D.text "let serve (node: Node) : string =" <> D.nest 4 (D.hardline <>
            D.text "Remote.serve node \"definitions\" \"eval\"" <> D.nest 4 (D.hardline <>
              D.text "[ for name, hash, arguments, result in signatures ->" <> D.nest 6 (D.hardline <>
                D.text "hash, { Arguments = arguments; Result = result; Invoke = Some invokers.Value.[name] } ]")))
        , D.text "/// Evaluates the named definition on the node at address, by its content" <> D.hardline <>
          D.text "/// hash; fails when that node does not answer within timeout (5s by default)." <> D.hardline <>
          D.text "[<CompiledName(\"EvaluateWithin\")>]" <> D.hardline <> D.text "let evaluateWithin (node: Node) (address: string) (name: string) (timeout: System.TimeSpan) (arguments: Value list) : Value =" <> D.nest 4 (D.hardline <>
            D.text "match signatures |> List.tryFind (fun (n, _, _, _) -> n = name) with" <> D.hardline <>
            D.text "| Some(_, hash, types, result) ->" <> D.nest 4 (D.hardline <>
              D.text "let client = Remote.connect node (address + \"/definitions\") \"eval\" [ hash, { Arguments = types; Result = result; Invoke = None } ] (int timeout.TotalMilliseconds)" <> D.hardline <>
              D.text "Remote.call client hash arguments") <> D.hardline <>
            D.text "| None -> Fail.raiseWith \"Remote\" (\"unknown definition \" + name)")
        , D.text "/// As evaluateWithin, waiting up to 5 seconds." <> D.hardline <>
          D.text "[<CompiledName(\"Evaluate\")>]" <> D.hardline <> D.text "let evaluate (node: Node) (address: string) (name: string) (arguments: Value list) : Value =" <> D.nest 4 (D.hardline <>
            D.text "evaluateWithin node address name (System.TimeSpan.FromSeconds 5.0) arguments") ] <> D.hardline
    late = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
      D.text "/// How each remotely evaluable definition runs: its checked entry." <> D.hardline <>
      D.text "module LawSpec.Generated.RemoteInvoke" <> D.hardline <> D.hardline <>
      D.text "open LawSpec.Runtime" <> D.hardline <> D.hardline <>
      D.text "let invokers : (string * (Value list -> Value)) list =" <> D.nest 4 (D.hardline <>
        D.text "[ " <> D.joinWith (D.hardline <> D.text "  ")
          [ D.text ("(" ++ quote (remoteName r) ++ ", fun arguments -> " ++ entryModule e ++ "." ++ entryFs e ++
              " LawSpec.Generated.Program.schema (Scalar.SymbolContext())" ++
              concat [" (Runtime.item " ++ show i ++ " arguments)" | i <- [0 .. length (remoteArguments r) - 1]] ++ ")")
          | (r, e) <- callable ] <> D.text " ]") <> D.hardline
    foldr1' sep xs = case xs of [] -> ""; _ -> foldr1 (\a b -> a ++ sep ++ b) xs
