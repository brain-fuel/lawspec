-- | Remote evaluation on .NET (see LawSpec.Remote): LawSpec.RemoteDefinitions
-- serves the program's checked definitions on a node, by content hash, and
-- evaluates one on another node. It compiles before the adapters, so an
-- adapter can use it; the functions it runs live in
-- LawSpec.Generated.RemoteInvoke, compiled after the entries they call, and
-- are found once by name. ref:DEC-distribution-canonical-wire
module LawSpec.DotNet.Remote (emitRemote) where

import qualified LawSpec.Core as C
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.Remote (Remote(..), remoteManifest)
import LawSpec.Testing (Plan)
import LawSpec.DotNet.Code (stringLiteral, Lang(..))
import LawSpec.DotNet.Entries
import qualified LawSpec.DotNet.Layout as L
import Data.List (intercalate)

-- | The serving module (before the adapters) and the invoking one (after
-- every entry).
emitRemote :: Lang -> D.Layout -> [C.Unit] -> Plan -> ([Artifact], [Artifact])
emitRemote CSharp layout units plan
  | null callable = ([], [])
  | otherwise = (early, [Artifact "src/LawSpec/RemoteInvoke.cs" (D.render layout doc) "generated" "source"])
  where
    (early, _) = emitRemote FSharp layout units plan
    (_, remotes) = remoteManifest plan
    callable = [(r, e) | r <- remotes, Just e <- [lookup (remoteId r) (entries units)]]
    doc = D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
      D.text "namespace LawSpec.Generated;" <> D.hardline <> D.hardline <>
      D.text "using System;" <> D.hardline <> D.text "using Microsoft.FSharp.Core;" <> D.hardline <>
      D.text "using Microsoft.FSharp.Collections;" <> D.hardline <> D.text "using LawSpec.Runtime;" <> D.hardline <>
      D.text "using LawSpec.CSharp;" <> D.hardline <> D.text "using Runtime = LawSpec.Runtime.Runtime;" <> D.hardline <>
      D.text "using Value = LawSpec.Runtime.Value;" <> D.hardline <> D.hardline <>
      D.text "/// <summary>How each remotely evaluable definition runs: its checked entry.</summary>" <> D.hardline <>
      D.text "public static class RemoteInvoke" <> D.hardline <>
      D.block 2 (D.text "public static FSharpList<Tuple<string, FSharpFunc<FSharpList<Value>, Value>>> Invokers =>" <> D.nest 4 (D.hardline <>
        D.text "Fn.List(" <> D.joinWith (D.text "," <> D.hardline <> D.text "    ")
          [ D.text ("Fn.Tuple(" ++ stringLiteral CSharp (remoteName r) ++ ", Fn.F1((FSharpList<Value> arguments) => " ++ entryModule e ++ "." ++ entryCs e ++
              "(" ++ intercalate ", " (["LawSpec.Generated.Program.Schema", "new Scalar.SymbolContext()"] ++
                ["Runtime.Item(" ++ show i ++ ", arguments)" | i <- [0 .. length (remoteArguments r) - 1]]) ++ ")))")
          | (r, e) <- callable ] <> D.text ");")) <> D.hardline
emitRemote FSharp _ units plan
  | null callable = ([], [])
  | otherwise = ([Artifact "src/LawSpec/RemoteDefinitions.fs" early "generated" "source"],
                 [Artifact "src/LawSpec/RemoteInvoke.fs" late "generated" "source"])
  where
    (forms, remotes) = remoteManifest plan
    prefix = concatMap (++ " ") forms
    callable = [(r, e) | r <- remotes, Just e <- [lookup (remoteId r) (entries units)]]
    quote = stringLiteral FSharp
    -- Serving and evaluating are the runtime's (Remote); the module holds
    -- the program's signatures.
    early = unlines (
      [ "// Generated by LawSpec. Do not edit."
      , "/// Checked definitions other nodes can evaluate, by content hash: serve lets"
      , "/// them run on a node, and evaluate runs one on the node at an address."
      , "/// Values are portable values, as the runtime's checks use them."
      , "module LawSpec.RemoteDefinitions", "", "open LawSpec.Runtime", "" ] ++
      L.separatedBy [""]
        [ "/// Each definition's qualified name, content hash and wire forms." :
          L.binding 0 "let private signatures: Remote.DefinitionSignature list"
            (L.List [ L.Tuple [L.A (quote (remoteName r)), L.A (quote (remoteDigest r)), L.List (map (L.A . quote . (prefix ++)) (remoteArguments r)),
                L.A (quote (prefix ++ remoteResult r))] | (r, _) <- callable ])
        , [ "/// The functions that evaluate each definition, by name."
          , "let private invokers = Remote.definitionInvokers ()" ]
        , [ "/// The content hash of the definition with this qualified name.", "[<CompiledName(\"Digest\")>]" ] ++
          L.function 0 "let digest" ["(name: string)"] (Just "string") (L.App "Remote.definitionDigest" [L.A "signatures", L.A "name"])
        , [ "/// Lets other nodes evaluate these definitions on node; the address they are served at.", "[<CompiledName(\"Serve\")>]" ] ++
          L.function 0 "let serve" ["(node: Node)"] (Just "string") (L.App "Remote.serveDefinitions" [L.A "node", L.A "signatures", L.A "invokers"])
        , [ "/// Evaluates the named definition on the node at address, by its content"
          , "/// hash; fails when that node does not answer within timeout (5s by default)."
          , "[<CompiledName(\"EvaluateWithin\")>]" ] ++
          L.function 0 "let evaluateWithin" ["(node: Node)", "(address: string)", "(name: string)", "(timeout: System.TimeSpan)", "(arguments: Value list)"] (Just "Value")
            (L.App "Remote.evaluateDefinition" (map L.A ["node", "signatures", "address", "name", "timeout", "arguments"]))
        , [ "/// As evaluateWithin, waiting up to 5 seconds.", "[<CompiledName(\"Evaluate\")>]" ] ++
          L.function 0 "let evaluate" ["(node: Node)", "(address: string)", "(name: string)", "(arguments: Value list)"] (Just "Value")
            (L.App "evaluateWithin" [L.A "node", L.A "address", L.A "name", L.App "System.TimeSpan.FromSeconds" [L.A "5.0"], L.A "arguments"]) ])
    late = unlines (
      [ "// Generated by LawSpec. Do not edit."
      , "/// How each remotely evaluable definition runs: its checked entry."
      , "module LawSpec.Generated.RemoteInvoke", "", "open LawSpec.Runtime", "" ] ++
      L.binding 0 "let invokers: (string * (Value list -> Value)) list"
        (L.List [ L.Tuple [L.A (quote (remoteName r)), L.Fun "arguments" (L.App (entryModule e ++ "." ++ entryFs e)
            ([L.A "LawSpec.Generated.Program.schema", L.A "(Scalar.SymbolContext())"] ++
              [L.App "Runtime.item" [L.A (show i), L.A "arguments"] | i <- [0 .. length (remoteArguments r) - 1]]))]
          | (r, e) <- callable ]))
