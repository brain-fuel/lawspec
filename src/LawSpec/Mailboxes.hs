-- Typed mailboxes for implementation code. Every `mailbox jobs of Job`
-- becomes, on each target, a mailbox type named JobsMailbox: send never
-- waits, one receiver takes messages in the order they arrived, and close
-- refuses later sends. A mailbox can also be offered on a node (serve) and
-- sent to from other nodes (connect); a send between nodes waits until the
-- mailbox has the message, and runs once however often it is resent.
module LawSpec.Mailboxes (mailboxArtifacts, mailboxClassName) where

import Data.Char (toUpper)
import Data.List (intercalate, nub)
import qualified LawSpec.Code.Doc as D
import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..), Diagnostic(..))
import LawSpec.MachineSpec (describe)
import LawSpec.PythonData (pythonTypeReferenceDoc, requiresSchema)
import LawSpec.PythonTypes (pythonDataTypeDoc)
import LawSpec.Testing (Plan(..), PlannedUnit(..))
import qualified LawSpec.GoData as GoData
import qualified LawSpec.WebTypes as Web

-- jobs's class is JobsMailbox.
mailboxClassName :: String -> String
mailboxClassName n = case n of
  c : cs -> toUpper c : cs ++ "Mailbox"
  [] -> "Mailbox"

mailboxArtifacts :: String -> Plan -> Either [Diagnostic] [Artifact]
mailboxArtifacts target plan = case concatMap C.unitMailboxes units of
  [] -> Right []
  boxes -> either (\message -> Left [Diagnostic "mailboxes" message Nothing]) Right $ case target of
    "python" -> python bits datas boxes
    "go" -> concat <$> mapM (\u -> goMailboxes bits datas (C.idText (C.unitId u)) (C.unitMailboxes u)) [u | u <- units, not (null (C.unitMailboxes u))]
    "javascript" -> web False bits datas boxes
    "typescript" -> web True bits datas boxes
    _ -> Right []
  where
    units = map plannedUnit (plannedUnits plan)
    datas = planDataDeclarations plan
    bits = planMachineBits plan

python :: Int -> [C.DataDeclaration] -> [C.Mailbox] -> Either String [Artifact]
python bits datas boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, classes) <- foldl (\acc b -> do
      (t, cs) <- acc
      native <- D.render (D.Pretty 1000) <$> pythonDataTypeDoc datas (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', cs ++ [cls b native (Just d)])
        Left _ -> pure (t, cs ++ [cls b native (Nothing :: Maybe String)])) (Right ([], [])) boxes
  let header =
        [ "# Generated by LawSpec. Do not edit."
        , "\"\"\"Typed mailboxes: many senders, one receiver."
        , ""
        , "send never waits; receive takes messages in the order they arrived;"
        , "close refuses later sends. serve(node, name) offers a mailbox to other"
        , "nodes, and connect(node, address) sends to one from another node: such a"
        , "send waits until the mailbox has the message, and it is delivered once."
        , "\"\"\""
        , "from __future__ import annotations"
        , ""
        , "import builtins as _builtins"
        , "import lawspec_runtime as ls"
        , "try:"
        , "    import lawspec_data as data"
        , "    import lawspec_schema as _schema"
        , "    _SCHEMA = data.make_schema()"
        , "except ImportError:"
        , "    _SCHEMA = None"
        , ""
        , "_TYPES = ls.Values({str(f[1]): f for f in ls.read_descriptor(" ++ show (unwords (map snd (reverse table))) ++ ")})"
        , ""
        , ""
        , "def _native(reference, value):"
        , "    return value if reference is None else _SCHEMA.to_native(reference, value)"
        , ""
        , ""
        , "def _logical(reference, value):"
        , "    return value if reference is None else _SCHEMA.from_native(reference, value)" ]
  pure [Artifact "src/lawspec_mailboxes.py" (unlines header ++ concatMap ("\n\n" ++) classes) "generated" "source"]
  where
    reference ty = if requiresSchema datas ty then either (const "None") (D.render (D.Pretty 1000)) (pythonTypeReferenceDoc ty) else "None"
    cls b native wire = unlines $
      [ "class " ++ name ++ ":"
      , "    \"\"\"Mailbox " ++ C.mailboxName b ++ ": messages of " ++ native ++ " from any number of senders,"
      , "    taken by one receiver.\"\"\""
      , ""
      , "    def __init__(self, mailbox: ls.Mailbox | None = None, logical: bool = False):"
      , "        self._mailbox = ls.Mailbox() if mailbox is None else mailbox"
      , "        self._logical = logical"
      , ""
      , "    def send(self, value: " ++ native ++ ") -> None:"
      , "        \"\"\"Queues value without waiting.\"\"\""
      , "        self._mailbox.send(_logical(" ++ ref ++ ", value) if self._logical else value)"
      , ""
      , "    def receive(self, timeout: float | None = None) -> " ++ native ++ ":"
      , "        \"\"\"The next message; waits up to timeout seconds (forever when None),"
      , "        then raises TimeoutError; raises ls.ActorStopped once closed and empty.\"\"\""
      , "        value = self._mailbox.receive(timeout)"
      , "        return _native(" ++ ref ++ ", value) if self._logical else value"
      , ""
      , "    def close(self) -> None:"
      , "        \"\"\"Refuses later sends; messages already sent can still be received.\"\"\""
      , "        self._mailbox.close()" ] ++
      case wire of
        Nothing -> []
        Just d ->
          [ ""
          , "    @staticmethod"
          , "    def serve(node: ls.Node, name: str) -> " ++ name ++ ":"
          , "        \"\"\"A mailbox on node that other nodes send to at <node address>/name.\"\"\""
          , "        return " ++ name ++ "(node.mailbox(name, ls.read_descriptor(" ++ show d ++ ")[0], _TYPES), logical=True)"
          , ""
          , "    @staticmethod"
          , "    def connect(node: ls.Node, address: str, timeout: float = 5.0) -> " ++ name ++ "Sender:"
          , "        \"\"\"Sends to the mailbox served at address on another node.\"\"\""
          , "        return " ++ name ++ "Sender(node.remote_mailbox(address, ls.read_descriptor(" ++ show d ++ ")[0], _TYPES, timeout))"
          , ""
          , ""
          , "class " ++ name ++ "Sender:"
          , "    \"\"\"Sends to mailbox " ++ C.mailboxName b ++ " on another node.\"\"\""
          , ""
          , "    def __init__(self, remote: ls.RemoteMailbox):"
          , "        self._remote = remote"
          , ""
          , "    def send(self, value: " ++ native ++ ") -> None:"
          , "        \"\"\"Sends value; waits until the mailbox has it, or raises ls.Unreachable.\"\"\""
          , "        self._remote.send(_logical(" ++ ref ++ ", value))" ]
      where
        name = mailboxClassName (C.mailboxName b)
        ref = reference (C.mailboxType b)

-- Go: a lawspec_mailboxes.go in each unit's package. NewJobsMailbox makes a
-- local mailbox; ServeJobsMailbox offers one on a node; ConnectJobsMailbox
-- sends to one on another node.
goMailboxes :: Int -> [C.DataDeclaration] -> String -> [C.Mailbox] -> Either String [Artifact]
goMailboxes bits datas unit boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, bodies) <- foldl (\acc b -> do
      (t, bs) <- acc
      native <- GoData.goDataType datas (C.mailboxType b)
      (wire, t') <- pure (case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> (Just d, t')
        Left _ -> (Nothing, t))
      body <- box b native wire
      pure (t', bs ++ [body])) (Right ([], [])) boxes
  let parts = splitDots unit
      wired = not (null table) || any (\b -> either (const False) (const True) (describe bits datas [] (C.mailboxType b))) boxes
      schemaUsed = any (GoData.requiresSchema datas . C.mailboxType) boxes
      header =
        [ "// Generated by LawSpec. Do not edit."
        , "package " ++ last parts
        , ""
        , "import \"time\""
        , ""
        , "// Typed mailboxes: many senders, one receiver. Send never waits; Receive"
        , "// takes messages in the order they arrived; Close refuses later sends."
        , "// Serve<Name>Mailbox offers one to other nodes, and Connect<Name>Mailbox"
        , "// sends to one on another node: such a send waits until the mailbox has"
        , "// the message, and it is delivered once." ] ++
        [ "\nvar lawSpecMailboxTypes = LawSpecTypes(" ++ show (unwords (map snd (reverse table))) ++ ")" | wired ] ++
        [ "\nvar lawSpecMailboxSchema = lawSpecDataSchemaRegistry()" | schemaUsed ] ++
        [ "\nvar _ = time.Second" ]
  pure [Artifact (intercalate "/" parts ++ "/lawspec_mailboxes.go") (unlines (header ++ concat bodies)) "generated" "source"]
  where
    splitDots s = case break (== '.') s of
      (a, []) -> [a]
      (a, _ : rest) -> a : splitDots rest
    unitType t = t == C.Constructor "Unit" []
    codec ty = replaceAll "schema, bits" ("lawSpecMailboxSchema, " ++ show bits) <$> GoData.goCodec datas ty
    toNative ty value
      | unitType ty = pure value
      | GoData.requiresSchema datas ty = (\c -> c ++ ".toNative(" ++ value ++ ")") <$> codec ty
      | C.Constructor n [] <- ty = (\g -> "lsToNative(" ++ show n ++ ", " ++ value ++ ", " ++ show bits ++ ").(" ++ g ++ ")") <$> GoData.goDataType datas ty
      | otherwise = Left "no Go conversion for this type"
    toLogical ty value
      | unitType ty = pure value
      | GoData.requiresSchema datas ty = (\c -> c ++ ".fromNative(" ++ value ++ ")") <$> codec ty
      | C.Constructor n [] <- ty = pure ("lsFromNative(" ++ show n ++ ", " ++ value ++ ", " ++ show bits ++ ")")
      | otherwise = Left "no Go conversion for this type"
    box b native wire = do
      let name = mailboxClassName (C.mailboxName b)
          ty = C.mailboxType b
      local <- pure
        [ ""
        , "// " ++ name ++ " is mailbox " ++ C.mailboxName b ++ ": messages of " ++ native ++ " from any number"
        , "// of senders, taken by one receiver."
        , "type " ++ name ++ " struct {"
        , "\tbox     *LawSpecMailbox"
        , "\tlogical bool"
        , "}"
        , ""
        , "// New" ++ name ++ " makes an empty mailbox."
        , "func New" ++ name ++ "() " ++ name ++ " { return " ++ name ++ "{box: NewLawSpecMailbox()} }"
        , ""
        , "// Close refuses later sends; messages already sent can still be received."
        , "func (m " ++ name ++ ") Close() { m.box.Close() }" ]
      remote <- case wire of
        Nothing -> pure
          [ ""
          , "// Send queues value without waiting; it fails once the mailbox is closed."
          , "func (m " ++ name ++ ") Send(value " ++ native ++ ") error { return m.box.Send(value) }"
          , ""
          , "// Receive is the next message, waiting up to timeout (forever when zero); it"
          , "// fails on timeout, or once closed and empty."
          , "func (m " ++ name ++ ") Receive(timeout time.Duration) (" ++ native ++ ", error) {"
          , "\tvalue, err := m.box.Receive(timeout)"
          , "\tif err != nil {"
          , "\t\tvar none " ++ native
          , "\t\treturn none, err"
          , "\t}"
          , "\treturn value.(" ++ native ++ "), nil"
          , "}" ]
        Just d -> do
          logical <- toLogical ty "value"
          back <- toNative ty "value.(LawSpecValue)"
          pure
            [ ""
            , "// Send queues value without waiting; it fails once the mailbox is closed."
            , "func (m " ++ name ++ ") Send(value " ++ native ++ ") error {"
            , "\tif m.logical {"
            , "\t\treturn m.box.Send(" ++ logical ++ ")"
            , "\t}"
            , "\treturn m.box.Send(value)"
            , "}"
            , ""
            , "// Receive is the next message, waiting up to timeout (forever when zero); it"
            , "// fails on timeout, or once closed and empty."
            , "func (m " ++ name ++ ") Receive(timeout time.Duration) (" ++ native ++ ", error) {"
            , "\tvalue, err := m.box.Receive(timeout)"
            , "\tif err != nil {"
            , "\t\tvar none " ++ native
            , "\t\treturn none, err"
            , "\t}"
            , "\tif m.logical {"
            , "\t\treturn " ++ back ++ ", nil"
            , "\t}"
            , "\treturn value.(" ++ native ++ "), nil"
            , "}"
            , ""
            , "// Serve" ++ name ++ " is a mailbox on node that other nodes send to at"
            , "// <node address>/name."
            , "func Serve" ++ name ++ "(node *LawSpecNode, name string) (" ++ name ++ ", error) {"
            , "\tbox, err := node.Mailbox(name, LawSpecDescriptor(" ++ show d ++ "), lawSpecMailboxTypes)"
            , "\tif err != nil {"
            , "\t\treturn " ++ name ++ "{}, err"
            , "\t}"
            , "\treturn " ++ name ++ "{box: box, logical: true}, nil"
            , "}"
            , ""
            , "// " ++ name ++ "Sender sends to mailbox " ++ C.mailboxName b ++ " on another node."
            , "type " ++ name ++ "Sender struct{ remote *LawSpecRemoteMailbox }"
            , ""
            , "// Connect" ++ name ++ " sends to the mailbox served at address on another"
            , "// node; each send waits up to timeout (5 seconds when zero)."
            , "func Connect" ++ name ++ "(node *LawSpecNode, address string, timeout time.Duration) " ++ name ++ "Sender {"
            , "\treturn " ++ name ++ "Sender{node.RemoteMailbox(address, LawSpecDescriptor(" ++ show d ++ "), lawSpecMailboxTypes, timeout)}"
            , "}"
            , ""
            , "// Send sends value and waits until the mailbox has it, or fails with"
            , "// LawSpecUnreachable."
            , "func (s " ++ name ++ "Sender) Send(value " ++ native ++ ") error { return s.remote.Send(" ++ logical ++ ") }" ]
      pure (local ++ remote)
    replaceAll old new s = case s of
      [] -> []
      _ | take (length old) s == old -> new ++ replaceAll old new (drop (length old) s)
      c : rest -> c : replaceAll old new rest
-- lawspec_mailboxes for JavaScript and TypeScript: receive and a send
-- between nodes are asynchronous.
web :: Bool -> Int -> [C.DataDeclaration] -> [C.Mailbox] -> Either String [Artifact]
web ts bits datas boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, classes) <- foldl (\acc b -> do
      (t, cs) <- acc
      native <- D.render (D.Pretty 1000) <$> Web.webDataTypeDocWith datas [] (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', cs ++ [cls b native (Just d)])
        Left _ -> pure (t, cs ++ [cls b native (Nothing :: Maybe String)])) (Right ([], [])) boxes
  let body = concat classes
      usesData = any (Web.requiresSchema datas . C.mailboxType) boxes
      importLine name file = "import * as " ++ name ++ " from './" ++ file ++ (if ts then ".js" else ".mjs") ++ "';"
      header =
        [ "// Generated by LawSpec; do not edit. Typed mailboxes: many senders, one"
        , "// receiver. send never waits; receive resolves to the next message in the"
        , "// order they arrived; close refuses later sends. serve(node, name) offers"
        , "// a mailbox to other nodes, and connect(node, address) sends to one from"
        , "// another node: such a send resolves once the mailbox has the message, and"
        , "// it is delivered once."
        , importLine "ls" "lawspec_runtime" ] ++
        [ line | usesData, line <- [importLine "data" "lawspec_data"] ] ++
        [ ""
        , "const _TYPES = ls.valuesFrom(" ++ show (unwords (map snd (reverse table) ++ ["(unit)"])) ++ ")[0];"
        , "const _SCHEMA" ++ anyT ++ " = " ++ (if usesData then "data.makeSchema()" else "null") ++ ";"
        , "const _native = (reference" ++ anyT ++ ", d" ++ anyT ++ ", value" ++ anyT ++ ")" ++ anyT ++ " => (reference === null ? ls.nativeScalar(d, value) : _SCHEMA.toNative(reference, value));"
        , "const _logical = (reference" ++ anyT ++ ", value" ++ anyT ++ ")" ++ anyT ++ " => (reference === null ? value : _SCHEMA.fromNative(reference, value));"
        , "const _d = (text" ++ anyT ++ ")" ++ anyT ++ " => ls.readDescriptor(text)[0];" ]
  pure [Artifact ("src/lawspec_mailboxes." ++ (if ts then "ts" else "mjs")) (unlines header ++ body) "generated" "source"]
  where
    anyT = if ts then ": any" else ""
    typed n = if ts then ": " ++ n else ""
    field n t = if ts then "  " ++ n ++ ": " ++ t ++ ";" else "  " ++ n ++ ";"
    reference ty = if Web.requiresSchema datas ty then either (const "null") (D.render (D.Pretty 1000)) (Web.webTypeReferenceDoc ty) else "null"
    cls b native wire = unlines $
      [ ""
      , "/** Mailbox " ++ C.mailboxName b ++ ": messages from any number of senders, taken by one receiver. */"
      , "export class " ++ name ++ " {"
      , field "mailbox" "ls.Mailbox"
      , field "logical" "boolean"
      , field "descriptor" "any"
      , "  constructor(mailbox" ++ (if ts then ": ls.Mailbox | null" else "") ++ " = null, logical" ++ typed "boolean" ++ " = false, descriptor" ++ anyT ++ " = null) {"
      , "    this.mailbox = mailbox ?? new ls.Mailbox();"
      , "    this.logical = logical;"
      , "    this.descriptor = descriptor;"
      , "  }"
      , "  /** Queues value without waiting. */"
      , "  send(value" ++ typed native ++ ")" ++ typed "void" ++ " {"
      , "    this.mailbox.send(this.logical ? _logical(" ++ ref ++ ", value) : value);"
      , "  }"
      , "  /**"
      , "   * The next message; waits up to timeoutMs (forever when omitted), then"
      , "   * rejects; rejects with ls.ActorStopped once closed and empty."
      , "   */"
      , "  async receive(timeoutMs" ++ (if ts then "?: number" else "") ++ ")" ++ typed ("Promise<" ++ native ++ ">") ++ " {"
      , "    const value" ++ anyT ++ " = await this.mailbox.receiveAsync(timeoutMs);"
      , "    return this.logical ? _native(" ++ ref ++ ", this.descriptor, value) : value;"
      , "  }"
      , "  /** Refuses later sends; messages already sent can still be received. */"
      , "  close()" ++ typed "void" ++ " {"
      , "    this.mailbox.close();"
      , "  }" ] ++
      (case wire of
        Nothing -> []
        Just d ->
          [ "  /** A mailbox on node that other nodes send to at <node address>/name. */"
          , "  static serve(node" ++ typed "ls.Node" ++ ", name" ++ typed "string" ++ ")" ++ typed name ++ " {"
          , "    return new " ++ name ++ "(node.mailbox(name, _d(" ++ show d ++ "), _TYPES), true, _d(" ++ show d ++ "));"
          , "  }"
          , "  /** Sends to the mailbox served at address on another node. */"
          , "  static connect(node" ++ typed "ls.Node" ++ ", address" ++ typed "string" ++ ", timeout" ++ typed "number" ++ " = 5)" ++ typed (name ++ "Sender") ++ " {"
          , "    return new " ++ name ++ "Sender(node.remoteMailbox(address, _d(" ++ show d ++ "), _TYPES, timeout));"
          , "  }" ]) ++
      [ "}" ] ++
      (case wire of
        Nothing -> []
        Just _ ->
          [ ""
          , "/** Sends to mailbox " ++ C.mailboxName b ++ " on another node. */"
          , "export class " ++ name ++ "Sender {"
          , field "remote" "ls.RemoteMailbox"
          , "  constructor(remote" ++ typed "ls.RemoteMailbox" ++ ") {"
          , "    this.remote = remote;"
          , "  }"
          , "  /** Sends value; resolves once the mailbox has it, or rejects with ls.Unreachable. */"
          , "  async send(value" ++ typed native ++ ")" ++ typed "Promise<void>" ++ " {"
          , "    await this.remote.send(_logical(" ++ ref ++ ", value));"
          , "  }"
          , "}" ])
      where
        name = mailboxClassName (C.mailboxName b)
        ref = reference (C.mailboxType b)
