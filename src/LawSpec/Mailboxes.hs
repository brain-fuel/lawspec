-- jobs's class is JobsMailbox.
mailboxClassName :: String -> String
mailboxClassName n = case n of
  c : cs -> toUpper c : cs ++ "Mailbox"
  [] -> "Mailbox"

mailboxArtifacts :: String -> Plan -> Either [Diagnostic] [Artifact]
mailboxArtifacts target plan = case concatMap C.unitMailboxes units of
  [] -> Right []
  boxes -> either (\message -> Left [Diagnostic "mailboxes" message Nothing]) Right $ case target of
    "python" -> python bits datas boxes
    "go" -> concat <$> mapM (\u -> goMailboxes bits datas (C.idText (C.unitId u)) (C.unitMailboxes u)) [u | u <- units, not (null (C.unitMailboxes u))]
    "javascript" -> web False bits datas boxes
    "typescript" -> web True bits datas boxes
    "rust" -> rust bits datas boxes
    "haskell" -> concat <$> mapM (haskell bits datas) [u | u <- units, not (null (C.unitMailboxes u))]
    "java" -> mapM (jvm False bits datas) boxes
    "kotlin" -> mapM (jvm True bits datas) boxes
    _ -> Right []
  where
    units = map plannedUnit (plannedUnits plan)
    datas = planDataDeclarations plan
    bits = planMachineBits plan

python :: Int -> [C.DataDeclaration] -> [C.Mailbox] -> Either String [Artifact]
python bits datas boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, classes) <- foldl (\acc b -> do
      (t, cs) <- acc
      native <- D.render (D.Pretty 1000) <$> pythonDataTypeDoc datas (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', cs ++ [cls b native (Just d)])
        Left _ -> pure (t, cs ++ [cls b native (Nothing :: Maybe String)])) (Right ([], [])) boxes
  let header =
        [ "# Generated by LawSpec. Do not edit."
        , "\"\"\"Typed mailboxes: many senders, one receiver."
        , ""
        , "send never waits; receive takes messages in the order they arrived;"
        , "close refuses later sends. serve(node, name) offers a mailbox to other"
        , "nodes, and connect(node, address) sends to one from another node: such a"
        , "send waits until the mailbox has the message, and it is delivered once."
        , "\"\"\""
        , "from __future__ import annotations"
        , ""
        , "import builtins as _builtins"
        , "import lawspec_runtime as ls"
        , "try:"
        , "    import lawspec_data as data"
        , "    import lawspec_schema as _schema"
        , "    _SCHEMA = data.make_schema()"
        , "except ImportError:"
        , "    _SCHEMA = None"
        , ""
        , "_TYPES = ls.Values({str(f[1]): f for f in ls.read_descriptor(" ++ show (unwords (map snd (reverse table))) ++ ")})"
        , ""
        , ""
        , "def _native(reference, value):"
        , "    return value if reference is None else _SCHEMA.to_native(reference, value)"
        , ""
        , ""
        , "def _logical(reference, value):"
        , "    return value if reference is None else _SCHEMA.from_native(reference, value)" ]
  pure [Artifact "src/lawspec_mailboxes.py" (unlines header ++ concatMap ("\n\n" ++) classes) "generated" "source"]
  where
    reference ty = if requiresSchema datas ty then either (const "None") (D.render (D.Pretty 1000)) (pythonTypeReferenceDoc ty) else "None"
    cls b native wire = unlines $
      [ "class " ++ name ++ ":"
      , "    \"\"\"Mailbox " ++ C.mailboxName b ++ ": messages of " ++ native ++ " from any number of senders,"
      , "    taken by one receiver.\"\"\""
      , ""
      , "    def __init__(self, mailbox: ls.Mailbox | None = None, logical: bool = False):"
      , "        self._mailbox = ls.Mailbox() if mailbox is None else mailbox"
      , "        self._logical = logical"
      , ""
      , "    def send(self, value: " ++ native ++ ") -> None:"
      , "        \"\"\"Queues value without waiting.\"\"\""
      , "        self._mailbox.send(_logical(" ++ ref ++ ", value) if self._logical else value)"
      , ""
      , "    def receive(self, timeout: float | None = None) -> " ++ native ++ ":"
      , "        \"\"\"The next message; waits up to timeout seconds (forever when None),"
      , "        then raises TimeoutError; raises ls.ActorStopped once closed and empty.\"\"\""
      , "        value = self._mailbox.receive(timeout)"
      , "        return _native(" ++ ref ++ ", value) if self._logical else value"
      , ""
      , "    def close(self) -> None:"
      , "        \"\"\"Refuses later sends; messages already sent can still be received.\"\"\""
      , "        self._mailbox.close()" ] ++
      case wire of
        Nothing -> []
        Just d ->
          [ ""
          , "    @staticmethod"
          , "    def serve(node: ls.Node, name: str) -> " ++ name ++ ":"
          , "        \"\"\"A mailbox on node that other nodes send to at <node address>/name.\"\"\""
          , "        return " ++ name ++ "(node.mailbox(name, ls.read_descriptor(" ++ show d ++ ")[0], _TYPES), logical=True)"
          , ""
          , "    @staticmethod"
          , "    def connect(node: ls.Node, address: str, timeout: float = 5.0) -> " ++ name ++ "Sender:"
          , "        \"\"\"Sends to the mailbox served at address on another node.\"\"\""
          , "        return " ++ name ++ "Sender(node.remote_mailbox(address, ls.read_descriptor(" ++ show d ++ ")[0], _TYPES, timeout))"
          , ""
          , ""
          , "class " ++ name ++ "Sender:"
          , "    \"\"\"Sends to mailbox " ++ C.mailboxName b ++ " on another node.\"\"\""
          , ""
          , "    def __init__(self, remote: ls.RemoteMailbox):"
          , "        self._remote = remote"
          , ""
          , "    def send(self, value: " ++ native ++ ") -> None:"
          , "        \"\"\"Sends value; waits until the mailbox has it, or raises ls.Unreachable.\"\"\""
          , "        self._remote.send(_logical(" ++ ref ++ ", value))" ]
      where
        name = mailboxClassName (C.mailboxName b)
        ref = reference (C.mailboxType b)

-- Go: a lawspec_mailboxes.go in each unit's package. NewJobsMailbox makes a
-- local mailbox; ServeJobsMailbox offers one on a node; ConnectJobsMailbox
-- sends to one on another node.
goMailboxes :: Int -> [C.DataDeclaration] -> String -> [C.Mailbox] -> Either String [Artifact]
goMailboxes bits datas unit boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, bodies) <- foldl (\acc b -> do
      (t, bs) <- acc
      native <- GoData.goDataType datas (C.mailboxType b)
      (wire, t') <- pure (case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> (Just d, t')
        Left _ -> (Nothing, t))
      body <- box b native wire
      pure (t', bs ++ [body])) (Right ([], [])) boxes
  let parts = splitDots unit
      wired = not (null table) || any (\b -> either (const False) (const True) (describe bits datas [] (C.mailboxType b))) boxes
      schemaUsed = any (GoData.requiresSchema datas . C.mailboxType) boxes
      header =
        [ "// Generated by LawSpec. Do not edit."
        , "package " ++ last parts
        , ""
        , "import \"time\""
        , ""
        , "// Typed mailboxes: many senders, one receiver. Send never waits; Receive"
        , "// takes messages in the order they arrived; Close refuses later sends."
        , "// Serve<Name>Mailbox offers one to other nodes, and Connect<Name>Mailbox"
        , "// sends to one on another node: such a send waits until the mailbox has"
        , "// the message, and it is delivered once." ] ++
        [ "\nvar lawSpecMailboxTypes = LawSpecTypes(" ++ show (unwords (map snd (reverse table))) ++ ")" | wired ] ++
        [ "\nvar lawSpecMailboxSchema = lawSpecDataSchemaRegistry()" | schemaUsed ] ++
        [ "\nvar _ = time.Second" ]
  pure [Artifact (intercalate "/" parts ++ "/lawspec_mailboxes.go") (unlines (header ++ concat bodies)) "generated" "source"]
  where
    splitDots s = case break (== '.') s of
      (a, []) -> [a]
      (a, _ : rest) -> a : splitDots rest
    unitType t = t == C.Constructor "Unit" []
    codec ty = replaceAll "schema, bits" ("lawSpecMailboxSchema, " ++ show bits) <$> GoData.goCodec datas ty
    toNative ty value
      | unitType ty = pure value
      | GoData.requiresSchema datas ty = (\c -> c ++ ".toNative(" ++ value ++ ")") <$> codec ty
      | C.Constructor n [] <- ty = (\g -> "lsToNative(" ++ show n ++ ", " ++ value ++ ", " ++ show bits ++ ").(" ++ g ++ ")") <$> GoData.goDataType datas ty
      | otherwise = Left "no Go conversion for this type"
    toLogical ty value
      | unitType ty = pure value
      | GoData.requiresSchema datas ty = (\c -> c ++ ".fromNative(" ++ value ++ ")") <$> codec ty
      | C.Constructor n [] <- ty = pure ("lsFromNative(" ++ show n ++ ", " ++ value ++ ", " ++ show bits ++ ")")
      | otherwise = Left "no Go conversion for this type"
    box b native wire = do
      let name = mailboxClassName (C.mailboxName b)
          ty = C.mailboxType b
      local <- pure
        [ ""
        , "// " ++ name ++ " is mailbox " ++ C.mailboxName b ++ ": messages of " ++ native ++ " from any number"
        , "// of senders, taken by one receiver."
        , "type " ++ name ++ " struct {"
        , "\tbox     *LawSpecMailbox"
        , "\tlogical bool"
        , "}"
        , ""
        , "// New" ++ name ++ " makes an empty mailbox."
        , "func New" ++ name ++ "() " ++ name ++ " { return " ++ name ++ "{box: NewLawSpecMailbox()} }"
        , ""
        , "// Close refuses later sends; messages already sent can still be received."
        , "func (m " ++ name ++ ") Close() { m.box.Close() }" ]
      remote <- case wire of
        Nothing -> pure
          [ ""
          , "// Send queues value without waiting; it fails once the mailbox is closed."
          , "func (m " ++ name ++ ") Send(value " ++ native ++ ") error { return m.box.Send(value) }"
          , ""
          , "// Receive is the next message, waiting up to timeout (forever when zero); it"
          , "// fails on timeout, or once closed and empty."
          , "func (m " ++ name ++ ") Receive(timeout time.Duration) (" ++ native ++ ", error) {"
          , "\tvalue, err := m.box.Receive(timeout)"
          , "\tif err != nil {"
          , "\t\tvar none " ++ native
          , "\t\treturn none, err"
          , "\t}"
          , "\treturn value.(" ++ native ++ "), nil"
          , "}" ]
        Just d -> do
          logical <- toLogical ty "value"
          back <- toNative ty "value.(LawSpecValue)"
          pure
            [ ""
            , "// Send queues value without waiting; it fails once the mailbox is closed."
            , "func (m " ++ name ++ ") Send(value " ++ native ++ ") error {"
            , "\tif m.logical {"
            , "\t\treturn m.box.Send(" ++ logical ++ ")"
            , "\t}"
            , "\treturn m.box.Send(value)"
            , "}"
            , ""
            , "// Receive is the next message, waiting up to timeout (forever when zero); it"
            , "// fails on timeout, or once closed and empty."
            , "func (m " ++ name ++ ") Receive(timeout time.Duration) (" ++ native ++ ", error) {"
            , "\tvalue, err := m.box.Receive(timeout)"
            , "\tif err != nil {"
            , "\t\tvar none " ++ native
            , "\t\treturn none, err"
            , "\t}"
            , "\tif m.logical {"
            , "\t\treturn " ++ back ++ ", nil"
            , "\t}"
            , "\treturn value.(" ++ native ++ "), nil"
            , "}"
            , ""
            , "// Serve" ++ name ++ " is a mailbox on node that other nodes send to at"
            , "// <node address>/name."
            , "func Serve" ++ name ++ "(node *LawSpecNode, name string) (" ++ name ++ ", error) {"
            , "\tbox, err := node.Mailbox(name, LawSpecDescriptor(" ++ show d ++ "), lawSpecMailboxTypes)"
            , "\tif err != nil {"
            , "\t\treturn " ++ name ++ "{}, err"
            , "\t}"
            , "\treturn " ++ name ++ "{box: box, logical: true}, nil"
            , "}"
            , ""
            , "// " ++ name ++ "Sender sends to mailbox " ++ C.mailboxName b ++ " on another node."
            , "type " ++ name ++ "Sender struct{ remote *LawSpecRemoteMailbox }"
            , ""
            , "// Connect" ++ name ++ " sends to the mailbox served at address on another"
            , "// node; each send waits up to timeout (5 seconds when zero)."
            , "func Connect" ++ name ++ "(node *LawSpecNode, address string, timeout time.Duration) " ++ name ++ "Sender {"
            , "\treturn " ++ name ++ "Sender{node.RemoteMailbox(address, LawSpecDescriptor(" ++ show d ++ "), lawSpecMailboxTypes, timeout)}"
            , "}"
            , ""
            , "// Send sends value and waits until the mailbox has it, or fails with"
            , "// LawSpecUnreachable."
            , "func (s " ++ name ++ "Sender) Send(value " ++ native ++ ") error { return s.remote.Send(" ++ logical ++ ") }" ]
      pure (local ++ remote)
    replaceAll old new s = case s of
      [] -> []
      _ | take (length old) s == old -> new ++ replaceAll old new (drop (length old) s)
      c : rest -> c : replaceAll old new rest
-- lawspec_mailboxes for JavaScript and TypeScript: receive and a send
-- between nodes are asynchronous.
web :: Bool -> Int -> [C.DataDeclaration] -> [C.Mailbox] -> Either String [Artifact]
web ts bits datas boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, classes) <- foldl (\acc b -> do
      (t, cs) <- acc
      native <- D.render (D.Pretty 1000) <$> Web.webDataTypeDocWith datas [] (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', cs ++ [cls b native (Just d)])
        Left _ -> pure (t, cs ++ [cls b native (Nothing :: Maybe String)])) (Right ([], [])) boxes
  let body = concat classes
      usesData = any (Web.requiresSchema datas . C.mailboxType) boxes
      importLine name file = "import * as " ++ name ++ " from './" ++ file ++ (if ts then ".js" else ".mjs") ++ "';"
      header =
        [ "// Generated by LawSpec; do not edit. Typed mailboxes: many senders, one"
        , "// receiver. send never waits; receive resolves to the next message in the"
        , "// order they arrived; close refuses later sends. serve(node, name) offers"
        , "// a mailbox to other nodes, and connect(node, address) sends to one from"
        , "// another node: such a send resolves once the mailbox has the message, and"
        , "// it is delivered once."
        , importLine "ls" "lawspec_runtime" ] ++
        [ line | usesData, line <- [importLine "data" "lawspec_data"] ] ++
        [ ""
        , "const _TYPES = ls.valuesFrom(" ++ show (unwords (map snd (reverse table) ++ ["(unit)"])) ++ ")[0];"
        , "const _SCHEMA" ++ anyT ++ " = " ++ (if usesData then "data.makeSchema()" else "null") ++ ";"
        , "const _native = (reference" ++ anyT ++ ", d" ++ anyT ++ ", value" ++ anyT ++ ")" ++ anyT ++ " => (reference === null ? ls.nativeScalar(d, value) : _SCHEMA.toNative(reference, value));"
        , "const _logical = (reference" ++ anyT ++ ", value" ++ anyT ++ ")" ++ anyT ++ " => (reference === null ? value : _SCHEMA.fromNative(reference, value));"
        , "const _d = (text" ++ anyT ++ ")" ++ anyT ++ " => ls.readDescriptor(text)[0];" ]
  pure [Artifact ("src/lawspec_mailboxes." ++ (if ts then "ts" else "mjs")) (unlines header ++ body) "generated" "source"]
  where
    anyT = if ts then ": any" else ""
    typed n = if ts then ": " ++ n else ""
    field n t = if ts then "  " ++ n ++ ": " ++ t ++ ";" else "  " ++ n ++ ";"
    reference ty = if Web.requiresSchema datas ty then either (const "null") (D.render (D.Pretty 1000)) (Web.webTypeReferenceDoc ty) else "null"
    cls b native wire = unlines $
      [ ""
      , "/** Mailbox " ++ C.mailboxName b ++ ": messages from any number of senders, taken by one receiver. */"
      , "export class " ++ name ++ " {"
      , field "mailbox" "ls.Mailbox"
      , field "logical" "boolean"
      , field "descriptor" "any"
      , "  constructor(mailbox" ++ (if ts then ": ls.Mailbox | null" else "") ++ " = null, logical" ++ typed "boolean" ++ " = false, descriptor" ++ anyT ++ " = null) {"
      , "    this.mailbox = mailbox ?? new ls.Mailbox();"
      , "    this.logical = logical;"
      , "    this.descriptor = descriptor;"
      , "  }"
      , "  /** Queues value without waiting. */"
      , "  send(value" ++ typed native ++ ")" ++ typed "void" ++ " {"
      , "    this.mailbox.send(this.logical ? _logical(" ++ ref ++ ", value) : value);"
      , "  }"
      , "  /**"
      , "   * The next message; waits up to timeoutMs (forever when omitted), then"
      , "   * rejects; rejects with ls.ActorStopped once closed and empty."
      , "   */"
      , "  async receive(timeoutMs" ++ (if ts then "?: number" else "") ++ ")" ++ typed ("Promise<" ++ native ++ ">") ++ " {"
      , "    const value" ++ anyT ++ " = await this.mailbox.receiveAsync(timeoutMs);"
      , "    return this.logical ? _native(" ++ ref ++ ", this.descriptor, value) : value;"
      , "  }"
      , "  /** Refuses later sends; messages already sent can still be received. */"
      , "  close()" ++ typed "void" ++ " {"
      , "    this.mailbox.close();"
      , "  }" ] ++
      (case wire of
        Nothing -> []
        Just d ->
          [ "  /** A mailbox on node that other nodes send to at <node address>/name. */"
          , "  static serve(node" ++ typed "ls.Node" ++ ", name" ++ typed "string" ++ ")" ++ typed name ++ " {"
          , "    return new " ++ name ++ "(node.mailbox(name, _d(" ++ show d ++ "), _TYPES), true, _d(" ++ show d ++ "));"
          , "  }"
          , "  /** Sends to the mailbox served at address on another node. */"
          , "  static connect(node" ++ typed "ls.Node" ++ ", address" ++ typed "string" ++ ", timeout" ++ typed "number" ++ " = 5)" ++ typed (name ++ "Sender") ++ " {"
          , "    return new " ++ name ++ "Sender(node.remoteMailbox(address, _d(" ++ show d ++ "), _TYPES, timeout));"
          , "  }" ]) ++
      [ "}" ] ++
      (case wire of
        Nothing -> []
        Just _ ->
          [ ""
          , "/** Sends to mailbox " ++ C.mailboxName b ++ " on another node. */"
          , "export class " ++ name ++ "Sender {"
          , field "remote" "ls.RemoteMailbox"
          , "  constructor(remote" ++ typed "ls.RemoteMailbox" ++ ") {"
          , "    this.remote = remote;"
          , "  }"
          , "  /** Sends value; resolves once the mailbox has it, or rejects with ls.Unreachable. */"
          , "  async send(value" ++ typed native ++ ")" ++ typed "Promise<void>" ++ " {"
          , "    await this.remote.send(_logical(" ++ ref ++ ", value));"
          , "  }"
          , "}" ])
      where
        name = mailboxClassName (C.mailboxName b)
        ref = reference (C.mailboxType b)
rust :: Int -> [C.DataDeclaration] -> [C.Mailbox] -> Either String [Artifact]
rust bits datas boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, structs) <- foldl (\acc b -> do
      (t, cs) <- acc
      native <- rustDataType datas (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', cs ++ [struct b native (Just d)])
        Left _ -> pure (t, cs ++ [struct b native (Nothing :: Maybe String)])) (Right ([], [])) boxes
  let header =
        [ "// Generated by LawSpec. Do not edit."
        , "//! Typed mailboxes: many senders, one receiver. send never waits; receive"
        , "//! takes messages in the order they arrived; close refuses later sends."
        , "//! serve offers a mailbox to other nodes, and connect sends to one from"
        , "//! another node: such a send waits until the mailbox has the message, and"
        , "//! it is delivered once."
        , "#![allow(dead_code)]"
        , ""
        , "use crate::lawspec_runtime as ls;"
        , ""
        , "/// The data types the mailboxes' messages use on the wire."
        , "fn wire_types() -> ls::Values {"
        , "    ls::values_table(" ++ show (unwords (map snd (reverse table))) ++ ")"
        , "}" ]
  pure [Artifact "src/lawspec_mailboxes.rs" (unlines header ++ concatMap ("\n" ++) structs) "generated" "source"]
  where
    struct b native wire = unlines $
      [ "/// Mailbox " ++ C.mailboxName b ++ ": messages of " ++ native ++ " from any number of"
      , "/// senders, taken by one receiver. Clones share the mailbox."
      , "#[derive(Clone)]"
      , "pub struct " ++ name ++ "(" ++ name ++ "Inner);"
      , ""
      , "#[derive(Clone)]"
      , "enum " ++ name ++ "Inner {"
      , "    Local(ls::actors::Mailbox<" ++ native ++ ">),"
      , "    Served(ls::actors::Mailbox<ls::Value>),"
      , "}"
      , ""
      , "impl Default for " ++ name ++ " {"
      , "    fn default() -> Self {"
      , "        Self::new()"
      , "    }"
      , "}"
      , ""
      , "impl " ++ name ++ " {"
      , "    /// A new, empty mailbox."
      , "    pub fn new() -> Self {"
      , "        " ++ name ++ "(" ++ name ++ "Inner::Local(ls::actors::Mailbox::new()))"
      , "    }"
      , ""
      , "    /// Queues value without waiting; fails once the mailbox is closed."
      , "    pub fn send(&self, value: " ++ native ++ ") -> ls::Result<()> {"
      , "        match &self.0 {"
      , "            " ++ name ++ "Inner::Local(mailbox) => mailbox.send(value),"
      , "            " ++ name ++ "Inner::Served(mailbox) => mailbox.send(ls::IntoValue::into_value(value)),"
      , "        }"
      , "    }"
      , ""
      , "    /// The next message, waiting up to timeout (forever when None); fails"
      , "    /// on timing out, or once closed and empty."
      , "    pub fn receive(&self, timeout: Option<std::time::Duration>) -> ls::Result<" ++ native ++ "> {"
      , "        match &self.0 {"
      , "            " ++ name ++ "Inner::Local(mailbox) => mailbox.receive(timeout),"
      , "            " ++ name ++ "Inner::Served(mailbox) => ls::FromValue::from_value(mailbox.receive(timeout)?),"
      , "        }"
      , "    }"
      , ""
      , "    /// Refuses later sends; messages already sent can still be received."
      , "    pub fn close(&self) {"
      , "        match &self.0 {"
      , "            " ++ name ++ "Inner::Local(mailbox) => mailbox.close(),"
      , "            " ++ name ++ "Inner::Served(mailbox) => mailbox.close(),"
      , "        }"
      , "    }" ] ++
      case wire of
        Nothing -> ["}"]
        Just d ->
          [ ""
          , "    /// A mailbox on node that other nodes send to at <node address>/name."
          , "    pub fn serve(node: &ls::net::Node, name: &str) -> ls::Result<Self> {"
          , "        Ok(" ++ name ++ "(" ++ name ++ "Inner::Served(node.mailbox(name, ls::descriptor(" ++ show d ++ "), wire_types())?)))"
          , "    }"
          , ""
          , "    /// Sends to the mailbox served at address on another node; each send"
          , "    /// waits up to timeout for delivery."
          , "    pub fn connect(node: &ls::net::Node, address: &str, timeout: std::time::Duration) -> " ++ name ++ "Sender {"
          , "        " ++ name ++ "Sender(node.remote_mailbox_within(address, ls::descriptor(" ++ show d ++ "), wire_types(), timeout))"
          , "    }"
          , "}"
          , ""
          , "/// Sends to mailbox " ++ C.mailboxName b ++ " on another node."
          , "pub struct " ++ name ++ "Sender(ls::net::RemoteMailbox);"
          , ""
          , "impl " ++ name ++ "Sender {"
          , "    /// Sends value; waits until the mailbox has it, or fails as unreachable."
          , "    pub fn send(&self, value: " ++ native ++ ") -> ls::Result<()> {"
          , "        self.0.send(&ls::IntoValue::into_value(value))"
          , "    }"
          , "}" ]
      where name = mailboxClassName (C.mailboxName b)
-- A unit's mailboxes as the module LawSpecMailboxes.<Unit>: for jobs of Job,
-- JobsMailbox with newJobsMailbox, sendJobs (never waits), receiveJobs,
-- receiveJobsWithin (microseconds), closeJobs; serveJobs offers one on a
-- node, and connectJobs / sendJobsTo send to one on another node, waiting
-- until it has the message.
haskell :: Int -> [C.DataDeclaration] -> C.Unit -> Either String [Artifact]
haskell bits datas unit = do
  let boxes = C.unitMailboxes unit
  (table, parts) <- foldl (\acc b -> do
      (t, ps) <- acc
      native <- haskellNativeTypeWithParameters datas [] [] (C.mailboxType b)
      codec <- D.render (D.Pretty 10000) <$> haskellCodecDoc datas "_lawspecSchema" "_lawspecBits" (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', ps ++ [(b, paren native, "(" ++ codec ++ " :: Codec.Codec " ++ paren native ++ ")", Just d)])
        Left _ -> pure (t, ps ++ [(b, paren native, "(" ++ codec ++ " :: Codec.Codec " ++ paren native ++ ")", Nothing)])) (Right ([], [])) boxes
  let body = concatMap box parts
      used prefix = prefix `isInfixOf'` body
      header =
        [ "-- Generated by LawSpec. Do not edit."
        , "-- | Typed mailboxes of unit " ++ unitName ++ ": many senders, one receiver."
        , "-- A send never waits; a receive takes messages in the order they arrived;"
        , "-- close refuses later sends. serve offers a mailbox on a node, and connect"
        , "-- sends to one on another node: such a send waits until the mailbox has"
        , "-- the message, and it is delivered once."
        , "module " ++ moduleName ++ " where"
        , ""
        , "import qualified Prelude as P"
        , "import qualified Control.Exception as E"
        , "import qualified LawSpecRuntime as LS"
        , "import qualified LawSpecCodecs as Codec"
        , "import qualified LawSpecSchema as Schema"
        , "import qualified LawSpecDataSchema as DataSchema" ] ++
        [ "import " ++ line | (prefix, line) <- imports, used prefix ] ++
        [ ""
        , "_lawspecSchema :: Schema.Schema"
        , "_lawspecSchema = P.either P.error P.id DataSchema.schema"
        , ""
        , "_lawspecBits :: P.Int"
        , "_lawspecBits = " ++ show bits
        , ""
        , "_lawspecTypes :: LS.DataTable"
        , "_lawspecTypes = [(LS.descriptorName n, f) | f@(LS.DescList (LS.DescAtom \"data\" : n : _)) <- LS.readDescriptor " ++ show (unwords (map snd (reverse table))) ++ "]"
        , ""
        , "_lawspecDescriptor :: P.String -> LS.Descriptor"
        , "_lawspecDescriptor text = case LS.readDescriptor text of"
        , "  form : _ -> form"
        , "  [] -> P.error \"empty descriptor\""
        , ""
        , "_lawspecOr :: P.Either P.String a -> P.IO a"
        , "_lawspecOr = P.either (E.throwIO P.. E.ErrorCall) P.pure" ]
  pure [Artifact ("src/" ++ map (\c -> if c == '.' then '/' else c) moduleName ++ ".hs") (unlines header ++ body) "generated" "source"]
  where
    unitName = C.idText (C.unitId unit)
    moduleName = intercalate "." ("LawSpecMailboxes" : map (concatMap cap . splitOn '_') (splitOn '.' unitName))
    cap s = case s of
      c : cs -> toUpper c : cs
      [] -> []
    splitOn delimiter value = case break (== delimiter) value of
      (a, []) -> [a]
      (a, _ : rest) -> a : splitOn delimiter rest
    paren t = if ' ' `elem` t && take 1 t /= "(" && take 1 t /= "[" then "(" ++ t ++ ")" else t
    isInfixOf' needle hay = any (\i -> take (length needle) (drop i hay) == needle) [0 .. length hay - length needle]
    imports =
      [ ("I.", "qualified Data.Int as I"), ("W.", "qualified Data.Word as W"), ("T.", "qualified Data.Text as T")
      , ("B.", "qualified Data.ByteString as B"), ("C.", "qualified Data.Complex as C")
      , ("Seq.", "qualified Data.Sequence as Seq"), ("Set.", "qualified Data.Set as Set")
      , ("Map.", "qualified Data.Map.Strict as Map"), ("Data.", "qualified LawSpecData as Data")
      , ("Codecs.", "qualified LawSpecDataCodecs as Codecs")
      , ("Collections.", "qualified LawSpecCollectionCodecs as Collections") ]
    box (b, native, codec, wire) = unlines $
      [ ""
      , "-- | Mailbox " ++ n ++ ": messages of " ++ native ++ " from any number of senders, taken by"
      , "-- one receiver."
      , "data " ++ cls ++ " = " ++ cls ++ " (LS.Mailbox " ++ native ++ ") | " ++ cls ++ "Served (LS.Mailbox LS.Scalar)"
      , ""
      , "-- | A mailbox in this process."
      , "new" ++ cls ++ " :: P.IO " ++ cls
      , "new" ++ cls ++ " = " ++ cls ++ " P.<$> LS.newMailbox"
      , ""
      , "-- | Queues a message without waiting."
      , "send" ++ base ++ " :: " ++ cls ++ " -> " ++ native ++ " -> P.IO ()"
      , "send" ++ base ++ " (" ++ cls ++ " box) value = LS.sendMailbox box value"
      , "send" ++ base ++ " (" ++ cls ++ "Served box) value = _lawspecOr (Codec.encode " ++ codec ++ " value) P.>>= LS.sendMailbox box"
      , ""
      , "-- | The next message, waiting for it; throws LS.ActorStopped once closed and empty."
      , "receive" ++ base ++ " :: " ++ cls ++ " -> P.IO " ++ native
      , "receive" ++ base ++ " (" ++ cls ++ " box) = LS.receiveMailbox box"
      , "receive" ++ base ++ " (" ++ cls ++ "Served box) = LS.receiveMailbox box P.>>= (_lawspecOr P.. Codec.decode " ++ codec ++ ")"
      , ""
      , "-- | The next message within the given microseconds, or Nothing."
      , "receive" ++ base ++ "Within :: P.Int -> " ++ cls ++ " -> P.IO (P.Maybe " ++ native ++ ")"
      , "receive" ++ base ++ "Within micros (" ++ cls ++ " box) = LS.receiveMailboxWithin micros box"
      , "receive" ++ base ++ "Within micros (" ++ cls ++ "Served box) = LS.receiveMailboxWithin micros box P.>>= P.traverse (_lawspecOr P.. Codec.decode " ++ codec ++ ")"
      , ""
      , "-- | Refuses later sends; messages already sent can still be received."
      , "close" ++ base ++ " :: " ++ cls ++ " -> P.IO ()"
      , "close" ++ base ++ " (" ++ cls ++ " box) = LS.closeMailbox box"
      , "close" ++ base ++ " (" ++ cls ++ "Served box) = LS.closeMailbox box" ] ++
      case wire of
        Nothing -> []
        Just d ->
          [ ""
          , "-- | A mailbox on a node that other nodes send to at <node address>/name."
          , "serve" ++ base ++ " :: LS.Node -> P.String -> P.IO " ++ cls
          , "serve" ++ base ++ " node name = " ++ cls ++ "Served P.<$> LS.nodeMailbox node name _lawspecTypes (_lawspecDescriptor " ++ show d ++ ")"
          , ""
          , "-- | Sends to a mailbox served on another node."
          , "newtype " ++ cls ++ "Sender = " ++ cls ++ "Sender LS.RemoteMailbox"
          , ""
          , "-- | The mailbox served at an address on another node."
          , "connect" ++ base ++ " :: LS.Node -> P.String -> " ++ cls ++ "Sender"
          , "connect" ++ base ++ " node address = " ++ cls ++ "Sender (LS.remoteMailbox node address _lawspecTypes (_lawspecDescriptor " ++ show d ++ "))"
          , ""
          , "-- | Sends a message; waits until the mailbox has it, or throws LS.Unreachable."
          , "send" ++ base ++ "To :: " ++ cls ++ "Sender -> " ++ native ++ " -> P.IO ()"
          , "send" ++ base ++ "To (" ++ cls ++ "Sender remote) value = _lawspecOr (Codec.encode " ++ codec ++ " value) P.>>= LS.sendRemote remote" ]
      where
        n = C.mailboxName b
        base = cap n
        cls = mailboxClassName n
-- lawspec.mailboxes.JobsMailbox: a Java class for Java projects and a Kotlin
-- class for Kotlin ones (whose data types and codecs are Kotlin's).
jvm :: Bool -> Int -> [C.DataDeclaration] -> C.Mailbox -> Either String Artifact
jvm kotlin bits datas b = do
  let ty = C.mailboxType b
      name = mailboxClassName (C.mailboxName b)
      scalar = case ty of
        C.Constructor n [] | isInteger n || n `elem` ["Bool", "Text"] -> Just n
        _ -> Nothing
      wire = either (const Nothing) Just (describe bits datas [] ty)
  native <- if kotlin then kotlinDataType datas ty else javaDataType datas ty
  codec <- case scalar of
    Just n -> pure ("LawSpecRuntime.scalarConversion(" ++ show n ++ ", " ++ show bits ++ ")")
    Nothing
      | kotlin -> (\c -> "run { val symbols = mutableMapOf<String, Any>(); val codec = " ++ c ++
                          "; LawSpecRuntime.conversion<" ++ native ++ ">({ codec.encode(it) }, { codec.decode(it) }) }")
                  . D.render (D.Pretty 1000) <$> kotlinCodecDocWithContext (D.text "symbols") datas ty
      | otherwise -> (\c -> "LawSpecRuntime.conversion((" ++ c ++ ")::encode, (" ++ c ++ ")::decode)")
                  . D.render (D.Pretty 1000) <$> javaCodecDocWithContext (D.text "symbols") datas bits ty
  let imports = [ "import lawspec.runtime." ++ x | x <- ["LawSpecDataCodecs", "LawSpecDataSchema", "LawSpecKotlinCodecs"], (x ++ ".") `isInfixOf` codec ]
      descriptorText = maybe "(unit)" fst wire
      typesText = maybe "" (unwords . map snd . reverse . snd) wire
      doc = "Mailbox " ++ C.mailboxName b ++ ": messages from any number of senders, taken by one receiver."
  pure $ if kotlin
    then Artifact ("src/main/kotlin/lawspec/mailboxes/" ++ name ++ ".kt") (unlines $
      [ "// Generated by LawSpec from mailbox " ++ C.mailboxName b ++ ". Do not edit."
      , "package lawspec.mailboxes"
      , ""
      , "import lawspec.runtime.LawSpecRuntime" ] ++ imports ++
      [ ""
      , "/**"
      , " * " ++ doc ++ " send never waits; receive takes messages in the order they"
      , " * arrived; close refuses later sends. serve offers it to other nodes, and connect sends to one"
      , " * on another node: such a send waits until the mailbox has the message, delivered once."
      , " */"
      , "class " ++ name ++ " private constructor(private val mailbox: LawSpecRuntime.Mailbox<Any>, private val logical: Boolean) {"
      , "    constructor() : this(LawSpecRuntime.Mailbox<Any>(), false)"
      , ""
      , "    /** Queues value without waiting. */"
      , "    fun send(value: " ++ native ++ ") = mailbox.send(if (logical) conversion().toLogical(value) else value)"
      , ""
      , "    /** The next message; waits up to timeout (forever when null), then throws IllegalStateException; throws ActorStopped once closed and empty. */"
      , "    @JvmOverloads"
      , "    fun receive(timeout: java.time.Duration? = null): " ++ native ++ " {"
      , "        val value = mailbox.receive(timeout)"
      , "        @Suppress(\"UNCHECKED_CAST\")"
      , "        return (if (logical) conversion().toNative(value as LawSpecRuntime.Value) else value) as " ++ native
      , "    }"
      , ""
      , "    /** Refuses later sends; messages already sent can still be received. */"
      , "    fun close() = mailbox.close()"
      , ""
      , "    /** Sends to mailbox " ++ C.mailboxName b ++ " on another node. */"
      , "    class Sender internal constructor(private val remote: LawSpecRuntime.RemoteMailbox) {"
      , "        /** Sends value; waits until the mailbox has it, or throws Unreachable. */"
      , "        fun send(value: " ++ native ++ ") = remote.send(conversion().toLogical(value))"
      , "    }"
      , ""
      , "    companion object {"
      , "        private val schema = lawspec.runtime.LawSpecDataSchema.create()"
      , "        private const val bits = " ++ show bits
      , "        private val TYPES = LawSpecRuntime.valuesOf(" ++ show typesText ++ ")"
      , "        private val DESCRIPTOR = LawSpecRuntime.descriptor(" ++ show descriptorText ++ ")"
      , ""
      , "        private fun conversion(): LawSpecRuntime.Conversion = " ++ codec
      , ""
      , "        /** A mailbox on node that other nodes send to at {node address}/name. */"
      , "        @JvmStatic"
      , "        @Suppress(\"UNCHECKED_CAST\")"
      , "        fun serve(node: LawSpecRuntime.Node, name: String): " ++ name ++ " ="
      , "            " ++ name ++ "(node.mailbox(name, DESCRIPTOR, TYPES) as LawSpecRuntime.Mailbox<Any>, true)"
      , ""
      , "        /** Sends to the mailbox served at address on another node. */"
      , "        @JvmStatic"
      , "        @JvmOverloads"
      , "        fun connect(node: LawSpecRuntime.Node, address: String, timeout: Double = 5.0): Sender ="
      , "            Sender(node.remoteMailbox(address, DESCRIPTOR, TYPES, timeout))"
      , "    }"
      , "}" ]) "generated" "source"
    else Artifact ("src/main/java/lawspec/mailboxes/" ++ name ++ ".java") (unlines $
      [ "// Generated by LawSpec from mailbox " ++ C.mailboxName b ++ ". Do not edit."
      , "package lawspec.mailboxes;"
      , ""
      , "import lawspec.runtime.LawSpecRuntime;"
      , ""
      , "/**"
      , " * " ++ doc ++ " send never waits; receive takes messages in the order they"
      , " * arrived; close refuses later sends. serve offers it to other nodes, and connect sends to one"
      , " * on another node: such a send waits until the mailbox has the message, delivered once."
      , " */"
      , "public final class " ++ name ++ " {"
      , "  private static final LawSpecRuntime.Values TYPES = LawSpecRuntime.valuesOf(" ++ show typesText ++ ");"
      , "  private static final Object DESCRIPTOR = LawSpecRuntime.descriptor(" ++ show descriptorText ++ ");"
      , "  private final LawSpecRuntime.Mailbox<Object> mailbox;"
      , "  private final boolean logical;"
      , ""
      , "  public " ++ name ++ "() {"
      , "    this(new LawSpecRuntime.Mailbox<Object>(), false);"
      , "  }"
      , ""
      , "  private " ++ name ++ "(LawSpecRuntime.Mailbox<Object> mailbox, boolean logical) {"
      , "    this.mailbox = mailbox;"
      , "    this.logical = logical;"
      , "  }"
      , ""
      ] ++ [ l | scalar == Nothing, l <- ["  private static final lawspec.runtime.LawSpecSchema _schema =", "      lawspec.runtime.LawSpecDataSchema.create();", ""] ] ++
      [ "  @SuppressWarnings(\"unused\")"
      , "  private static LawSpecRuntime.Conversion conversion() {"
      , "    var symbols = new java.util.HashMap<String, Object>();"
      , "    return " ++ codec ++ ";"
      , "  }"
      , ""
      , "  /** Queues value without waiting. */"
      , "  public void send(" ++ native ++ " value) {"
      , "    mailbox.send(logical ? conversion().toLogical(value) : value);"
      , "  }"
      , ""
      , "  /** The next message, waiting forever; throws ActorStopped once closed and empty. */"
      , "  public " ++ native ++ " receive() {"
      , "    return receive(null);"
      , "  }"
      , ""
      , "  /** The next message; waits up to timeout (forever when null), then throws IllegalStateException. */"
      , "  @SuppressWarnings(\"unchecked\")"
      , "  public " ++ native ++ " receive(java.time.Duration timeout) {"
      , "    var value = mailbox.receive(timeout);"
      , "    return (" ++ native ++ ") (logical ? conversion().toNative((LawSpecRuntime.Value) value) : value);"
      , "  }"
      , ""
      , "  /** Refuses later sends; messages already sent can still be received. */"
      , "  public void close() {"
      , "    mailbox.close();"
      , "  }"
      , ""
      , "  /** A mailbox on node that other nodes send to at {node address}/name. */"
      , "  @SuppressWarnings({\"unchecked\", \"rawtypes\"})"
      , "  public static " ++ name ++ " serve(LawSpecRuntime.Node node, String name) {"
      , "    return new " ++ name ++ "((LawSpecRuntime.Mailbox) node.mailbox(name, DESCRIPTOR, TYPES), true);"
      , "  }"
      , ""
      , "  /** Sends to the mailbox served at address on another node. */"
      , "  public static Sender connect(LawSpecRuntime.Node node, String address) {"
      , "    return connect(node, address, 5.0);"
      , "  }"
      , ""
      , "  public static Sender connect(LawSpecRuntime.Node node, String address, double timeout) {"
      , "    return new Sender(node.remoteMailbox(address, DESCRIPTOR, TYPES, timeout));"
      , "  }"
      , ""
      , "  /** Sends to mailbox " ++ C.mailboxName b ++ " on another node. */"
      , "  public static final class Sender {"
      , "    private final LawSpecRuntime.RemoteMailbox remote;"
      , ""
      , "    Sender(LawSpecRuntime.RemoteMailbox remote) {"
      , "      this.remote = remote;"
      , "    }"
      , ""
      , "    /** Sends value; waits until the mailbox has it, or throws Unreachable. */"
      , "    public void send(" ++ native ++ " value) {"
      , "      remote.send(conversion().toLogical(value));"
      , "    }"
      , "  }"
      , "}" ]) "generated" "source"
