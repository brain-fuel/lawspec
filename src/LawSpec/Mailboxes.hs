-- | Scalars whose native mailbox conversion needs no structural schema.
mailboxScalar :: C.Type -> Maybe String
mailboxScalar (C.Constructor name []) | isInteger name || name `elem` ["Bool","Text"] = Just name
mailboxScalar _ = Nothing
