-- | jobs's class is JobsMailbox.
mailboxClassName :: String -> String
mailboxClassName n = case n of
  c : cs -> toUpper c : cs ++ "Mailbox"
  [] -> "Mailbox"

-- | Programs without mailboxes get no mailbox files.
mailboxArtifacts :: String -> Plan -> Either [Diagnostic] [Artifact]
mailboxArtifacts target plan = case concatMap C.unitMailboxes units of
  [] -> Right []
  boxes -> either (\message -> Left [Diagnostic "mailboxes" message Nothing]) Right $ case target of
    "python" -> python bits datas boxes
    "go" -> concat <$> mapM (\u -> goMailboxes bits datas (C.idText (C.unitId u)) (C.unitMailboxes u)) [u | u <- units, not (null (C.unitMailboxes u))]
    "javascript" -> web False bits datas boxes
    "typescript" -> web True bits datas boxes
    "rust" -> rust bits datas boxes
    "haskell" -> concat <$> mapM (haskell bits datas) [u | u <- units, not (null (C.unitMailboxes u))]
    "java" -> mapM (jvm False bits datas) boxes
    "kotlin" -> mapM (jvm True bits datas) boxes
    "scala" -> mapM (scalaMailbox bits datas) boxes
    _ -> Right []
  where
    units = map plannedUnit (plannedUnits plan)
    datas = planDataDeclarations plan
    bits = planMachineBits plan

-- | A line of Python at an indentation, laid out as ruff lays it out.
pyLine :: Int -> D.Doc -> String
pyLine indent doc = D.render pythonLayout (D.text (replicate indent ' ') <> D.nest indent doc)

params :: [String] -> D.Doc
params = D.delimitTrailing 4 "(" ")" . map D.text

python :: Int -> [C.DataDeclaration] -> [C.Mailbox] -> Either String [Artifact]
python bits datas boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, classes) <- foldl (\acc b -> do
      (t, cs) <- acc
      native <- D.render (D.Pretty 1000) <$> pythonDataTypeDoc datas (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', cs ++ [cls b native (Just d)])
        Left _ -> pure (t, cs ++ [cls b native (Nothing :: Maybe String)])) (Right ([], [])) boxes
  let header =
        [ "# Generated by LawSpec. Do not edit."
        , "\"\"\"Typed mailboxes: many senders, one receiver."
        , ""
        , "send never waits; receive takes messages in the order they arrived;"
        , "close refuses later sends. serve(node, name) offers a mailbox to other"
        , "nodes, and connect(node, address) sends to one from another node: such a"
        , "send waits until the mailbox has the message, and it is delivered once."
        , "\"\"\""
        , ""
        , "from __future__ import annotations"
        , ""
        , "import builtins as _builtins"
        , "import lawspec_runtime as ls"
        , ""
        , "try:"
        , "    import lawspec_data as data"
        , "    import lawspec_schema as _schema"
        , ""
        , "    _SCHEMA = data.make_schema()"
        , "except ImportError:"
        , "    _SCHEMA = None"
        , ""
        , "_FORMS = " ++ literalFor "python" (unwords (map snd (reverse table)))
        , "_TYPES = ls.Values({str(form[1]): form for form in ls.read_descriptor(_FORMS)})"
        , ""
        , ""
        , "def _native(reference, value):"
        , "    return value if reference is None else _SCHEMA.to_native(reference, value)"
        , ""
        , ""
        , "def _logical(reference, value):"
        , "    return value if reference is None else _SCHEMA.from_native(reference, value)" ]
  pure [Artifact "src/lawspec_mailboxes.py" (unlines header ++ concatMap ("\n\n" ++) classes) "generated" "source"]
  where
    reference ty = if requiresSchema datas ty then either (const "None") (D.render D.Compact) (pythonTypeReferenceDoc ty) else "None"
    cls b native wire = unlines $
      [ "class " ++ name ++ ":"
      , "    \"\"\"Mailbox " ++ C.mailboxName b ++ ": messages of " ++ native ++ " from any number of senders,"
      , "    taken by one receiver.\"\"\""
      , ""
      , "    def __init__(self, mailbox: ls.Mailbox | None = None, logical: bool = False):"
      , "        self._mailbox = ls.Mailbox() if mailbox is None else mailbox"
      , "        self._logical = logical"
      , ""
      , "    def send(self, value: " ++ native ++ ") -> None:"
      , "        \"\"\"Queues value without waiting.\"\"\""
      , pyLine 8 (E.call "self._mailbox.send" [D.group (E.call "_logical" [D.text ref, D.text "value"] <> D.softline <>
          D.text "if self._logical" <> D.softline <> D.text "else value")])
      , ""
      , pyLine 4 (D.text "def receive" <> params ["self", "timeout: float | None = None"] <> D.text (" -> " ++ native ++ ":"))
      , "        \"\"\"The next message; waits up to timeout seconds (forever when None),"
      , "        then raises TimeoutError; raises ls.ActorStopped once closed and empty.\"\"\""
      , "        value = self._mailbox.receive(timeout)"
      , pyLine 8 (D.text "return " <> D.unparen (D.parens (E.call "_native" [D.text ref, D.text "value"] <> D.softline <>
          D.text "if self._logical" <> D.softline <> D.text "else value")))
      , ""
      , pyLine 4 (D.text "def receive_within" <> params ["self", "within: ls.timedelta", "clock=None"] <> D.text (" -> " ++ native ++ " | None:"))
      , "        \"\"\"The next message, or None when none arrives within the duration: the"
      , "        Mailbox ability's receive ... within d, on clock (a Clock handler; the"
      , "        real clock when None). Raises ls.ActorStopped once closed and empty.\"\"\""
      , "        micros = within // ls.timedelta(microseconds=1)"
      , "        value = self._mailbox.receive_within(micros, clock)"
      , "        if value is None:"
      , "            return None"
      , pyLine 8 (D.text "return " <> D.unparen (D.parens (E.call "_native" [D.text ref, D.text "value"] <> D.softline <>
          D.text "if self._logical" <> D.softline <> D.text "else value")))
      , ""
      , "    def close(self) -> None:"
      , "        \"\"\"Refuses later sends; messages already sent can still be received.\"\"\""
      , "        self._mailbox.close()" ] ++
      case wire of
        Nothing -> []
        Just d ->
          [ ""
          , "    @staticmethod"
          , "    def serve(node: ls.Node, name: str) -> " ++ name ++ ":"
          , "        \"\"\"A mailbox on node that other nodes send to at <node address>/name.\"\"\""
          , pyLine 8 (D.text "wire = " <> E.call "ls.read_descriptor" [E.quoted d] <> D.text "[0]")
          , pyLine 8 (D.text "return " <> E.call name [E.call "node.mailbox" [D.text "name", D.text "wire", D.text "_TYPES"], D.text "logical=True"])
          , ""
          , "    @staticmethod"
          , pyLine 4 (D.text "def connect" <> params ["node: ls.Node", "address: str", "timeout: float = 5.0"] <> D.text (" -> " ++ name ++ "Sender:"))
          , "        \"\"\"Sends to the mailbox served at address on another node.\"\"\""
          , pyLine 8 (D.text "wire = " <> E.call "ls.read_descriptor" [E.quoted d] <> D.text "[0]")
          , pyLine 8 (D.text "return " <> E.call (name ++ "Sender") [E.call "node.remote_mailbox" [D.text "address", D.text "wire", D.text "_TYPES", D.text "timeout"]])
          , ""
          , ""
          , "class " ++ name ++ "Sender:"
          , "    \"\"\"Sends to mailbox " ++ C.mailboxName b ++ " on another node.\"\"\""
          , ""
          , "    def __init__(self, remote: ls.RemoteMailbox):"
          , "        self._remote = remote"
          , ""
          , "    def send(self, value: " ++ native ++ ") -> None:"
          , "        \"\"\"Sends value; waits until the mailbox has it, or raises ls.Unreachable.\"\"\""
          , pyLine 8 (E.call "self._remote.send" [E.call "_logical" [D.text ref, D.text "value"]]) ]
      where
        name = mailboxClassName (C.mailboxName b)
        ref = reference (C.mailboxType b)

-- | Go: a lawspec_mailboxes.go in each unit's package. NewJobsMailbox makes a
-- local mailbox; ServeJobsMailbox offers one on a node; ConnectJobsMailbox
-- sends to one on another node.
goMailboxes :: Int -> [C.DataDeclaration] -> String -> [C.Mailbox] -> Either String [Artifact]
goMailboxes bits datas unit boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, bodies) <- foldl (\acc b -> do
      (t, bs) <- acc
      native <- GoData.goDataType datas (C.mailboxType b)
      (wire, t') <- pure (case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> (Just d, t')
        Left _ -> (Nothing, t))
      body <- box b native wire
      pure (t', bs ++ [body])) (Right ([], [])) boxes
  let parts = splitDots unit
      wired = not (null table) || any (\b -> either (const False) (const True) (describe bits datas [] (C.mailboxType b))) boxes
      schemaUsed = any (GoData.requiresSchema datas . C.mailboxType) boxes
      header =
        [ "// " ++ goGeneratedMarker
        , ""
        , "package " ++ last parts
        , ""
        , "import \"time\""
        , ""
        , "// Typed mailboxes: many senders, one receiver. Send never waits; Receive"
        , "// takes messages in the order they arrived; Close refuses later sends."
        , "// Serve<Name>Mailbox offers one to other nodes, and Connect<Name>Mailbox"
        , "// sends to one on another node: such a send waits until the mailbox has"
        , "// the message, and it is delivered once." ] ++
        [ "\nvar lawSpecMailboxTypes = LawSpecTypes(" ++ show (unwords (map snd (reverse table))) ++ ")" | wired ] ++
        [ "\nvar lawSpecMailboxSchema = lawSpecDataSchemaRegistry()" | schemaUsed ] ++
        [ "\nvar _ = time.Second" ]
  pure [Artifact (intercalate "/" parts ++ "/lawspec_mailboxes.go") (unlines (header ++ concat bodies)) "generated" "source"]
  where
    splitDots s = case break (== '.') s of
      (a, []) -> [a]
      (a, _ : rest) -> a : splitDots rest
    unitType t = t == C.Constructor "Unit" []
    codec ty = replaceAll "schema, bits" ("lawSpecMailboxSchema, " ++ show bits) <$> GoData.goCodec datas ty
    toNative ty value
      | unitType ty = pure value
      | GoData.requiresSchema datas ty = (\c -> c ++ ".toNative(" ++ value ++ ")") <$> codec ty
      | C.Constructor n [] <- ty = (\g -> "lsToNative(" ++ show n ++ ", " ++ value ++ ", " ++ show bits ++ ").(" ++ g ++ ")") <$> GoData.goDataType datas ty
      | otherwise = Left "no Go conversion for this type"
    toLogical ty value
      | unitType ty = pure value
      | GoData.requiresSchema datas ty = (\c -> c ++ ".fromNative(" ++ value ++ ")") <$> codec ty
      | C.Constructor n [] <- ty = pure ("lsFromNative(" ++ show n ++ ", " ++ value ++ ", " ++ show bits ++ ")")
      | otherwise = Left "no Go conversion for this type"
    box b native wire = do
      let name = mailboxClassName (C.mailboxName b)
          ty = C.mailboxType b
      local <- pure
        [ ""
        , "// " ++ name ++ " is mailbox " ++ C.mailboxName b ++ ": messages of " ++ native ++ " from any number"
        , "// of senders, taken by one receiver."
        , "type " ++ name ++ " struct {"
        , "\tbox     *LawSpecMailbox"
        , "\tlogical bool"
        , "}"
        , ""
        , "// New" ++ name ++ " makes an empty mailbox."
        , "func New" ++ name ++ "() " ++ name ++ " {"
        , "\treturn " ++ name ++ "{box: NewLawSpecMailbox()}"
        , "}"
        , ""
        , "// Close refuses later sends; messages already sent can still be received."
        , "func (m " ++ name ++ ") Close() {"
        , "\tm.box.Close()"
        , "}" ]
      remote <- case wire of
        Nothing -> pure
          [ ""
          , "// Send queues value without waiting; it fails once the mailbox is closed."
          , "func (m " ++ name ++ ") Send(value " ++ native ++ ") error {"
          , "\treturn m.box.Send(value)"
          , "}"
          , ""
          , "// Receive is the next message, waiting up to timeout (forever when zero); it"
          , "// fails on timeout, or once closed and empty."
          , "func (m " ++ name ++ ") Receive(timeout time.Duration) (" ++ native ++ ", error) {"
          , "\tvalue, err := m.box.Receive(timeout)"
          , "\tif err != nil {"
          , "\t\tvar none " ++ native
          , "\t\treturn none, err"
          , "\t}"
          , "\treturn value.(" ++ native ++ "), nil"
          , "}"
          , ""
          , "// ReceiveWithin is the next message and true, or false when none arrives"
          , "// within d: the Mailbox ability's receive ... within d, on clock (a Clock"
          , "// handler; real time when none is given). It fails once closed and empty."
          , "func (m " ++ name ++ ") ReceiveWithin(d time.Duration, clock ...any) (" ++ native ++ ", bool, error) {"
          , "\tvar none " ++ native
          , "\tvalue, ok, err := m.box.ReceiveWithin(d, clock...)"
          , "\tif err != nil || !ok {"
          , "\t\treturn none, false, err"
          , "\t}"
          , "\treturn value.(" ++ native ++ "), true, nil"
          , "}" ]
        Just d -> do
          logical <- toLogical ty "value"
          back <- toNative ty "value.(LawSpecValue)"
          pure
            [ ""
            , "// Send queues value without waiting; it fails once the mailbox is closed."
            , "func (m " ++ name ++ ") Send(value " ++ native ++ ") error {"
            , "\tif m.logical {"
            , "\t\treturn m.box.Send(" ++ logical ++ ")"
            , "\t}"
            , "\treturn m.box.Send(value)"
            , "}"
            , ""
            , "// Receive is the next message, waiting up to timeout (forever when zero); it"
            , "// fails on timeout, or once closed and empty."
            , "func (m " ++ name ++ ") Receive(timeout time.Duration) (" ++ native ++ ", error) {"
            , "\tvalue, err := m.box.Receive(timeout)"
            , "\tif err != nil {"
            , "\t\tvar none " ++ native
            , "\t\treturn none, err"
            , "\t}"
            , "\tif m.logical {"
            , "\t\treturn " ++ back ++ ", nil"
            , "\t}"
            , "\treturn value.(" ++ native ++ "), nil"
            , "}"
            , ""
            , "// ReceiveWithin is the next message and true, or false when none arrives"
            , "// within d: the Mailbox ability's receive ... within d, on clock (a Clock"
            , "// handler; real time when none is given). It fails once closed and empty."
            , "func (m " ++ name ++ ") ReceiveWithin(d time.Duration, clock ...any) (" ++ native ++ ", bool, error) {"
            , "\tvar none " ++ native
            , "\tvalue, ok, err := m.box.ReceiveWithin(d, clock...)"
            , "\tif err != nil || !ok {"
            , "\t\treturn none, false, err"
            , "\t}"
            , "\tif m.logical {"
            , "\t\treturn " ++ back ++ ", true, nil"
            , "\t}"
            , "\treturn value.(" ++ native ++ "), true, nil"
            , "}"
            , ""
            , "// Serve" ++ name ++ " is a mailbox on node that other nodes send to at"
            , "// <node address>/name."
            , "func Serve" ++ name ++ "(node *LawSpecNode, name string) (" ++ name ++ ", error) {"
            , "\tbox, err := node.Mailbox(name, LawSpecDescriptor(" ++ show d ++ "), lawSpecMailboxTypes)"
            , "\tif err != nil {"
            , "\t\treturn " ++ name ++ "{}, err"
            , "\t}"
            , "\treturn " ++ name ++ "{box: box, logical: true}, nil"
            , "}"
            , ""
            , "// " ++ name ++ "Sender sends to mailbox " ++ C.mailboxName b ++ " on another node."
            , "type " ++ name ++ "Sender struct{ remote *LawSpecRemoteMailbox }"
            , ""
            , "// Connect" ++ name ++ " sends to the mailbox served at address on another"
            , "// node; each send waits up to timeout (5 seconds when zero)."
            , "func Connect" ++ name ++ "(node *LawSpecNode, address string, timeout time.Duration) " ++ name ++ "Sender {"
            , "\treturn " ++ name ++ "Sender{node.RemoteMailbox(address, LawSpecDescriptor(" ++ show d ++ "), lawSpecMailboxTypes, timeout)}"
            , "}"
            , ""
            , "// Send sends value and waits until the mailbox has it, or fails with"
            , "// LawSpecUnreachable."
            , "func (s " ++ name ++ "Sender) Send(value " ++ native ++ ") error {"
            , "\treturn s.remote.Send(" ++ logical ++ ")"
            , "}" ]
      pure (local ++ remote)
    replaceAll old new s = case s of
      [] -> []
      _ | take (length old) s == old -> new ++ replaceAll old new (drop (length old) s)
      c : rest -> c : replaceAll old new rest
-- | lawspec_mailboxes for JavaScript and TypeScript: receive and a send
-- between nodes are asynchronous.
web :: Bool -> Int -> [C.DataDeclaration] -> [C.Mailbox] -> Either String [Artifact]
web ts bits datas boxes = do
  let names = map C.mailboxName boxes
  if length (nub names) /= length names then Left ("two mailboxes share a name: " ++ unwords names) else pure ()
  (table, classes) <- foldl (\acc b -> do
      (t, cs) <- acc
      native <- Web.webDataTypeOfWith datas [] (C.mailboxType b)
      case describe bits datas t (C.mailboxType b) of
        Right (d, t') -> pure (t', cs ++ [cls b native (Just d)])
        Left _ -> pure (t, cs ++ [cls b native (Nothing :: Maybe String)])) (Right ([], [])) boxes
  let usesData = any (Web.requiresSchema datas . C.mailboxType) boxes
      importLine name file = J.ImportDecl False (J.ImportNamespace name) ("./" ++ file ++ (if ts then ".js" else ".mjs"))
      ref' = J.Ident "reference"
      header =
        [ J.Comment
          [ "// Generated by LawSpec. Do not edit."
          , "// Typed mailboxes: many senders, one receiver. send never waits; receive"
          , "// resolves to the next message in the order they arrived; close refuses"
          , "// later sends. serve(node, name) offers a mailbox to other nodes, and"
          , "// connect(node, address) sends to one from another node: such a send"
          , "// resolves once the mailbox has the message, and it is delivered once." ]
        , importLine "ls" "lawspec_runtime" ] ++
        [ importLine "data" "lawspec_data" | usesData ] ++
        [ J.Blank
        , J.constDecl "_TYPES" (J.index (J.call "ls.valuesFrom" [J.Str (unwords (map snd (reverse table) ++ ["(unit)"]))]) (J.num 0))
        , J.VarDecl "const" (J.PIdent "_SCHEMA") anyT (Just (if usesData then J.call "data.makeSchema" [] else J.Null))
        , J.constDecl "_native" (J.Arrow False [anyP "reference", anyP "d", anyP "value"] anyT (J.ExpressionBody
            (J.Conditional (J.Binary "===" ref' J.Null) (J.call "ls.nativeScalar" [J.Ident "d", J.Ident "value"]) (J.call "_SCHEMA.toNative" [ref', J.Ident "value"]))))
        , J.constDecl "_logical" (J.Arrow False [anyP "reference", anyP "value"] anyT (J.ExpressionBody
            (J.Conditional (J.Binary "===" ref' J.Null) (J.Ident "value") (J.call "_SCHEMA.fromNative" [ref', J.Ident "value"]))))
        , J.constDecl "_d" (J.Arrow False [anyP "text"] anyT (J.ExpressionBody (J.index (J.call "ls.readDescriptor" [J.Ident "text"]) (J.num 0)))) ]
  pure [Artifact ("src/lawspec_mailboxes." ++ (if ts then "ts" else "mjs")) (J.printModule (if ts then J.TypeScript else J.JavaScript) (header ++ concat classes)) "generated" "source"]
  where
    anyT = typedT (J.TKeyword "any")
    typedT t = if ts then Just t else Nothing
    typedP n t = (J.param n) { J.paramType = typedT t }
    anyP n = (J.param n) { J.paramType = anyT }
    defaulted n t d = (typedP n t) { J.paramDefault = Just d }
    field n t = J.Field [] n (typedT t) Nothing
    this' n = J.member J.This n
    assignThis n v = J.ExprStmt (J.Assign "=" (this' n) v)
    reference ty = if Web.requiresSchema datas ty then either (const J.Null) id (Web.webTypeReference ty) else J.Null
    doc text = J.MemberComment ["/** " ++ text ++ " */"]
    docLines ls = J.MemberComment (["/**"] ++ map (" * " ++) ls ++ [" */"])
    method name params result body = J.Method False False "method" name params result body
    cls b native wire =
      [ J.Blank
      , J.Comment ["/** Mailbox " ++ C.mailboxName b ++ ": messages from any number of senders, taken by one receiver. */"]
      , J.ClassDecl True name [] Nothing [] (
        [ field "mailbox" (J.TRef "ls.Mailbox" [])
        , field "logical" (J.TKeyword "boolean")
        , field "descriptor" (J.TKeyword "any")
        , J.Method False False "method" "constructor"
            [ defaulted "mailbox" (J.TUnion [J.TRef "ls.Mailbox" [], J.TKeyword "null"]) J.Null
            , defaulted "logical" (J.TKeyword "boolean") (J.BoolLit False)
            , defaulted "descriptor" (J.TKeyword "any") J.Null ] Nothing
            [ assignThis "mailbox" (J.Binary "??" (J.Ident "mailbox") (J.new' "ls.Mailbox" []))
            , assignThis "logical" (J.Ident "logical")
            , assignThis "descriptor" (J.Ident "descriptor") ]
        , doc "Queues value without waiting."
        , method "send" [typedP "value" native] (typedT (J.TKeyword "void"))
            [J.ExprStmt (J.method (this' "mailbox") "send" [J.Conditional (this' "logical") (J.call "_logical" [ref, J.Ident "value"]) (J.Ident "value")])]
        , docLines [ "The next message; waits up to timeoutMs (forever when omitted), then"
                   , "rejects; rejects with ls.ActorStopped once closed and empty." ]
        , J.Method False True "method" "receive" [typedP (if ts then "timeoutMs?" else "timeoutMs") (J.TKeyword "number")] (typedT (J.TRef "Promise" [native]))
            [ J.VarDecl "const" (J.PIdent "value") anyT (Just (J.Await (J.method (this' "mailbox") "receiveAsync" [J.Ident "timeoutMs"])))
            , J.ret (J.Conditional (this' "logical") (J.call "_native" [ref, this' "descriptor", J.Ident "value"]) (J.Ident "value")) ]
        , docLines [ "The next message, or null when none arrives within withinMs: the"
                   , "Mailbox ability's receive ... within d, on clock (a Clock handler; the"
                   , "real clock when null). Rejects with ls.ActorStopped once closed and empty." ]
        , J.Method False True "method" "receiveWithin" [typedP "withinMs" (J.TKeyword "number"), defaulted "clock" (J.TKeyword "any") J.Null]
            (typedT (J.TRef "Promise" [J.TUnion [native, J.TKeyword "null"]]))
            [ J.VarDecl "const" (J.PIdent "value") anyT (Just (J.Await (J.method (this' "mailbox") "receiveWithin"
                [J.call "BigInt" [J.call "Math.round" [J.Binary "*" (J.Ident "withinMs") (J.num 1000)]], J.Ident "clock"])))
            , J.IfSingle (J.Binary "===" (J.Ident "value") J.Null) (J.ret J.Null)
            , J.ret (J.Conditional (this' "logical") (J.call "_native" [ref, this' "descriptor", J.Ident "value"]) (J.Ident "value")) ]
        , doc "Refuses later sends; messages already sent can still be received."
        , method "close" [] (typedT (J.TKeyword "void")) [J.ExprStmt (J.method (this' "mailbox") "close" [])] ] ++
        (case wire of
          Nothing -> []
          Just d ->
            [ doc "A mailbox on node that other nodes send to at <node address>/name."
            , J.Method True False "method" "serve" [typedP "node" (J.TRef "ls.Node" []), typedP "name" (J.TKeyword "string")] (typedT (J.TRef name []))
                [J.ret (J.new' name [J.method (J.Ident "node") "mailbox" [J.Ident "name", J.call "_d" [J.Str d], J.Ident "_TYPES"], J.BoolLit True, J.call "_d" [J.Str d]])]
            , doc "Sends to the mailbox served at address on another node."
