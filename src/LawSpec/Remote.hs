      , "  for (const [h, f, a, r] of Object.values(DEFINITIONS)) table[h] = [f, a, r];"
      , "  return node.serveDefinitions(table, TYPES);"
      , "}"
      , ""
      , "/** The content hash of the definition with this qualified name. */"
      , "export function digest(name" ++ typed "string" ++ ")" ++ typed "string" ++ " {"
