      , "}"
      , ""
      , "/**"
      , " * Evaluates the named definition on the node at address, by its content"
      , " * hash; rejects with ls.Unreachable when that node does not answer."
      , " */"
      , "export function evaluate(node" ++ typed "ls.Node" ++ ", address" ++ typed "string" ++ ", name" ++ typed "string" ++ ", ...args" ++ typed "any[]" ++ ")" ++ typed "Promise<any>" ++ " {"
      , "  const [h, , a, r] = DEFINITIONS[name];"
      , "  return node.evaluate(address, h, args, a, r, TYPES);"
      , "}" ]
      where
        ext = if ts then "js" else "mjs"
        typed t = if ts then ": " ++ t else ""
        wrap call = case stripAwait call of
          (True, f) -> "async (...args" ++ typed "any[]" ++ ") => " ++ callee f ++ "(new Map(), ...args)"
          (False, f) -> "(...args" ++ typed "any[]" ++ ") => " ++ callee f ++ "(new Map(), ...args)"
        callee f = if ts then "(" ++ f ++ " as any)" else f
        stripAwait c = if take 6 c == "await " then (True, drop 6 c) else (False, c)
    haskell = haskellRemote forms [(r, call) | r <- remotes, Just call <- [callable r]]

-- | The Haskell module LawSpecRemote: definitions, serve, digest and
-- evaluate, over logical values (LS.Scalar).
haskellRemote :: [String] -> [(Remote, String)] -> String
haskellRemote forms entries = unlines $
  [ "-- Generated by LawSpec. Do not edit."
  , "-- | Checked definitions that other nodes can evaluate, by content hash."
  , "--"
  , "-- serve lets other nodes evaluate them on a node; evaluate evaluates one,"
  , "-- by its qualified name, on the node at an address. Values are logical"
  , "-- values (LS.Scalar), as the runtime's checks use them."
  , "module LawSpecRemote (definitions, types, serve, digest, evaluate) where"
  , ""
  , "import qualified Prelude as P"
  , "import qualified Control.Exception as E"
  , "import qualified LawSpecRuntime as LS"
  , "import qualified LawSpecDefinitionBodies as Definitions"
  , ""
  , "-- | The data types the descriptors use."
  , "types :: LS.DataTable"
  , "types = [(LS.descriptorName n, f) | f@(LS.DescList (LS.DescAtom \"data\" : n : _)) <- LS.readDescriptor " ++ show (unwords forms) ++ "]"
  , ""
  , "d :: P.String -> LS.Descriptor"
  , "d text = case LS.readDescriptor text of"
  , "  form : _ -> form"
  , "  [] -> P.error \"empty descriptor\""
  , ""
  , "call :: (LS.SymbolContext -> [LS.Scalar] -> P.Either P.String LS.Scalar) -> [LS.Scalar] -> P.IO LS.Scalar"
  , "call f args = do"
  , "  symbols <- LS.newSymbolContext"
  , "  P.either (E.throwIO P.. E.ErrorCall) P.pure (f symbols args)"
  , ""
  , "-- | Each definition by qualified name: its content hash, function,"
  , "-- argument descriptors and result descriptor."
  , "definitions :: [(P.String, (P.String, [LS.Scalar] -> P.IO LS.Scalar, [LS.Descriptor], LS.Descriptor))]"
  , "definitions =" ] ++
  zipWith (\i (r, f) -> (if i == (0 :: Int) then "  [ " else "  , ") ++ "(" ++ show (remoteName r) ++ ", (" ++ show (remoteDigest r) ++
      ", call (\\s a -> case a of { [" ++ intercalate ", " (args r) ++ "] -> " ++ unwords (f : "s" : args r) ++
      "; _ -> P.Left \"wrong number of arguments\" }), [" ++ intercalate ", " ["d " ++ show x | x <- remoteArguments r] ++ "], d " ++
      show (remoteResult r) ++ "))") [0 ..] entries ++
  [ "  ]" | not (null entries) ] ++ [ "  []" | null entries ] ++
  [ ""
  , "-- | Lets other nodes evaluate these definitions on a node."
  , "serve :: LS.Node -> P.IO P.String"
  , "serve node = LS.serveDefinitions node types [(h, f, a, r) | (_, (h, f, a, r)) <- definitions]"
  , ""
  , "-- | The content hash of the definition with this qualified name."
  , "digest :: P.String -> P.Maybe P.String"
  , "digest name = (\\(h, _, _, _) -> h) P.<$> P.lookup name definitions"
  , ""
  , "-- | Evaluates the named definition on the node at an address, by its"
  , "-- content hash, waiting up to 5 seconds (LS.Unreachable after that)."
  , "evaluate :: LS.Node -> P.String -> P.String -> [LS.Scalar] -> P.IO LS.Scalar"
  , "evaluate node address name args = case P.lookup name definitions of"
  , "  P.Just (h, _, a, r) -> LS.evaluateRemote node address h args a r types 5"
  , "  P.Nothing -> E.throwIO (E.ErrorCall (\"no definition \" P.++ name))" ]
  where args r = ["x" ++ show k | k <- [0 .. length (remoteArguments r) - 1]]
