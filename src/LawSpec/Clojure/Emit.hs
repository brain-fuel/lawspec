-- | The Clojure project from the Java target's files for the same plan.
clojureFromProduct :: ClojureBindings -> Plan -> Product.JvmProduct -> Either [Diagnostic] [Artifact]
clojureFromProduct cb plan product = do
  -- The appended type index needs paths only. Materialize that small index
  -- before conversion so its thunk cannot retain all original Java contents.
  length (concat typeNames) `seq` pure ()
  converted <- concat <$> mapM convert javaFiles
  handlers <- mapM boundHandler (boundHandlers cb)
  mappings <- mapM failureEntry (boundFailures cb)
  pure (converted ++ runtime ++ handlers ++ [failures mappings, types] ++ [generators | not (null (boundGenerators cb))])
  where
    javaFiles = Product.jvmArtifacts product
    -- A bound handler's class, over the ability's interface.
    boundHandler (key, className, target) = do
      let unit = takeWhile (/= ':') key
          ability = filter isAlphaNum (reverse (takeWhile (/= ':') (reverse key)))
          parts = splitOn '.' unit
          owner = concatMap capital (splitOn '_' (last parts))
          file = "src/main/java/lawspec/abilities/" ++ concatMap (++ "/") (init parts) ++ owner ++ ".java"
          interface = intercalate "." (["lawspec", "abilities"] ++ init parts ++ [owner, ability])
      operations <- maybe (diagnose ("no checked ability interface for the bound handler of " ++ key))
        (Right . Abi.interfaceOperations) (listToMaybe [abi | abi <- Product.jvmInterfaces product, Abi.interfaceName abi == interface])
      pure (Artifact ("java/src/lawspec/clojure/bound/" ++ className ++ ".java")
        (boundHandlerJava className interface target operations) "generated" "source")
    -- Bound generators: test.check generators of tagged values, drawn from
    -- a seed and size the LawSpec generator gives.
    generators = Artifact "java/test/lawspec/clojure/bound/Generators.java" (unlines $
      [ "// Generated by LawSpec. Do not edit."
      , "package lawspec.clojure.bound;"
      , ""
      , "import clojure.java.api.Clojure;"
      , "import lawspec.testing.check.Generator;"
      , ""
      , "/** The generators lawspec.edn binds: test.check generators of tagged values. */"
      , "@SuppressWarnings(\"unchecked\")"
      , "public final class Generators {"
      , "  private Generators() {}"
      , ""
      , "  private static <T> Generator<T> of(String namespace, String function) {"
      , "    Object made = lawspec.clojure.LawSpecClojure.var(namespace, function).invoke();"
      , "    Object generate = lawspec.clojure.LawSpecClojure.var(\"clojure.test.check.generators\", \"generate\");"
      , "    return draws -> {"
      , "      long seed = draws.draw(Integer.MIN_VALUE, Integer.MAX_VALUE);"
      , "      Object value = ((clojure.lang.IFn) generate).invoke(made, (long) draws.getSizeHint(), seed);"
      , "      return (T) lawspec.clojure.LawSpecClojure.toJava(value, Object.class);"
      , "    };"
      , "  }" ] ++
      concat [ [ "", "  public static <T> Generator<T> " ++ m ++ "() {"
               , "    return of(" ++ show ns ++ ", " ++ show fn ++ ");", "  }" ]
             | (m, (ns, fn)) <- boundGenerators cb ] ++
      [ "}" ]) "generated" "test"
    -- The data types by their tags' namespaces, so a type named with an
    -- acronym (HTTPError, tagged :http-error/...) is found again.
    types = Artifact "java/src/lawspec/clojure/LawSpecClojureTypes.java" (unlines $
      [ "// Generated by LawSpec. Do not edit."
      , "package lawspec.clojure;"
      , ""
      , "/** The model's data types, by the namespace of their values' tags. */"
      , "public final class LawSpecClojureTypes {"
      , "  private LawSpecClojureTypes() {}"
      , ""
      , "  public static final java.util.Map<String, String> TYPES = java.util.Map.ofEntries(" ] ++
      [ intercalate ",\n" [ "      java.util.Map.entry(" ++ show (tagWords name) ++ ", " ++ show ("lawspec.data." ++ name) ++ ")"
                           | name <- typeNames ] ] ++
      [ "  );", "}" ]) "generated" "source"
    typeNames = [name | a <- javaFiles,
      Just rest <- [stripPrefix "src/main/java/lawspec/data/" (artifactPath a)],
      ".java" `isSuffixOf` rest, let name = take (length rest - 5) rest, '/' `notElem` name]
    -- The ex-info :types that bound failures name.
    failureEntry (kind,binding) = do
      rootClass <- messageClass (C.failureType binding) (C.failureConstructor binding)
      children <- payloadClasses (C.failurePayload binding)
      pure (kind,rootClass : (if C.failureMessage binding then "true" else "false") : children)
    messageClass (C.Constructor name _) tag = case
      [(d,c) | d <- planDataDeclarations plan, C.dataId d == C.Id name,
               c <- C.dataConstructors d, C.constructorId c == tag] of
      [(d,c)] -> either (\problem -> Left [Diagnostic "target" problem Nothing]) Right
        (JavaData.javaConstructorBinaryClass (planDataDeclarations plan) d c)
      _ -> Left [Diagnostic "target" "unresolved Clojure native failure constructor" Nothing]
    messageClass _ _ = Left [Diagnostic "target" "a Clojure native failure requires a concrete data type" Nothing]
    payloadClasses Nothing = pure []
    payloadClasses (Just C.ExceptionMessage) = pure []
    payloadClasses (Just (C.MessageProduct ty tag child)) = do
      name <- messageClass ty tag
      (name:) <$> payloadClasses (Just child)
    failures mappings = Artifact "java/src/lawspec/clojure/LawSpecClojureFailures.java" (unlines $
      [ "// Generated by LawSpec. Do not edit."
      , "package lawspec.clojure;"
      , ""
      , "/** The failures lawspec.edn binds: an ex-info's :type, the failure's tag, and whether it takes the message. */"
      , "public final class LawSpecClojureFailures {"
      , "  private LawSpecClojureFailures() {}"
      , ""
      , "  public static final java.util.Map<String, String[]> FAILURES = java.util.Map.ofEntries(" ] ++
      [ intercalate ",\n" [ "      java.util.Map.entry(" ++ show kind ++ ", new String[] {" ++ intercalate ", " (map show classes) ++ "})"
                           | (kind, classes) <- mappings ] ] ++
      [ "  );", "}" ]) "generated" "source"
    bound unit name = lookup (unit, name) (boundFunctions cb)
    units = [C.idText (C.unitId (plannedUnit pu)) | pu <- plannedUnits plan]
    -- The Java class of a unit: example.parse_port is example.ParsePort.
    javaClass unit = let parts = splitOn '.' unit
                     in intercalate "/" (init parts ++ [concatMap capital (splitOn '_' (last parts))])
    unitOfClass path = listToMaybe [u | u <- units, javaClass u ++ ".java" == path]
    diagnose message = Left [Diagnostic "target" message Nothing]
    convert a
      | path `elem` ["src/test/java/lawspec/testing/LawSpecOrder.java", "src/test/resources/junit-platform.properties"] = pure []
      -- The built-in units' default handlers stay Java.
      | ownership a == "user", Just rest <- stripPrefix "src/main/java/" path, "lawspec/" `isPrefixOf` rest =
          pure [a { artifactPath = "java/src/" ++ rest }]
      | ownership a == "user", Just rest <- stripPrefix "src/main/java/" path, ".java" `isSuffixOf` rest = do
          stub <- maybe (diagnose ("missing checked JVM adapter ABI for " ++ rest)) Right (lookup path (Product.jvmAdapters product))
          let unit = maybe (classUnit rest) id (unitOfClass rest)
              ns = namespaceOf unit
              user = clojureStub unit ns (bound unit) stub
              -- A unit whose functions lawspec.edn all binds has no namespace to write.
              unbound = [() | Function _ o <- stubItems stub, bound unit (opName o) == Nothing] ++ [() | Handler{} <- stubItems stub]
          pure ([ Artifact ("java/src/" ++ rest) (bridgeJava ns (bound unit) stub) "generated" "source" ] ++
                [ AdapterArtifact ("src/" ++ clojurePath ns) user "user" "source" user | not (null unbound) ])
      | Just rest <- stripPrefix "src/main/java/" path = pure [a { artifactPath = "java/src/" ++ rest }]
      | Just rest <- stripPrefix "src/test/java/" path, Just cases <- listToMaybe [info | info <- Product.jvmCases product, Abi.casePath info == path] = do
          let package = Abi.casePackage cases
              className = Abi.caseClass cases
              casesClass = (if null package then "" else package ++ ".") ++ className
              unitTest = listToMaybe [pu | pu <- plannedUnits plan, Just (C.idText (C.unitId (plannedUnit pu))) == Abi.caseUnit cases]
              ns = case unitTest of
                Just pu -> namespaceOf (C.idText (C.unitId (plannedUnit pu))) ++ "-lawspec-test"
                Nothing -> (if null package then "" else namespaceOf package ++ ".") ++ kebab className
              title name = maybe (kebab name) (`clojureTestTitle` name) unitTest
          pure [a { artifactPath = "java/test/" ++ rest },
                Artifact ("test/" ++ clojurePath ns) (testNamespaceForAbi ns unitTest casesClass title cases) "generated" "test"]
      | Just rest <- stripPrefix "src/test/java/" path = pure [a { artifactPath = "java/test/" ++ rest }]
      | otherwise = pure [a]
      where path = artifactPath a
    -- A class no unit names: its package and kebab name.
    classUnit rest = let parts = splitOn '/' (take (length rest - 5) rest)
                     in intercalate "." (init parts ++ [kebab (last parts)])
    runtime =
      [ Artifact "src/lawspec/clojure.clj" (clojureSource "src/lawspec/clojure.clj") "generated" "source"
      , Artifact "src/lawspec/build.clj" (clojureSource "src/lawspec/build.clj") "generated" "source"
      , Artifact "java/src/lawspec/clojure/LawSpecClojure.java" (clojureSource "java/lawspec/clojure/LawSpecClojure.java") "generated" "source"
      , Artifact "test/lawspec/check.clj" (clojureSource "test/lawspec/check.clj") "generated" "test"
      , Artifact "test/lawspec/test.clj" (clojureSource "test/lawspec/test.clj") "generated" "test"
      , Artifact "test/lawspec/test_runner.clj" (clojureSource "test/lawspec/test_runner.clj") "generated" "test" ] ++
      [ Artifact ("java/test/lawspec/testing/check/" ++ file) (clojureSource ("java-test/lawspec/testing/check/" ++ file)) "generated" "test"
      | file <- ["Assertions.java", "Draws.java", "GenerationEnvironment.java", "Generator.java", "IntDistribution.java", "PropertyChecker.java"] ]

-- | A project's own source and test directories, when it names them: the
-- namespaces move there; the Java model stays in java/.
clojureLayout :: Maybe String -> Maybe String -> [Artifact] -> [Artifact]
clojureLayout sourceDir testDir = map move
  where
    move a = maybe a (\p -> a { artifactPath = p }) (relocate (artifactPath a))
    relocate path =
      listToMaybe [ d ++ "/" ++ rest | (Just d, base) <- [(sourceDir, "src/"), (testDir, "test/")]
                  , Just rest <- [stripPrefix base path] ]

-- | Register one named clojure.test var per checked case descriptor.
testNamespaceForAbi :: String -> Maybe PlannedUnit -> String -> (String -> String) -> Abi.CaseClass -> String
testNamespaceForAbi ns unit casesClass title cases = unlines
  ([ ";; " ++ generatedHeader (unit >>= unitSourceFile . plannedUnit)
   , "(ns " ++ ns
   , "  " ++ string (maybe ("Tests of " ++ casesClass ++ ".") (\pu -> "The laws of " ++ C.idText (C.unitId (plannedUnit pu)) ++ ".") unit)
   , "  (:require [lawspec.test :as law]))"
   , ""
   , "(def ^:private cases (law/cases " ++ string casesClass ++ "))"
   , "" ] ++
   [";; " ++ labelled (displayLabel (C.propertyName (plannedProperty property))) (lawLink property) | info <- Abi.caseTests cases, Just property <- [lawOf info]] ++
   [ "(def lawspec-tests"
   , "  \"The tests in their order.\""
   , "  (law/register-cases"
   , "   *ns* cases" ]) ++
  D.render (D.Pretty 100) (D.text "   [" <> D.nest 4 (D.joinWith D.hardline (map descriptor (Abi.caseTests cases))) <> D.text "]))") ++ "\n" ++
  unlines
   [ ""
   , "(def lawspec-schedule"
   , "  {:order " ++ (if Abi.caseOrderRandom cases then ":random" else ":declared") ++ ", :parallel " ++ (if Abi.caseParallel cases then "true" else "false") ++ "})"
   , ""
   , "(defn test-ns-hook []"
   , "  (law/run " ++ show ns ++ " lawspec-tests lawspec-schedule))" ]
  where
    descriptor info = D.text "{:name " <> quoted (title (Abi.caseName info)) <>
      D.nest 1 (mconcat [D.hardline <> D.text (key ++ " ") <> quoted value | (key,value) <-
        [(":method", Abi.caseMethod info)] ++
        [(":skipped", reason) | Just reason <- [Abi.caseSkip info]] ++
        [(":source", source) | Abi.FiniteCases source _ _ <- [Abi.caseKind info]] ++
        [(":statement", statement property) | Just property <- [lawOf info]]]) <> D.text "}"
    quoted = D.text . string
    lawOf info = case unit of
      Just pu -> listToMaybe [property | property <- plannedProperties pu,
        Just (C.idText (C.propertyId (plannedProperty property))) == Abi.caseOwner info]
      Nothing -> Nothing

-- | Text as a Clojure string literal.
string :: String -> String
string = literalFor "clojure"

-- | A law's source line.
lawLink :: PlannedProperty -> Maybe String
lawLink p = let l = C.propertyLocation (plannedProperty p) in if null (file l) then Nothing else Just (locationLink l)

-- | What a law's tests check: its statement, with its binders' source names.
statement :: PlannedProperty -> String
statement p = map (\c -> if c < ' ' then ' ' else c) (prettyExpandedWith True (sourceNames (plannedProperty p)) p)

-- | A law case's test: the law's words, a double dash and the kind of test
-- (example-0, boundary-1, property, skipped, known-discrepancy).
clojureTestTitle :: PlannedUnit -> String -> String
clojureTestTitle pu name =
  case [ c ++ kindSuffix "clojure" kind | (j, c) <- zip (unitTestNames "java" labels) (unitTestNames "clojure" labels)
       , Just ('_' : kind) <- [stripPrefix j name] ] ++
       [ "benchmark--" ++ intercalate "-" (lawWords n) | (n, _) <- benchmarks, name == "benchmark" ++ concatMap capital (lawWords n) ] of
    t : _ -> t
    [] -> kebab name
  where
    labels = map (C.propertyName . plannedProperty) (plannedProperties pu)
    benchmarks = maybe [] C.harnessBenchmarks (C.unitHarnessSettings (plannedUnit pu))

-- | A Java type name as a tag's words, as LawSpecClojure.kebab writes it:
-- ProducerEpoch is producer-epoch, HTTPError http-error, USD usd.
tagWords :: String -> String
tagWords name = go Nothing name
  where
    go _ [] = []
    go previous (c : rest)
      | c == '_' = '-' : go (Just c) rest
      | isUpper c =
          let afterLower = maybe False (\p -> not (isUpper p) && p /= '_') previous
              endsAcronym = maybe False isUpper previous && take 1 (map isLower rest) == [True]
          in (if afterLower || endsAcronym then "-" else "") ++ [toLower c] ++ go (Just c) rest
      | otherwise = c : go (Just c) rest

capital :: String -> String
capital (c : cs) = toUpper c : cs
capital [] = []

splitOnText :: String -> String -> [String]
splitOnText sep s = go "" s
  where
    go acc rest@(c : more)
      | take (length sep) rest == sep = reverse acc : go "" (drop (length sep) rest)
      | otherwise = go (c : acc) more
    go acc [] = [reverse acc]

splitOn :: Char -> String -> [String]
splitOn c s = case break (== c) s of
  (a, []) -> [a]
  (a, _ : b) -> a : splitOn c b

-- The Java test file of a unit (LawSpec.TestManifest's for Java).
javaTestPath :: String -> String
javaTestPath unit = "src/test/java/" ++ concatMap (++ "/") (init parts) ++ concatMap capital (splitOn '_' (last parts)) ++ "LawSpecTest.java"
  where parts = splitOn '.' unit
