capitalize :: String -> String
capitalize (c : cs) = toUpper c : cs
capitalize [] = []

split :: Char -> String -> [String]
split c s = case break (== c) s of
  (a, []) -> [a]
  (a, _ : rest) -> a : split c rest

-- The generated class holding a unit's abilities, fully qualified.
abilitiesClass :: C.Unit -> String
abilitiesClass = abilitiesClassOf . C.idText . C.unitId

-- The same, by the unit's name: an imported ability's pieces are its owner's.
abilitiesClassOf :: String -> String
abilitiesClassOf unit =
  let parts = split '.' unit
  in intercalate "." ("lawspec" : "abilities" : init parts ++ [concatMap capitalize (split '_' (last parts))])

-- A unit's user-owned adapter class, fully qualified: example.abilities is
-- example.Abilities. It holds the production handlers of the unit's abilities.
adapterClassOf :: String -> String
adapterClassOf unit =
  let parts = split '.' unit
  in intercalate "." (init parts ++ [concatMap capitalize (split '_' (last parts))])

emit :: Bool -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emit minify bits datas units = Product.jvmArtifacts <$> emitProduct minify bits datas units

emitProduct :: Bool -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String Product.JvmProduct
emitProduct minify bits datas units = do
  typed <- emitJvmTyped JavaStyle datas units
  mconcat <$> mapM (unitFile typed) (filter unitAbilityPieces units)
  where
    layout = if minify then D.Compact else D.Pretty 100
    calls = Definitions.definitionCalls units
    line = D.text
    unitFile typed u = do
      let qualified = split '.' (abilitiesClass u)
          package = intercalate "." (init qualified)
          name = last qualified
      nestedClashes "Java" name u
      interfaces <- mapM interface (ownAbilities u)
      handlers <- mapM (\h -> if isTypedHandler (jvmTypedPlan typed) h then typedHandler typed u h else specHandler u h) (C.unitHandlers u)
      recordings <- mapM recording (ownAbilities u)
      let source = line "// Generated by LawSpec. Do not edit." <> D.hardline <> D.hardline <>
            line ("package " ++ package ++ ";") <> D.hardline <> D.hardline <>
            line "import java.util.Map;" <> D.hardline <>
            line "import lawspec.runtime.LawSpecRuntime;" <> D.hardline <>
            line "import lawspec.runtime.LawSpecRuntime.Value;" <> D.hardline <> D.hardline <>
            javadoc 100 ("The abilities of " ++ C.idText (C.unitId u) ++ ": an interface for each, its spec handlers, and a recording of any handler of it.") <> D.hardline <>
            line ("public final class " ++ name ++ "") <> D.hardline <> D.block 2 (D.joinWith (D.hardline <> D.hardline)
              ([line ("private " ++ name ++ "() {}"),
                line "private static final lawspec.runtime.LawSpecSchema SCHEMA =" <> D.nest 4 (D.hardline <> line "lawspec.runtime.LawSpecDataSchema.create();")] ++
               map snd interfaces ++ handlers ++ recordings)) <> D.hardline
      pure (Product.JvmProduct [Artifact ("src/main/java/" ++ intercalate "/" qualified ++ ".java") (D.render layout source) "generated" "source"]
        [] (map fst interfaces) [])
    signature op ty = operationDoc <$> operationAbi datas op ty
    interface a = do
      operations <- mapM (uncurry (operationAbi datas)) (C.abilityOperations a)
      let methods = [operationDoc operation <> line ";" | operation <- operations]
          abi = Abi.InterfaceAbi (abilitiesClassOf (ownerName a) ++ "." ++ interfaceName a) operations
      pure (abi, javadoc 98 ("The " ++ C.abilityName a ++ " ability: a handler answers each of its operations.") <> D.hardline <>
        line ("public interface " ++ interfaceName a ++ "") <> D.hardline <> D.block 2 (D.joinWith (D.hardline <> D.hardline) methods))
    codec ty = Native.javaCodecDocWithContext (line "symbols") datas bits ty
    capitalizeFirst (c : cs) = toUpper c : cs
    capitalizeFirst [] = []
    specHandler u h = do
      -- A handler of several abilities answers all their operations.
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
      initialState <- case C.handlerState h of
        Nothing -> pure []
        -- A computed start value is its own definition (<handler>Start).
        Just (_, C.Expr _ (C.ExternalCall startDefinition _) _) -> do
          evaluate <- maybe (Left ("unresolved start of " ++ C.handlerName h)) Right (lookup startDefinition calls)
          pure [line "this.state = " <> E.call evaluate [line "symbols", line "LawSpecRuntime.absent(\"Unit\")"] <> line ";"]
        Just (_, start) -> do
          value <- E.renderExpression datas bits (jvmLocal "java" [] . localName) (\_ _ -> Left "a handler's start value calls nothing") start
          pure [line "this.state = " <> value <> line ";"]
      let name = specName h
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        evaluate <- maybe (Left ("unresolved clause " ++ C.idText clause)) Right (lookup clause calls)
        s <- signature op ty
        let (args, result) = C.functionType ty
        argumentCodecs <- mapM codec args
        resultCodec <- codec result
        let arguments = line "symbols" : [line "state" | Just _ <- [C.handlerState h]] ++
              (if null args && C.handlerState h == Nothing then [line "LawSpecRuntime.absent(\"Unit\")"]
               else [c <> line (".encode(value" ++ show i ++ ")") | (i, c) <- zip [0 :: Int ..] argumentCodecs])
            invocation = E.call evaluate arguments
            outcome = case C.handlerState h of
              Nothing -> [line "var result = " <> invocation <> line ";"]
              Just _ -> [line "var pair = " <> D.group (line "LawSpecRuntime.pairFields(" <> D.nest 4 (D.softbreak <> invocation) <> line ")") <> line ";", line "state = pair.get(1);", line "var result = pair.get(0);"]
            returned
              | result == C.scalarType "Unit" = []
              | otherwise = [line "return " <> resultCodec <> line ".decode(result);"]
        pure (line "@Override" <> D.hardline <> line "public " <> s <> line "" <> D.hardline <> D.block 2 (D.joinWith D.hardline (outcome ++ returned)))) (C.abilityOperations ability)
      pure (javadoc 98 ("The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ".") <> D.hardline <>
        implementing name [abilitiesClassOf (ownerName a) ++ "." ++ interfaceName a | a <- answered] <> D.hardline <> D.block 2 (D.joinWith (D.hardline <> D.hardline)
          ([ line "private final Map<String, Object> symbols;" <> D.hardline <> line "private Value state;"
           , line ("public " ++ name ++ "(Map<String, Object> symbols)") <> D.hardline <> D.block 2 (D.joinWith D.hardline (line "this.symbols = symbols;" : initialState)) ] ++
           methods)))
    -- A typed spec handler keeps its state typed: each operation converts its
    -- arguments, runs the typed clause and keeps the next state, which shares
    -- all it did not change with the state before.
    typedHandler typed u h = do
      -- A handler of several abilities answers all their operations.
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
      stateType <- traverse (jvmTypedTypeDoc typed . fst) (C.handlerState h)
      let start = jvmTypedStart typed (C.handlerId h)
      let name = specName h
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        function <- maybe (Left ("untyped clause " ++ C.idText clause)) Right (jvmTypedFunction typed clause)
        s <- signature op ty
        let (args, result) = C.functionType ty
        argumentCodecs <- mapM codec args
        typedCodecs <- mapM (jvmTypedCodec typed) args
        resultCodec <- codec result
        typedResult <- jvmTypedCodec typed result
        -- A value converts directly between its native and typed forms where
        -- it can; otherwise through its codecs and the dynamic Value.
        let direct = jvmTypedNative typed
            argument i ty c t = case direct ty of
              Just (fromNative, _) -> line (fromNative ++ "(value" ++ show i ++ ")")
              Nothing -> line (t ++ ".decode(") <> c <> line (".encode(value" ++ show i ++ "))")
            arguments = [line "symbols" | isContextual (jvmTypedPlan typed) clause] ++ [line "state" | Just _ <- [C.handlerState h]] ++
              (if null args && C.handlerState h == Nothing then [line "lawspec.runtime.LawSpecFast.Unit.UNIT"]
               else [argument i ty c t | (i, (ty, (c, t))) <- zip [0 :: Int ..] (zip args (zip argumentCodecs typedCodecs))])
            invocation = line function <> D.delimit 4 "(" ")" arguments
            outcome = case C.handlerState h of
              Nothing -> [line "var result = " <> invocation <> line ";"]
              Just _ -> [line "var pair = " <> invocation <> line ";", line "state = pair.second;", line "var result = pair.first;"]
            returned
              | result == C.scalarType "Unit" = []
              | Just (_, toNative) <- direct result = [line ("return " ++ toNative ++ "(result);")]
              | otherwise = [line "return " <> resultCodec <> line (".decode(" ++ typedResult ++ ".encode(result));")]
        pure (line "@Override" <> D.hardline <> line "public synchronized " <> s <> line "" <> D.hardline <> D.block 2 (D.joinWith D.hardline (outcome ++ returned)))) (C.abilityOperations ability)
      -- The state, read and replaced in its native types, and typed.
      accessors <- case (C.handlerState h, stateType) of
        (Just (t, _), Just typedType) -> do
          native <- Native.javaDataTypeDoc datas t
          stateCodec <- codec t
          typedCodec <- jvmTypedCodec typed t
          let (read', write') = case jvmTypedNative typed t of
                Just (fromNative, toNative) -> (line ("return " ++ toNative ++ "(state);"), line ("this.state = " ++ fromNative ++ "(state);"))
                Nothing -> ( line "return " <> stateCodec <> line (".decode(" ++ typedCodec ++ ".encode(this.state));")
                           , line ("this.state = " ++ typedCodec ++ ".decode(") <> stateCodec <> line ".encode(state));" )
          pure [ line "/** The handler's state, in its native types: a snapshot to show or keep. */" <> D.hardline <>
                 line "public synchronized " <> native <> line " state()" <> D.hardline <> D.block 2 read'
               , line "/** Replaces the handler's state: to force it, reset it or restore a snapshot. */" <> D.hardline <>
                 line "public synchronized void setState(" <> native <> line " state)" <> D.hardline <> D.block 2 write'
               , line "/** The typed state, shared rather than copied. */" <> D.hardline <>
                 D.group (line "public synchronized " <> typedType <> D.nest 4 (D.softline <> line "typedState()")) <> D.hardline <> D.block 2 (line "return state;")
               , line "/** Replaces the typed state. */" <> D.hardline <>
                 D.group (line "public synchronized void setTypedState(" <> D.nest 4 (D.softbreak <> typedType <> line " state") <> line ")") <> D.hardline <> D.block 2 (line "this.state = state;") ]
        _ -> pure []
      -- Each operation that fails with E, with its failure as an Outcome.
      attempts <- fmap concat $ forM answered $ \a -> forM [ (op, ty, failing, failure) | (op, ty) <- C.abilityOperations a
                                                         , Just failing@(C.AbilityRef _ [failure]) <- [lookup op (C.abilityFailures a)] ] $ \(op, ty, failing, failure) -> do
        let (args, result) = C.functionType ty
        types <- mapM (Native.javaDataTypeDoc datas) args
        resultType <- if result == C.scalarType "Unit" then pure (line "Void") else Native.javaDataTypeDoc datas result
        failureType <- Native.javaDataTypeDoc datas failure
        failureCodec <- codec failure
        let values = ["value" ++ show i | i <- [0 .. length args - 1]]
            call = op ++ "(" ++ intercalate ", " values ++ ")"
            outcome = line "lawspec.runtime.LawSpecFast.Outcome<" <> resultType <> line ", " <> failureType <> line ">"
        pure (javadoc 98 ("" ++ op ++ ", with the failure it raises as an Outcome rather than an exception.") <> D.hardline <>
          line "public " <> outcome <> line (" try" ++ capitalizeFirst op) <> D.delimit 4 "(" ")" [t <> line (" " ++ v) | (v, t) <- zip values types] <> D.hardline <>
          D.block 2 (line "try" <> D.hardline <> D.block 2
              (if result == C.scalarType "Unit"
                 then line (call ++ ";") <> D.hardline <> line "return lawspec.runtime.LawSpecFast.Outcome.success(null);"
                 else line ("return lawspec.runtime.LawSpecFast.Outcome.success(" ++ call ++ ");")) <>
            D.hardline <> line "catch (LawSpecRuntime.Failure failure)" <> D.hardline <> D.block 2 (D.joinWith D.hardline
              [ line ("if (!failure.ability.equals(" ++ show (C.abilityKey failing) ++ "))") <> D.hardline <> D.block 2 (line "throw failure;")
              , line "return " <> D.group (line "lawspec.runtime.LawSpecFast.Outcome.failure(" <> D.nest 4 (D.softbreak <> failureCodec <> line ".decode(failure.value)") <> line ")") <> line ";" ])))
      pure (javadoc 98 ("The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ", with its state typed.") <> D.hardline <>
        implementing name [abilitiesClassOf (ownerName a) ++ "." ++ interfaceName a | a <- answered] <> D.hardline <> D.block 2 (D.joinWith (D.hardline <> D.hardline)
          ([ line "private final Map<String, Object> symbols;" <> maybe mempty (\t -> D.hardline <> line "private " <> t <> line " state;") stateType
           , line "/** The handler for a law, in its context. */" <> D.hardline <>
             line ("public " ++ name ++ "(Map<String, Object> symbols)") <> D.hardline <> D.block 2 (D.joinWith D.hardline
               (line "this.symbols = symbols;" : [line ("this.state = " ++ v ++ ";") | Just v <- [start]]))
           , line "/** The handler on its own, outside any law: the embedding entry point. */" <> D.hardline <>
             line ("public " ++ name ++ "()") <> D.hardline <> D.block 2 (line "this(new java.util.HashMap<>());") ] ++
           methods ++ accessors ++ attempts)))
    recording a = do
      let name = recordingName a
      methods <- mapM (\(op, ty) -> do
        s <- signature op ty
        let (args, result) = C.functionType ty
        argumentCodecs <- mapM codec args
        let logged = E.call "java.util.List.of" [c <> line (".encode(value" ++ show i ++ ")") | (i, c) <- zip [0 :: Int ..] argumentCodecs]
            forward = "inner." ++ op ++ "(" ++ intercalate ", " ["value" ++ show i | i <- [0 .. length args - 1]] ++ ");"
        pure (line "@Override" <> D.hardline <> line "public " <> s <> line "" <> D.hardline <> D.block 2 (D.joinWith D.hardline
          [ line ("calls.add(new LawSpecRuntime.RecordedCall(" ++ show op ++ ", ") <> logged <> line "));"
          , line (if result == C.scalarType "Unit" then forward else "return " ++ forward) ]))) (C.abilityOperations a)
      pure (javadoc 98 ("Records each call to a " ++ C.abilityName a ++ " handler, then passes it on.") <> D.hardline <>
        line ("public static final class " ++ name ++ " implements " ++ interfaceName a ++ ", LawSpecRuntime.Recorded") <> D.hardline <> D.block 2 (D.joinWith (D.hardline <> D.hardline)
          ([ line "private final Map<String, Object> symbols;" <> D.hardline <>
             line ("public final " ++ interfaceName a ++ " inner;") <> D.hardline <>
             line "public final java.util.List<LawSpecRuntime.RecordedCall> calls = new java.util.ArrayList<>();"
           , line ("public " ++ name ++ "(" ++ interfaceName a ++ " inner, Map<String, Object> symbols)") <> D.hardline <>
             D.block 2 (line "this.inner = inner;" <> D.hardline <> line "this.symbols = symbols;")
           , line "@Override" <> D.hardline <> line "public java.util.List<LawSpecRuntime.RecordedCall> lawSpecCalls()" <> D.hardline <> D.block 2 (line "return calls;") ] ++
           methods)))

-- The user-owned production handler of each ability, nested in the unit's
-- adapter class: new <Unit>.<Ability>Handler() is what the tests use.
productionStub :: [C.DataDeclaration] -> C.Unit -> C.Ability -> Either String D.Doc
productionStub datas u a = snd <$> productionProduct datas u a

-- | The production implementation and its ABI are made from the same checked
-- operation types, before any source is rendered.
productionProduct :: [C.DataDeclaration] -> C.Unit -> C.Ability -> Either String (Abi.Item, D.Doc)
productionProduct datas u a = do
  operations <- mapM (uncurry (operationAbi datas)) (C.abilityOperations a)
  let methods = [D.text "@Override" <> D.hardline <> D.text "public " <> operationDoc operation <> D.hardline <>
        D.block 2 (D.text ("throw new UnsupportedOperationException(" ++ show (Abi.opName operation) ++ ");")) | operation <- operations]
  -- ability A with T: the handler is made with the case's T.
  made <- case C.abilityResource a of
    Nothing -> pure []
    Just t -> do
      resourceType <- Native.javaDataTypeDoc datas t
      pure [ D.text "public final " <> resourceType <> D.text " resource;"
           , D.text ("public " ++ productionName a ++ "(") <> resourceType <> D.text " resource)" <> D.hardline <> D.block 2 (D.text "this.resource = resource;") ]
  resourceType <- mapM (Native.javaDataTypeDoc datas) (C.abilityResource a)
  let description = "The native handler of " ++ displayName a ++ ": " ++ intercalate ", " (map fst (C.abilityOperations a)) ++ "."
      abi = Abi.Handler ["// " ++ description] (productionName a) (abilitiesClass u ++ "." ++ interfaceName a)
        (C.abilityResource a /= Nothing) resourceType operations
  pure (abi, javadoc 98 description <> D.hardline <>
    D.group (D.text ("public static final class " ++ productionName a) <> D.nest 4 (D.softline <> D.text ("implements " ++ abilitiesClass u ++ "." ++ interfaceName a))) <> D.hardline <>
    D.block 2 (D.joinWith (D.hardline <> D.hardline) (made ++ methods)))

-- The exact same checked signature is used in interfaces, production stubs,
-- recordings and downstream JVM bridges.
operationAbi :: [C.DataDeclaration] -> String -> C.Type -> Either String Abi.Operation
operationAbi datas name ty = do
  let (args, result) = C.functionType ty
  types <- mapM (Native.javaDataTypeDoc datas) args
  resultType <- if result == C.scalarType "Unit" then pure (D.text "void") else Native.javaDataTypeDoc datas result
  pure (Abi.operation resultType name [(t, "value" ++ show i) | (i,t) <- zip [0::Int ..] types] name)

operationDoc :: Abi.Operation -> D.Doc
operationDoc operation = Abi.opResultLayout operation <> D.text (" " ++ Abi.opName operation) <>
  D.delimit 4 "(" ")" [ty <> D.text (" " ++ name) | (ty,name) <- Abi.opParameterLayouts operation]

-- | A class header that breaks before implements, and between interfaces.
implementing :: String -> [String] -> D.Doc
implementing name interfaces = D.group (D.text ("public static final class " ++ name) <>
  D.nest 4 (D.softline <> D.text "implements " <> D.group (D.nest 4 (D.joinWith (D.text "," <> D.softline) (map D.text interfaces)))))
