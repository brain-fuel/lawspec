-- Kotlin pieces of a unit's abilities (see LawSpec.AbilityNames), in the
-- object lawspec.abilities.<unit package>.<Unit>: a nested interface per
-- ability, a class per spec handler and a recording class per ability.
-- Handlers travel in the symbols map generated code passes to every
-- definition; the shared JVM bodies reach a Kotlin handler through a bridge
-- in LawSpecKotlinAdapters (see LawSpec.KotlinDefinitions).
module LawSpec.AbilityEmit.Kotlin (emit, productionStub, abilitiesObject, abilitiesObjectOf) where

import Data.Char (toUpper)
import Data.List (intercalate)
import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..))
import LawSpec.AbilityNames
import qualified LawSpec.KotlinData as Native
import qualified LawSpec.JavaDefinitions as Definitions
import qualified LawSpec.KotlinExpr as E
import qualified LawSpec.Code.Doc as D
import LawSpec.Typed.Plan (isTypedHandler, isContextual)
import LawSpec.Typed.Jvm (JvmTyped(..), JvmStyle(..), emitJvmTyped)

capitalize :: String -> String
capitalize (c : cs) = toUpper c : cs
capitalize [] = []

split :: Char -> String -> [String]
split c s = case break (== c) s of
  (a, []) -> [a]
  (a, _ : rest) -> a : split c rest

-- The generated object holding a unit's abilities, fully qualified.
abilitiesObject :: C.Unit -> String
abilitiesObject = abilitiesObjectOf . C.idText . C.unitId

-- The same, by the unit's name: an imported ability's pieces are its owner's.
abilitiesObjectOf :: String -> String
abilitiesObjectOf unit =
  let parts = split '.' unit
  in intercalate "." ("lawspec" : "abilities" : init parts ++ [concatMap capitalize (split '_' (last parts))])

emit :: Bool -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emit minify bits datas units = do
  typed <- emitJvmTyped KotlinStyle datas units
  mapM (unitFile typed) (filter unitAbilityPieces units)
  where
    layout = if minify then D.Compact else D.Pretty 100
    calls = Definitions.definitionCalls units
    line = D.text
    unitFile typed u = do
      let qualified = split '.' (abilitiesObject u)
          package = intercalate "." (init qualified)
          name = last qualified
      nestedClashes "Kotlin" name u
      interfaces <- mapM interface (ownAbilities u)
      handlers <- mapM (\h -> if isTypedHandler (jvmTypedPlan typed) h then typedHandler typed u h else specHandler u h) (C.unitHandlers u)
      recordings <- mapM recording (ownAbilities u)
      let source = line "// Generated by LawSpec. Do not edit." <> D.hardline <>
            line ("package " ++ package) <> D.hardline <> D.hardline <>
            line "import lawspec.runtime.LawSpecRuntime" <> D.hardline <>
            line "import lawspec.runtime.LawSpecDataSchema" <> D.hardline <>
            line "import lawspec.runtime.LawSpecSchema" <> D.hardline <>
            line "import lawspec.runtime.LawSpecDataCodecs" <> D.hardline <>
            line "import lawspec.runtime.LawSpecKotlinCodecs" <> D.hardline <> D.hardline <>
            line ("/** The abilities of " ++ C.idText (C.unitId u) ++ ": an interface for each, its spec handlers, and a recording of any handler of it. */") <> D.hardline <>
            line ("object " ++ name ++ " ") <> D.block 4 (D.joinWith (D.hardline <> D.hardline)
              ([line "private val schema = LawSpecDataSchema.create()",
                line "private val _schema = schema",
                line ("private const val bits = " ++ show bits)] ++
               interfaces ++ handlers ++ recordings)) <> D.hardline
      pure (Artifact ("src/main/kotlin/" ++ intercalate "/" qualified ++ ".kt") (D.render layout source) "generated" "source")
    signature op ty = do
      let (args, result) = C.functionType ty
      types <- mapM (Native.kotlinDataTypeDoc datas) args
      resultType <- if result == C.scalarType "Unit" then pure (line "Unit") else Native.kotlinDataTypeDoc datas result
      pure (line ("fun " ++ op) <> D.delimitTrailing 4 "(" ")" [line ("value" ++ show i ++ ": ") <> t | (i, t) <- zip [0 :: Int ..] types] <>
        line ": " <> resultType)
    interface a = do
      methods <- mapM (\(op, ty) -> signature op ty) (C.abilityOperations a)
      pure (line ("/** The " ++ C.abilityName a ++ " ability: a handler answers each of its operations. */") <> D.hardline <>
        line ("interface " ++ interfaceName a ++ " ") <> D.block 4 (D.joinWith D.hardline methods))
    codec ty = Native.kotlinCodecDocWithContext (line "symbols") datas ty
    capitalizeFirst (c : cs) = toUpper c : cs
    capitalizeFirst [] = []
    specHandler u h = do
      -- A handler of several abilities answers all their operations.
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
      initialState <- case C.handlerState h of
        Nothing -> pure (line "null")
        -- A computed start value is its own definition (<handler>Start).
        Just (_, C.Expr _ (C.ExternalCall startDefinition _) _) -> do
          evaluate <- maybe (Left ("unresolved start of " ++ C.handlerName h)) Right (lookup startDefinition calls)
          pure (E.call evaluate [line "symbols", line "LawSpecRuntime.absent(\"Unit\")"])
        Just (_, start) -> E.renderExpression datas bits (const "_unbound") (\_ _ -> Left "a handler's start value calls nothing") start
      let name = specName h
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        evaluate <- maybe (Left ("unresolved clause " ++ C.idText clause)) Right (lookup clause calls)
        s <- signature op ty
        let (args, result) = C.functionType ty
        argumentCodecs <- mapM codec args
        resultCodec <- codec result
        let arguments = line "symbols" : [line "state!!" | Just _ <- [C.handlerState h]] ++
              (if null args && C.handlerState h == Nothing then [line "LawSpecRuntime.absent(\"Unit\")"]
               else [c <> line (".encode(value" ++ show i ++ ")") | (i, c) <- zip [0 :: Int ..] argumentCodecs])
            invocation = E.call evaluate arguments
            outcome = case C.handlerState h of
              Nothing -> [line "val result = " <> invocation]
              Just _ -> [line "val pair = LawSpecRuntime.pairFields(" <> invocation <> line ")", line "state = pair[1]", line "val result = pair[0]"]
            returned
              | result == C.scalarType "Unit" = []
              | otherwise = [line "return " <> resultCodec <> line ".decode(result)"]
        pure (line "override " <> s <> line " " <> D.block 4 (D.joinWith D.hardline (outcome ++ returned)))) (C.abilityOperations ability)
      pure (line ("/** The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ". */") <> D.hardline <>
        line ("class " ++ name ++ "(private val symbols: MutableMap<String, Any>) : " ++ intercalate ", " [abilitiesObjectOf (ownerName a) ++ "." ++ interfaceName a | a <- answered] ++ " ") <>
        D.block 4 (D.joinWith (D.hardline <> D.hardline)
          (line "private var state: LawSpecRuntime.Value? = " <> initialState : methods)))
    -- A typed spec handler keeps its state typed (in the shared JVM typed
    -- code): each operation converts its arguments, runs the typed clause and
    -- keeps the next state, which shares all it did not change with the
    -- state before.
    typedHandler typed u h = do
      -- A handler of several abilities answers all their operations.
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
      stateType <- traverse (jvmTypedType typed . fst) (C.handlerState h)
      let name = specName h
          start = jvmTypedStart typed (C.handlerId h)
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        function <- maybe (Left ("untyped clause " ++ C.idText clause)) Right (jvmTypedFunction typed clause)
        s <- signature op ty
        let (args, result) = C.functionType ty
        argumentCodecs <- mapM codec args
        typedCodecs <- mapM (jvmTypedCodec typed) args
        resultCodec <- codec result
        typedResult <- jvmTypedCodec typed result
        -- A value converts directly between its native and typed forms where
        -- it can; otherwise through its codecs and the dynamic Value.
        let direct = jvmTypedNative typed
            argument i ty c t = case direct ty of
              Just (fromNative, _) -> line (fromNative ++ "(value" ++ show i ++ ")")
              Nothing -> line (t ++ ".decode(") <> c <> line (".encode(value" ++ show i ++ "))")
            arguments = [line "symbols" | isContextual (jvmTypedPlan typed) clause] ++ [line "state" | Just _ <- [C.handlerState h]] ++
              (if null args && C.handlerState h == Nothing then [line "lawspec.runtime.LawSpecFast.Unit.UNIT"]
               else [argument i ty c t | (i, (ty, (c, t))) <- zip [0 :: Int ..] (zip args (zip argumentCodecs typedCodecs))])
            invocation = line function <> D.delimitTrailing 4 "(" ")" arguments
            outcome = case C.handlerState h of
              Nothing -> [line "val result = " <> invocation]
              Just _ -> [line "val pair = " <> invocation, line "state = pair.second", line "val result = pair.first"]
            returned
              | result == C.scalarType "Unit" = []
              | Just (_, toNative) <- direct result = [line ("return " ++ toNative ++ "(result)")]
              | otherwise = [line "return " <> resultCodec <> line (".decode(" ++ typedResult ++ ".encode(result))")]
        pure (line "@Synchronized override " <> s <> line " " <> D.block 4 (D.joinWith D.hardline (outcome ++ returned)))) (C.abilityOperations ability)
      -- The state, read and replaced in its native types, and typed.
      accessors <- case (C.handlerState h, stateType) of
        (Just (t, _), Just typedType) -> do
          native <- Native.kotlinDataTypeDoc datas t
          stateCodec <- codec t
          typedCodec <- jvmTypedCodec typed t
          let (read', write') = case jvmTypedNative typed t of
                Just (fromNative, toNative) -> (line ("return " ++ toNative ++ "(state)"), line ("this.state = " ++ fromNative ++ "(state)"))
                Nothing -> ( line "return " <> stateCodec <> line (".decode(" ++ typedCodec ++ ".encode(this.state))")
                           , line ("this.state = " ++ typedCodec ++ ".decode(") <> stateCodec <> line ".encode(state))" )
          pure [ line "/** The handler's state, in its native types: a snapshot to show or keep. */" <> D.hardline <>
                 line "@Synchronized fun state(): " <> native <> line " " <> D.block 4 read'
               , line "/** Replaces the handler's state: to force it, reset it or restore a snapshot. */" <> D.hardline <>
                 line "@Synchronized fun setState(state: " <> native <> line ") " <> D.block 4 write'
               , line "/** The typed state, shared rather than copied. */" <> D.hardline <>
                 line ("@Synchronized fun typedState(): " ++ typedType ++ " = state")
               , line "/** Replaces the typed state. */" <> D.hardline <>
                 line ("@Synchronized fun setTypedState(state: " ++ typedType ++ ") ") <> D.block 4 (line "this.state = state") ]
        _ -> pure []
      -- Each operation that fails with E, with its failure as an Outcome.
      attempts <- fmap concat $ mapM (\a -> mapM (\(op, ty, failing, failure) -> do
          let (args, result) = C.functionType ty
          types <- mapM (Native.kotlinDataTypeDoc datas) args
          resultType <- if result == C.scalarType "Unit" then pure (line "Unit") else Native.kotlinDataTypeDoc datas result
          failureType <- Native.kotlinDataTypeDoc datas failure
          failureCodec <- codec failure
          let values = ["value" ++ show i | i <- [0 .. length args - 1]]
              call = op ++ "(" ++ intercalate ", " values ++ ")"
          pure (line ("/** " ++ op ++ ", with the failure it raises as an Outcome rather than an exception. */") <> D.hardline <>
            line ("fun try" ++ capitalizeFirst op) <> D.delimitTrailing 4 "(" ")" [line (v ++ ": ") <> t | (v, t) <- zip values types] <>
            line ": lawspec.runtime.LawSpecFast.Outcome<" <> resultType <> line ", " <> failureType <> line "> " <>
            D.block 4 (line "try " <> D.block 4 (line ("return lawspec.runtime.LawSpecFast.Outcome.success(" ++ call ++ ")")) <>
              line " catch (failure: LawSpecRuntime.Failure) " <> D.block 4 (D.joinWith D.hardline
                [ line ("if (failure.ability != " ++ show (C.abilityKey failing) ++ ") throw failure")
                , line "return lawspec.runtime.LawSpecFast.Outcome.failure(" <> failureCodec <> line ".decode(failure.value))" ])))
        ) [ (op, ty, failing, failure) | (op, ty) <- C.abilityOperations a, Just failing@(C.AbilityRef _ [failure]) <- [lookup op (C.abilityFailures a)] ]) answered
      pure (line ("/** The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ", with its state typed. */") <> D.hardline <>
        line ("class " ++ name ++ "(private val symbols: MutableMap<String, Any>) : " ++ intercalate ", " [abilitiesObjectOf (ownerName a) ++ "." ++ interfaceName a | a <- answered] ++ " ") <>
        D.block 4 (D.joinWith (D.hardline <> D.hardline)
          ([line ("private var state: " ++ t ++ " = " ++ v) | Just t <- [stateType], Just v <- [start]] ++
           [ line "/** The handler on its own, outside any law: the embedding entry point. */" <> D.hardline <>
             line "constructor() : this(mutableMapOf())" ] ++ methods ++ accessors ++ attempts)))
    recording a = do
      let name = recordingName a
      methods <- mapM (\(op, ty) -> do
        s <- signature op ty
        let (args, _) = C.functionType ty
        argumentCodecs <- mapM codec args
        let logged = E.call "listOf" [c <> line (".encode(value" ++ show i ++ ")") | (i, c) <- zip [0 :: Int ..] argumentCodecs]
            forward = "inner." ++ op ++ "(" ++ intercalate ", " ["value" ++ show i | i <- [0 .. length args - 1]] ++ ")"
        pure (line "override " <> s <> line " " <> D.block 4 (D.joinWith D.hardline
          [ line ("calls.add(LawSpecRuntime.RecordedCall(" ++ show op ++ ", ") <> logged <> line "))"
          , line ("return " ++ forward) ]))) (C.abilityOperations a)
      pure (line ("/** Records each call to a " ++ C.abilityName a ++ " handler, then passes it on. */") <> D.hardline <>
        line ("class " ++ name ++ "(val inner: " ++ interfaceName a ++ ", private val symbols: MutableMap<String, Any>) : " ++
          interfaceName a ++ ", LawSpecRuntime.Recorded ") <> D.block 4 (D.joinWith (D.hardline <> D.hardline)
          ([ line "val calls: MutableList<LawSpecRuntime.RecordedCall> = mutableListOf()"
           , line "override fun lawSpecCalls(): List<LawSpecRuntime.RecordedCall> = calls" ] ++
           methods)))

-- The user-owned production handler of each ability, nested in the unit's
-- adapter object: <Unit>.<Ability>Handler() is what the tests use.
productionStub :: [C.DataDeclaration] -> C.Unit -> C.Ability -> Either String D.Doc
productionStub datas u a = do
  methods <- mapM (\(op, ty) -> do
    let (args, result) = C.functionType ty
    types <- mapM (Native.kotlinDataTypeDoc datas) args
    resultType <- if result == C.scalarType "Unit" then pure (D.text "Unit") else Native.kotlinDataTypeDoc datas result
    pure (D.text ("override fun " ++ op) <>
      D.delimitTrailing 4 "(" ")" [D.text ("value" ++ show i ++ ": ") <> t | (i, t) <- zip [0 :: Int ..] types] <>
      D.text ": " <> resultType <> D.text (" = TODO(" ++ show op ++ ")"))) (C.abilityOperations a)
  -- ability A with T: the handler is made with the case's T.
  made <- traverse (Native.kotlinDataTypeDoc datas) (C.abilityResource a)
  pure (D.text ("/** The native handler of " ++ displayName a ++ ": " ++ intercalate ", " (map fst (C.abilityOperations a)) ++ ". */") <> D.hardline <>
    D.text ("class " ++ productionName a) <> maybe mempty (\t -> D.text "(val resource: " <> t <> D.text ")") made <>
    D.text (" : " ++ abilitiesObject u ++ "." ++ interfaceName a ++ " ") <>
    D.block 4 (D.joinWith D.hardline methods))
