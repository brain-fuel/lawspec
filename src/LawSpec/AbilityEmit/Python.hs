-- Python pieces of a unit's abilities (see LawSpec.AbilityNames): a
-- typing.Protocol per ability, a class per spec handler and a recording
-- class per ability, in lawspec_abilities/<unit path>.py.
--
-- Handlers travel in the symbols context that generated code already passes
-- to every definition (evidence passing): a law installs them with
-- ls.install_handlers, and a performed operation finds its handler with
-- ls.handler(symbols, key). Native code gets them as arguments instead.
module LawSpec.AbilityEmit.Python (emit, modulePath, moduleName, moduleNameOf, productionStub) where

import Data.List (intercalate)
import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..), pythonUnitFile)
import LawSpec.AbilityNames
import LawSpec.PythonTypes (pythonDataTypeDoc, pythonTypeReferenceDoc)
import qualified LawSpec.PythonDefinitions as Definitions
import qualified LawSpec.Code.Doc as D
import qualified LawSpec.PythonExpr as E
import LawSpec.Scalar (Scalar(..))
import LawSpec.Typed.Plan (isTypedHandler, isContextual)
import LawSpec.Typed.Python (PythonTyped(..), emitPythonTyped)

-- The generated module of a unit's abilities.
moduleName :: C.Unit -> String
moduleName = moduleNameOf . C.idText . C.unitId

-- The generated module of the unit of this name.
moduleNameOf :: String -> String
moduleNameOf unit = "lawspec_abilities." ++ unit

modulePath :: [C.Unit] -> C.Unit -> String
modulePath units u = "src/lawspec_abilities/" ++ pythonUnitFile (map (C.idText . C.unitId) units) (C.idText (C.unitId u))

emit :: Bool -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emit minify bits datas units = do
  typed <- emitPythonTyped bits datas units
  mapM (unitModule typed) (filter unitAbilityPieces units)
  where
    layout = D.selectLayout minify (D.Pretty 79)
    calls = Definitions.definitionCalls units
    width = D.text (show bits)
    schemaCall name ty value = do
      ref <- pythonTypeReferenceDoc ty
      pure (E.call ("ls.handler_schema(_lawspec_schema)." ++ name) [ref, value, width, D.text "symbols"])
    unitModule typed u = do
      protocols <- mapM protocol (ownAbilities u)
      let typedHandlers = [h | h <- C.unitHandlers u, isTypedHandler (pyTypedPlan typed) h]
      handlers <- mapM (\h -> if h `elem` typedHandlers then typedHandler typed u h else specHandler u h) (C.unitHandlers u)
      recordings <- mapM recording (ownAbilities u)
      let header = D.joinWith D.hardline (map D.text
            [ "# Generated by LawSpec. Do not edit."
            , "\"\"\"The abilities of " ++ C.idText (C.unitId u) ++ ": an interface for each,"
            , "its spec handlers, and a recording of any handler of it.\"\"\""
            , "from __future__ import annotations"
            , ""
            , "import builtins as _builtins"
            , "import typing as _typing"
            , ""
            , "import lawspec_data as data"
            , "import lawspec_runtime as ls"
            , "import lawspec_schema as _schema" ] ++
            [D.text "import lawspec_definition_bodies as _definitions" | not (null (C.unitHandlers u))] ++
            [D.text "import lawspec_typed as _typed" | not (null typedHandlers)] ++
            [D.text "import threading as _threading" | not (null typedHandlers)] ++
            [D.hardline <> D.text "_lawspec_schema = data.make_schema()"])
          body = D.joinWith (D.hardline <> D.hardline <> D.hardline) (protocols ++ handlers ++ recordings)
      pure (Artifact (modulePath units u) (D.render layout (header <> D.hardline <> D.hardline <> D.hardline <> body <> D.hardline)) "generated" "source")
    parameters ty = do
      let (args, result) = C.functionType ty
      types <- mapM (pythonDataTypeDoc datas) args
      resultType <- if result == C.scalarType "Unit" then pure (D.text "None") else pythonDataTypeDoc datas result
      pure (D.delimitTrailing 4 "(" ")" (D.text "self" : [D.text ("value" ++ show i ++ ": ") <> t | (i, t) <- zip [0 :: Int ..] types]) <>
        D.text " -> " <> resultType)
    protocol a = do
      methods <- mapM (\(op, ty) -> (\ps -> D.text ("def " ++ op) <> ps <> D.text ": ...") <$> parameters ty) (C.abilityOperations a)
      pure (E.suite (D.text ("class " ++ interfaceName a ++ "(_typing.Protocol)"))
        (D.joinWith D.hardline (D.text ("\"\"\"The " ++ interfaceName a ++ " ability: a handler answers each of its operations.\"\"\"") : methods)))
    specHandler u h = do
      -- A handler of several abilities answers all their operations.
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
      initialState <- case C.handlerState h of
        Nothing -> pure []
        -- A computed start value is its own definition (<handler>Start).
        Just (_, C.Expr _ (C.ExternalCall startDefinition _) _) -> do
          evaluate <- maybe (Left ("unresolved start of " ++ C.handlerName h)) Right (lookup startDefinition calls)
          pure [D.text "symbols = self._symbols", D.text "self._state = " <> E.call evaluate [D.text "symbols", E.scalarLiteral (SAbsent "Unit")]]
        Just (_, start) -> do
          value <- E.renderExpression datas bits (const "_unbound") (\_ _ -> Left "a handler's start value calls nothing") start
          pure [D.text "symbols = self._symbols", D.text "self._state = " <> value]
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        evaluate <- maybe (Left ("unresolved clause " ++ C.idText clause)) Right (lookup clause calls)
        ps <- parameters ty
        let (args, result) = C.functionType ty
        inputs <- sequence [schemaCall "from_native" t (D.text ("value" ++ show i)) | (i, t) <- zip [0 :: Int ..] args]
        let arguments = D.text "symbols" : [D.text "self._state" | Just _ <- [C.handlerState h]] ++
              (if null args && C.handlerState h == Nothing then [E.scalarLiteral (SAbsent "Unit")] else inputs)
            invocation = E.call evaluate arguments
        output <- schemaCall "to_native" result (D.text "result")
        let statements = case C.handlerState h of
              Nothing -> [D.text "result = " <> invocation]
              Just _ -> [D.text "pair = " <> invocation, D.text "self._state = pair.fields[1]", D.text "result = pair.fields[0]"]
        pure (E.suite (D.text ("def " ++ op) <> ps)
          (D.joinWith D.hardline (D.text "symbols = self._symbols" : statements ++ [D.text "return " <> output])))) (C.abilityOperations ability)
      pure (E.suite (D.text ("class " ++ specName h))
        (D.joinWith D.hardline (D.text ("\"\"\"The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ".\"\"\"") : D.text "" :
          E.suite (D.text "def __init__(self, symbols=None)")
            (D.joinWith D.hardline (D.text "self._symbols = {} if symbols is None else symbols" : initialState)) :
          concatMap (\m -> [D.text "", m]) methods)))
    -- A typed spec handler keeps its state typed: each operation converts its
    -- arguments, runs the typed clause and keeps the next state, which shares
    -- all it did not change with the state before. Its operations apply one
    -- at a time.
    typedHandler typed u h = do
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
          stateful = C.handlerState h /= Nothing
      start <- case C.handlerState h of
        Nothing -> pure []
        Just _ -> do
          name <- maybe (Left ("untyped start of " ++ C.handlerName h)) Right (pyTypedStart typed (C.handlerId h))
          pure [D.text "self._lock = _threading.Lock()", D.text ("self._state = _typed." ++ name ++ "(self._symbols)")]
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        function <- maybe (Left ("untyped clause " ++ C.idText clause)) Right (pyTypedFunction typed clause)
        ps <- parameters ty
        let (args, result) = C.functionType ty
            inputs = [D.text ("argument" ++ show i ++ " = _typed." ++ pyTypedNativeIn typed t ++ "(value" ++ show i ++ ", symbols)") | (i, t) <- zip [0 :: Int ..] args]
            arguments = ["symbols" | isContextual (pyTypedPlan typed) clause] ++ ["self._state" | stateful] ++
              (if null args && not stateful then ["None"] else ["argument" ++ show i | i <- [0 .. length args - 1]])
            invocation = "_typed." ++ function ++ "(" ++ intercalate ", " arguments ++ ")"
            out x = D.text ("return _typed." ++ pyTypedNativeOut typed result ++ "(" ++ x ++ ", symbols)")
            statements = if stateful
              then [E.suite (D.text "with self._lock") (D.joinWith D.hardline [D.text ("pair = " ++ invocation), D.text "self._state = pair[1]"]), out "pair[0]"]
              else [out invocation]
        pure (E.suite (D.text ("def " ++ op) <> ps)
          (D.joinWith D.hardline (D.text "symbols = self._symbols" : inputs ++ statements)))) (C.abilityOperations ability)
      -- The state, read and replaced in its native types, and typed.
      let accessors = case C.handlerState h of
            Nothing -> []
            Just (t, _) ->
              [ E.suite (D.text "def state(self)") (D.joinWith D.hardline
                  [ D.text "\"\"\"The handler's state, in its native types: a snapshot to show or keep.\"\"\""
                  , E.suite (D.text "with self._lock") (D.text ("return _typed." ++ pyTypedNativeOut typed t ++ "(self._state, self._symbols)")) ])
              , E.suite (D.text "def set_state(self, state)") (D.joinWith D.hardline
                  [ D.text "\"\"\"Replaces the handler's state: to force it, reset it or restore a snapshot.\"\"\""
                  , D.text ("typed = _typed." ++ pyTypedNativeIn typed t ++ "(state, self._symbols)")
                  , E.suite (D.text "with self._lock") (D.text "self._state = typed") ])
              , E.suite (D.text "def typed_state(self)") (D.joinWith D.hardline
                  [ D.text "\"\"\"The typed state, shared rather than copied.\"\"\"", D.text "return self._state" ])
              , E.suite (D.text "def set_typed_state(self, state)") (D.joinWith D.hardline
                  [ D.text "\"\"\"Replaces the typed state.\"\"\"", E.suite (D.text "with self._lock") (D.text "self._state = state") ]) ]
      -- Each operation that fails with E, with its failure as Left.
      attempts <- fmap concat $ mapM (\a -> mapM (\(op, ty, failing, failure) -> do
          ref <- pythonTypeReferenceDoc failure
          let (args, result) = C.functionType ty
              values = [D.text ("value" ++ show i) | i <- [0 .. length args - 1]]
          types <- mapM (pythonDataTypeDoc datas) args
          resultType <- if result == C.scalarType "Unit" then pure (D.text "None") else pythonDataTypeDoc datas result
          failureType <- pythonDataTypeDoc datas failure
          let ps' = D.delimitTrailing 4 "(" ")" (D.text "self" : [D.text ("value" ++ show i ++ ": ") <> t | (i, t) <- zip [0 :: Int ..] types]) <>
                D.text " -> _schema.Either[" <> failureType <> D.text ", " <> resultType <> D.text "]"
          pure (E.suite (D.text ("def try_" ++ op) <> ps') (D.joinWith D.hardline
            [ D.text ("\"\"\"" ++ op ++ ", with the failure it raises as Left rather than an exception.\"\"\"")
            , E.suite (D.text "try") (D.text "return _schema.Right(self." <> E.call op values <> D.text ")")
            , E.suite (D.text "except ls.Failure as failure") (D.joinWith D.hardline
                [ E.suite (D.text ("if failure.ability != " ++ show (C.abilityKey failing))) (D.text "raise")
                , D.text "return _schema.Left(ls.handler_schema(_lawspec_schema).to_native(" <> ref <> D.text (", failure.value, " ++ show bits ++ ", self._symbols))") ]) ]))
          ) [ (op, ty, failing, failure) | (op, ty) <- C.abilityOperations a, Just failing@(C.AbilityRef _ [failure]) <- [lookup op (C.abilityFailures a)] ]) answered
      pure (E.suite (D.text ("class " ++ specName h))
        (D.joinWith D.hardline (D.text ("\"\"\"The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ", with its state typed.") :
          D.text "" : D.text (specName h ++ "() makes it on its own, outside any law: the embedding entry point.\"\"\"") : D.text "" :
          E.suite (D.text "def __init__(self, symbols=None)")
            (D.joinWith D.hardline (D.text "self._symbols = {} if symbols is None else symbols" : start)) :
          concatMap (\m -> [D.text "", m]) (methods ++ accessors ++ attempts))))
    recording a = do
      methods <- mapM (\(op, ty) -> do
        ps <- parameters ty
        let (args, _) = C.functionType ty
        logged <- sequence [schemaCall "from_native" t (D.text ("value" ++ show i)) | (i, t) <- zip [0 :: Int ..] args]
        let values = [D.text ("value" ++ show i) | i <- [0 .. length args - 1]]
        pure (E.suite (D.text ("def " ++ op) <> ps) (D.joinWith D.hardline
          [ D.text "symbols = self._symbols"
          , D.text "self.calls.append(" <> D.delimitTrailing 4 "(" ")" [E.quoted op, E.array logged] <> D.text ")"
          , D.text "return self.inner." <> E.call op values ]))) (C.abilityOperations a)
      pure (E.suite (D.text ("class " ++ recordingName a))
        (D.joinWith D.hardline ([ D.text ("\"\"\"Records each call to a " ++ C.abilityName a ++ " handler, then passes it on.\"\"\"")
          , D.text ""
          , E.suite (D.text "def __init__(self, inner, symbols=None)") (D.joinWith D.hardline (map D.text
              [ "self.inner = inner"
              , "self.calls = []"
              , "self._symbols = {} if symbols is None else symbols" ])) ] ++
          concatMap (\m -> [D.text "", m]) methods)))

-- The user-owned production handler of each ability, in the unit's
-- adapter module.
productionStub :: [C.DataDeclaration] -> C.Ability -> Either String String
productionStub datas a = do
  -- ability A with T: the handler is made with the case's T.
  made <- case C.abilityResource a of
    Nothing -> pure []
    Just t -> do
      resourceType <- pythonDataTypeDoc datas t
      pure [D.text "", E.suite (D.text "def __init__(self, resource: " <> resourceType <> D.text ") -> None")
        (D.text "self.resource = resource")]
  methods <- mapM (\(op, ty) -> do
    let (args, result) = C.functionType ty
    types <- mapM (pythonDataTypeDoc datas) args
    resultType <- if result == C.scalarType "Unit" then pure (D.text "None") else pythonDataTypeDoc datas result
    pure (E.suite (D.text ("def " ++ op) <>
      D.delimitTrailing 4 "(" ")" (D.text "self" : [D.text ("value" ++ show i ++ ": ") <> t | (i, t) <- zip [0 :: Int ..] types]) <>
      D.text " -> " <> resultType) (D.text ("raise NotImplementedError(" ++ show op ++ ")")))) (C.abilityOperations a)
  pure (D.render (D.Pretty 79) (E.suite (D.text ("class " ++ productionName a))
    (D.joinWith D.hardline (D.text ("\"\"\"The native handler of " ++ displayName a ++ ": " ++
      intercalate ", " (map fst (C.abilityOperations a)) ++ ".\"\"\"") : made ++ concatMap (\m -> [D.text "", m]) methods))) ++ "\n")
