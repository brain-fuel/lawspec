-- How a test makes the handler a law chose for an ability, as an
-- ls::Installed; root is "" in a test crate and "crate::" in the library.
handlerConstruction :: Maybe String -> [C.Unit] -> C.Unit -> C.AbilityRef -> C.HandlerRef -> L.Expr
handlerConstruction library units current = handlerConstructionWith library units current (\_ _ -> Nothing)

-- As handlerConstruction, with what makes some handlers: a shared handler
-- of several abilities, or a native handler made with a resource, given as
-- the Arc of the ability's trait.
handlerConstructionWith :: Maybe String -> [C.Unit] -> C.Unit -> (String -> C.HandlerRef -> Maybe L.Expr) -> C.AbilityRef -> C.HandlerRef -> L.Expr
handlerConstructionWith library units current made ref choice = case choice of
  -- Each handler is made into a binding of the ability's trait, so no cast
  -- is needed, then installed.
  C.RecordingHandler inner -> L.Block
    [ L.Let ("handler: " ++ arc) (handle inner)
    , L.Let "recording" (L.call (base ++ recordingFor ++ "::new") [L.atom "handler"])
    , L.Let "calls" (L.method (L.Field (L.atom "recording") "calls") "clone" [])
    , L.Let ("recording: " ++ arc) (L.call "std::sync::Arc::new" [L.atom "recording"]) ]
    (Just (L.call "ls::installed_recording" [L.atom "recording", L.atom "calls"]))
  -- The default handler names its own type, so a reader can tell it (the
  -- real clock, for lawspec.time's).
  C.ProductionHandler | Nothing <- native ->
    typed (L.call ("ls::installed_native::<" ++ adapterModule ++ "::" ++ productionFor ++ ", _>") [L.atom "handler"])
  _ -> typed (L.call "ls::installed" [L.atom "handler"])
  where
    trait = traitPath units ref
    arc = "std::sync::Arc<dyn " ++ trait ++ ">"
    found = snd <$> C.findAbility units ref
    base = case found of
      Just a -> "lawspec_abilities::" ++ moduleOfName (ownerName a) ++ "::"
      Nothing -> ""
    recordingFor = maybe "Unknown" recordingName found
    adapterModule = case found of
      Just a | ownerName a /= C.idText (C.unitId current) -> moduleOfName (ownerName a)
      _ -> "adapter"
    handle c = case c of
      _ | Just given <- made trait c -> given
      C.ProductionHandler | Just parts <- native ->
        L.call "std::sync::Arc::new" [L.call (intercalate "::" [if p == "crate" then maybe p id library else p | p <- parts]) []]
      C.ProductionHandler -> L.call "std::sync::Arc::new" [L.call (adapterModule ++ "::" ++ productionFor ++ "::default") []]
      C.SpecHandler h -> L.call "std::sync::Arc::new" [L.call ("lawspec_abilities::" ++ moduleOf current ++ "::" ++ maybe "Unknown" specName (specHandlerOf units h) ++ "::new") [L.atom "ctx"]]
      C.RecordingHandler inner -> handle inner
    typed installing = L.Block [L.Let ("handler: " ++ arc) (handle choice)] (Just installing)
    native = found >>= C.abilityNative
    productionFor = maybe "Unknown" productionName found

emit :: Bool -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String String
emit minify bits datas units = do
  typed <- emitRustTyped datas units
  modules <- mapM (unitModule typed) (filter unitAbilityPieces units)
  pure (D.render layout (D.text "// Generated by LawSpec. Do not edit." <> D.hardline <>
    D.text "use crate::lawspec_runtime as ls;" <> D.hardline <> D.hardline <>
    D.joinWith (D.hardline <> D.hardline) modules <> D.hardline))
  where
    layout = D.selectLayout minify (D.styleLayout (D.styleFor "rust"))
    calls = Definitions.definitionNames units
    line = D.text
    width = show bits
    -- A clause's or conversion's error ends the operation (ls::answered).
    answered e = L.call "ls::answered" [e]
    locked field = L.call "ls::locked" [L.atom ("&self." ++ field)]
    nativeType ty = Native.rustDataType datas ty
    impl head' items = line head' <> D.hardline <> D.block 4 (D.joinWith (D.hardline <> D.hardline) items)
    unitModule typed u = do
      traits <- mapM trait (ownAbilities u)
      handlers <- mapM (\h -> if isTypedHandler (rustTypedPlan typed) h then typedHandler typed u h else specHandler u h) (C.unitHandlers u)
      recordings <- mapM recording (ownAbilities u)
      bridges <- concat <$> mapM bridge (ownAbilities u)
      pure (line ("pub mod " ++ moduleOf u) <> D.hardline <> D.block 4 (line "use super::ls;" <> D.hardline <> D.hardline <>
        D.joinWith (D.hardline <> D.hardline) (traits ++ handlers ++ recordings ++ bridges)))
    -- An operation's method: its name, parameters and result type.
    signature op ty = do
      let (args, result) = C.functionType ty
      types <- mapM nativeType args
      resultType <- nativeType result
      pure ("fn " ++ op, "&self" : ["value" ++ show i ++ ": " ++ t | (i, t) <- zip [0 :: Int ..] types], resultType)
    method op ty body = (\(h, ps, r) -> L.function h ps r body) <$> signature op ty
    trait a = do
      methods <- mapM (\(op, ty) -> (\(h, ps, r) -> L.declaration h ps r) <$> signature op ty) (C.abilityOperations a)
      pure (line ("/// The " ++ C.abilityName a ++ " ability: a handler answers each of its operations.") <> D.hardline <>
        line ("pub trait " ++ interfaceName a ++ ": Send + Sync") <> D.hardline <> D.block 4 (D.joinWith D.hardline methods))
    -- A native result from a logical value, as the definitions' wrappers do.
    toNative ty value = do
      native <- nativeType ty
      ref <- E.reference ty
      pure ([ L.Let "schema" (answered (L.call "crate::lawspec_schema::schema" []))
            , L.Let "result" (answered (L.method (L.atom "schema") "native_value_with_context" [value, L.prefix "&" (L.Laid ref), L.atom width, L.atom "ctx"])) ],
            answered (L.call ("<" ++ native ++ " as ls::FromValue>::from_value") [L.atom "result"]))
    attemptMethods answered' = fmap concat $ forM answered' $ \answer -> forM [ (op, ty, failing, failure) | (op, ty) <- C.abilityOperations answer
                                                             , Just failing@(C.AbilityRef _ [failure]) <- [lookup op (C.abilityFailures answer)] ] $ \(op, ty, failing, failure) -> do
      let (args, _) = C.functionType ty
      (_, params, resultType) <- signature op ty
      failureType <- nativeType failure
      (decodeStatements, decoded) <- toNative failure (L.atom "failure")
      let values = ["value" ++ show i | i <- [0 .. length args - 1]]
          traitName = "super::" ++ moduleOfName (ownerName answer) ++ "::" ++ interfaceName answer
          attempted = L.call "ls::fast::attempt" [L.atom (show (C.abilityKey failing)),
            L.closure "||" (L.call "Ok" [L.call ("<Self as " ++ traitName ++ ">::" ++ op) (map L.atom ("self" : values))])]
      pure (line ("/// " ++ op ++ ", with the failure it raises as Err rather than a panic.") <> D.hardline <>
        L.function ("pub fn try_" ++ op) params ("std::result::Result<" ++ resultType ++ ", " ++ failureType ++ ">")
          (L.expr (L.Match attempted
            [ Arm "Ok(Ok(result))" Nothing (L.call "Ok" [L.atom "result"])
            , Arm "Ok(Err(failure))" Nothing (L.Block
                ([L.Let "mut ctx" (L.method (locked "ctx") "clone" []), L.Let "ctx" (L.atom "&mut ctx")] ++ decodeStatements)
                (Just (L.call "Err" [decoded])))
            , Arm "Err(error)" Nothing (L.macroCall "panic" [L.atom "\"{error}\""]) ])))
    -- The handler for a law; it evaluates its clauses in a copy of the
    -- law's context.
    -- A handler keeps a copy of the law's context and its state only when
    -- its operations read them.
    construction keepsContext start = line "/// The handler for a law; it evaluates its clauses in a copy of the law's context." <> D.hardline <>
      let needsContext = keepsContext || maybe False (E.mentions "ctx" . L.expr) start
          made = L.struct "Self" ([("ctx", L.call "std::sync::Mutex::new" [L.atom "ctx"]) | keepsContext] ++
                                  [("state", L.call "std::sync::Mutex::new" [L.atom "state"]) | Just _ <- [start]])
      in L.function "pub fn new" [(if needsContext then "ctx" else "_ctx") ++ ": &ls::Context"] "Self" (L.stmts
        ([L.Let (if maybe False (E.mentions "ctx" . L.expr) start then "mut ctx" else "ctx") (L.method (L.atom "ctx") "clone" []) | needsContext] ++
         [L.Let "state" st | Just st <- [start]])
        (Just made))
    fields keepsContext stateField = D.joinWith D.hardline
      ([line "ctx: std::sync::Mutex<ls::Context>," | keepsContext] ++ [L.fieldDoc "state" ("std::sync::Mutex<" ++ t ++ ">") <> line "," | Just t <- [stateField]])
    structDoc name keepsContext stateField = if not keepsContext && stateField == Nothing
      then line ("pub struct " ++ name ++ ";")
      else line ("pub struct " ++ name) <> D.hardline <> D.block 4 (fields keepsContext stateField)
    starting = line "/// The handler on its own, outside any law: the embedding entry point." <> D.hardline <>
      L.function "pub fn start" [] "Self" (L.expr (L.call "Self::new" [L.atom "&ls::Context::default()"]))
    implementations name answered' methodBlocks = D.joinWith (D.hardline <> D.hardline)
      [ impl ("impl super::" ++ moduleOfName (ownerName answer) ++ "::" ++ interfaceName answer ++ " for " ++ name) methods
      | (answer, methods) <- zip answered' methodBlocks ]
    specHandler u h = do
      -- A handler of several abilities implements each one's trait.
      answered' <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered' of
            first : _ -> first { C.abilityName = intercalate ", " (map C.abilityName answered') }
            [] -> C.failAbility
      start <- case C.handlerState h of
        Nothing -> pure (L.atom "None")
        -- A computed start value is its own definition (<handler>Start).
        Just (_, C.Expr _ (C.ExternalCall startDefinition _) _) -> do
          evaluate <- maybe (Left ("unresolved start of " ++ C.handlerName h)) Right (lookup startDefinition calls)
          pure (L.call "Some" [answered (L.call ("crate::lawspec_definitions::" ++ evaluate) [L.atom "&mut ctx", L.vecOf [L.atom "ls::Value::Unit"]])])
        Just (_, value) -> do
          rendered <- E.renderExpressionL datas bits [] [] value
          pure (L.call "Some" [answered (L.Call (L.Paren (L.closure "|| -> ls::Result<ls::Value>"
            (L.Block [L.Let "ctx" (L.atom "&mut ctx"), L.Let "value" rendered] (Just (L.call "Ok" [L.atom "value"]))))) [])])
      let methodsOf answer = mapM (\(op, ty) -> clauseMethod op ty) (C.abilityOperations answer)
          clauseMethod op ty = do
            clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
            evaluate <- maybe (Left ("unresolved clause " ++ C.idText clause)) Right (lookup clause calls)
            let (args, result) = C.functionType ty
            (convertStatements, converted) <- toNative result (L.atom "result")
            let arguments = [L.method (L.method (locked "state") "clone" []) "unwrap" [] | Just _ <- [C.handlerState h]] ++
                  (if null args && C.handlerState h == Nothing then [L.atom "ls::Value::Unit"]
                   else [L.call "ls::IntoValue::into_value" [L.atom ("value" ++ show i)] | i <- [0 .. length args - 1]])
                invocation = answered (L.call ("crate::lawspec_definitions::" ++ evaluate) [L.atom "ctx", L.vecOf arguments])
                outcome = case C.handlerState h of
                  Nothing -> [L.Let "result" invocation]
                  Just _ -> [ L.Let "pair" invocation
                            , L.Let "(result, next)" (answered (L.call "ls::pair_fields" [L.atom "pair"]))
                            , L.Semi (L.Infix 1 "=" (L.prefix "*" (locked "state")) (L.call "Some" [L.atom "next"])) ]
            method op ty (L.stmts ([L.Let "mut guard" (locked "ctx"), L.Let "ctx" (L.atom "&mut *guard")] ++ outcome ++ convertStatements) (Just converted))
      methodBlocks <- mapM methodsOf answered'
      attempts <- attemptMethods answered'
      accessors <- case C.handlerState h of
        Nothing -> pure []
        Just (t, _) -> do
          native <- nativeType t
          ref <- E.reference t
          (convertStatements, converted) <- toNative t (L.atom "snapshot")
          pure [ line "/// A native snapshot of the handler's dynamic state." <> D.hardline <>
                 L.function "pub fn state" ["&self"] native (L.stmts
                   ([ L.Let "mut guard" (locked "ctx"), L.Let "ctx" (L.atom "&mut *guard")
                    , L.Let "snapshot" (L.method (L.method (locked "state") "clone" []) "unwrap" []) ] ++ convertStatements) (Just converted))
               , line "/// Replace the state after checking its declared schema." <> D.hardline <>
                 L.function "pub fn set_state" ["&self", "state: " ++ native] "" (L.stmts
                   [ L.Let "mut guard" (locked "ctx"), L.Let "ctx" (L.atom "&mut *guard")
                   , L.Let "schema" (answered (L.call "crate::lawspec_schema::schema" []))
                   , L.Let "next" (answered (L.method (L.atom "schema") "validate_with_context"
                       [L.call "ls::IntoValue::into_value" [L.atom "state"], L.prefix "&" (L.Laid ref), L.atom width, L.atom "ctx"]))
                   , L.Semi (L.Infix 1 "=" (L.prefix "*" (locked "state")) (L.call "Some" [L.atom "next"])) ] Nothing) ]
      let name = specName h
      pure (line ("/// The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ".") <> D.hardline <>
        structDoc name True (Just "Option<ls::Value>" <* C.handlerState h) <> D.hardline <> D.hardline <>
        impl ("impl " ++ name) ([construction True (start <$ C.handlerState h), starting] ++ accessors ++ attempts) <> D.hardline <> D.hardline <>
        implementations name answered' methodBlocks)
    -- A typed spec handler keeps its state typed: each operation converts
    -- its arguments, runs the typed clause and keeps the next state, which
    -- shares all it did not change with the state before.
    typedHandler typed u h = do
      -- A handler of several abilities implements each one's trait.
      answered' <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered' of
            first : _ -> first { C.abilityName = intercalate ", " (map C.abilityName answered') }
            [] -> C.failAbility
      stateType <- traverse (rustTypedType typed . fst) (C.handlerState h)
      start <- traverse (rustTypedValue typed . snd) (C.handlerState h)
      methodBlocks <- forM answered' $ \answer -> mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        function <- maybe (Left ("untyped clause " ++ C.idText clause)) Right (rustTypedFunction typed clause)
        let (args, result) = C.functionType ty
        argumentTypes <- mapM (rustTypedType typed) args
        nativeResult <- nativeType result
        -- A typed value converts to its public type directly where it can,
        -- otherwise through the dynamic Value.
        let direct = rustTypedNative typed
            (convertStatements, converted)
              | direct result = ([], L.call "ls::fast::Public::to_native" [L.atom "&result"])
              | otherwise = ([L.Let "result" (L.call "ls::fast::Dyn::to_dyn" [L.atom "&result"])],
                  answered (L.call ("<" ++ nativeResult ++ " as ls::FromValue>::from_value") [L.atom "result"]))
            decoded = [ if direct ty then L.call ("<" ++ t ++ " as ls::fast::Public>::from_native") [L.atom ("value" ++ show i)]
                        else answered (L.call ("<" ++ t ++ " as ls::fast::Dyn>::from_dyn") [L.call "ls::IntoValue::into_value" [L.atom ("value" ++ show i)]])
                      | (i, (ty, t)) <- zip [0 :: Int ..] (zip args argumentTypes)]
            contextual = isContextual (rustTypedPlan typed) clause
            arguments = [L.atom "&mut *ctx" | contextual] ++ [L.method (L.atom "state") "clone" [] | Just _ <- [C.handlerState h]] ++
              (if null args && C.handlerState h == Nothing then [L.atom "()"] else decoded)
            invocation = answered (L.call function arguments)
            -- A clause that performs other abilities' operations finds their
            -- handlers in the handler's context.
            lockedContext = [L.Let "mut ctx" (locked "ctx") | contextual]
            outcome = lockedContext ++ case C.handlerState h of
              Nothing -> [L.Let "result" invocation]
              -- The state stays locked for the whole operation, so
              -- concurrent operations apply one after another.
              Just _ -> [ L.Let "mut state" (locked "state")
                        , L.Let "pair" invocation
                        , L.Let "(result, next)" (L.call (rustPairFields typed) [L.atom "pair"])
                        , L.Semi (L.atom "*state = next")
                        , L.Semi (L.call "drop" [L.atom "state"]) ]
        method op ty (L.stmts (outcome ++ convertStatements) (Just converted))) (C.abilityOperations answer)
      let name = specName h
      -- The state, read and replaced in its native types, and typed.
      accessors <- case C.handlerState h of
        Nothing -> pure []
        Just (t, _) -> do
          native <- nativeType t
          typedType <- rustTypedType typed t
          (convertStatements, converted) <- toNative t (L.call "ls::fast::Dyn::to_dyn" [L.atom "&*state"])
          let direct = rustTypedNative typed t
              readNative = if direct then L.stmts [L.Let "state" (locked "state")] (Just (L.call "ls::fast::Public::to_native" [L.atom "&*state"]))
                else L.stmts ([L.Let "state" (locked "state"), L.Let "mut ctx" (L.method (locked "ctx") "clone" []), L.Let "ctx" (L.atom "&mut ctx")] ++ convertStatements) (Just converted)
              made = if direct then L.call ("<" ++ typedType ++ " as ls::fast::Public>::from_native") [L.atom "state"]
                else answered (L.call ("<" ++ typedType ++ " as ls::fast::Dyn>::from_dyn") [L.call "ls::IntoValue::into_value" [L.atom "state"]])
          pure [ line "/// The handler's state, in its native types: a snapshot to show or keep." <> D.hardline <>
                 L.function "pub fn state" ["&self"] native readNative
               , line "/// Replaces the handler's state, as an operation would: to force it, reset it or restore a snapshot." <> D.hardline <>
                 L.function "pub fn set_state" ["&self", "state: " ++ native] "" (L.stmts
                   [ L.Let "next" made, L.Semi (L.Infix 1 "=" (L.prefix "*" (locked "state")) (L.atom "next")) ] Nothing)
               , line "/// The typed state, shared rather than copied." <> D.hardline <>
                 L.function "pub fn typed_state" ["&self"] typedType (L.expr (L.method (locked "state") "clone" []))
               , line "/// Replaces the typed state." <> D.hardline <>
                 L.function "pub fn set_typed_state" ["&self", "state: " ++ typedType] "" (L.stmts
                   [L.Semi (L.Infix 1 "=" (L.prefix "*" (locked "state")) (L.atom "state"))] Nothing) ]
      attempts <- attemptMethods answered'
      let keepsContext = or [isContextual (rustTypedPlan typed) clause | answer <- answered', (op, _) <- C.abilityOperations answer, Just clause <- [lookup op (C.handlerClauses h)]] ||
            not (null attempts) || maybe False (not . rustTypedNative typed . fst) (C.handlerState h)
          startValue = maybe (L.atom "()") (\v -> answered (L.Call (L.Paren (L.closure "|| -> ls::Result<_>"
            (L.Block [L.Let (if E.mentions "ctx" (L.expr v) then "ctx" else "_ctx") (L.atom "&mut ctx")] (Just (L.call "Ok" [v]))))) [])) start
      pure (line ("/// The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ", with its state typed.") <> D.hardline <>
        structDoc name keepsContext stateType <> D.hardline <> D.hardline <>
        impl ("impl " ++ name) ([construction keepsContext (startValue <$ C.handlerState h), starting] ++ accessors ++ attempts) <> D.hardline <> D.hardline <>
        implementations name answered' methodBlocks)
    recording a = do
      methods <- mapM (\(op, ty) -> do
        let (args, _) = C.functionType ty
            values = ["value" ++ show i | i <- [0 .. length args - 1]]
        method op ty (L.stmts
          [ L.Semi (L.method (L.Field (L.atom "self") "calls") "record" [L.atom (show op), L.vecOf [L.call "ls::IntoValue::into_value" [L.method (L.atom v) "clone" []] | v <- values]]) ]
          (Just (L.method (L.Field (L.atom "self") "inner") op (map L.atom values))))) (C.abilityOperations a)
      let name = recordingName a
      pure (line ("/// Records each call to a " ++ C.abilityName a ++ " handler, then passes it on.") <> D.hardline <>
        line ("pub struct " ++ name) <> D.hardline <> D.block 4 (D.joinWith D.hardline
          [line ("pub inner: std::sync::Arc<dyn " ++ interfaceName a ++ ">,"), line "pub calls: ls::Calls,"]) <> D.hardline <> D.hardline <>
        impl ("impl " ++ name) [L.function "pub fn new" ["inner: std::sync::Arc<dyn " ++ interfaceName a ++ ">"] "Self"
          (L.expr (L.struct "Self" [("inner", L.atom "inner"), ("calls", L.call "ls::Calls::default" [])]))] <> D.hardline <> D.hardline <>
        impl ("impl " ++ interfaceName a ++ " for " ++ name) methods)
    -- Each operation's bridge: the handler from the context, the arguments
    -- to native values and the result back.
    bridge a = mapM (\(op, ty) -> do
      let (args, result) = C.functionType ty
      types <- mapM nativeType args
      refs <- mapM E.reference args
      resultRef <- E.reference result
      let natives = ["native_" ++ show n | n <- [0 .. length args - 1]]
          decode (n, native, t, ref) =
            [ L.Let "value" (L.try' (L.method (L.atom "schema") "native_value_with_context"
                [L.method (L.atom ("arguments[" ++ show n ++ "]")) "clone" [], L.prefix "&" (L.Laid ref), L.atom width, L.atom "ctx"]))
            , L.Let native (L.try' (L.call ("<" ++ t ++ " as ls::FromValue>::from_value") [L.atom "value"])) ]
          called = L.method (L.atom "handler") op (map L.atom natives)
          performed = case lookup op (C.abilityFailures a) of
            -- An operation that fails with E: a native handler calls
            -- ls::fail with a native E, which becomes the failure.
            Just failing@(C.AbilityRef _ [failure]) ->
              L.call ("ls::native_failures::<" ++ either error id (nativeType failure) ++ ", _>")
                [L.atom (show (C.abilityKey failing)), L.closure "|native|" (L.call "ls::IntoValue::into_value" [L.atom "native"]), L.closure "||" called, L.atom "vec![]"]
            _ -> called
          unit = result == C.scalarType "Unit"
          statements' =
            [L.Let "schema" (L.try' (L.call "crate::lawspec_schema::schema" [])) | not unit || not (null args)] ++
            [L.Let ("handler: std::sync::Arc<dyn " ++ interfaceName a ++ ">") (L.try' (L.method (L.atom "ctx") "handler" [L.atom (show (C.abilityKey (C.abilityInstance a)))]))] ++
            concat [decode (n, native, t, ref) | (n, native, t, ref) <- zip4 [0 :: Int ..] natives types refs] ++
            (if unit then [L.Semi performed] else [L.Let "native_result" performed])
          -- The result is checked against its type, which also gives Bytes
          -- (a Vec<u8> natively) its own representation.
          final = if unit then L.call "Ok" [L.atom "ls::Value::Unit"]
            else L.method (L.atom "schema") "validate_with_context" [L.call "ls::IntoValue::into_value" [L.atom "native_result"], L.prefix "&" (L.Laid resultRef), L.atom width, L.atom "ctx"]
          body = L.stmts statements' (Just final)
      pure (line ("/// " ++ op ++ ", answered by the handler installed for " ++ C.abilityName a ++ ".") <> D.hardline <>
        L.function ("pub fn perform_" ++ bridgeName a op) ["ctx: &mut ls::Context", E.unusedAs "arguments" body ++ ": Vec<ls::Value>"] "ls::Result<ls::Value>" body)) (C.abilityOperations a)
    zip4 (w : ws) (x : xs) (y : ys) (z : zs) = (w, x, y, z) : zip4 ws xs ys zs
    zip4 _ _ _ _ = []

-- The user-owned production handler of each ability, in the unit's adapter
-- module: <Ability>Handler::default() is what the tests use.
productionStub :: [C.DataDeclaration] -> C.Unit -> C.Ability -> Either String D.Doc
productionStub datas u a = do
  methods <- mapM (\(op, ty) -> do
    let (args, result) = C.functionType ty
    types <- mapM (Native.rustDataType datas) args
    resultType <- Native.rustDataType datas result
    pure (D.text ("fn " ++ op ++ "(&self" ++ concat [", value" ++ show i ++ ": " ++ t | (i, t) <- zip [0 :: Int ..] types] ++ ") -> " ++ resultType ) <> D.hardline <>
