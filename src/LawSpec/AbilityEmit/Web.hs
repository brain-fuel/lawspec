-- JavaScript and TypeScript pieces of a unit's abilities (see
-- LawSpec.AbilityNames): an interface per ability (TypeScript), a class per
-- spec handler and a recording class per ability, in
-- lawspec_abilities/<unit path>.mjs (or .ts). Handlers travel in the symbols
-- Map generated code passes to every definition, as in Python.
module LawSpec.AbilityEmit.Web (emit, emitWithNativeBridge, modulePath, productionStub) where

import Data.List (intercalate)
import Data.Char (toUpper)
import qualified LawSpec.Core as C
import LawSpec.Backend (localName)
import LawSpec.Common (Artifact(..))
import LawSpec.AbilityNames
import LawSpec.WebData (webDataTypeOf, webTypeReference)
import qualified LawSpec.WebDefinitions as Definitions
import qualified LawSpec.Code.Doc as D
import qualified LawSpec.Code.ECMAScript as E
import qualified LawSpec.WebExpr as X
import LawSpec.Typed.Plan (isTypedHandler, isContextual)
import LawSpec.Typed.Web (WebTyped(..), emitWebTyped)
import LawSpec.WebModule (Support(..), webModule, printWebModule, commentLines, importExtension)

-- The generated module of a unit's abilities, from the project root.
modulePath :: Bool -> C.Unit -> String
modulePath ts u = "src/lawspec_abilities/" ++ map (\c -> if c == '.' then '/' else c) (C.idText (C.unitId u)) ++ (if ts then ".ts" else ".mjs")

emit :: Bool -> Bool -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emit = emitWithNativeBridge False

-- | Register bound handler representations before generated methods run.
emitWithNativeBridge :: Bool -> Bool -> Bool -> Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitWithNativeBridge nativeBridge ts minify bits datas units = do
  typed <- emitWebTyped ts bits datas units
  mapM (unitModule typed) (filter unitAbilityPieces units)
  where
    layout = D.selectLayout minify (D.Pretty 80)
    calls = Definitions.definitionCalls datas units
    width = X.machineBits
    annotated name ty = (E.param name) { E.paramType = if ts then Just ty else Nothing }
    symbolsHere = E.member E.This "_symbols"
    schemaCall name ty value = do
      ref <- webTypeReference ty
      pure (E.method (E.call "ls.handlerSchema" [E.Ident "_lawspec_schema"]) name [ref, value, width, E.Ident "symbols"])
    unitModule typed u = do
      let depth = 1 + length (filter (== '.') (C.idText (C.unitId u)))
          root = concat (replicate depth "../")
          typedHandlers = [h | h <- C.unitHandlers u, isTypedHandler (webTypedPlan typed) h]
          namespace alias file = (alias, E.ImportDecl False (E.ImportNamespace alias) (root ++ file ++ "." ++ importExtension ts))
      interfaces <- if ts then mapM interface (ownAbilities u) else pure []
      handlers <- mapM (\h -> if h `elem` typedHandlers then typedHandler typed u h else specHandler u h) (C.unitHandlers u)
      recordings <- mapM recording (ownAbilities u)
      let leading = [E.Comment (["// @ts-nocheck" | ts] ++ ["// Generated by LawSpec. Do not edit."] ++
            commentLines ("The abilities of " ++ C.idText (C.unitId u) ++ ": " ++ (if ts then "an interface for each, " else "") ++
              "its spec handlers, and a recording of any handler of it."))]
          imports = [namespace "data" "lawspec_data", namespace "ls" "lawspec_runtime"] ++
            [("ls", E.ImportDecl False E.ImportEffect (root ++ "lawspec_native." ++ importExtension ts)) | nativeBridge] ++
            [namespace "schema" "lawspec_schema",
                     namespace "_definitions" "lawspec_definition_bodies", namespace "_typed" "lawspec_typed"]
          support = [ Support "_lawspec_schema" [E.constDecl "_lawspec_schema" (E.call "data.makeSchema" [])]
                    , Support "MACHINE_BITS" (X.machineBitsDeclaration bits) ]
      pure (Artifact (modulePath ts u) (printWebModule layout ts (webModule ts leading imports support (interfaces ++ handlers ++ recordings))) "generated" "source")
    parametersOf ty = do
      let (args, result) = C.functionType ty
      types <- mapM (webDataTypeOf datas) args
      resultType <- if result == C.scalarType "Unit" then pure (E.TKeyword "void") else webDataTypeOf datas result
      pure ([annotated ("value" ++ show i) t | (i, t) <- zip [0 :: Int ..] types], if ts then Just resultType else Nothing)
    method op params result body = E.Method False False "method" op params result body
    doc text = E.MemberComment ["/** " ++ text ++ " */"]
    interface a = do
      methods <- mapM (\(op, ty) -> do
        (params, result) <- parametersOf ty
        pure (E.Signature op params result)) (C.abilityOperations a)
      pure [ E.Comment ["/** The " ++ interfaceName a ++ " ability: a handler answers each of its operations. */"]
           , E.Interface True (interfaceName a) [] methods ]
    implementsOf answered = if ts then [E.TRef (interfaceName a) [] | a <- answered] else []
    constructorWith params body = E.Method False False "method" "constructor" params Nothing body
    symbolsParam = E.Param (E.PIdent "symbols") Nothing (Just (E.new' "Map" [])) False
    setState x = E.ExprStmt (E.Assign "=" (E.member E.This "_state") x)
    unitLiteral = E.call "ls.literal" [E.Object [E.Prop (E.KName "type") (E.Str "Unit")], E.Ident "symbols"]
    specHandler u h = do
      -- A handler of several abilities answers all their operations.
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
      initialState <- case C.handlerState h of
        Nothing -> pure []
        -- A computed start value is its own definition (<handler>Start).
        Just (_, C.Expr _ (C.ExternalCall startDefinition _) _) -> do
          evaluate <- maybe (Left ("unresolved start of " ++ C.handlerName h)) Right (lookup startDefinition calls)
          pure [setState (E.call (Definitions.plainCall evaluate) [E.Ident "symbols", unitLiteral])]
        Just (_, start) -> do
          value <- X.renderExpression ts datas localName (\_ _ -> Left "a handler's start value calls nothing") start
          pure [setState value]
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        evaluate <- maybe (Left ("unresolved clause " ++ C.idText clause)) Right (lookup clause calls)
        (params, resultType) <- parametersOf ty
        let (args, result) = C.functionType ty
        inputs <- sequence [schemaCall "fromNative" t (E.Ident ("value" ++ show i)) | (i, t) <- zip [0 :: Int ..] args]
        let arguments = E.Ident "symbols" : [E.member E.This "_state" | Just _ <- [C.handlerState h]] ++
              (if null args && C.handlerState h == Nothing then [unitLiteral] else inputs)
            invocation = E.call (Definitions.plainCall evaluate) arguments
        output <- schemaCall "toNative" result (E.Ident "result")
        let statements = case C.handlerState h of
              Nothing -> [E.constDecl "result" invocation]
              Just _ -> [ E.constDecl "pair" invocation
                        , setState (E.index (E.member (E.Ident "pair") "fields") (E.num 1))
                        , E.constDecl "result" (E.index (E.member (E.Ident "pair") "fields") (E.num 0)) ]
        pure (method op params resultType (E.constDecl "symbols" symbolsHere : statements ++ [E.ret output]))) (C.abilityOperations ability)
      pure [ E.Comment ["/** The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ". */"]
           , E.ClassDecl True (specName h) [] Nothing (implementsOf answered)
               (constructorWith [symbolsParam] (E.ExprStmt (E.Assign "=" symbolsHere (E.Ident "symbols")) : initialState) : methods) ]
    -- A typed spec handler keeps its state typed: each operation converts its
    -- arguments, runs the typed clause and keeps the next state, which shares
    -- all it did not change with the state before.
    typedHandler typed u h = do
      answered <- mapM (\ref -> maybe (Left ("unknown ability of handler " ++ C.handlerName h)) Right (unitAbility u ref)) (C.handlerAbilities h)
      let ability = case answered of
            first : _ -> first { C.abilityOperations = concatMap C.abilityOperations answered
                               , C.abilityName = intercalate ", " (map C.abilityName answered) }
            [] -> C.failAbility
          stateful = C.handlerState h /= Nothing
      start <- case C.handlerState h of
        Nothing -> pure []
        Just _ -> do
          name <- maybe (Left ("untyped start of " ++ C.handlerName h)) Right (webTypedStart typed (C.handlerId h))
          pure [setState (E.call ("_typed." ++ name) [E.Ident "symbols"])]
      methods <- mapM (\(op, ty) -> do
        clause <- maybe (Left (C.handlerName h ++ ": no clause for " ++ op)) Right (lookup op (C.handlerClauses h))
        function <- maybe (Left ("untyped clause " ++ C.idText clause)) Right (webTypedFunction typed clause)
        (params, resultType) <- parametersOf ty
        let (args, result) = C.functionType ty
            inputs = [E.constDecl ("argument" ++ show i) (E.call ("_typed." ++ webTypedNativeIn typed t) [E.Ident ("value" ++ show i), E.Ident "symbols"])
                     | (i, t) <- zip [0 :: Int ..] args]
            arguments = [E.Ident "symbols" | isContextual (webTypedPlan typed) clause] ++ [E.member E.This "_state" | stateful] ++
              (if null args && not stateful then [E.Null] else [E.Ident ("argument" ++ show i) | i <- [0 .. length args - 1]])
            invocation = E.call ("_typed." ++ function) arguments
            out x = E.ret (E.call ("_typed." ++ webTypedNativeOut typed result) [x, E.Ident "symbols"])
            statements = if stateful
              then [E.constDecl "pair" invocation, setState (E.member (E.Ident "pair") "second"), out (E.member (E.Ident "pair") "first")]
              else [out invocation]
        pure (method op params resultType (E.constDecl "symbols" symbolsHere : inputs ++ statements))) (C.abilityOperations ability)
      -- The state, read and replaced in its native types, and typed.
      accessors <- case C.handlerState h of
        Nothing -> pure []
        Just (t, _) -> do
          native <- webDataTypeOf datas t
          let state = E.member E.This "_state"
          pure [ doc "The handler's state, in its native types: a snapshot to show or keep."
               , method "state" [] (if ts then Just native else Nothing) [E.ret (E.call ("_typed." ++ webTypedNativeOut typed t) [state, symbolsHere])]
               , doc "Replaces the handler's state: to force it, reset it or restore a snapshot."
               , method "setState" [annotated "state" native] (if ts then Just (E.TKeyword "void") else Nothing)
                   [setState (E.call ("_typed." ++ webTypedNativeIn typed t) [E.Ident "state", symbolsHere])]
               , doc "The typed state, shared rather than copied."
               , method "typedState" [] Nothing [E.ret state]
               , doc "Replaces the typed state."
               , method "setTypedState" [annotated "state" (E.TKeyword "any")] (if ts then Just (E.TKeyword "void") else Nothing) [setState (E.Ident "state")] ]
      -- Each operation that fails with E, with its failure as Left.
      attempts <- fmap concat $ mapM (\a -> mapM (\(op, ty, failing, failure) -> do
          ref <- webTypeReference failure
          let (args, result) = C.functionType ty
              values = [E.Ident ("value" ++ show i) | i <- [0 .. length args - 1]]
              failed = if ts then E.As (E.Ident "failure") (E.TKeyword "any") else E.Ident "failure"
          types <- mapM (webDataTypeOf datas) args
          resultType <- if result == C.scalarType "Unit" then pure (E.TKeyword "undefined") else webDataTypeOf datas result
          failureType <- webDataTypeOf datas failure
          pure [ doc (op ++ ", with the failure it raises as Left rather than an exception.")
               , method ("try" ++ capitalizeFirst op) [annotated ("value" ++ show i) t | (i, t) <- zip [0 :: Int ..] types]
                   (if ts then Just (E.TRef "data.Either" [failureType, resultType]) else Nothing)
                   [E.Try [E.ret (E.new' "data.Right" [E.method E.This op values])] (Just (Just (E.PIdent "failure"),
                     [ E.IfSingle (E.or' (E.notE (E.Binary "instanceof" (E.Ident "failure") (E.member (E.Ident "ls") "Failure")))
                                         (E.Binary "!==" (E.member failed "ability") (E.Str (C.abilityKey failing)))) (E.Throw (E.Ident "failure"))
                     , E.ret (E.new' "data.Left" [E.method (E.call "ls.handlerSchema" [E.Ident "_lawspec_schema"]) "toNative"
                         [ref, E.member failed "value", width, symbolsHere]]) ])) Nothing] ]
          ) [ (op, ty, failing, failure) | (op, ty) <- C.abilityOperations a, Just failing@(C.AbilityRef _ [failure]) <- [lookup op (C.abilityFailures a)] ]) answered
      pure [ E.Comment (commentLines' ("The spec handler " ++ C.handlerName h ++ " for " ++ C.abilityName ability ++ ", with its state typed: new " ++
               specName h ++ "() makes it on its own, outside any law."))
           , E.ClassDecl True (specName h) [] Nothing (implementsOf answered)
               (constructorWith [symbolsParam] (E.ExprStmt (E.Assign "=" symbolsHere (E.Ident "symbols")) : start) : methods ++ accessors ++ concat attempts) ]
    capitalizeFirst (c : cs) = toUpper c : cs
    capitalizeFirst [] = []
    recording a = do
      methods <- mapM (\(op, ty) -> do
        (params, resultType) <- parametersOf ty
        let (args, _) = C.functionType ty
        logged <- sequence [schemaCall "fromNative" t (E.Ident ("value" ++ show i)) | (i, t) <- zip [0 :: Int ..] args]
        let values = [E.Ident ("value" ++ show i) | i <- [0 .. length args - 1]]
        pure (method op params resultType
          [ E.constDecl "symbols" symbolsHere
          , E.ExprStmt (E.method (E.member E.This "calls") "push" [E.Array [E.Str op, E.Array logged]])
          , E.ret (E.method (E.member E.This "inner") op values) ])) (C.abilityOperations a)
      pure [ E.Comment ["/** Records each call to a " ++ C.abilityName a ++ " handler, then passes it on. */"]
           , E.ClassDecl True (recordingName a) [] Nothing (if ts then [E.TRef (interfaceName a) []] else [])
               (constructorWith [E.param "inner", symbolsParam]
                 [ E.ExprStmt (E.Assign "=" (E.member E.This "inner") (E.Ident "inner"))
                 , E.ExprStmt (E.Assign "=" (E.member E.This "calls") (E.Array []))
                 , E.ExprStmt (E.Assign "=" symbolsHere (E.Ident "symbols")) ] : methods) ]
    -- A JSDoc comment, wrapped.
    commentLines' text = ["/**"] ++ map (" * " ++) (wrapped text) ++ [" */"]
    wrapped text = map (drop 3) (commentLines text)

-- The user-owned production handler of each ability, in the unit's adapter
-- module.
productionStub :: Bool -> [C.DataDeclaration] -> C.Ability -> Either String [E.Stmt]
productionStub ts datas a = do
  methods <- mapM (\(op, ty) -> do
    let (args, result) = C.functionType ty
    types <- mapM (webDataTypeOf datas) args
    resultType <- if result == C.scalarType "Unit" then pure (E.TKeyword "void") else webDataTypeOf datas result
    pure (E.Method False False "method" op [(E.param ("value" ++ show i)) { E.paramType = if ts then Just t else Nothing } | (i, t) <- zip [0 :: Int ..] types]
      (if ts then Just resultType else Nothing) [E.Throw (E.new' "Error" [E.Str op])])) (C.abilityOperations a)
  -- ability A with T: the handler is made with the case's T.
  made <- case C.abilityResource a of
    Nothing -> pure []
    Just t -> do
      resourceType <- webDataTypeOf datas t
      pure ([E.Field [] "resource" (Just resourceType) Nothing | ts] ++
        [E.Method False False "method" "constructor" [(E.param "resource") { E.paramType = if ts then Just resourceType else Nothing }] Nothing
          [E.ExprStmt (E.Assign "=" (E.member E.This "resource") (E.Ident "resource"))]])
  pure [ E.Comment (["/**"] ++ map (" * " ++) (map (drop 3) (commentLines ("The native handler of " ++ displayName a ++ ": " ++
           intercalate ", " (map fst (C.abilityOperations a)) ++ "."))) ++ [" */"])
       , E.ClassDecl True (productionName a) [] Nothing (if ts then [E.TRef ("abilities." ++ interfaceName a) []] else []) (made ++ methods) ]
