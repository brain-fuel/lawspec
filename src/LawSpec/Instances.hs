-- | The operations of the built-in capability instances, as a built-in unit,
-- lawspec.instances, added to a program that imports it. Each is an ordinary
-- structurally recursive definition: the meaning of the operation that the
-- targets run natively, and what a proof about it unfolds.
-- ref:DEC-capability-instances
module LawSpec.Instances
  ( instancesUnit, instancesSource, instanceLawsUnit, instanceLawsSource
  ) where

instancesUnit :: String
instancesUnit = "lawspec.instances"

instancesSource :: String
instancesSource = unlines
  [ "unit " ++ instancesUnit
  , "-- Mappable List: prelude.map."
  , "function mapList (f :: a -> b) (xs :: List a) -> List b is"
  , "  first matching case of xs:"
  , "    when Nil then []"
  , "    when Cons x rest then Cons (f x) (mapList f rest)"
  , "  end case"
  , "end function"
  , ""
  , "-- Mappable (Either e): prelude.map over the success value."
  , "function mapEither (f :: a -> b) (value :: Either e a) -> Either e b is"
  , "  first matching case of value:"
  , "    when Left failure then Left failure"
  , "    when Right x then Right (f x)"
  , "  end case"
  , "end function"
  , ""
  , "-- Filterable List: prelude.filter."
  , "function filterList (keep :: a -> Bool) (xs :: List a) -> List a is"
  , "  first matching case of xs:"
  , "    when Nil then []"
  , "    when Cons x rest then"
  , "      if keep x then Cons x (filterList keep rest) else filterList keep rest end if"
  , "  end case"
  , "end function"
  , ""
  , "-- Foldable List: prelude.foldLeft, prelude.foldRight, prelude.all,"
  , "-- prelude.any and prelude.length."
  , "function foldLeftList (step :: b -> a -> b) (initial :: b) (xs :: List a) -> b is"
  , "  first matching case of xs:"
  , "    when Nil then initial"
  , "    when Cons x rest then foldLeftList step (step initial x) rest"
  , "  end case"
  , "end function"
  , ""
  , "function foldRightList (step :: a -> b -> b) (initial :: b) (xs :: List a) -> b is"
  , "  first matching case of xs:"
  , "    when Nil then initial"
  , "    when Cons x rest then step x (foldRightList step initial rest)"
  , "  end case"
  , "end function"
  , ""
  , "function allList (holds :: a -> Bool) (xs :: List a) -> Bool is"
  , "  first matching case of xs:"
  , "    when Nil then true"
  , "    when Cons x rest then holds x and allList holds rest"
  , "  end case"
  , "end function"
  , ""
  , "function anyList (holds :: a -> Bool) (xs :: List a) -> Bool is"
  , "  first matching case of xs:"
  , "    when Nil then false"
  , "    when Cons x rest then holds x or anyList holds rest"
  , "  end case"
  , "end function"
  , ""
  , "function lengthList (xs :: List a) -> Integer is"
  , "  first matching case of xs:"
  , "    when Nil then 0"
  , "    when Cons x rest then 1 + lengthList rest"
  , "  end case"
  , "end function"
  , ""
  , "-- Appendable (List a): ++, and prelude.concat by folding it."
  , "function appendList (xs :: List a) (ys :: List a) -> List a is"
  , "  first matching case of xs:"
  , "    when Nil then ys"
  , "    when Cons x rest then Cons x (appendList rest ys)"
  , "  end case"
  , "end function"
  , ""
  , "function concatList (xss :: List (List a)) -> List a is"
  , "  first matching case of xss:"
  , "    when Nil then []"
  , "    when Cons xs rest then appendList xs (concatList rest)"
  , "  end case"
  , "end function"
  , "end unit"
  ]

-- | The laws of the capabilities, stated once for the built-in instances
-- over types and functions of which nothing is known: the handles and the
-- adapters of this unit, which the solver takes as uninterpreted sorts and
-- functions, and only here. LawSpec's own checks prove each; a proof then
-- holds for whatever types and functions a spec writes in their place.
-- ref:DEC-capability-laws
instanceLawsUnit :: String
instanceLawsUnit = "lawspec.instances.laws"

instanceLawsSource :: String
instanceLawsSource = unlines
  [ "unit " ++ instanceLawsUnit
  , "handle Element"
  , "handle Mapped"
  , "handle Further"
  , "handle Folded"
  , "handle Failure"
  , "first :: Element -> Mapped"
  , "second :: Mapped -> Further"
  , "third :: Further -> Folded"
  , "accepts :: Element -> Bool"
  , "alsoAccepts :: Element -> Bool"
  , "acceptsMapped :: Mapped -> Bool"
  , "combineLeft :: Folded -> Element -> Folded"
  , "combineRight :: Element -> Folded -> Folded"
  , "partial :: Element -> Either Failure Mapped"
  , ""
  , "function same (x :: Element) -> Element is x end function"
  , "function sameMapped (x :: Mapped) -> Mapped is x end function"
  , "function negated (b :: Bool) -> Bool is not b end function"
  , ""
  , "law \"|map of the identity changes nothing| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.map same xs = xs"
  , "  end for all"
  , "end definition end law"
  , "law \"|map of a composition is two maps| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.map second (prelude.map first xs) = prelude.map (second . first) xs"
  , "  end for all"
  , "end definition end law"
  , "law \"|map over an Either of the identity changes nothing| is definition:"
  , "  for all (x :: Element) =>"
  , "    prelude.map sameMapped (partial x) = partial x"
  , "  end for all"
  , "end definition end law"
  , "law \"|map over an Either of a composition is two maps| is definition:"
  , "  for all (x :: Element) =>"
  , "    prelude.map third (prelude.map second (partial x)) = prelude.map (third . second) (partial x)"
  , "  end for all"
  , "end definition end law"
  , "law \"|filter keeps only what is accepted| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.all accepts (prelude.filter accepts xs)"
  , "  end for all"
  , "end definition end law"
  , "law \"|filter never lengthens| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.length (prelude.filter accepts xs) <= prelude.length xs"
  , "  end for all"
  , "end definition end law"
  , "law \"|filters commute| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.filter accepts (prelude.filter alsoAccepts xs) = prelude.filter alsoAccepts (prelude.filter accepts xs)"
  , "  end for all"
  , "end definition end law"
  , "law \"|filter of what is all accepted changes nothing| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.all accepts xs implies prelude.filter accepts xs = xs"
  , "  end for all"
  , "end definition end law"
  , "law \"|length is never negative| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.length xs >= 0"
  , "  end for all"
  , "end definition end law"
  , "law \"|all and any are dual| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    if prelude.any accepts xs then not prelude.all (negated . accepts) xs else prelude.all (negated . accepts) xs end if"
  , "  end for all"
  , "end definition end law"
  , "law \"|appending nothing changes nothing| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    xs ++ [] = xs and [] ++ xs = xs"
  , "  end for all"
  , "end definition end law"
  , "law \"|append associates| is definition:"
  , "  for all (xs :: List Element) (ys :: List Element) (zs :: List Element) =>"
  , "    (xs ++ ys) ++ zs = xs ++ (ys ++ zs)"
  , "  end for all"
  , "end definition end law"
  , "law \"|length of an append is the sum| is definition:"
  , "  for all (xs :: List Element) (ys :: List Element) =>"
  , "    prelude.length (xs ++ ys) = prelude.length xs + prelude.length ys"
  , "  end for all"
  , "end definition end law"
  , "law \"|map keeps the length| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.length (prelude.map first xs) = prelude.length xs"
  , "  end for all"
  , "end definition end law"
  , "law \"|map distributes over append| is definition:"
  , "  for all (xs :: List Element) (ys :: List Element) =>"
  , "    prelude.map first (xs ++ ys) = prelude.map first xs ++ prelude.map first ys"
  , "  end for all"
  , "end definition end law"
  , "law \"|filter distributes over append| is definition:"
  , "  for all (xs :: List Element) (ys :: List Element) =>"
  , "    prelude.filter accepts (xs ++ ys) = prelude.filter accepts xs ++ prelude.filter accepts ys"
  , "  end for all"
  , "end definition end law"
  , "law \"|all of an append is all of both| is definition:"
  , "  for all (xs :: List Element) (ys :: List Element) =>"
  , "    prelude.all accepts (xs ++ ys) = (prelude.all accepts xs and prelude.all accepts ys)"
  , "  end for all"
  , "end definition end law"
  , "law \"|a right fold of an append folds the second first| is definition:"
  , "  for all (start :: Folded) (xs :: List Element) (ys :: List Element) =>"
  , "    prelude.foldRight combineRight start (xs ++ ys) = prelude.foldRight combineRight (prelude.foldRight combineRight start ys) xs"
  , "  end for all"
  , "end definition end law"
  , "law \"|a left fold of an append folds the first first| is definition:"
  , "  for all (start :: Folded) (xs :: List Element) (ys :: List Element) =>"
  , "    prelude.foldLeft combineLeft start (xs ++ ys) = prelude.foldLeft combineLeft (prelude.foldLeft combineLeft start xs) ys"
  , "  end for all"
  , "end definition end law"
  , "law \"|filter after map is map after filter| is definition:"
  , "  for all (xs :: List Element) =>"
  , "    prelude.filter acceptsMapped (prelude.map first xs) = prelude.map first (prelude.filter (acceptsMapped . first) xs)"
  , "  end for all"
  , "end definition end law"
  , ""
  , "harness " ++ instanceLawsUnit ++ ".proofs for " ++ instanceLawsUnit ++ " is"
  , "  for law \"|append associates|"
  , "    prove by induction on xs"
  , "  end for law"
  , "  for law \"|length of an append is the sum|"
  , "    prove by induction on xs"
  , "  end for law"
  , "  for law \"|map distributes over append|"
  , "    prove by induction on xs"
  , "  end for law"
  , "  for law \"|filter distributes over append|"
  , "    prove by induction on xs"
  , "  end for law"
  , "  for law \"|all of an append is all of both|"
  , "    prove by induction on xs"
  , "  end for law"
  , "  for law \"|a right fold of an append folds the second first|"
  , "    prove by induction on xs"
  , "  end for law"
  , "  for law \"|a left fold of an append folds the first first|"
  , "    prove by induction on xs"
  , "  end for law"
  , "end harness"
  , "end unit" ]
