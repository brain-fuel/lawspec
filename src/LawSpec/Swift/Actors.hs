-- | Typed actors for Swift implementation code (see LawSpec.Actors). Every
-- actor becomes a class named for its handle type in LawSpec.Actors, and
-- the functions it runs (its start, handlers and restart) a struct of
-- functions, usually the unit's adapters (its adapters property). Each
-- handler is a method that sends its message and waits for the reply, an
-- async overload of it that awaits the reply on a runtime thread, and a
-- tell form that does not wait; an actor whose messages have wire
-- descriptors can be served to and called from other nodes. Supervisors
-- start their children under the runtime's supervision tree; their children
-- are properties. ref:DEC-actors-otp-supervision ref:DEC-swift-runtime-from-scratch
module LawSpec.Swift.Actors (emitActors) where

import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..))
import LawSpec.Actors.Types
import LawSpec.Core.Machine (SupervisionStrategy(..), Lifetime(..))
import LawSpec.MachineSpec (describe)
import LawSpec.Swift.Code (stringLiteral)
import LawSpec.Swift.Names
import qualified LawSpec.Swift.Data as Data
import LawSpec.Swift.Definitions (nativeSignature)
import Control.Monad (foldM, forM, unless)
import Data.List (intercalate, nubBy)

emitActors :: Int -> [C.DataDeclaration] -> [C.Unit] -> Either String [Artifact]
emitActors bits datas units
  | null actors && null supervisors = pure []
  | otherwise = do
      names <- dataNames datas
      groups <- mapM (actorGroup names) actors
      supervised <- mapM supervisorClass supervisors
      let body = intercalate [""] (concat groups ++ supervised)
          header =
            [ "// Generated by LawSpec. Do not edit."
            , "import LawSpecRuntime"
            , ""
            , "extension LawSpec {"
            , "    /// Typed actors and supervisors: each actor runs the functions of its"
            , "    /// handlers, one message at a time; a handler that throws crashes the"
            , "    /// actor, and a supervised one restarts (from its restart function, or"
            , "    /// its start) while any other stops."
            , "    public enum Actors {" ]
      pure [Artifact "src/LawSpec/LawSpecActors.swift" (unlines (header ++ map indent2 body ++ ["    }", "}"])) "generated" "source"]
  where
    actors = concatMap actorsOf units
    supervisors = concatMap supervisionsOf units
    indent2 l = if null l then l else "        " ++ l
    indent l = if null l then l else "    " ++ l
    runtime = "LawSpecRuntime.Actors"
    handlersName a = actorClass a ++ "Handlers"
    field d = escape (camel (C.declarationName d))
    argName (n, _) = escape (camel n)
    declarations a = actorStart a : map handlerDeclaration (actorHandlers a) ++ maybe [] pure (actorRestart a)

    -- A declaration's adapter signature: its value parameters' types, its
    -- result, its failure and whether it is async.
    signature names d = do
      (params, r, failure, async) <- nativeSignature bits names units d
      unless (length params == length [p | p <- fst (C.functionType (C.declarationType d)), p /= C.Constructor "Unit" []])
        (Left ("an actor's function cannot use abilities on Swift: " ++ C.idText (C.declarationId d)))
      pure (map snd params, r, failure, async)
    closureType (ts, r, failure, async) =
      "@Sendable (" ++ intercalate ", " ts ++ ")" ++ (if async then " async" else "") ++
      maybe "" (\e -> " throws(" ++ e ++ ")") failure ++ " -> " ++ r
    -- A call of a handlers field, as the actor's worker runs it.
    invoke (_, r, failure, async) call
      | async = "try Runtime.awaitBoxed(UncheckedBox({ () async throws -> " ++ r ++ " in " ++ maybe "" (const "try ") failure ++ "await " ++ call ++ " }))"
      | otherwise = maybe "" (const "try ") failure ++ call

    actorGroup names a = do
      sigs <- forM (declarations a) $ \d -> (,) d <$> signature names d
      stateType <- Data.nativeType bits names [] (actorState a)
      let sigOf d = maybe (error "actor declaration") id (lookup (C.declarationId d) [(C.declarationId x, s) | (x, s) <- sigs])
          cls = actorClass a
          startParams = [(argName p, t) | p@(_, t) <- actorStartArguments a, t /= C.Constructor "Unit" []]
      startTypes <- mapM (Data.nativeType bits names [] . snd) startParams
      let startCall = invoke (sigOf (actorStart a)) ("handlers." ++ field (actorStart a) ++ "(" ++ intercalate ", " (map fst startParams) ++ ")")
          restart = case actorRestart a of
            Just d -> "{ state in " ++ invoke (sigOf d) ("handlers." ++ field d ++ "(state as! " ++ stateType ++ ")") ++ " }"
            Nothing -> "{ _ in " ++ startCall ++ " }"
          paramDecl = concatMap (\((n, _), t) -> ", _ " ++ n ++ ": " ++ t) (zip startParams startTypes)
          paramArgs = concatMap ((", " ++) . fst) startParams
          record =
            [ "/// The functions actor " ++ actorName a ++ " runs: usually its unit's adapters."
            , "public struct " ++ handlersName a ++ ": Sendable {" ] ++
            concat [ [ "    /// " ++ C.idText (C.declarationId d), "    public let " ++ field d ++ ": " ++ closureType s ] | (d, s) <- sigs ] ++
            [ ""
            , "    public init(" ++ intercalate ", " [field d ++ ": @escaping " ++ closureType s | (d, s) <- sigs] ++ ") {" ] ++
            [ "        self." ++ field d ++ " = " ++ field d | (d, _) <- sigs ] ++
            [ "    }"
            , ""
            , "    /// The handlers of actor " ++ actorName a ++ ", from the adapters."
            , "    public static let adapters = " ++ handlersName a ++ "(" ++
                intercalate ", " [field d ++ ": " ++ unitQualified (C.unitId (actorUnit a)) ++ "." ++ functionName d | (d, _) <- sigs] ++ ")"
            , "}" ]
      methods <- forM (actorHandlers a) $ \h -> do
        args <- forM (handlerArguments h) $ \p@(_, t) -> (,) (argName p) <$> Data.nativeType bits names [] t
        reply <- traverse (Data.nativeType bits names []) (handlerReply h)
        let d = handlerDeclaration h
            call = invoke (sigOf d) ("handlers." ++ field d ++ "(current" ++ concatMap ((", " ++) . fst) args ++ ")")
            params = intercalate ", " ["_ " ++ n ++ ": " ++ t | (n, t) <- args]
            name = escape (camel (handlerName h))
            step = case reply of
              Just _ -> [ "    let pair = " ++ call, "    return (pair.first, pair.second)" ]
              Nothing -> [ "    return (Unit(), " ++ call ++ ")" ]
            inner = map (indent . indent) (("let current = state as! " ++ stateType) : map (drop 4) step)
        pure $
          [ "/// Sends " ++ handlerName h ++ " and waits for the reply." ] ++
          [ "@discardableResult" | reply /= Nothing ] ++
          [ "public func " ++ name ++ "(" ++ params ++ ") throws" ++ maybe "" (" -> " ++) reply ++ " {"
          , "    let handlers = self.handlers" ] ++
          (case reply of
            Just r -> [ "    return try " ++ runtime ++ ".call(handle) { state in" ] ++ inner ++ ["    } as! " ++ r]
            Nothing -> [ "    _ = try " ++ runtime ++ ".call(handle) { state in" ] ++ inner ++ ["    }"]) ++
          [ "}"
          , ""
          , "/// Sends " ++ handlerName h ++ " and awaits the reply, waiting on a runtime thread, not Swift's cooperative pool." ] ++
          [ "@discardableResult" | reply /= Nothing ] ++
          [ "public func " ++ name ++ "(" ++ params ++ ") async throws" ++ maybe "" (" -> " ++) reply ++ " {"
          , "    try await LawThread.run { try self." ++ name ++ "(" ++ intercalate ", " (map fst args) ++ ") }"
          , "}"
          , ""
          , "/// Sends " ++ handlerName h ++ " without waiting."
          , "public func tell" ++ pascal (handlerName h) ++ "(" ++ params ++ ") throws {"
          , "    let handlers = self.handlers"
          , "    try " ++ runtime ++ ".tell(handle) { state in" ] ++ inner ++ [ "    }", "}" ]
      remote <- case wires a of
        Nothing -> pure ([], [])
        Just hs -> do
          entries <- forM hs $ \(h, argWires, replyWire) -> do
            argCodecs <- mapM (Data.codec bits names [] . snd) (handlerArguments h)
            args <- forM (handlerArguments h) $ \p@(_, t) -> (,) (argName p) <$> Data.nativeType bits names [] t
            replyType <- traverse (Data.nativeType bits names []) (handlerReply h)
            replyCodec <- traverse (Data.codec bits names []) (handlerReply h)
            let values = ["try " ++ c ++ ".toNative(arguments[" ++ show i ++ "])" | (i, c) <- zip [0 :: Int ..] argCodecs]
                callText = "self." ++ escape (camel (handlerName h)) ++ "(" ++ intercalate ", " values ++ ")"
                body = case replyCodec of
                  Just c -> "{ arguments in try " ++ c ++ ".fromNative(try " ++ callText ++ ") }"
                  Nothing -> "{ arguments in\n    try " ++ callText ++ "\n    return Value.unit\n}"
                entry inv = "(" ++ stringLiteral (handlerName h) ++ ", RemoteEntry([" ++ intercalate ", " (map stringLiteral argWires) ++ "], " ++
                  stringLiteral replyWire ++ ", " ++ inv ++ "))"
                sent = "[" ++ intercalate ", " ["try " ++ c ++ ".fromNative(" ++ n ++ ")" | (c, (n, _)) <- zip argCodecs args] ++ "]"
                remoteCall = "try Remote.call(client, " ++ stringLiteral (handlerName h) ++ ", " ++ sent ++ ")"
                method =
                  [ "/// Sends " ++ handlerName h ++ " and waits for the reply." ] ++
                  [ "@discardableResult" | replyType /= Nothing ] ++
                  [ "public func " ++ escape (camel (handlerName h)) ++ "(" ++ intercalate ", " ["_ " ++ n ++ ": " ++ t | (n, t) <- args] ++ ") throws" ++
                      maybe "" (" -> " ++) replyType ++ " {"
                  , case replyCodec of
                      Just c -> "    try " ++ c ++ ".toNative(" ++ remoteCall ++ ")"
                      Nothing -> "    _ = " ++ remoteCall
                  , "}" ]
            pure (entry body, entry "nil", method)
          let served =
                [ "/// Lets other nodes call this actor at <node address>/name; that address."
                , "@discardableResult"
                , "public func serve(_ node: Node, _ name: String) throws -> String {"
                , "    try Remote.serve(node, name, \"call\", [" ] ++
                map ("        " ++) (lines (intercalate ",\n" [s | (s, _, _) <- entries])) ++
                [ "    ])"
                , "}"
                , ""
                , "/// The actor served at address on another node; each call waits up to timeout."
                , "public static func connect(_ node: Node, _ address: String, timeout: Duration = .seconds(5)) throws -> " ++ cls ++ "Remote {"
                , "    " ++ cls ++ "Remote(try Remote.connect(node, address, \"call\", ["
                ] ++ map ("        " ++) [s ++ "," | (_, s, _) <- entries] ++
                [ "    ], Timeouts.milliseconds(timeout)))"
                , "}" ]
              client =
                [ "/// Actor " ++ actorName a ++ " on another node: each method sends its message and waits for the reply."
                , "public final class " ++ cls ++ "Remote: Sendable {"
                , "    let client: RemoteClient"
                , ""
                , "    init(_ client: RemoteClient) { self.client = client }" ] ++
                concatMap (\(_, _, m) -> "" : map indent m) entries ++ ["}"]
          pure (served, [client])
      let members =
            [ [ "/// The runtime handle: stable across supervised restarts."
              , "public let handle: " ++ runtime ++ ".Handle"
              , "let handlers: " ++ handlersName a
              , ""
              , "init(_ handle: " ++ runtime ++ ".Handle, _ handlers: " ++ handlersName a ++ ") {"
              , "    self.handle = handle"
              , "    self.handlers = handlers"
              , "}" ]
            , [ "/// The runtime's spec of this actor, for a supervisor to start."
              , "public static func spec(_ handlers: " ++ handlersName a ++ paramDecl ++ ") -> " ++ runtime ++ ".Spec {"
              , "    " ++ runtime ++ ".actor({ " ++ startCall ++ " }, " ++ restart ++ ")"
              , "}" ]
            , [ "/// Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor."
              , "public static func start(_ handlers: " ++ handlersName a ++ paramDecl ++ ") throws -> " ++ cls ++ " {"
              , "    " ++ cls ++ "(try " ++ runtime ++ ".start(spec(handlers" ++ paramArgs ++ ")), handlers)"
              , "}" ]
            , [ "/// The actor a supervisor started, by its handle."
              , "public static func fromHandle(_ handle: " ++ runtime ++ ".Handle, _ handlers: " ++ handlersName a ++ ") -> " ++ cls ++ " {"
              , "    " ++ cls ++ "(handle, handlers)"
              , "}" ] ] ++
            methods ++
            [ [ "/// Crashes the actor as a failing handler would, after the messages already sent."
              , "public func crash() throws { try " ++ runtime ++ ".crash(handle) }" ]
            , [ "/// Tells inbox about each crash, and once it stops."
              , "public func monitor(_ inbox: " ++ runtime ++ ".Inbox) { " ++ runtime ++ ".monitor(handle, inbox) }" ]
            , [ "/// When either actor crashes, the other crashes too."
              , "public func link(_ other: " ++ runtime ++ ".Handle) { " ++ runtime ++ ".link(handle, other) }" ]
            , [ "/// Refuses further messages; those already sent are still handled."
              , "public func stop() { " ++ runtime ++ ".stop(handle) }" ] ] ++
            [fst remote | not (null (fst remote))]
          cls' =
            [ "/// Actor " ++ actorName a ++ ": owns its state and handles one message at a time."
            , "public final class " ++ cls ++ ": Sendable {" ] ++ map indent (intercalate [""] members) ++ ["}"]
      pure ([record, cls'] ++ snd remote)

    -- Each message's argument and reply descriptors, with the data types
    -- they use; Nothing when a type has no descriptor (the actor stays local).
    wires a = either (const Nothing) Just $ do
      (table, hs) <- foldM (\(t, acc) h -> do
          (args, t') <- foldM (\(xs, tt) (_, ty) -> (\(x, tt') -> (xs ++ [x], tt')) <$> describe bits datas tt ty) ([], t) (handlerArguments h)
          (reply, t'') <- describe bits datas t' (maybe (C.Constructor "Unit" []) id (handlerReply h))
          pure (t'', acc ++ [(h, args, reply)])) ([], []) (actorHandlers a)
      let prefix = concatMap ((++ " ") . snd) (reverse table)
      pure [(h, map (prefix ++) args, prefix ++ reply) | (h, args, reply) <- hs]

    -- The actors beneath a supervisor, each once: its start takes their
    -- handlers.
    beneath s = nubBy (\x y -> actorName x == actorName y) (concatMap child (supervisionChildren s))
      where child (_, _, ActorChild a) = [a]
            child (_, _, SupervisorChild cls) = concat [beneath s' | s' <- supervisors, supervisionClass s' == cls]
    handlersParam a = escape (camel (actorName a)) ++ "Handlers"
    supervisorClass s = do
      let cls = supervisionClass s
          params = beneath s
          paramText = intercalate ", " ["_ " ++ handlersParam a ++ ": " ++ handlersName a | a <- params]
          args = intercalate ", " (map handlersParam params)
          childClass c = case c of ActorChild a -> actorClass a; SupervisorChild n -> n
          childArgs c = case c of
            ActorChild a -> handlersParam a
            SupervisorChild n -> intercalate ", " [handlersParam a | s' <- supervisors, supervisionClass s' == n, a <- beneath s']
          childTry c = case c of ActorChild _ -> ""; SupervisorChild _ -> "try "
          strategy = case supervisionStrategy s of OneForOne -> ".oneForOne"; OneForAll -> ".oneForAll"; RestForOne -> ".restForOne"
          lifetime l = case l of Permanent -> ".permanent"; Transient -> ".transient"; Temporary -> ".temporary"
          childSpec (l, n, c) = "(" ++ stringLiteral n ++ ", " ++ lifetime l ++ ", " ++ childTry c ++ childClass c ++ ".spec(" ++ childArgs c ++ "))"
          children = supervisionChildren s
          member n = escape (camel n)
      pure $
        [ "/// Supervisor " ++ supervisionName s ++ ": its children restart by its strategy, within its restart budget."
        , "public final class " ++ cls ++ ": Sendable {"
        , "    public let handle: " ++ runtime ++ ".Handle" ] ++
        concat [ ["    /// Child " ++ n ++ ".", "    public let " ++ member n ++ ": " ++ childClass c] | (_, n, c) <- children ] ++
        [ ""
        , "    init(_ handle: " ++ runtime ++ ".Handle" ++ concatMap (\(_, n, c) -> ", _ " ++ member n ++ ": " ++ childClass c) children ++ ") {"
        , "        self.handle = handle" ] ++
        [ "        self." ++ member n ++ " = " ++ member n | (_, n, _) <- children ] ++
        [ "    }"
        , ""
        , "    /// The runtime's spec of this supervisor and its children."
        , "    public static func spec(" ++ paramText ++ ") throws -> " ++ runtime ++ ".Spec {"
        , "        try " ++ runtime ++ ".supervisor(" ++ strategy ++ ", " ++ show (supervisionRestarts s) ++ ", " ++ show (supervisionPeriod s) ++ ", ["
        ] ++ [ "            " ++ childSpec c ++ "," | c <- children ] ++
        [ "        ])"
        , "    }"
        , ""
        , "    /// The supervisor a parent started, by its handle."
        , "    public static func fromHandle(_ handle: " ++ runtime ++ ".Handle" ++ concatMap (", " ++) ["_ " ++ handlersParam a ++ ": " ++ handlersName a | a <- params] ++
            ") throws -> " ++ cls ++ " {"
        , "        " ++ cls ++ "(handle" ++ concatMap (\(_, n, c) -> ", " ++ childTry c ++ childClass c ++ ".fromHandle(try " ++ runtime ++ ".child(handle, " ++ stringLiteral n ++ "), " ++ childArgs c ++ ")") children ++ ")"
        , "    }"
        , ""
        , "    /// Starts the supervisor and its children, in order."
        , "    public static func start(" ++ paramText ++ ") throws -> " ++ cls ++ " {"
        , "        try fromHandle(try " ++ runtime ++ ".start(try spec(" ++ args ++ "))" ++ concatMap ((", " ++) . handlersParam) params ++ ")"
        , "    }"
        , ""
        , "    /// Tells inbox when it passes its restart limit, and once stopped."
        , "    public func monitor(_ inbox: " ++ runtime ++ ".Inbox) { " ++ runtime ++ ".monitor(handle, inbox) }"
        , ""
        , "    /// Stops every child, last started first, without restarting them."
        , "    public func stop() { " ++ runtime ++ ".stop(handle) }"
        , "}" ]
