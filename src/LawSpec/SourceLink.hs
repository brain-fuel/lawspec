-- | Links from generated code back to the specification. Core carries an
-- origin on every declaration and expression; a link is its file, relative
-- as the host sent it, and line. Absolute paths are cut to their file name,
-- so output never depends on where a project lives. ref:DEC-readable-output-default
module LawSpec.SourceLink
  ( sourceLink, locationLink, originLocation, exampleLocation, labelled, unitSourceFile
  , generatedHeader, goGeneratedMarker
  ) where

import Data.List (isPrefixOf)
import Data.Maybe (listToMaybe, mapMaybe)
import qualified LawSpec.Core as C
import LawSpec.Common (Location(..), Span(..))

-- | Where an origin starts, if it is written in a source.
originLocation :: C.Origin -> Maybe Location
originLocation origin = case origin of
  C.SourceSpan s | not (null (file (spanStart s))) -> Just (spanStart s)
  _ -> Nothing

-- | file:line, for a source origin.
sourceLink :: C.Origin -> Maybe String
sourceLink = fmap locationLink . originLocation

-- | file:line.
locationLink :: Location -> String
locationLink l = relative (file l) ++ ":" ++ show (line l)
  where
    relative path
      | "/" `isPrefixOf` path || drop 1 (take 3 path) == ":\\" = reverse (takeWhile (`notElem` ("/\\" :: String)) (reverse path))
      | otherwise = path

-- | An example has no span of its own; its first written value or
-- expectation does.
exampleLocation :: C.Example -> Maybe Location
exampleLocation example = listToMaybe (mapMaybe (originLocation . C.expressionOrigin) expressions)
  where
    expressions = map snd (C.exampleBindings example) ++ concatMap proposition (C.exampleExpectations example)
    proposition p = case p of
      C.Equation _ a b -> [a, b]
      C.Implication a q -> a : proposition q
      C.Conjunction ps -> concatMap proposition ps
      C.Negation q -> proposition q
      C.Quantified _ _ q -> proposition q

-- | A unit's source file: where its first declaration, definition or law is.
unitSourceFile :: C.Unit -> Maybe FilePath
unitSourceFile unit = listToMaybe (map (relative . file) located)
  where
    located = mapMaybe originLocation
      (map C.declarationOrigin (C.unitDeclarations unit ++ map C.definitionDeclaration (C.unitDefinitions unit)))
      ++ [C.propertyLocation p | p <- C.unitProperties unit, not (null (file (C.propertyLocation p)))]
    relative path = takeWhile (/= ':') (locationLink (Location path 0 0))

-- | "label — file:line", the one-line comment on every generated function,
-- type, test and handler.
labelled :: String -> Maybe String -> String
labelled label link = label ++ maybe "" (" — " ++) link

-- | The header of every generated file.
generatedHeader :: Maybe FilePath -> String
generatedHeader source = "Generated by LawSpec" ++ maybe "" (" from " ++) source ++ ". Do not edit."

-- | Go's tools recognise generated files by this exact line.
goGeneratedMarker :: String
goGeneratedMarker = "Code generated by LawSpec. DO NOT EDIT."
