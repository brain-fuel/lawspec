-- Typed actors for Python implementation code (see LawSpec.Actors).
--
-- Every actor becomes a class named for its handle type in lawspec_actors:
-- AccountActor.start(...) makes the state with the start adapter and runs it
-- in an lawspec_runtime.Actor; each handler is a method that sends its
-- message and returns the reply, and tell_<handler> sends it without
-- waiting. stop() refuses further messages.
module LawSpec.Actors.Python (emit) where

import Data.List (intercalate, nub)
import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..))
import LawSpec.Backend (adapterName, unitName)
import LawSpec.PythonTypes (identifier, pythonDataTypeDoc)
import qualified LawSpec.Code.Doc as D
import LawSpec.Actors.Types (Actor(..), Handler(..))

emit :: String -> Bool -> Int -> [C.DataDeclaration] -> [Actor] -> Either String [Artifact]
emit _ _ _ datas actors = do
  mapM_ (identifier . actorClass) actors
  classes <- mapM (actorClassText datas) actors
  let modules = nub (map (unitName . actorUnit) actors)
      header =
        [ "# Generated by LawSpec. Do not edit."
        , "\"\"\"Actors of " ++ intercalate ", " modules ++ "."
        , ""
        , "Each class runs one actor: start(...) makes its state and returns the"
        , "actor. Each handler method sends a message and returns the reply;"
        , "tell_<handler> sends it without waiting. Messages are handled one at a"
        , "time, in the order they arrive."
        , "\"\"\""
        , "from __future__ import annotations"
        , ""
        , "import builtins as _builtins"
        , "import lawspec_runtime as ls"
        , "import lawspec_data as data" ] ++
        [ "import " ++ m ++ " as " ++ alias m | m <- modules ]
      helper =
        [ ""
        , ""
        , "def _split(pair):"
        , "    return pair.first, pair.second" ]
  pure [Artifact "src/lawspec_actors.py" (unlines (header ++ helper) ++ concatMap ("\n\n" ++) classes) "generated" "source"]

alias :: String -> String
alias m = "_" ++ map (\c -> if c == '.' then '_' else c) m

actorClassText :: [C.DataDeclaration] -> Actor -> Either String String
actorClassText datas a = do
  startArgs <- mapM argument (actorStartArguments a)
  methods <- mapM handler (actorHandlers a)
  let cls = actorClass a
      impl d = alias (unitName (actorUnit a)) ++ "." ++ adapterName (actorUnit a) (C.declarationId d)
      startParams = [arg | arg@(_, (t, _)) <- startArgs, not (unit t)]
      startValues = [if unit t then "ls.UNIT" else p | (p, (t, _)) <- startArgs]
  pure $ unlines $
    [ "class " ++ cls ++ ":"
    , "    \"\"\"Actor " ++ actorName a ++ ": owns its state and handles one message at a time.\"\"\""
    , ""
    , "    def __init__(self, actor: ls.Actor):"
    , "        self._actor = actor"
    , ""
    , "    @staticmethod"
    , "    def start(" ++ intercalate ", " (map typed startParams) ++ ") -> " ++ cls ++ ":"
    , "        \"\"\"Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor.\"\"\""
    , "        return " ++ cls ++ "(ls.Actor(" ++ awaited (actorStart a) (impl (actorStart a) ++ "(" ++ intercalate ", " startValues ++ ")") ++ "))"
    ] ++ concatMap (\m -> "" : m) methods ++
    [ ""
    , "    def stop(self) -> None:"
    , "        \"\"\"Refuses further messages; those already sent are still handled.\"\"\""
    , "        self._actor.stop()" ]
  where
    unit t = t == C.Constructor "Unit" []
    typed (p, (_, native)) = p ++ ": " ++ native
    argument (p, t) = do
      native <- nativeType t
      pure (p, (t, native))
    nativeType t = D.render (D.Pretty 1000) <$> pythonDataTypeDoc datas t
    awaited d call = if C.declarationAsync d then "ls.await_task(" ++ call ++ ")" else call
    handler h = do
      args <- mapM argument (handlerArguments h)
      reply <- traverse nativeType (handlerReply h)
      let params = "self" : map (\(p, (_, n)) -> p ++ ": " ++ n) args
          call = awaited (handlerDeclaration h) (alias (unitName (actorUnit a)) ++ "." ++
            adapterName (actorUnit a) (C.declarationId (handlerDeclaration h)) ++ "(" ++ intercalate ", " ("s" : map fst args) ++ ")")
          step = case reply of
            Just _ -> "lambda s: _split(" ++ call ++ ")"
            Nothing -> "lambda s: (None, " ++ call ++ ")"
          name = handlerName h
      pure
        [ "    def " ++ name ++ "(" ++ intercalate ", " params ++ ") -> " ++ maybe "None" id reply ++ ":"
        , "        \"\"\"Sends " ++ name ++ " and waits for the reply.\"\"\""
        , "        return self._actor.call(" ++ step ++ ")"
        , ""
        , "    def tell_" ++ name ++ "(" ++ intercalate ", " params ++ ") -> None:"
        , "        \"\"\"Sends " ++ name ++ " without waiting for the reply.\"\"\""
        , "        self._actor.cast(" ++ step ++ ")" ]
