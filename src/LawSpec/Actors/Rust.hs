-- | Typed actors for Rust implementation code (see LawSpec.Actors).
--
-- Every actor becomes a struct named for its handle type in the module
-- lawspec_actors: AccountActor::start(...) makes the state with the start
-- adapter and runs it in an ls::actors::Actor; each handler is a method that
-- sends its message and returns the reply, and tell_<handler> sends it
-- without waiting. Both return ls::Result, which fails once the actor has
-- stopped (stop()), or when the handler crashed the actor. start_under runs
-- it under a supervisor, which restarts it (restart from, or its start)
-- after a crash. Every supervisor becomes a struct that starts its children
-- under a runtime ls::actors::Supervisor; its children are public fields.
-- Clones share the actor.
module LawSpec.Actors.Rust (emit) where

import Data.Char (isAlphaNum)
import Data.List (intercalate, nub)
import qualified LawSpec.Code.Doc as D
import LawSpec.Naming (NameKind(..), nativeIdentifier)
import qualified LawSpec.RustLayout as L
import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..))
import LawSpec.Backend (adapterName, unitName)
import LawSpec.RustData (rustDataType)
import LawSpec.Actors.Types (Actor(..), Handler(..), Supervision(..), Child(..))
import LawSpec.Core.Machine (SupervisionStrategy(..), Lifetime(..))
import LawSpec.MachineSpec (describe)
import Control.Monad (foldM)

-- | Actors become a typed class, or Rust's idiom for one, generated from the
-- declaration. ref:DEC-actors-otp-supervision
emit :: String -> Bool -> Int -> [C.DataDeclaration] -> [Actor] -> [Supervision] -> Either String [Artifact]
emit _ minify bits datas actors supervisions = do
  -- Each actor's messages as wire descriptors, for serving it and calling
  -- it across nodes; an actor whose types have none yet stays local.
  let wired (table, acc) a = case foldM (handlerWire bits datas) (table, []) (actorHandlers a) of
        Right (table', hs) -> (table', acc ++ [(actorName a, reverse hs)])
        Left _ -> (table, acc)
      (types, wires) = foldl wired ([], []) actors
  structs <- (++ map supervisorStruct supervisions) <$> mapM (\a -> actorStruct datas (lookup (actorName a) wires) a) actors
  let modules = nub (map (unitName . actorUnit) actors)
      header = map D.text
        [ "// Generated by LawSpec. Do not edit."
        , "//! Actors of " ++ intercalate ", " modules ++ "."
        , "//!"
        , "//! Each struct runs one actor: start(...) makes its state and returns the"
        , "//! actor. Each handler method sends a message and returns the reply;"
        , "//! tell_<handler> sends it without waiting. Messages are handled one at a"
        , "//! time, in the order they arrive. A handler that fails (an Err or a"
        , "//! panic) crashes the actor: the call fails with \"the actor crashed: ...\","
        , "//! and a supervised actor restarts while any other stops. start_under"
        , "//! starts one under a supervisor. Each supervisor struct starts its"
        , "//! children, which are its public fields. Clones share the actor."
        , "use crate::lawspec_runtime as ls;"
        , ""
        , "// The data types the actors' messages use on the wire." ]
      wireTypes = L.function "fn wire_types" [] "ls::Values" (body (L.call "ls::values_table" [L.atom (show (unwords (map snd (reverse types))))]))
      layout = D.selectLayout minify (D.styleLayout (D.styleFor "rust"))
      file = D.joinWith D.hardline header <> D.hardline <> wireTypes <>
        mconcat [D.hardline <> D.hardline <> d | d <- structs] <> D.hardline
  pure [Artifact "src/lawspec_actors.rs" (D.render layout file) "generated" "source"]

-- | The crate module a unit's adapters are mounted at.
unitModule :: C.Unit -> String
unitModule = map (\c -> if isAlphaNum c || c == '_' then c else '_') . unitName

-- | A handler's argument and reply descriptors, adding data types to the table.
type HandlerWire = (Handler, [String], String)

handlerWire :: Int -> [C.DataDeclaration] -> ([(String, String)], [HandlerWire]) -> Handler -> Either String ([(String, String)], [HandlerWire])
handlerWire bits datas (table, acc) h = do
  (args, table') <- foldM (\(xs, t) (_, ty) -> (\(x, t') -> (xs ++ [x], t')) <$> describe bits datas t ty) ([], table) (handlerArguments h)
  (reply, table'') <- describe bits datas table' (maybe (C.Constructor "Unit" []) id (handlerReply h))
  pure (table'', (h, args, reply) : acc)

actorStruct :: [C.DataDeclaration] -> Maybe [HandlerWire] -> Actor -> Either String D.Doc
actorStruct datas wire a = do
  state <- rustDataType datas (actorState a)
  startArgs <- mapM argument (actorStartArguments a)
  methods <- mapM handler (actorHandlers a)
  remote <- maybe (pure Nothing) (fmap Just . remoteParts) wire
  let cls = actorClass a
      startParams = [p ++ ": " ++ t | (p, ty, t) <- startArgs, not (unit ty)]
      startNames = [L.atom p | (p, ty, _) <- startArgs, not (unit ty)]
      startCall = awaited (actorStart a) (adapter (actorStart a)
        [if unit ty then L.atom "()" else L.method (L.atom p) "clone" [] | (p, ty, _) <- startArgs])
      restart = case actorRestart a of
        Just d -> L.closure "move |state|" (L.call "Ok" [awaited d (adapter d [L.atom "state"])])
        Nothing -> L.closure "move |_|" (L.call "Ok" [startCall])
      supervision = ["supervisor: &ls::actors::Supervisor", "lifetime: ls::actors::Lifetime"]
      fixed =
        [ comment ["Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor."]
            (L.function "pub fn start" startParams cls
              (body (L.call cls [L.call "ls::actors::Actor::with_restart" [startCall, restart]])))
        , comment [ "Starts the actor under supervisor, which restarts it after a crash"
                  , case actorRestart a of
                      Just d -> "from its last state, with " ++ C.declarationName d ++ "."
                      Nothing -> "from its start." ]
            (L.function "pub fn start_under" (supervision ++ startParams) cls (L.stmts
              [ L.Let "actor" (L.call (cls ++ "::start") startNames)
              , L.Semi (L.method (L.atom "supervisor") "supervise" [L.method (L.Field (L.atom "actor") "0") "clone" [], L.atom "lifetime"]) ]
              (Just (L.atom "actor")))) ]
      common =
        [ comment ["Crashes the actor as a failing handler would, after the messages", "already sent: for testing how it restarts."]
            (L.function "pub fn crash" ["&self"] "ls::Result<()>" (body (L.method (self0) "crash" [L.atom "\"crashed on purpose\""])))
        , comment ["notify(Exit::Crashed(cause)) after each crash, and notify(Exit::Stopped)", "once it stops."]
            (L.function "pub fn monitor" ["&self", "notify: impl Fn(ls::actors::Exit) + Send + Sync + 'static"] ""
              (L.stmts [L.Semi (L.method (self0) "monitor" [L.atom "notify"])] Nothing))
        , comment ["When either actor crashes, the other crashes too."]
            (L.function "pub fn link<T: Send + 'static>" ["&self", "other: &ls::actors::Actor<T>"] ""
              (L.stmts [L.Semi (L.method (self0) "link" [L.atom "other"])] Nothing))
        , comment ["The runtime actor, to link it or supervise it."]
            (L.function "pub fn actor" ["&self"] ("&ls::actors::Actor<" ++ state ++ ">") (D.text "&self.0"))
        , comment ["Refuses further messages; those already sent are still handled."]
            (L.function "pub fn stop" ["&self"] "" (L.stmts [L.Semi (L.method (self0) "stop" [])] Nothing)) ]
      items = fixed ++ concat methods ++ common ++ maybe [] fst remote
  pure (D.joinWith D.hardline
    [ D.text ("/// Actor " ++ actorName a ++ ": owns its state and handles one message at a time.")
    , D.text "#[derive(Clone)]"
    , D.text ("pub struct " ++ cls ++ "(ls::actors::Actor<" ++ state ++ ">);")
    , D.text ""
    , impl ("impl " ++ cls) items ] <> maybe mempty snd remote)
  where
    -- Each message's name with its argument and reply descriptors.
    signature h ds r = [L.atom (show (handlerName h)), L.prefix "&" (arrayOf (map (L.atom . show) ds)), L.atom (show r)]
    remoteParts hs = do
      typed <- mapM (\(h, ds, r) -> do
        args <- mapM argument (handlerArguments h)
        reply <- traverse (rustDataType datas) (handlerReply h)
        pure (h, ds, r, args, maybe "()" id reply)) hs
      let cls = actorClass a
          served (h, ds, r, args, _) = L.call "ls::net::message" (L.atom "self" : signature h ds r ++
            [L.closure (if null args then "|actor, _|" else "|actor, arguments|") (L.method (L.atom "actor") (method h) [L.try' (L.method (L.atom "arguments") "next" []) | _ <- args])])
          methods' =
            [ comment ["Lets other nodes call this actor at <node address>/name; returns", "that address."]
                (L.function "pub fn serve" ["&self", "node: &ls::net::Node", "name: &str"] "ls::Result<String>" (L.stmts
                  [L.Let "handlers" (L.vecOf (map served typed))]
                  (Just (L.method (L.atom "node") "serve" [L.atom "name", L.atom "handlers", L.call "wire_types" []]))))
            , comment ["The actor served at address on another node; each call waits up", "to timeout, then fails as unreachable."]
                (L.function "pub fn connect" ["node: &ls::net::Node", "address: &str", "timeout: std::time::Duration"] (cls ++ "Remote") (L.stmts
                  [L.Let "signatures" (L.vecOf [L.call "ls::net::signature" (signature h ds r) | (h, ds, r, _, _) <- typed])]
                  (Just (L.call (cls ++ "Remote") [L.method (L.atom "node") "remote_actor" [L.atom "address", L.atom "signatures", L.call "wire_types" [], L.atom "timeout"]])))) ]
          proxy = D.hardline <> D.hardline <> D.joinWith D.hardline
            [ D.text ("/// Actor " ++ actorName a ++ " on another node: each method sends its message and")
            , D.text "/// waits for the reply."
            , D.text ("pub struct " ++ cls ++ "Remote(ls::net::RemoteActor);")
            , D.text ""
            , impl ("impl " ++ cls ++ "Remote")
                [ comment ["Sends " ++ handlerName h ++ " and waits for the reply."]
                    (L.function ("pub fn " ++ method h) ("&self" : [p ++ ": " ++ t | (p, _, t) <- args]) ("ls::Result<" ++ reply ++ ">") (L.stmts
                      [L.Let "reply" (L.try' (L.method (self0) "call" [L.atom (show (handlerName h)), L.prefix "&" (arrayOf [L.call "ls::IntoValue::into_value" [L.atom p] | (p, _, _) <- args])]))]
                      (Just (L.call "ls::FromValue::from_value" [L.atom "reply"]))))
                | (h, _, _, args, reply) <- typed ] ]
      pure (methods', proxy)
    unit t = t == C.Constructor "Unit" []
    adapter d = L.call ("crate::" ++ unitModule (actorUnit a) ++ "::" ++ adapterName (actorUnit a) (C.declarationId d))
    awaited d call = if C.declarationAsync d then L.call "ls::block_on" [call] else call
    argument (p, t) = (\native -> (rustName p, t, native)) <$> rustDataType datas t
    rustName p = nativeIdentifier "rust" ValueName (map (\c -> if isAlphaNum c || c == '_' then c else '_') p)
    method h = nativeIdentifier "rust" FunctionName (handlerName h)
    handler h = do
      args <- mapM argument (handlerArguments h)
      reply <- traverse (rustDataType datas) (handlerReply h)
      let params = "&self" : [p ++ ": " ++ t | (p, _, t) <- args]
          called = awaited (handlerDeclaration h) (adapter (handlerDeclaration h) (L.atom "state" : [L.atom p | (p, _, _) <- args]))
          step = case reply of
            Just _ -> L.closure "move |state|" (L.Block [L.Let "pair" called] (Just (L.call "Ok" [L.atom "(pair.first, pair.second)"])))
            Nothing -> L.closure "move |state|" (L.call "Ok" [L.call "" [L.atom "()", called]])
          name = method h
      pure
        [ comment ["Sends " ++ handlerName h ++ " and waits for the reply."]
            (L.function ("pub fn " ++ name) params ("ls::Result<" ++ maybe "()" id reply ++ ">") (body (L.method (self0) "call" [step])))
        , comment ["Sends " ++ handlerName h ++ " without waiting for the reply."]
            (L.function ("pub fn tell_" ++ name) params "ls::Result<()>" (body (L.method (self0) "tell" [step]))) ]

-- | Doc comment lines above an item.
comment :: [String] -> D.Doc -> D.Doc
comment ls item = mconcat [D.text ("/// " ++ l) <> D.hardline | l <- ls] <> item

-- | An impl block with blank lines between its items.
impl :: String -> [D.Doc] -> D.Doc
impl head' items = D.text head' <> D.hardline <> D.block 4 (D.joinWith (D.hardline <> D.hardline) items)

-- | A supervisor's struct: start() makes the runtime supervisor and starts
-- each child under it, in order; each child is a public field.
supervisorStruct :: Supervision -> D.Doc
supervisorStruct s = D.joinWith D.hardline (map D.text
  ([ "/// Supervisor " ++ supervisionName s ++ ": " ++ strategyText ++ ", at most " ++
       show (supervisionRestarts s) ++ " restarts in " ++ show (supervisionPeriod s) ++ " microseconds."
   , "#[derive(Clone)]"
   , "pub struct " ++ cls
   , "{"
   , "    supervisor: ls::actors::Supervisor," ] ++
   [ "    pub " ++ field name ++ ": " ++ childClass child ++ "," | (_, name, child) <- supervisionChildren s ] ++
   [ "}", "" ]) ++
  [ impl ("impl " ++ cls)
    [ comment ["Starts the supervisor and its children."]
        (L.function "pub fn start" [] cls (body (L.call (cls ++ "::begin") [L.atom "None"])))
    , comment ["Starts the supervisor and its children under parent."]
        (L.function "pub fn start_under" ["parent: &ls::actors::Supervisor", "lifetime: ls::actors::Lifetime"] cls
          (body (L.call (cls ++ "::begin") [L.call "Some" [L.atom "(parent, lifetime)"]])))
    , L.function "fn begin" ["parent: Option<(&ls::actors::Supervisor, ls::actors::Lifetime)>"] cls (L.stmts
        ([ L.Let "own" (L.call "ls::actors::Supervisor::new"
             [ L.atom ("ls::actors::Strategy::" ++ strategy), L.atom (show (supervisionRestarts s))
             , L.call "std::time::Duration::from_micros" [L.atom (show (supervisionPeriod s))] ]) ] ++
         [ L.Let (field name) (L.call (childClass child ++ "::start_under") [L.atom "&own", L.atom ("ls::actors::Lifetime::" ++ lifetime l)])
         | (l, name, child) <- supervisionChildren s ] ++
         [ L.Item (D.text "if let Some((parent, lifetime)) = parent" <> D.hardline <> D.block 4 (L.stmts [L.Semi (L.method (L.atom "parent") "supervise" [L.method (L.atom "own") "clone" [], L.atom "lifetime"])] Nothing)) ])
        (Just (L.struct cls (("supervisor", L.atom "own") : [(field name, L.atom (field name)) | (_, name, _) <- supervisionChildren s]))))
    , comment ["The runtime supervisor, to supervise more children."]
        (L.function "pub fn supervisor" ["&self"] "&ls::actors::Supervisor" (D.text "&self.supervisor"))
    , comment ["notify(Exit::Crashed(cause)) when it passes its restart limit, and", "notify(Exit::Stopped) once stopped."]
        (L.function "pub fn monitor" ["&self", "notify: impl Fn(ls::actors::Exit) + Send + Sync + 'static"] ""
          (L.stmts [L.Semi (L.method (L.Field (L.atom "self") "supervisor") "monitor" [L.atom "notify"])] Nothing))
    , comment ["Stops every child, last started first, without restarting them."]
        (L.function "pub fn stop" ["&self"] "" (L.stmts [L.Semi (L.method (L.Field (L.atom "self") "supervisor") "stop" [])] Nothing)) ] ])
  where
    cls = supervisionClass s
    field = nativeIdentifier "rust" ValueName . map (\c -> if isAlphaNum c || c == '_' then c else '_')
    childClass c = case c of
      ActorChild a -> actorClass a
      SupervisorChild n -> n
    strategy = case supervisionStrategy s of
      OneForOne -> "OneForOne"
      OneForAll -> "OneForAll"
      RestForOne -> "RestForOne"
    strategyText = case supervisionStrategy s of
      OneForOne -> "one for one" :: String
      OneForAll -> "one for all"
      RestForOne -> "rest for one"
    lifetime l = case l of
      Permanent -> "Permanent" :: String
      Transient -> "Transient"
      Temporary -> "Temporary"

-- | An array literal, [a, b].
arrayOf :: [L.Expr] -> L.Expr
arrayOf = L.Macro "" "[" "]"

-- | The struct's runtime actor.
self0 :: L.Expr
self0 = L.Field (L.atom "self") "0"

-- | A function's body that is its value.
body :: L.Expr -> D.Doc
body e = L.stmts [] (Just e)
