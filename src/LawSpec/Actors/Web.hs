-- Typed actors for JavaScript and TypeScript implementation code (see
-- LawSpec.Actors).
--
-- Every actor becomes a class named for its handle type in lawspec_actors:
-- AccountActor.start(...) makes the state with the start adapter and runs it
-- in a lawspec_runtime Actor; each handler is an async method that sends its
-- message and resolves to the reply, and tell<Handler> sends it without
-- waiting. stop() refuses further messages.
module LawSpec.Actors.Web (emit) where

import Control.Monad (forM, when)
import Data.Char (toUpper)
import Data.List (intercalate, isInfixOf, nub)
import qualified LawSpec.Core as C
import qualified LawSpec.Code.Doc as D
import LawSpec.Common (Artifact(..))
import LawSpec.Backend (adapterName, unitName)
import LawSpec.WebTypes (webDataTypeDocWith)
import LawSpec.Actors.Types (Actor(..), Handler(..))

emit :: String -> Bool -> Int -> [C.DataDeclaration] -> [Actor] -> Either String [Artifact]
emit target _ _ datas actors = do
  classes <- mapM (actorClassText ts datas) actors
  let modules = nub (map (unitName . actorUnit) actors)
      body = concatMap ("\n" ++) classes
      header =
        [ "// Generated by LawSpec; do not edit. Actors of " ++ intercalate ", " modules ++ ","
        , "// for implementation code. Each class runs one actor: start(...) makes its"
        , "// state and returns the actor. Each handler method sends a message and"
        , "// resolves to the reply; tell<Handler> sends it without waiting. Messages"
        , "// are handled one at a time, in the order they arrive."
        , importLine "ls" "lawspec_runtime" ] ++
        [ importLine "data" "lawspec_data" | "data." `isInfixOf` body ] ++
        [ importLine (alias m) (map (\c -> if c == '.' then '/' else c) m) | m <- modules ]
  pure [Artifact ("src/lawspec_actors." ++ (if ts then "ts" else "mjs")) (unlines header ++ body) "generated" "source"]
  where
    ts = target == "typescript"
    importLine name file = "import * as " ++ name ++ " from './" ++ file ++ (if ts then ".js" else ".mjs") ++ "';"

alias :: String -> String
alias m = "_adapters_" ++ map (\c -> if c == '.' then '_' else c) m

actorClassText :: Bool -> [C.DataDeclaration] -> Actor -> Either String String
actorClassText ts datas a = do
  let names = map handlerName (actorHandlers a)
  forM_' names $ \n -> when (n `elem` ["start", "stop", "constructor"] || ("tell" ++ capital n) `elem` names || (n ++ "Now") `elem` names)
    (Left ("actor " ++ actorName a ++ "'s handler " ++ n ++ " clashes with a method of its generated class"))
  startArgs <- mapM argument (actorStartArguments a)
  methods <- forM (actorHandlers a) handler
  let cls = actorClass a
      startParams = [arg | arg@(_, (t, _)) <- startArgs, not (unit t)]
      startValues = [if unit t then "ls.UNIT" else p | (p, (t, _)) <- startArgs]
      field = if ts then "  readonly #actor: ls.Actor;" else "  #actor;"
  pure $ unlines $
    [ "/** Actor " ++ actorName a ++ ": owns its state and handles one message at a time. */"
    , "export class " ++ cls ++ " {"
    , field
    , ""
    , "  constructor(actor" ++ typed "ls.Actor" ++ ") {"
    , "    this.#actor = actor;"
    , "  }"
    , ""
    , "  /** Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor. */"
    , "  static " ++ asyncWord (actorStart a) ++ "start(" ++ intercalate ", " (map param startParams) ++ ")" ++
        typed (promised (actorStart a) cls) ++ " {"
    , "    return new " ++ cls ++ "(new ls.Actor(" ++ awaited (actorStart a) (impl (actorStart a) ++ "(" ++ intercalate ", " startValues ++ ")") ++ "));"
    , "  }"
    ] ++ concatMap ("" :) methods ++
    [ ""
    , "  /** Refuses further messages; those already sent are still handled. */"
    , "  stop()" ++ typed "void" ++ " {"
    , "    this.#actor.stop();"
    , "  }"
    , "}" ]
  where
    forM_' xs f = mapM_ f xs
    unit t = t == C.Constructor "Unit" []
    typed t = if ts then ": " ++ t else ""
    param (p, (_, native)) = p ++ typed native
    argument (p, t) = do
      native <- nativeType t
      pure (p, (t, native))
    nativeType t = D.render (D.Pretty 1000) <$> webDataTypeDocWith datas [] t
    impl d = alias (unitName (actorUnit a)) ++ "." ++ adapterName (actorUnit a) (C.declarationId d)
    asyncWord d = if C.declarationAsync d then "async " else ""
    promised d t = if C.declarationAsync d then "Promise<" ++ t ++ ">" else t
    awaited d call = if C.declarationAsync d then "(await " ++ call ++ ")" else call
    capital (c : cs) = toUpper c : cs
    capital [] = []
    handler h = do
      args <- mapM argument (handlerArguments h)
      reply <- traverse nativeType (handlerReply h)
      let params = intercalate ", " (map param args)
          d = handlerDeclaration h
          call = impl d ++ "(" ++ intercalate ", " ("s" : map fst args) ++ ")"
          stateType = if ts then "(s: any)" else "(s)"
          step = case reply of
            Just _ -> asyncWord d ++ stateType ++ " => { const out = " ++ awaited d call ++ "; return [out.first, out.second]; }"
            Nothing -> asyncWord d ++ stateType ++ " => [undefined, " ++ awaited d call ++ "]"
          nowStep = case reply of
            Just _ -> stateType ++ " => { const out = " ++ call ++ "; return [out.first, out.second]; }"
            Nothing -> stateType ++ " => [undefined, " ++ call ++ "]"
          name = handlerName h
          result = maybe "void" id reply
      pure $
        [ "  /** Sends " ++ name ++ " and resolves to the reply. */"
        , "  " ++ name ++ "(" ++ params ++ ")" ++ typed ("Promise<" ++ result ++ ">") ++ " {"
        , "    return this.#actor.call(" ++ step ++ ")" ++ (if ts then " as Promise<" ++ result ++ ">" else "") ++ ";"
        , "  }"
        ] ++
        (if C.declarationAsync d then [] else
        [ ""
        , "  /** Handles " ++ name ++ " at once, for synchronous code; the actor must have no messages waiting. */"
        , "  " ++ name ++ "Now(" ++ params ++ ")" ++ typed result ++ " {"
        , "    return this.#actor.callNow(" ++ nowStep ++ ")" ++ (if ts then " as " ++ result else "") ++ ";"
        , "  }" ]) ++
        [ ""
        , "  /** Sends " ++ name ++ " without waiting for the reply. */"
        , "  tell" ++ capital name ++ "(" ++ params ++ ")" ++ typed "void" ++ " {"
        , "    this.#actor.cast(" ++ step ++ ");"
        , "  }" ]
