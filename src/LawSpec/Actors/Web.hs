-- | Typed actors for JavaScript and TypeScript implementation code (see
-- LawSpec.Actors).
--
-- Every actor becomes a class named for its handle type in lawspec_actors:
-- AccountActor.start(...) makes the state with the start adapter and runs it
-- in a lawspec_runtime Actor; each handler is an async method that sends its
-- message and resolves to the reply, and tell<Handler> sends it without
-- waiting. stop() refuses further messages.
module LawSpec.Actors.Web (emit) where

import Control.Monad (foldM, forM, when)
import Data.Char (toUpper)
import Data.List (intercalate, isInfixOf, nub)
import qualified LawSpec.Core as C
import qualified LawSpec.Code.ECMAScript as E
import LawSpec.Common (Artifact(..))
import LawSpec.Backend (adapterName, unitName)
import LawSpec.WebTypes (webDataTypeOfWith, webTypeReference, requiresSchema)
import LawSpec.WebModule (commentLines)
import LawSpec.MachineSpec (describe)
import LawSpec.Actors.Types (Actor(..), Handler(..), Supervision(..), Child(..))
import LawSpec.Core.Machine (SupervisionStrategy(..), Lifetime(..))

-- | Actors become a typed class, or JavaScript and TypeScript's idiom for one,
-- generated from the declaration. ref:DEC-actors-otp-supervision
emit :: String -> Bool -> Int -> [C.DataDeclaration] -> [Actor] -> [Supervision] -> Either String [Artifact]
emit target _ bits datas actors supervisions = do
  -- Each actor's messages as wire descriptors, for serving it and calling
  -- it across nodes; an actor whose types have none yet stays local.
  let wired (table, acc) a = case foldM (handlerWire bits datas) (table, []) (actorHandlers a) of
        Right (table', hs) -> (table', acc ++ [(actorName a, reverse hs)])
        Left _ -> (table, acc)
      (types, wires) = foldl wired ([], []) actors
  classes <- (++ map (supervisorClass ts supervisions) supervisions) <$>
    mapM (\a -> actorClassCode ts datas (lookup (actorName a) wires) a) actors
  let modules = nub (map (unitName . actorUnit) actors)
      remote = not (null wires)
      body = concatMap (E.Blank :) classes
      bodyText = E.printModule dialect body
      anyP n = (E.param n) { E.paramType = if ts then Just (E.TKeyword "any") else Nothing }
      anyR = if ts then Just (E.TKeyword "any") else Nothing
      ref = E.Ident "reference"
      helpers = if not remote then [] else
        [ E.Blank
        , E.Comment ["// Values crossing the network are logical; handlers and callers use", "// native ones."]
        , E.constDecl "_TYPES" (E.index (E.call "ls.valuesFrom" [E.Str (unwords (map snd (reverse types) ++ ["(unit)"]))]) (E.num 0))
        , E.VarDecl "const" (E.PIdent "_SCHEMA") (if ts then Just (E.TKeyword "any") else Nothing) (Just (if "data." `isInfixOf` bodyText then E.call "data.makeSchema" [] else E.Null))
        , E.constDecl "_native" (E.Arrow False [anyP "reference", anyP "d", anyP "value"] anyR (E.ExpressionBody
            (E.Conditional (E.Binary "===" ref E.Null) (E.call "ls.nativeScalar" [E.Ident "d", E.Ident "value"]) (E.call "_SCHEMA.toNative" [ref, E.Ident "value"]))))
        , E.constDecl "_logical" (E.Arrow False [anyP "reference", anyP "value"] anyR (E.ExpressionBody
            (E.Conditional (E.Binary "===" ref E.Null) (E.Ident "value") (E.call "_SCHEMA.fromNative" [ref, E.Ident "value"]))))
        , E.constDecl "_served" (E.Arrow False [anyP "reference", anyP "pair"] anyR (E.ExpressionBody
            (E.Array [E.call "_logical" [ref, E.member (E.Ident "pair") "first"], E.member (E.Ident "pair") "second"])))
        , E.constDecl "_d" (E.Arrow False [(E.param "text") { E.paramType = if ts then Just (E.TKeyword "string") else Nothing }] anyR
            (E.ExpressionBody (E.index (E.call "ls.readDescriptor" [E.Ident "text"]) (E.num 0)))) ]
      header =
        [ E.Comment (["// Generated by LawSpec. Do not edit."] ++ commentLines
            ("Actors of " ++ intercalate ", " modules ++ ", for implementation code. Each class runs one actor: start(...) makes its " ++
             "state and returns the actor. Each handler method sends a message and resolves to the reply; tell<Handler> sends it " ++
             "without waiting. Messages are handled one at a time, in the order they arrive. A handler that throws crashes the actor: " ++
             "the call rejects with ls.ActorCrashed, and a supervised actor restarts (from its restart adapter, or its start) while " ++
             "any other stops. start's last argument may be {supervisor, lifetime}. Each supervisor class starts its children and " ++
             "restarts them after a crash; its children are properties named as in the specification."))
        , importLine "ls" "lawspec_runtime" ] ++
        [ importLine "data" "lawspec_data" | "data." `isInfixOf` bodyText ] ++
        [ importLine "schema" "lawspec_schema" | "schema." `isInfixOf` bodyText ] ++
        [ importLine (alias m) (map (\c -> if c == '.' then '/' else c) m) | m <- modules ] ++ helpers
  pure [Artifact ("src/lawspec_actors." ++ (if ts then "ts" else "mjs")) (E.printModule dialect (header ++ body)) "generated" "source"]
  where
    ts = target == "typescript"
    dialect = if ts then E.TypeScript else E.JavaScript
    importLine name file = E.ImportDecl False (E.ImportNamespace name) ("./" ++ file ++ (if ts then ".js" else ".mjs"))

alias :: String -> String
alias m = "_adapters_" ++ map (\c -> if c == '.' then '_' else c) m

-- | A handler's argument and reply descriptors, adding data types to the table.
type HandlerWire = (Handler, [String], String)

handlerWire :: Int -> [C.DataDeclaration] -> ([(String, String)], [HandlerWire]) -> Handler -> Either String ([(String, String)], [HandlerWire])
handlerWire bits datas (table, acc) h = do
  (args, table') <- foldM (\(xs, t) (_, ty) -> (\(x, t') -> (xs ++ [x], t')) <$> describe bits datas t ty) ([], table) (handlerArguments h)
  (reply, table'') <- describe bits datas table' (maybe (C.Constructor "Unit" []) id (handlerReply h))
  pure (table'', (h, args, reply) : acc)

-- | A JSDoc comment on one line.
doc :: String -> E.Member
doc text = E.MemberComment ["/** " ++ text ++ " */"]

-- | A JSDoc comment, wrapped.
docLines :: [String] -> E.Member
docLines ls = E.MemberComment (["/**"] ++ map (" * " ++) ls ++ [" */"])

method :: String -> [E.Param] -> Maybe E.Type -> [E.Stmt] -> E.Member
method name params result = E.Method False False "method" name params result

private' :: String -> E.Expr
private' n = E.member E.This n

supervisionOptions :: Bool -> E.Param
supervisionOptions ts = E.Param (E.PIdent "options")
  (if ts then Just (E.TObject [("supervisor", True, E.TRef "ls.Supervisor" []), ("lifetime", True, E.TKeyword "string")]) else Nothing)
  (Just (E.Object [])) False

-- | options.supervisor?.supervise(...), when a supervisor is given.
supervise :: E.Expr -> E.Stmt
supervise child = E.IfSingle (E.Binary "!==" (E.member (E.Ident "options") "supervisor") (E.Ident "undefined"))
  (E.ExprStmt (E.method (E.member (E.Ident "options") "supervisor") "supervise"
    [child, E.Binary "??" (E.member (E.Ident "options") "lifetime") (E.Str "permanent")]))

actorClassCode :: Bool -> [C.DataDeclaration] -> Maybe [HandlerWire] -> Actor -> Either String [E.Stmt]
actorClassCode ts datas wire a = do
  let names = map handlerName (actorHandlers a)
  forM_' names $ \n -> when (n `elem` ["start", "stop", "constructor", "crash", "crashNow", "monitor", "link", "serve", "connect"] || ("tell" ++ capital n) `elem` names || (n ++ "Now") `elem` names)
    (Left ("actor " ++ actorName a ++ "'s handler " ++ n ++ " clashes with a method of its generated class"))
  startArgs <- mapM argument (actorStartArguments a)
  methods <- forM (actorHandlers a) handler
  let cls = actorClass a
      startParams = [arg | arg@(_, (t, _)) <- startArgs, not (unit t)]
      startValues = [if unit t then E.Ident "ls.UNIT" else E.Ident p | (p, (t, _)) <- startArgs]
      startCall = E.call (impl (actorStart a)) startValues
      restart = case actorRestart a of
        Just d -> E.Arrow (C.declarationAsync d) [typedP "s" (E.TKeyword "any")] Nothing (E.ExpressionBody (awaited d (E.call (impl d) [E.Ident "s"])))
        Nothing -> E.Arrow (C.declarationAsync (actorStart a)) [] Nothing (E.ExpressionBody (awaited (actorStart a) startCall))
      actorField = E.Field (["readonly" | ts]) "#actor" (typedT (E.TRef "ls.Actor" [])) Nothing
      actor = private' "#actor"
  pure $
    [ E.Comment ["/** Actor " ++ actorName a ++ ": owns its state and handles one message at a time. */"]
    , E.ClassDecl True cls [] Nothing [] (
      [ actorField
      , E.MemberBlank
      , E.Method False False "method" "constructor" [typedP "actor" (E.TRef "ls.Actor" [])] Nothing [E.ExprStmt (E.Assign "=" actor (E.Ident "actor"))]
      , E.MemberBlank
      , docLines [ "Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor, under"
                 , "options.supervisor when given, with options.lifetime ('permanent' by default)." ]
      , E.Method True (C.declarationAsync (actorStart a)) "method" "start" (map param startParams ++ [supervisionOptions ts])
          (typedT (promised (actorStart a) (E.TRef cls [])))
          [ E.constDecl "actor" (E.new' "ls.Actor" [awaited (actorStart a) startCall, E.Object [E.Prop (E.KName "restart") restart]])
          , supervise (E.Ident "actor")
          , E.ret (E.new' cls [E.Ident "actor"]) ] ] ++
      concatMap (E.MemberBlank :) methods ++
      [ E.MemberBlank
      , doc "Crashes the actor as a failing handler would, after the messages already sent: for testing how it restarts."
      , method "crash" [] (typedT (E.TRef "Promise" [E.TKeyword "void"])) [E.ret (E.method actor "crash" [])]
      , E.MemberBlank
      , doc "crash for synchronous code; the actor must have no messages waiting."
      , method "crashNow" [] (typedT (E.TKeyword "void")) [E.ExprStmt (E.method actor "crashNow" [])]
      , E.MemberBlank
      , doc "notify(['crashed', cause]) after each crash, and notify(['stopped', null]) once it stops."
      , method "monitor" [typedP "notify" notifyType] (typedT (E.TKeyword "void")) [E.ExprStmt (E.method actor "monitor" [E.Ident "notify"])]
      , E.MemberBlank
      , doc "When either actor crashes, the other crashes too."
      , method "link" [typedP "other" (E.TObject [("readonly actor", False, E.TRef "ls.Actor" [])])] (typedT (E.TKeyword "void"))
          [E.ExprStmt (E.method actor "link" [E.member (E.Ident "other") "actor"])]
      , E.MemberBlank
      , doc "The runtime actor, for links and supervision."
      , E.Method False False "get" "actor" [] (typedT (E.TRef "ls.Actor" [])) [E.ret actor]
      , E.MemberBlank
      , doc "Refuses further messages; those already sent are still handled."
      , method "stop" [] (typedT (E.TKeyword "void")) [E.ExprStmt (E.method actor "stop" [])] ] ++ serving) ] ++ proxy
  where
    notifyType = E.TFunction [typedP "event" (E.TTuple [E.TKeyword "string", E.TKeyword "unknown"])] (E.TKeyword "void")
    reference ty = if requiresSchema datas ty then either (const E.Null) id (webTypeReference ty) else E.Null
    replyType h = maybe (C.Constructor "Unit" []) id (handlerReply h)
    descriptors ds = E.Array [E.call "_d" [E.Str d] | d <- ds]
    serving = case wire of
      Nothing -> []
      Just hs ->
        [ E.MemberBlank
        , doc "Lets other nodes call this actor at <node address>/name; returns that address."
        , method "serve" [typedP "node" (E.TRef "ls.Node" []), typedP "name" (E.TKeyword "string")] (typedT (E.TKeyword "string"))
            [E.ret (E.method (E.Ident "node") "serve" [E.Ident "name", private' "#actor", E.Object
              [ E.Prop (E.KString (handlerName h)) (E.Array
                  [ E.Arrow (C.declarationAsync d) (typedP "s" (E.TKeyword "any") : [typedP p (E.TKeyword "any") | (p, _) <- handlerArguments h]) Nothing
                      (E.ExpressionBody (let call = awaited d (E.call (impl d) (E.Ident "s" : [E.call "_native" [reference ty, E.call "_d" [E.Str x], E.Ident p] | ((p, ty), x) <- zip (handlerArguments h) ds]))
                                         in case handlerReply h of
                                              Just r' -> E.call "_served" [reference r', call]
                                              Nothing -> E.Array [E.Ident "ls.UNIT", call]))
                  , descriptors ds, E.call "_d" [E.Str r] ])
              | (h, ds, r) <- hs, let d = handlerDeclaration h ], E.Ident "_TYPES"])]
        , E.MemberBlank
        , doc "The actor served at address on another node; each call waits up to timeout seconds, then rejects with ls.Unreachable."
        , E.Method True False "method" "connect" [typedP "node" (E.TRef "ls.Node" []), typedP "address" (E.TKeyword "string"), (E.param "timeout") { E.paramDefault = Just (E.num 5) }]
            (typedT (E.TRef (actorClass a ++ "Remote") []))
            [E.ret (E.new' (actorClass a ++ "Remote") [E.method (E.Ident "node") "remoteActor" [E.Ident "address", E.Object
              [E.Prop (E.KString (handlerName h)) (E.Array [descriptors ds, E.call "_d" [E.Str r]]) | (h, ds, r) <- hs], E.Ident "_TYPES", E.Ident "timeout"]])] ]
    proxy = case wire of
      Nothing -> []
      Just hs ->
        [ E.Blank
        , E.Comment ["/** Actor " ++ actorName a ++ " on another node: each method sends its message and resolves to the reply. */"]
        , E.ClassDecl True (actorClass a ++ "Remote") [] Nothing [] (
          [ E.Field (["readonly" | ts]) "#remote" (typedT (E.TRef "ls.RemoteActor" [])) Nothing
          , E.MemberBlank
          , E.Method False False "method" "constructor" [typedP "remote" (E.TRef "ls.RemoteActor" [])] Nothing
              [E.ExprStmt (E.Assign "=" (private' "#remote") (E.Ident "remote"))] ] ++
          concat
          [ [ E.MemberBlank
            , E.Method False True "method" (handlerName h) [typedP p (E.TKeyword "any") | (p, _) <- handlerArguments h] (typedT (E.TRef "Promise" [E.TKeyword "any"]))
                [E.ret (E.call "_native" [reference (replyType h), E.call "_d" [E.Str r],
                  E.Await (E.method (private' "#remote") "call" (E.Str (handlerName h) : [E.call "_logical" [reference ty, E.Ident p] | (p, ty) <- handlerArguments h]))])] ]
          | (h, _, r) <- hs ]) ]
    forM_' xs f = mapM_ f xs
    unit t = t == C.Constructor "Unit" []
    typedT t = if ts then Just t else Nothing
    typedP n t = (E.param n) { E.paramType = typedT t }
    param (p, (_, native)) = typedP p native
    argument (p, t) = do
      native <- nativeType t
      pure (p, (t, native))
    nativeType t = webDataTypeOfWith datas [] t
    impl d = alias (unitName (actorUnit a)) ++ "." ++ adapterName (actorUnit a) (C.declarationId d)
    promised d t = if C.declarationAsync d then E.TRef "Promise" [t] else t
    awaited d call = if C.declarationAsync d then E.Await call else call
    capital (c : cs) = toUpper c : cs
    capital [] = []
    handler h = do
      args <- mapM argument (handlerArguments h)
      reply <- traverse nativeType (handlerReply h)
      let params = map param args
          d = handlerDeclaration h
          call = E.call (impl d) (E.Ident "s" : map (E.Ident . fst) args)
          stateParam = typedP "s" (E.TKeyword "any")
          pairOut c = [E.constDecl "out" c, E.ret (E.Array [E.member (E.Ident "out") "first", E.member (E.Ident "out") "second"])]
          step = case reply of
            Just _ -> E.Arrow (C.declarationAsync d) [stateParam] Nothing (E.BlockBody (pairOut (awaited d call)))
            Nothing -> E.Arrow (C.declarationAsync d) [stateParam] Nothing (E.ExpressionBody (E.Array [E.Ident "undefined", awaited d call]))
          nowStep = case reply of
            Just _ -> E.Arrow False [stateParam] Nothing (E.BlockBody (pairOut call))
            Nothing -> E.Arrow False [stateParam] Nothing (E.ExpressionBody (E.Array [E.Ident "undefined", call]))
          name = handlerName h
          result = maybe (E.TKeyword "void") id reply
          actor = private' "#actor"
          castTo t x = if ts then E.As x t else x
      pure $
        [ doc ("Sends " ++ name ++ " and resolves to the reply.")
        , method name params (typedT (E.TRef "Promise" [result])) [E.ret (castTo (E.TRef "Promise" [result]) (E.method actor "call" [step]))] ] ++
        (if C.declarationAsync d then [] else
        [ E.MemberBlank
        , doc ("Handles " ++ name ++ " at once, for synchronous code; the actor must have no messages waiting.")
        , method (name ++ "Now") params (typedT result) [E.ret (castTo result (E.method actor "callNow" [nowStep]))] ]) ++
        [ E.MemberBlank
        , doc ("Sends " ++ name ++ " without waiting for the reply.")
        , method ("tell" ++ capital name) params (typedT (E.TKeyword "void")) [E.ExprStmt (E.method actor "cast" [step])] ]

-- | A supervisor's class: start() makes the runtime supervisor and starts each
-- child under it, in order; each child is a property. start is async when a
-- child's start is.
supervisorClass :: Bool -> [Supervision] -> Supervision -> [E.Stmt]
supervisorClass ts all' s =
  [ E.Comment ["/** Supervisor " ++ supervisionName s ++ ": " ++ strategyText ++ ", at most " ++
      show (supervisionRestarts s) ++ " restarts in " ++ seconds ++ "s. */"]
  , E.ClassDecl True cls [] Nothing [] (
    [ E.Field (["readonly" | ts]) "#supervisor" (typedT (E.TRef "ls.Supervisor" [])) Nothing ] ++
    [ E.Field (["readonly" | ts]) name (typedT (E.TRef (childClass child) [])) Nothing | (_, name, child) <- children ] ++
    [ E.MemberBlank
    , E.Method False False "method" "constructor" (typedP "supervisor" (E.TRef "ls.Supervisor" []) : [typedP name (E.TRef (childClass child) []) | (_, name, child) <- children]) Nothing
        (E.ExprStmt (E.Assign "=" supervisor (E.Ident "supervisor")) : [E.ExprStmt (E.Assign "=" (E.member E.This name) (E.Ident name)) | (_, name, _) <- children])
    , E.MemberBlank
    , doc "Starts the supervisor and its children, under options.supervisor when given."
    , E.Method True isAsync "method" "start" [supervisionOptions ts] (typedT (if isAsync then E.TRef "Promise" [E.TRef cls []] else E.TRef cls []))
        ([ E.constDecl "own" (E.new' "ls.Supervisor" [E.Str strategyName, E.num (toInteger (supervisionRestarts s)), E.Num seconds]) ] ++
         [ E.constDecl name ((if childAsync child then E.Await else id) (E.call (childClass child ++ ".start")
             [E.Object [E.Prop (E.KName "supervisor") (E.Ident "own"), E.Prop (E.KName "lifetime") (E.Str (lifetimeName l))]]))
         | (l, name, child) <- children ] ++
         [ supervise (E.Ident "own")
         , E.ret (E.new' cls (E.Ident "own" : [E.Ident name | (_, name, _) <- children])) ])
    , E.MemberBlank
    , doc "notify(['crashed', cause]) when it passes its restart limit, and notify(['stopped', null]) once stopped."
    , method "monitor" [typedP "notify" (E.TFunction [typedP "event" (E.TTuple [E.TKeyword "string", E.TKeyword "unknown"])] (E.TKeyword "void"))]
        (typedT (E.TKeyword "void")) [E.ExprStmt (E.method supervisor "monitor" [E.Ident "notify"])]
    , E.MemberBlank
    , doc "Stops every child, last started first, without restarting them."
    , method "stop" [] (typedT (E.TKeyword "void")) [E.ExprStmt (E.method supervisor "stop" [])]
    , E.MemberBlank
    , doc "The runtime supervisor, for nesting."
    , E.Method False False "get" "supervisor" [] (typedT (E.TRef "ls.Supervisor" [])) [E.ret supervisor] ]) ]
  where
    cls = supervisionClass s
    supervisor = private' "#supervisor"
    children = supervisionChildren s
    typedT t = if ts then Just t else Nothing
    typedP n t = (E.param n) { E.paramType = typedT t }
    childClass c = case c of
      ActorChild a -> actorClass a
      SupervisorChild n -> n
    childAsync c = case c of
      ActorChild a -> C.declarationAsync (actorStart a)
      SupervisorChild n -> supervisorAsync n
    supervisorAsync n = or [any (childAsyncOf . thd) (supervisionChildren t) | t <- all', supervisionClass t == n]
    childAsyncOf c = case c of
      ActorChild a -> C.declarationAsync (actorStart a)
      SupervisorChild n -> supervisorAsync n
    thd (_, _, c) = c
    isAsync = any (childAsync . thd) children
    strategyName = case supervisionStrategy s of
      OneForOne -> "one_for_one" :: String
      OneForAll -> "one_for_all"
      RestForOne -> "rest_for_one"
    strategyText = case supervisionStrategy s of
      OneForOne -> "one for one" :: String
      OneForAll -> "one for all"
      RestForOne -> "rest for one"
    lifetimeName l = case l of
      Permanent -> "permanent" :: String
      Transient -> "transient"
      Temporary -> "temporary"
    seconds = let (whole, micros) = supervisionPeriod s `divMod` 1000000
              in show whole ++ (if micros == 0 then "" else "." ++ reverse (dropWhile (== '0') (reverse (pad (show micros)))))
    pad m = replicate (6 - length m) '0' ++ m
