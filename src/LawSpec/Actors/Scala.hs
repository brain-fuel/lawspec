-- | Typed actors for Scala implementation code (see LawSpec.Actors), over the
-- shared JVM runtime's actors and supervisors.
--
-- Every actor becomes a class lawspec.actors.<Handle> (AccountActor) whose
-- companion's start(...) makes the state with the start adapter and runs it
-- in a LawSpecRuntime.Actor; each handler is a method that sends its message
-- and returns the reply, tell<Handler> sends it without waiting, and stop()
-- refuses further messages.
module LawSpec.Actors.Scala (emit) where

import Data.List (intercalate, isInfixOf)
import qualified LawSpec.Code.Doc as D
import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..))
import LawSpec.ScalaData (scalaCodecDocWithContext, scalaDataType, identifier, scalaQuoted)
import LawSpec.Actors.Types (Actor(..), Handler(..), Supervision(..))
import LawSpec.Actors.Jvm (Wire(..), actorWire, replyOf, adapterCall, isUnit, childClass, strategyName, strategyText, lifetimeName, seconds, capital)

-- | Actors become a typed class with a companion, Scala's idiom for one,
-- generated from the declaration. ref:DEC-actors-otp-supervision
emit :: String -> Bool -> Int -> [C.DataDeclaration] -> [Actor] -> [Supervision] -> Either String [Artifact]
emit _ _ bits datas actors supervisions = (++) <$> mapM artifact actors <*> mapM supervisorArtifact supervisions
  where
    directory = "src/main/scala/lawspec/actors/"
    artifact a = do
      identifier (actorClass a)
      mapM_ (reserved a) (actorHandlers a)
      source <- scalaSource datas (either (const Nothing) Just (actorWire bits datas a)) a
      pure (Artifact (directory ++ actorClass a ++ ".scala") source "generated" "source")
    supervisorArtifact s = do
      identifier (supervisionClass s)
      mapM_ (\(_, name, _) -> identifier name) (supervisionChildren s)
      pure (Artifact (directory ++ supervisionClass s ++ ".scala") (scalaSupervisor s) "generated" "source")
    reserved a h
      | handlerName h `elem` ["start", "stop", "crash", "monitor", "link", "serve", "connect"] || ("tell" ++ capital (handlerName h)) `elem` map handlerName (actorHandlers a) =
          Left ("actor " ++ actorName a ++ ": handler " ++ handlerName h ++ " clashes with a method of " ++ actorClass a ++ "; rename it")
      | otherwise = pure ()

scalaSource :: [C.DataDeclaration] -> Maybe Wire -> Actor -> Either String String
scalaSource datas wire a = do
  own <- scalaDataType datas (actorState a)
  let startArgs = actorStartArguments a
  startParams <- sequence [(\n -> p ++ ": " ++ n) <$> scalaDataType datas t | (p, t) <- startArgs, not (isUnit t)]
  methods <- mapM (handler own) (actorHandlers a)
  remote <- maybe (pure ([], [])) (scalaRemote own) wire
  let body = unlines (fst remote ++ snd remote)
      imports = [ "import lawspec.runtime." ++ c | c <- ["LawSpecDataCodecs", "LawSpecDataSchema", "LawSpecScala", "LawSpecScalaCodecs"], (c ++ ".") `isInfixOf` body ]
      startValues = [if isUnit t then "()" else p | (p, t) <- startArgs]
      initial = awaited (actorStart a) (adapterCall a (actorStart a) startValues)
      restart = case actorRestart a of
        Just d -> "(s: " ++ own ++ ") => " ++ awaited d (adapterCall a d ["s"])
        Nothing -> "(_: " ++ own ++ ") => " ++ initial
  pure $ unlines $
    [ "// Generated by LawSpec from actor " ++ actorName a ++ ". Do not edit."
    , "package lawspec.actors"
    , ""
    , "import lawspec.runtime.LawSpecRuntime" ] ++ imports ++
    [ ""
    , "/**"
    , " * Actor " ++ actorName a ++ ": owns its state and handles one message at a time, in the order they"
    , " * arrive. Each handler method sends a message and returns the reply; tell methods send it"
    , " * without waiting. A handler that throws crashes the actor: the caller gets"
    , " * LawSpecRuntime.ActorCrashed, and a supervised actor restarts (from its restart adapter, or its"
    , " * start) while any other stops."
    , " */"
    , "final class " ++ cls ++ " private (private val actor: LawSpecRuntime.Actor[" ++ own ++ "]) {"
    ] ++ concatMap ("" :) methods ++
    [ ""
    , "  /** Crashes the actor as a failing handler would, after the messages already sent: for testing how it restarts. */"
    , "  def crash(): Unit = actor.crash()"
    , ""
    , "  /** notify gets Exit(\"crashed\", cause) after each crash, and Exit(\"stopped\", null) once it stops. */"
    , "  def monitor(notify: LawSpecRuntime.Exit => Unit): Unit = actor.monitor(exit => notify(exit))"
    , ""
    , "  /** When either actor crashes, the other crashes too. */"
    , "  def link(other: " ++ cls ++ "): Unit = actor.link(other.actor)"
    , ""
    , "  /** Refuses further messages; those already sent are still handled. */"
    , "  def stop(): Unit = actor.stop()"
    ] ++ snd remote ++
    [ "}"
    , ""
    , "object " ++ cls ++ " {" ] ++ fst remote ++
    [ "  /**"
    , "   * Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor, under"
    , "   * supervisor (when given) with the given lifetime."
    , "   */"
    , "  def start(" ++ intercalate ", " (startParams ++ ["supervisor: LawSpecRuntime.Supervisor = null", "lifetime: String = LawSpecRuntime.Supervisor.PERMANENT"]) ++ "): " ++ cls ++ " = {"
    , "    val actor = LawSpecRuntime.Actor[" ++ own ++ "](" ++ initial ++ ", " ++ restart ++ ")"
    , "    if (supervisor != null) supervisor.supervise(actor, lifetime)"
    , "    new " ++ cls ++ "(actor)"
    , "  }"
    , "}" ]
  where
    cls = actorClass a
    awaited d call = if C.declarationAsync d then "scala.concurrent.Await.result(" ++ call ++ ", scala.concurrent.duration.Duration.Inf)" else call
    codec ty = D.render (D.Pretty 1000) <$> scalaCodecDocWithContext (D.text "symbols") datas ty
    -- The companion's members, and the class's.
    scalaRemote own w = do
      served <- mapM (\(h, ds, r) -> do
        argCodecs <- mapM (codec . snd) (handlerArguments h)
        replyCodec <- codec (replyOf h)
        let call = awaited (handlerDeclaration h) (adapterCall a (handlerDeclaration h)
              ("s" : [c ++ ".decode(args.get(" ++ show i ++ "))" | (i, c) <- zip [0 :: Int ..] argCodecs]))
            result = case handlerReply h of
              Just _ -> [ "        val next = " ++ call
                        , "        LawSpecRuntime.Next[LawSpecRuntime.Value, " ++ own ++ "](" ++ replyCodec ++ ".encode(next.first), next.second)" ]
              Nothing -> [ "        LawSpecRuntime.Next[LawSpecRuntime.Value, " ++ own ++ "](LawSpecRuntime.absent(\"Unit\"), " ++ call ++ ")" ]
        pure $
          [ "    handlers.put(" ++ scalaQuoted (handlerName h) ++ ", LawSpecRuntime.Served[" ++ own ++ "]("
          , "      (s: " ++ own ++ ", args: java.util.List[LawSpecRuntime.Value]) => {"
          , "        val symbols = LawSpecScala.symbols()" ] ++ result ++
          [ "      },"
          , "      java.util.List.of[Object](" ++ intercalate ", " ["LawSpecRuntime.descriptor(" ++ scalaQuoted d ++ ")" | d <- ds] ++ "),"
          , "      LawSpecRuntime.descriptor(" ++ scalaQuoted r ++ "),"
          , "    ))" ]) (wireHandlers w)
      methods <- mapM (\(h, _, _) -> do
        params <- sequence [(\n -> p ++ ": " ++ n) <$> scalaDataType datas t | (p, t) <- handlerArguments h]
        argCodecs <- mapM (codec . snd) (handlerArguments h)
        replyCodec <- codec (replyOf h)
        reply <- traverse (scalaDataType datas) (handlerReply h)
        let call = "remote.call(" ++ scalaQuoted (handlerName h) ++ ", java.util.List.of[LawSpecRuntime.Value](" ++
              intercalate ", " [c ++ ".encode(" ++ p ++ ")" | (c, (p, _)) <- zip argCodecs (handlerArguments h)] ++ "))"
        pure
          [ ""
          , "    /** Sends " ++ handlerName h ++ " to the actor and waits for the reply. */"
          , "    def " ++ handlerName h ++ "(" ++ intercalate ", " params ++ "): " ++ maybe "Unit" id reply ++ " = {"
          , "      val symbols = LawSpecScala.symbols()"
          , "      " ++ (if handlerReply h == Nothing then call ++ "\n      ()" else replyCodec ++ ".decode(" ++ call ++ ")")
          , "    }" ]) (wireHandlers w)
      let companion =
            [ "  private val schema: lawspec.runtime.LawSpecSchema = LawSpecDataSchema.create()"
            , ""
            , "  private val bits = " ++ show (wireBits w)
            , ""
            , "  private val TYPES = LawSpecRuntime.valuesOf(" ++ scalaQuoted (wireTypes w) ++ ")"
            , ""
            , "  /** The actor served at address on another node; a call not answered within timeout seconds throws Unreachable. */"
            , "  def connect(node: LawSpecRuntime.Node, address: String, timeout: Double = 5.0): Remote = {"
            , "    val signatures = java.util.HashMap[String, LawSpecRuntime.Signature]()" ] ++
            [ "    signatures.put(" ++ scalaQuoted (handlerName h) ++ ", LawSpecRuntime.Signature(java.util.List.of[Object](" ++
                intercalate ", " ["LawSpecRuntime.descriptor(" ++ scalaQuoted d ++ ")" | d <- ds] ++ "), LawSpecRuntime.descriptor(" ++ scalaQuoted r ++ ")))"
            | (h, ds, r) <- wireHandlers w ] ++
            [ "    Remote(node.remoteActor(address, signatures, TYPES, timeout))"
            , "  }"
            , ""
            , "  /** Actor " ++ actorName a ++ " on another node: each method sends its message and waits for the reply. */"
            , "  final class Remote private[" ++ cls ++ "] (private val remote: LawSpecRuntime.RemoteActor) {" ] ++
            concat methods ++ [ "  }", "" ]
          members =
            [ ""
            , "  /** Lets other nodes call this actor at {node address}/name; returns that address. */"
            , "  def serve(node: LawSpecRuntime.Node, name: String): String = {"
            , "    import " ++ cls ++ ".{TYPES, bits, schema}"
            , "    val handlers = java.util.HashMap[String, LawSpecRuntime.Served[" ++ own ++ "]]()" ] ++ concat served ++
            [ "    node.serve(name, actor, handlers, TYPES)"
            , "  }" ]
      pure (companion, members)
    handler own h = do
      params <- sequence [(\n -> p ++ ": " ++ n) <$> scalaDataType datas t | (p, t) <- handlerArguments h]
      reply <- traverse (scalaDataType datas) (handlerReply h)
      let call = awaited (handlerDeclaration h) (adapterCall a (handlerDeclaration h) ("s" : map fst (handlerArguments h)))
          replyType = maybe "Unit" id reply
          step = case reply of
            Just _ -> "(s: " ++ own ++ ") => {\n      val next = " ++ call ++ "\n      LawSpecRuntime.Next[" ++ replyType ++ ", " ++ own ++
              "](next.first, next.second)\n    }"
            Nothing -> "(s: " ++ own ++ ") => LawSpecRuntime.Next[" ++ replyType ++ ", " ++ own ++ "]((), " ++ call ++ ")"
          name = handlerName h
      pure
        [ "  /** Sends " ++ name ++ " and waits for the reply. */"
        , "  def " ++ name ++ "(" ++ intercalate ", " params ++ "): " ++ replyType ++ " ="
        , "    actor.call[" ++ replyType ++ "](" ++ step ++ ")"
        , ""
        , "  /** Sends " ++ name ++ " without waiting for the reply. */"
        , "  def tell" ++ capital name ++ "(" ++ intercalate ", " params ++ "): Unit ="
        , "    actor.cast(" ++ step ++ ")" ]

scalaSupervisor :: Supervision -> String
scalaSupervisor s = unlines $
  [ "// Generated by LawSpec from supervisor " ++ supervisionName s ++ ". Do not edit."
  , "package lawspec.actors"
  , ""
  , "import lawspec.runtime.LawSpecRuntime"
  , ""
  , "/** Supervisor " ++ supervisionName s ++ ": " ++ strategyText s ++ ", at most " ++ show (supervisionRestarts s) ++
      " restarts in " ++ seconds s ++ "s. */"
  , "final class " ++ cls ++ " private ("
  , "  private val supervisor: LawSpecRuntime.Supervisor" ++ concatMap (\(_, name, c) -> ",\n  val " ++ name ++ ": " ++ childClass c) (supervisionChildren s) ++ ","
  , ") {"
  , "  /** notify gets Exit(\"crashed\", cause) when it passes its restart limit, and Exit(\"stopped\", null) once stopped. */"
  , "  def monitor(notify: LawSpecRuntime.Exit => Unit): Unit = supervisor.monitor(exit => notify(exit))"
  , ""
  , "  /** Stops every child, last started first, without restarting them. */"
  , "  def stop(): Unit = supervisor.stop()"
  , "}"
  , ""
  , "object " ++ cls ++ " {"
  , "  /** Starts the supervisor and its children, under parent (when given) with the given lifetime. */"
  , "  def start(parent: LawSpecRuntime.Supervisor = null, lifetime: String = LawSpecRuntime.Supervisor.PERMANENT): " ++ cls ++ " = {"
  , "    val own = LawSpecRuntime.Supervisor(" ++ scalaQuoted (strategyName s) ++ ", " ++ show (supervisionRestarts s) ++ ", " ++ seconds s ++ ")" ] ++
  [ "    val " ++ name ++ " = " ++ childClass c ++ ".start(own, " ++ scalaQuoted (lifetimeName l) ++ ")" | (l, name, c) <- supervisionChildren s ] ++
  [ "    if (parent != null) parent.supervise(own, lifetime)"
  , "    new " ++ cls ++ "(" ++ intercalate ", " ("own" : [name | (_, name, _) <- supervisionChildren s]) ++ ")"
  , "  }"
  , "}" ]
  where cls = supervisionClass s
