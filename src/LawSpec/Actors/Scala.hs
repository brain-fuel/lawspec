-- | Typed actors for Scala implementation code (see LawSpec.Actors), over the
-- shared JVM runtime's actors and supervisors.
--
-- Every actor becomes a class lawspec.actors.<Handle> (AccountActor) whose
-- companion's start(...) makes the state with the start adapter and runs it
-- in a LawSpecRuntime.Actor; each handler is a method that sends its message
-- and returns the reply, tell<Handler> sends it without waiting, and stop()
-- refuses further messages.
module LawSpec.Actors.Scala (emit) where

import Data.List (isInfixOf)
import qualified LawSpec.Code.Doc as D
import qualified LawSpec.Core as C
import LawSpec.Common (Artifact(..))
import LawSpec.ScalaData (scalaCodecDocIn, scalaDataType, identifier, scalaQuoted)
import qualified LawSpec.ScalaLayout as L
import LawSpec.Actors.Types (Actor(..), Handler(..), Supervision(..))
import LawSpec.Actors.Jvm (Wire(..), actorWire, replyOf, adapterFunction, isUnit, childClass, strategyName, strategyText, lifetimeName, seconds, capital)

-- | Actors become a typed class with a companion, Scala's idiom for one,
-- generated from the declaration. ref:DEC-actors-otp-supervision
emit :: String -> Bool -> Int -> [C.DataDeclaration] -> [Actor] -> [Supervision] -> Either String [Artifact]
emit _ _ bits datas actors supervisions = (++) <$> mapM artifact actors <*> mapM supervisorArtifact supervisions
  where
    directory = "src/main/scala/lawspec/actors/"
    artifact a = do
      identifier (actorClass a)
      mapM_ (reserved a) (actorHandlers a)
      source <- scalaSource datas (either (const Nothing) Just (actorWire bits datas a)) a
      pure (Artifact (directory ++ actorClass a ++ ".scala") source "generated" "source")
    supervisorArtifact s = do
      identifier (supervisionClass s)
      mapM_ (\(_, name, _) -> identifier name) (supervisionChildren s)
      pure (Artifact (directory ++ supervisionClass s ++ ".scala") (scalaSupervisor s) "generated" "source")
    reserved a h
      | handlerName h `elem` ["start", "stop", "crash", "monitor", "link", "serve", "connect"] || ("tell" ++ capital (handlerName h)) `elem` map handlerName (actorHandlers a) =
          Left ("actor " ++ actorName a ++ ": handler " ++ handlerName h ++ " clashes with a method of " ++ actorClass a ++ "; rename it")
      | otherwise = pure ()

scalaSource :: [C.DataDeclaration] -> Maybe Wire -> Actor -> Either String String
scalaSource datas wire a = do
  own <- scalaDataType datas (actorState a)
  let startArgs = actorStartArguments a
  startParams <- sequence [(\n -> p ++ ": " ++ n) <$> scalaDataType datas t | (p, t) <- startArgs, not (isUnit t)]
  methods <- mapM (handler own) (actorHandlers a)
  remote <- maybe (pure ([], [])) (scalaRemote own) wire
  let startValues = [if isUnit t then D.text "()" else D.text p | (p, t) <- startArgs]
      initial = awaited (actorStart a) (adapterCallDoc (actorStart a) startValues)
      restart = case actorRestart a of
        Just d -> D.text ("(s: " ++ own ++ ") => ") <> awaited d (adapterCallDoc d [D.text "s"])
        Nothing -> D.text ("(_: " ++ own ++ ") => ") <> initial
      classMembers = methods ++
        [ comment 2 "Crashes the actor as a failing handler would, after the messages already sent: for testing how it restarts." <>
          D.text "def crash(): Unit = actor.crash()"
        , comment 2 "notify gets Exit(\"crashed\", cause) after each crash, and Exit(\"stopped\", null) once it stops." <>
          L.equalsBody (D.text "def monitor(notify: LawSpecRuntime.Exit => Unit): Unit") (D.text "actor.monitor(exit => notify(exit))")
        , comment 2 "When either actor crashes, the other crashes too." <>
          D.text ("def link(other: " ++ cls ++ "): Unit = actor.link(other.actor)")
        , comment 2 "Refuses further messages; those already sent are still handled." <>
          D.text "def stop(): Unit = actor.stop()" ] ++ snd remote
      start = comment 2 ("Makes the actor's state with " ++ C.declarationName (actorStart a) ++ " and starts the actor, under supervisor (when given) with the given lifetime.") <>
        L.parameters (D.text "def start") (map D.text (startParams ++ ["supervisor: LawSpecRuntime.Supervisor = null", "lifetime: String = LawSpecRuntime.Supervisor.PERMANENT"])) <>
        D.text (": " ++ cls ++ " = ") <> L.block
          [ L.bind "actor" (L.call ("LawSpecRuntime.Actor[" ++ own ++ "]") [initial, restart])
          , D.text "if (supervisor != null) supervisor.supervise(actor, lifetime)"
          , D.text ("new " ++ cls ++ "(actor)") ]
      body = D.render D.Compact (D.joinWith D.hardline (classMembers ++ fst remote))
      imports = [ "import lawspec.runtime." ++ c | c <- ["LawSpecDataCodecs", "LawSpecDataSchema", "LawSpecRuntime", "LawSpecScala", "LawSpecScalaCodecs"], (c ++ ".") `isInfixOf` body || c == "LawSpecRuntime" ]
  pure $ D.render L.scalaStyle $
    D.text ("// Generated by LawSpec from actor " ++ actorName a ++ ". Do not edit.") <> D.hardline <>
    D.text "package lawspec.actors" <> D.hardline <> D.hardline <>
    D.joinWith D.hardline (map D.text imports) <> D.hardline <> D.hardline <>
    comment 0 ("Actor " ++ actorName a ++ ": owns its state and handles one message at a time, in the order they arrive. " ++
      "Each handler method sends a message and returns the reply; tell methods send it without waiting. " ++
      "A handler that throws crashes the actor: the caller gets LawSpecRuntime.ActorCrashed, and a supervised actor restarts " ++
      "(from its restart adapter, or its start) while any other stops.") <>
    D.group (D.text ("final class " ++ cls ++ " private (") <> D.nest 4 (D.softbreak <> D.text ("private val actor: LawSpecRuntime.Actor[" ++ own ++ "]")) <> D.softbreak <> D.text ")") <>
    D.text " " <> L.block [D.joinWith (D.hardline <> D.hardline) classMembers] <> D.hardline <> D.hardline <>
    D.text ("object " ++ cls ++ " ") <> L.block [D.joinWith (D.hardline <> D.hardline) (fst remote ++ [start])] <> D.hardline
  where
    cls = actorClass a
    comment indentation = L.comment (80 - indentation)
    awaited d call = if C.declarationAsync d then L.call "scala.concurrent.Await.result" [call, D.text "scala.concurrent.duration.Duration.Inf"] else call
    adapterCallDoc d = L.call (adapterFunction a d)
    codec ty = scalaCodecDocIn ("Schema", "MachineBits") (D.text "symbols") datas ty
    descriptor d = L.call "LawSpecRuntime.descriptor" [D.text (scalaQuoted d)]
    -- The companion's members, and the class's.
    scalaRemote own w = do
      served <- mapM (\(h, ds, r) -> do
        argCodecs <- mapM (codec . snd) (handlerArguments h)
        replyCodec <- codec (replyOf h)
        let call = awaited (handlerDeclaration h) (adapterCallDoc (handlerDeclaration h)
              (D.text "s" : [L.chain c [("decode", [D.text ("args.get(" ++ show i ++ ")")])] | (i, c) <- zip [0 :: Int ..] argCodecs]))
            next = "LawSpecRuntime.Next[LawSpecRuntime.Value, " ++ own ++ "]"
            result = case handlerReply h of
              Just _ -> [ L.bind "next" call, L.call next [L.chain replyCodec [("encode", [D.text "next.first"])], D.text "next.second"] ]
              Nothing -> [ L.call next [D.text "LawSpecRuntime.absent(\"Unit\")", call] ]
        pure (L.call "handlers.put" [D.text (scalaQuoted (handlerName h)), L.call ("LawSpecRuntime.Served[" ++ own ++ "]")
          [ D.text ("(s: " ++ own ++ ", args: java.util.List[LawSpecRuntime.Value]) => ") <> L.block (D.text "val symbols = LawSpecScala.symbols()" : result)
          , L.call "java.util.List.of[Object]" (map descriptor ds)
          , descriptor r ]])) (wireHandlers w)
      methods <- mapM (\(h, _, _) -> do
        params <- sequence [(\n -> p ++ ": " ++ n) <$> scalaDataType datas t | (p, t) <- handlerArguments h]
        argCodecs <- mapM (codec . snd) (handlerArguments h)
        replyCodec <- codec (replyOf h)
        reply <- traverse (scalaDataType datas) (handlerReply h)
        let call = L.call "remote.call" [D.text (scalaQuoted (handlerName h)),
              L.call "java.util.List.of[LawSpecRuntime.Value]" [L.chain c [("encode", [D.text p])] | (c, (p, _)) <- zip argCodecs (handlerArguments h)]]
        pure (comment 4 ("Sends " ++ handlerName h ++ " to the actor and waits for the reply.") <>
          L.parameters (D.text ("def " ++ handlerName h)) (map D.text params) <> D.text (": " ++ maybe "Unit" id reply ++ " = ") <>
          L.block ([D.text "val symbols = LawSpecScala.symbols()"] ++
            (if handlerReply h == Nothing then [call, D.text "()"] else [L.chain replyCodec [("decode", [call])]])))) (wireHandlers w)
      let companion =
            [ D.text "private val Schema = LawSpecDataSchema.create()"
            , D.text ("private val MachineBits = " ++ show (wireBits w))
            , L.bind "Types" (L.call "LawSpecRuntime.valuesOf" [D.text (scalaQuoted (wireTypes w))])
            , comment 2 "The actor served at address on another node; a call not answered within timeout seconds throws Unreachable." <>
              L.parameters (D.text "def connect") (map D.text ["node: LawSpecRuntime.Node", "address: String", "timeout: Double = 5.0"]) <>
              D.text ": Remote = " <> L.block
                ([ D.text "val signatures = java.util.HashMap[String, LawSpecRuntime.Signature]()" ] ++
                 [ L.call "signatures.put" [D.text (scalaQuoted (handlerName h)),
                     L.call "LawSpecRuntime.Signature" [L.call "java.util.List.of[Object]" (map descriptor ds), descriptor r]]
                 | (h, ds, r) <- wireHandlers w ] ++
                 [ D.text "Remote(node.remoteActor(address, signatures, Types, timeout))" ])
            , comment 2 ("Actor " ++ actorName a ++ " on another node: each method sends its message and waits for the reply.") <>
              D.group (D.text ("final class Remote private[" ++ cls ++ "] (") <> D.nest 4 (D.softbreak <> D.text "private val remote: LawSpecRuntime.RemoteActor") <> D.softbreak <> D.text ")") <>
              D.text " " <> L.block [D.joinWith (D.hardline <> D.hardline) methods] ]
          members =
            [ comment 2 "Lets other nodes call this actor at {node address}/name; returns that address." <>
              D.text "def serve(node: LawSpecRuntime.Node, name: String): String = " <> L.block
                ([ D.text ("import " ++ cls ++ ".{Types, MachineBits, Schema}")
                 , L.bind "handlers" (D.text ("java.util.HashMap[String, LawSpecRuntime.Served[" ++ own ++ "]]()")) ] ++ served ++
                 [ D.text "node.serve(name, actor, handlers, Types)" ]) ]
      pure (companion, members)
    handler own h = do
      params <- sequence [(\n -> p ++ ": " ++ n) <$> scalaDataType datas t | (p, t) <- handlerArguments h]
      reply <- traverse (scalaDataType datas) (handlerReply h)
      let call = awaited (handlerDeclaration h) (adapterCallDoc (handlerDeclaration h) (D.text "s" : map (D.text . fst) (handlerArguments h)))
          replyType = maybe "Unit" id reply
          next = "LawSpecRuntime.Next[" ++ replyType ++ ", " ++ own ++ "]"
          step = case reply of
            Just _ -> [L.bind "next" call, L.call next [D.text "next.first", D.text "next.second"]]
            Nothing -> [L.call next [D.text "()", call]]
          name = handlerName h
          signature n result = L.parameters (D.text ("def " ++ n)) (map D.text params) <> D.text (": " ++ result)
      pure $ D.joinWith (D.hardline <> D.hardline)
        [ comment 2 ("Sends " ++ name ++ " and waits for the reply.") <>
          L.equalsBody (signature name replyType) (L.trailing (D.text ("actor.call[" ++ replyType ++ "]")) ["(s: " ++ own ++ ")"] step)
        , comment 2 ("Sends " ++ name ++ " without waiting for the reply.") <>
          L.equalsBody (signature ("tell" ++ capital name) "Unit") (L.trailing (D.text "actor.cast") ["(s: " ++ own ++ ")"] step) ]

scalaSupervisor :: Supervision -> String
scalaSupervisor s = D.render L.scalaStyle $
  D.text ("// Generated by LawSpec from supervisor " ++ supervisionName s ++ ". Do not edit.") <> D.hardline <>
  D.text "package lawspec.actors" <> D.hardline <> D.hardline <>
  D.text "import lawspec.runtime.LawSpecRuntime" <> D.hardline <> D.hardline <>
  L.comment 80 ("Supervisor " ++ supervisionName s ++ ": " ++ strategyText s ++ ", at most " ++ show (supervisionRestarts s) ++
    " restarts in " ++ seconds s ++ "s.") <>
  L.parameters (D.text ("final class " ++ cls ++ " private "))
    (D.text "private val supervisor: LawSpecRuntime.Supervisor" : [D.text ("val " ++ name ++ ": " ++ childClass c) | (_, name, c) <- supervisionChildren s]) <>
  D.text " " <> L.block [D.joinWith (D.hardline <> D.hardline)
    [ L.comment 78 "notify gets Exit(\"crashed\", cause) when it passes its restart limit, and Exit(\"stopped\", null) once stopped." <>
      L.equalsBody (D.text "def monitor(notify: LawSpecRuntime.Exit => Unit): Unit") (D.text "supervisor.monitor(exit => notify(exit))")
    , L.comment 78 "Stops every child, last started first, without restarting them." <>
      D.text "def stop(): Unit = supervisor.stop()" ]] <> D.hardline <> D.hardline <>
  D.text ("object " ++ cls ++ " ") <> L.block
    [ L.comment 78 "Starts the supervisor and its children, under parent (when given) with the given lifetime." <>
      L.parameters (D.text "def start") (map D.text ["parent: LawSpecRuntime.Supervisor = null", "lifetime: String = LawSpecRuntime.Supervisor.PERMANENT"]) <>
      D.text (": " ++ cls ++ " = ") <> L.block
        ([ L.bind "own" (L.call "LawSpecRuntime.Supervisor" [D.text (scalaQuoted (strategyName s)), D.text (show (supervisionRestarts s)), D.text (seconds s)]) ] ++
         [ L.bind name (L.call (childClass c ++ ".start") [D.text "own", D.text (scalaQuoted (lifetimeName l))]) | (l, name, c) <- supervisionChildren s ] ++
         [ D.text "if (parent != null) parent.supervise(own, lifetime)"
         , L.call ("new " ++ cls) (map D.text ("own" : [name | (_, name, _) <- supervisionChildren s])) ]) ] <> D.hardline
  where cls = supervisionClass s
